def _grouped_bar(
    ax: plt.Axes,
    data: pd.DataFrame,
    title: str,
    ylabel: str,
    sig: pd.DataFrame | None = None,
) -> None:
    n_groups, n_methods = data.shape
    width = 0.8 / n_methods
    x = np.arange(n_groups)
    for i, method in enumerate(data.columns):
        ax.bar(
            x + i * width,
            data[method],
            width,
            label=SCORE_LABELS[method],
            color=SCORE_COLORS[method],
        )
        if sig is not None:
            for xi, (val, is_sig) in enumerate(
                zip(data[method], sig[method], strict=True)
            ):
                if is_sig:
                    ax.text(
                        x[xi] + i * width,
                        val,
                        "*",
                        ha="center",
                        va="bottom",
                        fontsize=9,
                    )
    ax.set_xticks(x + width * (n_methods - 1) / 2)
    ax.set_xticklabels(data.index)
    ax.set_xlabel("CP component (reference numbering)")
    ax.set_ylabel(ylabel)
    ax.set_title(title, fontsize=8)
    ax.legend(fontsize=5, loc="best")


def _load_method_csv(filename: str, method: str) -> pd.DataFrame:
    return load_runner_csv(
        filename, root=comparison_output_dir(method), hint=ALT_COMM_SCORE_HINT
    )


def _factor_comparison_data(adata_raw) -> dict[str, pd.DataFrame]:
    """Per-metric (component x alternate method) tables for panels a-d."""
    comparisons = {
        method: _match_and_compare(DEFAULT_SCORE, method, adata_raw).set_index(
            "Component"
        )
        for method in ALT_SCORES
    }
    return {
        metric: pd.DataFrame({m: comparisons[m][metric] for m in ALT_SCORES})
        for metric in ("MatchScore", "MeanBCCosine", "TopLRJaccard", "CelltypeJaccard")
    }


def _aligned_anova(method: str) -> tuple[pd.Series, pd.Series]:
    """`method`'s ANOVA eta-squared and p<0.05 flags per component, in the
    default score's component numbering."""
    df = _load_method_csv(SPEC.anova_point_estimate_filename(), method)
    if method == DEFAULT_SCORE:
        df = df.set_index("Component")
        return df["EtaSquared"], df["P"] < 0.05

    ref_factors, method_factors = _cp_factors(DEFAULT_SCORE), _cp_factors(method)

    def align(values: np.ndarray) -> pd.Series:
        return align_to_reference_components(
            ref_factors, method_factors, values, MATCH_MODE_WEIGHTS
        ).set_index("Component")["Value"]

    eta = align(df["EtaSquared"].to_numpy())
    sig = align((df["P"] < 0.05).to_numpy().astype(float)) > 0.5
    return eta, sig


def _anova_data() -> tuple[pd.DataFrame, pd.DataFrame, str]:
    """Panel e: eta-squared and significance tables, and the outcome tested."""
    aligned = {method: _aligned_anova(method) for method in ALL_SCORES}
    eta_df = pd.DataFrame({m: eta for m, (eta, _) in aligned.items()})
    eta_df.index.name = "Component"
    sig_df = pd.DataFrame({m: sig for m, (_, sig) in aligned.items()})
    outcome = read_metadata(
        comparison_output_dir(DEFAULT_SCORE) / SPEC.anova_point_estimate_filename()
    )["group_column"]
    return eta_df, sig_df, outcome


def _significance_data() -> tuple[dict[str, float], dict[str, float]]:
    """Panel f: mean fraction of significant entries per method, and each
    method's top-LR Jaccard overlap with the default."""
    frac_sig, top_sig_lr = {}, {}
    for method in ALL_SCORES:
        sig_df = _load_method_csv(SPEC.significance_lr_filename(), method)
        frac_sig[method] = float(sig_df["FractionSignificant_p05"].mean())
        top_sig_lr[method] = set(sig_df.nlargest(TOP_N_LR, "MeanZScore")["LRPair"])
    sig_jaccard = {
        method: _jaccard(top_sig_lr[DEFAULT_SCORE], top_sig_lr[method])
        for method in ALL_SCORES
    }
    return frac_sig, sig_jaccard


def _stability_data() -> pd.DataFrame:
    """Panel g: median CP component FMS per axis (rows) and method (columns)."""
    medians = {}
    for method in ALL_SCORES:
        df = _load_method_csv(SPEC.stability_filename(), method)
        medians[method] = df[df["Stage"] == "CPD"].groupby("Axis")["FMS"].median()
    return pd.DataFrame(medians)


def _draw_significance(
    ax: plt.Axes, frac_sig: dict[str, float], sig_jaccard: dict[str, float]
) -> None:
    bars = ax.bar(
        [SCORE_LABELS[m] for m in ALL_SCORES],
        [frac_sig[m] for m in ALL_SCORES],
        color="#3a6b9c",
    )
    for bar, method in zip(bars, ALL_SCORES, strict=True):
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            bar.get_height(),
            f"J={sig_jaccard[method]:.2f}",
            ha="center",
            va="bottom",
            fontsize=6,
        )
    ax.set_ylabel("Mean fraction of entries\nsignificant per LR pair (p<0.05)")
    ax.set_title(
        f"Permutation significance (label: top-{TOP_N_LR} LR-pair\n"
        "Jaccard vs. default)",
        fontsize=8,
    )
    ax.tick_params(axis="x", labelrotation=25)


def _draw_stability(ax: plt.Axes, stability_df: pd.DataFrame) -> None:
    x = np.arange(len(stability_df.index))
    width = 0.8 / len(ALL_SCORES)
    for i, method in enumerate(ALL_SCORES):
        ax.bar(
            x + i * width,
            stability_df[method],
            width,
            label=SCORE_LABELS[method],
            color=SCORE_COLORS[method],
        )
    ax.set_xticks(x + width * (len(ALL_SCORES) - 1) / 2)
    ax.set_xticklabels(stability_df.index)
    ax.set_ylabel("Median CP component FMS")
    ax.set_title(
        f"CP component stability (n={N_REPLICATES_SMOKE} placeholder)", fontsize=8
    )
    ax.set_ylim(0, 1.3)
    ax.legend(fontsize=5, loc="upper center", ncol=2)


def _draw_caveats(ax: plt.Axes) -> None:
    ax.axis("off")
    ax.text(
        0.0,
        1.0,
        (
            f"Dataset: {SPEC.label}\n"
            f"RISE rank {RISE_RANK}, CP rank {CP_RANK}\n"
            f"All 4 methods: n_perms={N_PERMS_SMOKE}, "
            f"n_replicates={N_REPLICATES_SMOKE} (smoke test)\n\n"
            "Caveats:\n"
            "- ANOVA is a point estimate, not a bootstrap.\n"
            "- All results here are smoke-test scale, not\n"
            "  statistically powered -- a separate, comprehensive\n"
            "  copy of the default score's results lives in the\n"
            "  root data dir for manuscript interpretation."
        ),
        transform=ax.transAxes,
        va="top",
        ha="left",
        fontsize=6,
        family="monospace",
    )


def makeFigure():
    factor_tables = _factor_comparison_data(SPEC.load())
    anova_eta_df, anova_sig_df, outcome = _anova_data()
    frac_sig, sig_jaccard = _significance_data()
    stability_df = _stability_data()

    axs, fig = getSetup((16, 8), (2, 4))
    factor_panels = [
        ("MatchScore", "CP component match quality (LR-mode cosine)", "Match score"),
        (
            "MeanBCCosine",
            "Aligned sender/receiver (B/C) cosine similarity",
            "Cosine similarity",
        ),
        ("TopLRJaccard", f"Top-{TOP_N_LR} LR-pair Jaccard overlap", "Jaccard index"),
        (
            "CelltypeJaccard",
            f"Top-{TOP_N_CELLTYPE} sender/receiver cell-type Jaccard",
            "Jaccard index",
        ),
    ]
    for ax, (metric, title, ylabel) in zip(axs[:4], factor_panels, strict=True):
        _grouped_bar(ax, factor_tables[metric], title, ylabel)
    _grouped_bar(
        axs[4],
        anova_eta_df,
        f"ANOVA eta-squared vs {outcome} (point estimate, * p<0.05)",
        "Eta-squared",
        sig=anova_sig_df,
    )
    _draw_significance(axs[5], frac_sig, sig_jaccard)
    _draw_stability(axs[6], stability_df)
    _draw_caveats(axs[7])

    subplotLabel(axs)
    return fig
