def _grouped_bar(
    ax: plt.Axes,
    data: pd.DataFrame,
    title: str,
    ylabel: str,
    sig: pd.DataFrame | None = None,
) -> None:
    n_groups, n_methods = data.shape
    width = 0.8 / n_methods
    x = np.arange(n_groups)
    for i, method in enumerate(data.columns):
        ax.bar(
            x + i * width,
            data[method],
            width,
            label=SCORE_LABELS[method],
            color=SCORE_COLORS[method],
        )
        if sig is not None:
            for xi, (val, is_sig) in enumerate(
                zip(data[method], sig[method], strict=True)
            ):
                if is_sig:
                    ax.text(
                        x[xi] + i * width,
                        val,
                        "*",
                        ha="center",
                        va="bottom",
                        fontsize=9,
                    )
    ax.set_xticks(x + width * (n_methods - 1) / 2)
    ax.set_xticklabels(data.index)
    ax.set_xlabel("CP component (core-fit numbering)")
    ax.set_ylabel(ylabel)
    ax.set_title(title, fontsize=8)
    ax.legend(fontsize=5, loc="best")


def _draw_top_k_overlap(
    ax: plt.Axes, overlaps: pd.DataFrame, title: str, xlabel: str
) -> None:
    """One line per alternate method: top-K Jaccard overlap with the default
    against K, as the mean with an SD error bar over the rows (CP components)
    sharing a K; a single row per K (significance) draws no bar."""
    for method in overlaps["Method"].unique():
        rows = overlaps[overlaps["Method"] == method]
        stats = rows.groupby("K")["Jaccard"].agg(["mean", "std"])
        ax.errorbar(
            stats.index,
            stats["mean"],
            yerr=stats["std"] if stats["std"].notna().any() else None,
            marker="o",
            markersize=3,
            linewidth=1,
            capsize=2,
            label=SCORE_LABELS[method],
            color=SCORE_COLORS[method],
        )
    ax.set_ylim(0, 1.05)
    ax.xaxis.set_major_locator(MaxNLocator(integer=True))
    ax.set_xlabel(xlabel)
    ax.set_ylabel("Jaccard overlap with default")
    ax.set_title(title, fontsize=8)
    ax.legend(fontsize=5, loc="best")


def _draw_significance(ax: plt.Axes, frac_sig: dict[str, float]) -> None:
    ax.bar(
        [SCORE_LABELS[m] for m in ALL_SCORES],
        [frac_sig[m] for m in ALL_SCORES],
        color=[SCORE_COLORS[m] for m in ALL_SCORES],
    )
    ax.set_ylabel("Mean fraction of entries\nsignificant per LR pair (p<0.05)")
    ax.set_title("Permutation significance", fontsize=8)
    ax.tick_params(axis="x", labelrotation=25)


def _draw_stability(
    ax: plt.Axes, stability_df: pd.DataFrame, n_replicates: int
) -> None:
    x = np.arange(len(stability_df.index))
    width = 0.8 / len(ALL_SCORES)
    for i, method in enumerate(ALL_SCORES):
        ax.bar(
            x + i * width,
            stability_df[method],
            width,
            label=SCORE_LABELS[method],
            color=SCORE_COLORS[method],
        )
    ax.set_xticks(x + width * (len(ALL_SCORES) - 1) / 2)
    ax.set_xticklabels(stability_df.index)
    ax.set_ylabel("Aggregate CP FMS (median over replicates)")
    ax.set_title(
        f"CP component stability ({n_replicates} replicates per axis)", fontsize=8
    )
    ax.set_ylim(0, 1.3)
    ax.legend(fontsize=5, loc="upper center", ncol=2)


def makeFigure():
    factor_tables, factor_overlaps = _factor_comparison_data(SPEC.load())
    anova_eta_df, anova_sig_df, outcome = _anova_data()
    frac_sig, sig_overlaps = _significance_data()
    stability_df, n_stability_replicates = _stability_data()

    axs, fig = getSetup((16, 8), (2, 4))
    _grouped_bar(
        axs[0],
        factor_tables["MatchScore"],
        "CP component match quality (condition + LR |cosine|)",
        "Match score",
    )
    _grouped_bar(
        axs[1],
        factor_tables["MeanBCCosine"],
        "Matched sender/receiver (B/C) |cosine|",
        "Cosine similarity",
    )
    for ax, kind, noun, xlabel in (
        (axs[2], "LR", "LR pairs", "K (top LR pairs by |D| loading)"),
        (
            axs[3],
            "Celltype",
            "cell types",
            "K (top sender/receiver cell types by |mean loading|)",
        ),
    ):
        _draw_top_k_overlap(
            ax,
            factor_overlaps[factor_overlaps["Kind"] == kind],
            f"Top-K {noun} (mean ± SD over components)",
            xlabel,
        )
    _grouped_bar(
        axs[4],
        anova_eta_df,
        f"ANOVA eta-squared vs {outcome} (point estimate, * p<0.05)",
        "Eta-squared",
        sig=anova_sig_df,
    )
    _draw_significance(axs[5], frac_sig)
    _draw_top_k_overlap(
        axs[6],
        sig_overlaps,
        "Top-K most significant LR pairs",
        "K (top LR pairs by mean z-score)",
    )
    _draw_stability(axs[7], stability_df, n_stability_replicates)

    subplotLabel(axs)
    return fig
