"""
Figure comparing CCC-RISE results across the four communication-scoring
methods on ALAD, at the ranks recorded in the comparison's provenance:

    1. CPD factor matrices -- component match quality, aligned factor cosine
       similarity, and top-K overlap of ligand-receptor pairs and of
       sender/receiver cell types against the default score.
    2. ANOVA association between CP components and the dataset's outcome
       (`DatasetSpec.outcome_column`; point estimate, no bootstrap).
    3. Permutation significance of ligand-receptor pairs, and top-K overlap of
       the most significant pairs against the default score.
    4. CP component stability.

Only loads results; never generates them. All four methods, including the
default, are read from ``VALIDATION_DIR/alt_score_methods/<method>/``,
generated by `cccrise-altcommscore` sharing one RISE fit across all four
methods -- kept separate from the default's comprehensive results that every
other figure reads.
"""

from typing import Any

import numpy as np
import pandas as pd
from matplotlib import pyplot as plt
from matplotlib.ticker import MaxNLocator

from ...factors import load_factors_netcdf, load_factors_to_anndata
from ...runners.datasets import (
    COMMUNICATION_SCORES,
    COMPARISON_PROVENANCE_FILENAME,
    DATASETS,
    DEFAULT_COMMUNICATION_SCORE,
    comparison_output_dir,
)
from ...runners.provenance import read_metadata_at
from ...validation.anova_stability import align_to_reference_components
from ...validation.component_stability import STAGE_CPD, metric_interval
from ..common import getSetup, load_runner_output, subplotLabel

DATASET_KEY = "alad"
SPEC = DATASETS[DATASET_KEY]

DEFAULT_SCORE = DEFAULT_COMMUNICATION_SCORE
ALL_SCORES = list(COMMUNICATION_SCORES)
ALT_SCORES = [m for m in ALL_SCORES if m != DEFAULT_SCORE]
# Fixed per method, so a method keeps its color in panels that omit the default.
SCORE_COLORS = {method: f"C{i}" for i, method in enumerate(ALL_SCORES)}
SCORE_LABELS = {
    "expression_product": "product (default)",
    "expression_mean": "mean (CellPhoneDB-style)",
    "expression_gmean": "geometric mean",
    "expression_hill": "Hill (CellChat-style)",
}

#: K values the top-K ligand-receptor-pair overlaps are computed at (CP
#: loadings and significance alike).
LR_TOP_KS = range(1, 20, 2)
#: K values the top-K sender/receiver cell-type overlaps are computed at.
CELLTYPE_KS = range(1, 4)

#: Modes CP components are matched across methods on: condition and
#: ligand-receptor. All four methods share one RISE fit, so every mode shares
#: its coordinates; sender/receiver (B/C) stay out of the match so panels b
#: and d, which read them, remain independent checks of it.
MATCH_MODES = (0, 3)

ALT_COMM_SCORE_HINT = (
    f"    uv run cccrise-altcommscore --dataset {DATASET_KEY} "
    "--rise-rank <N> --cp-rank <M>"
)


# =============================================================================
# Result loading
# =============================================================================


def cp_factors(method: str) -> tuple[list[np.ndarray], np.ndarray]:
    """`method`'s CP factors [A, B, C, D] and the LR-pair labels of D's rows."""
    ds = load_factors_netcdf(comparison_output_dir(method) / SPEC.factors_filename)
    return [ds[f"cp_{mode}"].values for mode in "ABCD"], ds.coords["lr_pair"].values


def celltype_loadings(method: str, adata_raw) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Mean sender (sc_B) and receiver (rc_C) loading per cell type, per
    component. All four methods share the same RISE eigen-states, so
    aligning CP components on the LR mode makes B/C directly comparable."""
    ad = load_factors_to_anndata(
        comparison_output_dir(method) / SPEC.factors_filename,
        adata=adata_raw,
        condition_column=SPEC.condition_column,
    )
    celltypes = ad.obs[SPEC.celltype_column].to_numpy()
    sender = pd.DataFrame(ad.obsm["sc_B"], index=celltypes).groupby(level=0).mean()
    receiver = pd.DataFrame(ad.obsm["rc_C"], index=celltypes).groupby(level=0).mean()
    return sender, receiver


def match_components(reference_method: str, method: str) -> pd.DataFrame:
    """Pair `method`'s CP components with `reference_method`'s on
    `MATCH_MODES` (`align_to_reference_components`): one row per reference
    component, with its 'MatchedComponent' and 'MatchScore'."""
    ref_factors, _ = cp_factors(reference_method)
    alt_factors, _ = cp_factors(method)
    return align_to_reference_components(
        ref_factors,
        alt_factors,
        np.arange(1, ref_factors[0].shape[1] + 1),
        MATCH_MODES,
    )


def _load_method_output(filename: str, method: str) -> pd.DataFrame:
    return load_runner_output(
        filename, root=comparison_output_dir(method), hint=ALT_COMM_SCORE_HINT
    )


def _default_score_provenance(section: str, key: str) -> Any:
    """`key` from `section` of the default score's consolidated provenance
    (`run_alt_comm_score`), where a field shared between sections is hoisted
    to the top level."""
    meta = read_metadata_at(
        comparison_output_dir(DEFAULT_SCORE) / COMPARISON_PROVENANCE_FILENAME
    )
    return meta[key] if key in meta else meta[section][key]


def _jaccard(a: set, b: set) -> float:
    if not a and not b:
        return 1.0
    return len(a & b) / len(a | b)


def _top_k(scores: pd.Series, k: int) -> set:
    """Labels of the `k` largest-magnitude entries of `scores`."""
    return set(scores.abs().nlargest(k).index)


def _top_k_jaccard(ref: pd.Series, alt: pd.Series, ks) -> list[dict]:
    return [{"K": k, "Jaccard": _jaccard(_top_k(ref, k), _top_k(alt, k))} for k in ks]


def _cosine(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b)))


def _match_and_compare(
    reference_method: str, method: str, adata_raw
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Compare `method`'s CP fit to `reference_method`'s, component by
    matched component.

    Returns
    -------
    tuple[pd.DataFrame, pd.DataFrame]
        Per reference component, 'MatchScore' and 'MeanBCCosine' (the matched
        pair's mean absolute sender/receiver cosine); and a long table of top-K Jaccard overlaps,
        columns 'Component', 'Kind' ('LR' or 'Celltype', the latter the mean
        of the sender and receiver overlaps), 'K', 'Jaccard'.
    """
    ref_factors, lr_symbols = cp_factors(reference_method)
    alt_factors, _ = cp_factors(method)
    matching = match_components(reference_method, method)
    ref_sender, ref_receiver = celltype_loadings(reference_method, adata_raw)
    alt_sender, alt_receiver = celltype_loadings(method, adata_raw)

    rows, overlaps = [], []
    for _, row in matching.iterrows():
        ref_i, alt_i = int(row["Component"]) - 1, int(row["MatchedComponent"]) - 1
        rows.append(
            {
                "Component": ref_i + 1,
                "MatchScore": float(row["MatchScore"]),
                "MeanBCCosine": np.mean(
                    [
                        abs(_cosine(ref_factors[m][:, ref_i], alt_factors[m][:, alt_i]))
                        for m in (1, 2)
                    ]
                ),
            }
        )
        lr = _top_k_jaccard(
            pd.Series(ref_factors[3][:, ref_i], index=lr_symbols),
            pd.Series(alt_factors[3][:, alt_i], index=lr_symbols),
            LR_TOP_KS,
        )
        sender = _top_k_jaccard(
            ref_sender.iloc[:, ref_i], alt_sender.iloc[:, alt_i], CELLTYPE_KS
        )
        receiver = _top_k_jaccard(
            ref_receiver.iloc[:, ref_i], alt_receiver.iloc[:, alt_i], CELLTYPE_KS
        )
        overlaps += [{"Component": ref_i + 1, "Kind": "LR"} | o for o in lr]
        overlaps += [
            {
                "Component": ref_i + 1,
                "Kind": "Celltype",
                "K": s["K"],
                "Jaccard": np.mean([s["Jaccard"], r["Jaccard"]]),
            }
            for s, r in zip(sender, receiver, strict=True)
        ]
    return pd.DataFrame(rows).set_index("Component"), pd.DataFrame(overlaps)


def _factor_comparison_data(
    adata_raw,
) -> tuple[dict[str, pd.DataFrame], pd.DataFrame]:
    """Panels a-d: (component x alternate method) tables of match score and
    B/C cosine, and a long table of every alternate method's top-K overlaps."""
    comparisons = {
        method: _match_and_compare(DEFAULT_SCORE, method, adata_raw)
        for method in ALT_SCORES
    }
    tables = {
        metric: pd.DataFrame({m: comparisons[m][0][metric] for m in ALT_SCORES})
        for metric in ("MatchScore", "MeanBCCosine")
    }
    overlaps = pd.concat(
        [comparisons[m][1].assign(Method=m) for m in ALT_SCORES], ignore_index=True
    )
    return tables, overlaps


def _aligned_anova(method: str) -> tuple[pd.Series, pd.Series]:
    """`method`'s ANOVA eta-squared and p<0.05 flags per component, in the
    default score's component numbering."""
    df = _load_method_output(SPEC.anova_point_estimate_filename(), method)
    if method == DEFAULT_SCORE:
        df = df.set_index("Component")
        return df["EtaSquared"], df["P"] < 0.05

    ref_factors, _ = cp_factors(DEFAULT_SCORE)
    method_factors, _ = cp_factors(method)

    def align(values: np.ndarray) -> pd.Series:
        return align_to_reference_components(
            ref_factors, method_factors, values, MATCH_MODES
        ).set_index("Component")["Value"]

    eta = align(df["EtaSquared"].to_numpy())
    sig = align((df["P"] < 0.05).to_numpy().astype(float)) > 0.5
    return eta, sig


def _anova_data() -> tuple[pd.DataFrame, pd.DataFrame, str]:
    """Panel e: eta-squared and significance tables, and the outcome tested."""
    aligned = {method: _aligned_anova(method) for method in ALL_SCORES}
    eta_df = pd.DataFrame({m: eta for m, (eta, _) in aligned.items()})
    eta_df.index.name = "Component"
    sig_df = pd.DataFrame({m: sig for m, (_, sig) in aligned.items()})
    outcome = _default_score_provenance("anova_point_estimate", "group_column")
    return eta_df, sig_df, outcome


def _significance_data() -> tuple[dict[str, float], pd.DataFrame]:
    """Panels f-g: mean fraction of significant entries per method, and a
    long table of each alternate method's top-K most significant LR pairs'
    overlap with the default's."""
    frac_sig, ranked = {}, {}
    for method in ALL_SCORES:
        sig_df = _load_method_output(SPEC.significance_lr_filename(), method)
        frac_sig[method] = float(sig_df["FractionSignificant_p05"].mean())
        # The largest positive z-scores are the most significant: rank signed.
        ranked[method] = sig_df.sort_values("MeanZScore", ascending=False)["LRPair"]
    overlaps = [
        {
            "Method": method,
            "K": k,
            "Jaccard": _jaccard(
                set(ranked[DEFAULT_SCORE].head(k)), set(ranked[method].head(k))
            ),
        }
        for method in ALT_SCORES
        for k in LR_TOP_KS
    ]
    return frac_sig, pd.DataFrame(overlaps)


def _stability_data() -> tuple[pd.DataFrame, int]:
    """Panel h: aggregate CP FMS per axis (rows) and method (columns) -- the
    median over replicates of each replicate's mean over components, as in
    `figureComponentStability`'s aggregate panel -- and replicates per axis."""
    medians = {}
    for method in ALL_SCORES:
        df = _load_method_output(SPEC.stability_filename(), method)
        stats = metric_interval(df[df["Stage"] == STAGE_CPD], "FMS", by=("Axis",))
        medians[method] = stats.set_index("Axis")["Median"]
    n_replicates = _default_score_provenance("stability", "n_replicates")
    return pd.DataFrame(medians), n_replicates


