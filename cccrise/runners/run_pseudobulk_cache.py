#!/usr/bin/env python
"""
Runner: the per-(sample, fine type) pseudobulk cache (`comparators.pseudobulk_cache`).

One pass over the dataset's cells (the cohort its cccRISE factors were fit on)
stores, per sample and fine cell type: the cell count, the expression sums of
every gene an LR pair uses, and the sums and active-cell counts of cccRISE's
sample-scaled per-cell sender and receiver loadings. Every labelling that
merges fine types (the coarse annotation, and the sampled granularity
levels) is then built from it without reloading the cells. As a check, the
coarse tensor built from the cache is compared with
`benchmark.pseudobulk_tensor` on the cells; the run fails if they differ.

Writes ``output/cache/pseudobulk/<dataset>.npz`` (git-ignored; derived and
reproducible) with a provenance file beside it.

    uv run python -m cccrise.runners.run_pseudobulk_cache --dataset ibd
"""

import argparse
from pathlib import Path

import numpy as np

from ..benchmark import pseudobulk_tensor
from ..ccc_rise import calc_communication_score_pseudobulk
from ..comparators.pseudobulk_cache import (
    group_sums,
    labelled_matrices,
    loading_sums,
    lr_genes,
)
from ..factors import ensure_decompressed, load_factors_to_anndata
from ..import_data import import_ligand_receptor_pairs
from ._cli import add_dataset_argument, dataset_metadata, resolve_dataset
from .datasets import DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

CACHE_DIR = Path(__file__).resolve().parents[2] / "output" / "cache" / "pseudobulk"
FINE_COLUMN = "celltype"
HEADER = """\
Per-(sample, fine type) pseudobulk cache. Generated by
cccrise.runners.run_pseudobulk_cache -- do not hand-edit.
"""


def cache_path(dataset: str) -> Path:
    return CACHE_DIR / f"{dataset}.npz"


def _coarse_check(adata, spec, genes, cache, lr_pairs) -> float:
    """Largest |difference| between the cache's coarse tensor and
    `pseudobulk_tensor` on the cells."""
    print(">> Checking the cache against the coarse tensor built from the cells")
    coarse = dict(zip(cache["fine_types"], cache["fine_to_coarse"], strict=True))
    matrices, groups = labelled_matrices(
        cache["counts"], cache["sums"], cache["fine_types"], genes, coarse
    )
    from_cache, _ = calc_communication_score_pseudobulk(matrices, lr_pairs=lr_pairs)
    direct, types, _ = pseudobulk_tensor(
        adata[:, genes], spec.condition_column, spec.celltype_column, lr_pairs
    )
    if list(map(str, types)) != list(map(str, groups)):
        raise ValueError(f"coarse types differ: {list(types)} vs {list(groups)}")
    return float(np.max(np.abs(from_cache - direct)))


def build_cache(spec: DatasetSpec) -> dict:
    git_sha()
    factors = ensure_decompressed(spec.factors_path())
    print(f">> Loading {spec.label} and cccRISE's per-cell loadings")
    adata = load_factors_to_anndata(factors, adata=spec.load())
    lr_pairs = import_ligand_receptor_pairs()
    genes = [g for g in lr_genes(lr_pairs) if g in set(adata.var_names)]
    obs = adata.obs
    samples = obs[spec.condition_column].astype(str).to_numpy()
    fine = obs[FINE_COLUMN].astype(str).to_numpy()
    sample_order, fine_order = np.unique(samples), np.unique(fine)
    print(
        f">> Summing {len(genes)} LR genes over {len(sample_order)} x {len(fine_order)} groups"
    )
    counts, sums = group_sums(
        adata[:, genes].X, samples, fine, sample_order, fine_order
    )
    out = {
        "samples": sample_order,
        "fine_types": fine_order,
        "fine_to_coarse": obs.groupby(FINE_COLUMN, observed=True)[spec.celltype_column]
        .first()
        .astype(str)
        .reindex(fine_order)
        .to_numpy(),
        "genes": np.array(genes),
        "counts": counts,
        "sums": sums,
    }
    for side, key in (("sender", "sc_B"), ("receiver", "rc_C")):
        out[f"{side}_sums"], out[f"{side}_active"] = loading_sums(
            np.asarray(adata.obsm[key]), samples, fine, sample_order, fine_order
        )
    out = {k: np.asarray(v) for k, v in out.items()}
    out["coarse_check_max_abs"] = _coarse_check(adata, spec, genes, out, lr_pairs)
    print(
        f"   Largest difference from the direct tensor: {out['coarse_check_max_abs']:.3g}"
    )
    if out["coarse_check_max_abs"] > 1e-8:
        raise ValueError("the cache does not reproduce the coarse tensor")
    path = cache_path(spec.output_key)
    path.parent.mkdir(parents=True, exist_ok=True)
    # labels as fixed-width strings, so the cache loads without pickle
    np.savez_compressed(
        path,
        **{
            k: v.astype(str) if v.dtype == object else v
            for k, v in ((k, np.asarray(v)) for k, v in out.items())
        },
    )
    write_metadata(
        path,
        build_metadata(
            dataset_metadata(spec)
            | {
                "factors_path": relpath(factors),
                "factors_sha256": sha256_file(factors),
                "fine_column": FINE_COLUMN,
                "n_genes": len(genes),
                "coarse_check_max_abs": out["coarse_check_max_abs"],
            }
        ),
        header=HEADER,
    )
    print(f"   Wrote {path}")
    return out


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    add_dataset_argument(parser)
    args = parser.parse_args(argv)
    build_cache(resolve_dataset(args))


if __name__ == "__main__":
    main()
