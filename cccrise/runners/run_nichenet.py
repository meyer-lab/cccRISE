#!/usr/bin/env python
"""
Runner: NicheNet-style downstream-target validation of CPD components.

Unlike the other runners, this does not refit RISE/CPD -- it loads an
already-finalized factor fit (``spec.factors_path()``, produced by
``cccrise-run``) and scores it (``cccrise.nichenet.component_accuracy_scores``)
for every CPD component, under every requested receiver-population
definition. The expensive step is per-component differential expression
(``scanpy.tl.rank_genes_groups`` over the full single-cell dataset), which
this caches to a CSV so ``figureNicheNet.py`` can plot without re-running it.

Writes the long-format CSV `figureNicheNet` reads:

    nichenet_scores_<dataset>.csv   one row per (receiver_mode, component, ligand)

    uv run cccrise-nichenet --dataset alad
"""

import argparse
from pathlib import Path
from typing import Literal, cast

import pandas as pd

from ..factors import load_factors_to_anndata
from ..nichenet import (
    ReceiverMode,
    component_accuracy_scores,
    load_ligand_target_matrix,
)
from ._cli import add_dataset_argument, dataset_metadata, resolve_output, resulting_dims
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

DeMethod = Literal["logreg", "t-test", "wilcoxon", "t-test_overestim_var"]

DEFAULT_RECEIVER_MODES: tuple[ReceiverMode, ...] = ("within_celltype", "vs_rest")

HEADER = """\
NicheNet-style ligand-activity AUROCs per CPD component, scored against an
already-finalized factor fit. Generated by cccrise.runners.run_nichenet --
do not hand-edit.
"""


def _lr_pairs_from_adata(adata) -> pd.DataFrame:
    """Recover ligand/receptor columns from `adata.uns["lr_pairs"]`
    ("LIGAND^RECEPTOR[&RECEPTOR2...]" strings), in the row order matching
    `adata.uns["D"]`."""
    ligand, receptor = zip(*(s.split("^", 1) for s in adata.uns["lr_pairs"]))
    return pd.DataFrame({"ligand": ligand, "receptor": receptor})


def run_nichenet(
    spec: DatasetSpec,
    receiver_modes: tuple[ReceiverMode, ...] = DEFAULT_RECEIVER_MODES,
    top_m_lr: int = 10,
    top_perc: float = 10.0,
    de_method: DeMethod = "wilcoxon",
    celltype_col: str | None = None,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Score every CPD component's top ligands against the NicheNet v2 prior,
    for each requested receiver-population definition.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry. Its `factors_path()` must already exist
        (produced by `uv run cccrise-run`); this runner does not fit RISE/CPD.
    receiver_modes : tuple[ReceiverMode, ...], default=("within_celltype", "vs_rest")
        Receiver-population definitions to run; see
        `nichenet.component_accuracy_scores`.
    top_m_lr : int, default=10
        Top LR pairs scored per component.
    top_perc : float, default=10.0
        Percentile split defining "high"/"low" component loading.
    de_method : str, default="wilcoxon"
        `scanpy.tl.rank_genes_groups` method.
    celltype_col : str, optional
        Column in `adata.obs` naming cell types. Defaults to
        `spec.celltype_column`.
    output_path : Path, optional
        CSV destination; defaults to the registry's NicheNet scores filename.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The long per-(mode, component, ligand) table, the CSV path, and the
        sidecar path.
    """
    celltype_col = celltype_col or spec.celltype_column
    if celltype_col is None:
        raise ValueError(
            f"Dataset {spec.key!r} has no celltype_column in the registry; "
            "pass --celltype-col explicitly."
        )

    factors_path = spec.factors_path()
    if not factors_path.exists():
        raise FileNotFoundError(
            f"{factors_path} not found. Produce it with:\n"
            f"    uv run cccrise-run --dataset {spec.key} "
            "--rise-rank <N> --cp-rank <M>"
        )

    output_path = output_path or (DATA_DIR / spec.nichenet_scores_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== NicheNet validation: {spec.label} ===")
    print(
        f"    receiver_modes={receiver_modes}  top_m_lr={top_m_lr}  "
        f"top_perc={top_perc}  de_method={de_method!r}  celltype_col={celltype_col!r}"
    )

    print(f"1. Loading factors from {factors_path}...")
    raw = spec.load()
    adata = load_factors_to_anndata(factors_path, adata=raw)
    lr_pairs = _lr_pairs_from_adata(adata)
    cp_rank = adata.uns["D"].shape[1]
    components = list(range(1, cp_rank + 1))
    print(f"   CP rank {cp_rank}; {len(lr_pairs)} LR pairs; {adata.n_obs} cells")

    print("2. Loading the cached NicheNet v2 ligand-target prior...")
    lt_df = load_ligand_target_matrix()
    print(f"   {lt_df['ligand'].nunique()} ligands in the prior")

    print("3. Scoring each component (this runs a DE test per component/mode)...")
    scored = []
    for mode in receiver_modes:
        print(f"   receiver_mode={mode!r}...")
        mode_scores = component_accuracy_scores(
            adata,
            lr_pairs=lr_pairs,
            lt_df=lt_df,
            components=components,
            top_m_lr=top_m_lr,
            receiver_mode=mode,
            celltype_col=celltype_col,
            top_perc=top_perc,
            de_method=de_method,
        )
        mode_scores.insert(0, "receiver_mode", mode)
        scored.append(mode_scores)
    scores = pd.concat(scored, ignore_index=True)

    print("4. Per-component summary:")
    summary = (
        scores.groupby(["receiver_mode", "component"])["auroc"]
        .agg(mean_auroc="mean", median_auroc="median", n_scored="count")
        .reset_index()
    )
    print(summary.to_string(index=False))

    print(f"5. Writing {len(scores)} rows to {output_path}...")
    scores.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_path": relpath(factors_path),
            "factors_sha256": sha256_file(factors_path),
            "cp_rank": cp_rank,
            "components": components,
            "receiver_modes": list(receiver_modes),
            "top_m_lr": top_m_lr,
            "top_perc": top_perc,
            "de_method": de_method,
            "celltype_col": celltype_col,
            "nichenet_ligand_target_url": (
                "https://zenodo.org/records/7074291/files/"
                "ligand_target_matrix_nsga2r_final.rds"
            ),
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=len(lr_pairs)),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")

    return scores, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--receiver-modes",
        type=str,
        default=",".join(DEFAULT_RECEIVER_MODES),
        help="Comma-separated receiver-population definitions "
        "(within_celltype, vs_rest).",
    )
    parser.add_argument("--top-m-lr", type=int, default=10)
    parser.add_argument("--top-perc", type=float, default=10.0)
    parser.add_argument(
        "--de-method",
        type=str,
        default="wilcoxon",
        choices=["logreg", "t-test", "wilcoxon", "t-test_overestim_var"],
    )
    parser.add_argument(
        "--celltype-col",
        type=str,
        default=None,
        help="Column in adata.obs naming cell types "
        "(default: the dataset registry's celltype_column).",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV destination; defaults to data/nichenet_scores_<dataset>.csv.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    receiver_modes = cast(
        "tuple[ReceiverMode, ...]",
        tuple(mode.strip() for mode in args.receiver_modes.split(",") if mode.strip()),
    )
    run_nichenet(
        spec,
        receiver_modes=receiver_modes,
        top_m_lr=args.top_m_lr,
        top_perc=args.top_perc,
        de_method=cast(DeMethod, args.de_method),
        celltype_col=args.celltype_col,
        output_path=resolve_output(
            args.output, DATA_DIR, spec.nichenet_scores_filename()
        ),
    )


if __name__ == "__main__":
    main()
