#!/usr/bin/env python
"""
Runner: NicheNet-style downstream-target validation of CPD components.

Unlike the other runners, this does not refit RISE/CPD -- it loads an
already-finalized factor fit (``spec.factors_path()``, produced by
``cccrise-run``) and, for every CPD component, scores every ligand the model
sees on that component's receiver ranking -- its receiver cell types'
highest-loading cells against the lowest-loading cells of the whole dataset
(``cccrise.validation.nichenet.component_ligand_scores``). The expensive step
is the per-component differential expression over the full single-cell
dataset, so the result is cached for ``figures/figure2/nichenet.py`` to plot.

Each scored ligand is also re-scored on `--n-cell-shuffle` receiver rankings
with the high/low cell labels permuted (``nichenet.shuffled_cell_scores``),
the null of the weighted-mean score test. Writes the long-format tables
`figures/figure2/nichenet.py` reads:

    nichenet_scores_<dataset>.parquet      one row per (component, ligand)
    nichenet_cell_null_<dataset>.parquet   one row per (component, shuffle, ligand)

    uv run cccrise-nichenet --dataset alad
"""

import argparse
from pathlib import Path
from typing import cast, get_args

import pandas as pd

from ..factors import load_factors_to_anndata
from ..validation.nichenet import (
    DeMethod,
    component_ligand_scores,
    load_ligand_target_matrix,
    receiver_celltypes,
    receiver_rankings,
    shuffled_cell_scores,
    weighted_score_tests,
)
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    resolve_dataset,
    resolve_output,
    resulting_dims,
)
from .datasets import VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

HEADER = """\
NicheNet-style target scores (AUROCs) of every ligand the model sees, per CPD component, on
genes expressed in the receiver groups, scored against an already-finalized
factor fit. Generated by cccrise.runners.run_nichenet -- do not hand-edit.
"""


def _lr_pairs_from_adata(adata) -> pd.DataFrame:
    """Recover ligand/receptor columns from `adata.uns["lr_pairs"]`
    ("LIGAND^RECEPTOR[&RECEPTOR2...]" strings), in the row order matching
    `adata.uns["D"]`."""
    ligand, receptor = zip(*(s.split("^", 1) for s in adata.uns["lr_pairs"]))
    return pd.DataFrame({"ligand": ligand, "receptor": receptor})


def run_nichenet(
    spec: DatasetSpec,
    top_perc: float = 10.0,
    de_method: DeMethod = "wilcoxon",
    min_expr_frac: float = 0.1,
    rel_cutoff: float = 0.4,
    n_cell_shuffle: int = 1000,
    n_jobs: int = 16,
    output_path: Path | None = None,
    receiver_celltype_column: str | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Score every ligand on each CPD component's receiver ranking.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry. Its `factors_path()` must already exist
        (produced by `uv run cccrise-run`); this runner does not fit RISE/CPD.
    top_perc, de_method, min_expr_frac
        Passed to `nichenet.receiver_rankings`, along with the cell-type
        column (receiver groups taken among each component's
        `nichenet.receiver_celltypes`).
    rel_cutoff
        Passed to `nichenet.component_ligand_scores`.
    n_cell_shuffle, n_jobs
        Passed, with the ranking settings, to
        `nichenet.shuffled_cell_scores`.
    output_path : Path, optional
        Parquet destination; defaults to the registry's NicheNet scores filename.
    receiver_celltype_column : str, optional
        `obs` column of the cell types receivers are chosen among; defaults
        to the registry's cell-type column.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The per-(component, ligand) table, its output path, and its sidecar path.
    """
    factors_path = spec.factors_path()
    if not factors_path.exists():
        raise FileNotFoundError(
            f"{factors_path} not found. Produce it with:\n"
            f"    uv run cccrise-run --dataset {spec.key} "
            "--rise-rank <N> --cp-rank <M>"
        )
    output_path = output_path or (VALIDATION_DIR / spec.nichenet_scores_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)
    celltype_key = receiver_celltype_column or spec.celltype_column

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== NicheNet validation: {spec.label} ===")
    print(
        f"    top_perc={top_perc}  de_method={de_method!r}  "
        f"min_expr_frac={min_expr_frac}  rel_cutoff={rel_cutoff}"
    )
    print(f"1. Loading factors from {factors_path}...")
    adata = load_factors_to_anndata(factors_path, adata=spec.load())
    lr_pairs = _lr_pairs_from_adata(adata)
    components = list(range(1, adata.uns["D"].shape[1] + 1))

    print("2. Scoring every ligand on each component (one DE test per component)...")
    lt_df = load_ligand_target_matrix()
    rankings = receiver_rankings(
        adata,
        components,
        top_perc=top_perc,
        de_method=de_method,
        min_expr_frac=min_expr_frac,
        celltype_key=celltype_key,
    )
    scores = component_ligand_scores(
        adata.uns["D"], lr_pairs, lt_df, rankings, rel_cutoff
    )
    for cmp in components:
        types = receiver_celltypes(adata, cmp, celltype_key)
        print(f"   Cmp {cmp} receiver cell types: {', '.join(types)}")
    print(f"3. Re-scoring on {n_cell_shuffle} cell-shuffled receiver rankings...")
    cell_null = shuffled_cell_scores(
        adata,
        scores,
        lt_df,
        n_cell_shuffle,
        n_jobs,
        top_perc=top_perc,
        de_method=de_method,
        min_expr_frac=min_expr_frac,
        celltype_key=spec.celltype_column,
    )
    print("   Weighted-mean scores vs the shuffled cells:")
    print(weighted_score_tests(scores, cell_null)[0].round(4).to_string(index=False))

    cell_null_path = output_path.with_name(spec.nichenet_cell_null_filename())
    print(
        f"4. Writing {len(scores)} rows to {output_path} and the null to "
        f"{cell_null_path}..."
    )
    scores.to_parquet(output_path, index=False)
    cell_null.to_parquet(cell_null_path, index=False)
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_path": relpath(factors_path),
            "factors_sha256": sha256_file(factors_path),
            "cp_rank": len(components),
            "components": components,
            "top_perc": top_perc,
            "de_method": de_method,
            "min_expr_frac": min_expr_frac,
            "rel_cutoff": rel_cutoff,
            "receiver_celltype_column": celltype_key,
            "n_cell_shuffle": n_cell_shuffle,
            "nichenet_ligand_target_url": (
                "https://zenodo.org/records/7074291/files/"
                "ligand_target_matrix_nsga2r_final.rds"
            ),
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=len(lr_pairs)),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")

    return scores, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--top-perc", type=float, default=10.0)
    parser.add_argument(
        "--de-method",
        type=str,
        default="wilcoxon",
        choices=get_args(DeMethod),
    )
    parser.add_argument(
        "--min-expr-frac",
        type=float,
        default=0.1,
        help="Minimum detection fraction in the high or the low receiver group "
        "for a gene to be scored.",
    )
    parser.add_argument(
        "--rel-cutoff",
        type=float,
        default=0.4,
        help="Top-ligand threshold: LR pairs with |loading| >= this fraction of "
        "the component's largest scorable pair.",
    )
    parser.add_argument(
        "--n-cell-shuffle",
        type=int,
        default=1000,
        help="Cell-label permutations in the null of the weighted-mean score test.",
    )
    parser.add_argument("--n-jobs", type=int, default=16)
    parser.add_argument(
        "--receiver-celltype-column",
        default=None,
        help="`obs` column of the cell types receivers are chosen among; "
        "defaults to the registry's cell-type column.",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Parquet destination; defaults to data/validation_results/nichenet_scores_<dataset>.parquet.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = resolve_dataset(args)
    run_nichenet(
        spec,
        top_perc=args.top_perc,
        de_method=cast(DeMethod, args.de_method),
        min_expr_frac=args.min_expr_frac,
        rel_cutoff=args.rel_cutoff,
        n_cell_shuffle=args.n_cell_shuffle,
        n_jobs=args.n_jobs,
        output_path=resolve_output(
            args.output, VALIDATION_DIR, spec.nichenet_scores_filename()
        ),
        receiver_celltype_column=args.receiver_celltype_column,
    )


if __name__ == "__main__":
    main()
