#!/usr/bin/env python
"""
Runner: NicheNet-style downstream-target validation of CPD components.

Unlike the other runners, this does not refit RISE/CPD -- it loads an
already-finalized factor fit (``spec.factors_path()``, produced by
``cccrise-run``) and, for every CPD component, scores every ligand the model
sees on that component's receiver ranking
(``cccrise.validation.nichenet.component_ligand_scores``). The expensive step
is the per-component differential expression over the full single-cell
dataset, so the result is cached for ``figures/figure2/nichenet.py`` to plot.

Writes the long-format table `figures/figure2/nichenet.py` reads:

    nichenet_scores_<dataset>.parquet   one row per (component, ligand)

    uv run cccrise-nichenet --dataset alad

With ``--comparators`` it instead scores every CP comparator fit cached by
``cccrise-benchmark`` (pseudobulk CPD and Tensor-cell2cell, each rank mode;
`validation.nichenet_comparators`), with the same settings:

    nichenet_comparator_scores_<dataset>.parquet   one row per (fit, component, ligand)

    uv run cccrise-nichenet --dataset alad --comparators
"""

import argparse
from pathlib import Path
from typing import cast, get_args

import pandas as pd

from ..benchmark import read_fits
from ..factors import ensure_decompressed, load_factors_to_anndata
from ..validation.nichenet import (
    DeMethod,
    component_ligand_scores,
    load_ligand_target_matrix,
    top_ligand_tests,
)
from ..validation.nichenet_comparators import comparator_ligand_scores
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    resolve_dataset,
    resolve_output,
    resulting_dims,
)
from .datasets import VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

HEADER = """\
NicheNet-style AUROCs of every ligand the model sees, per CPD component, on
genes expressed in the receiver groups, scored against an already-finalized
factor fit. Generated by cccrise.runners.run_nichenet -- do not hand-edit.
"""


COMPARATOR_HEADER = """\
NicheNet-style AUROCs of every ligand each CP comparator fit sees, per
component, on genes expressed in its (cell-type-broadcast) receiver groups.
Generated by cccrise.runners.run_nichenet --comparators -- do not hand-edit.
"""


def _lr_pairs_from_adata(adata) -> pd.DataFrame:
    """Recover ligand/receptor columns from `adata.uns["lr_pairs"]`
    ("LIGAND^RECEPTOR[&RECEPTOR2...]" strings), in the row order matching
    `adata.uns["D"]`."""
    ligand, receptor = zip(*(s.split("^", 1) for s in adata.uns["lr_pairs"]))
    return pd.DataFrame({"ligand": ligand, "receptor": receptor})


def run_nichenet(
    spec: DatasetSpec,
    top_perc: float = 10.0,
    de_method: DeMethod = "wilcoxon",
    min_expr_frac: float = 0.1,
    rel_cutoff: float = 0.4,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Score every ligand on each CPD component's receiver ranking.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry. Its `factors_path()` must already exist
        (produced by `uv run cccrise-run`); this runner does not fit RISE/CPD.
    top_perc, de_method, min_expr_frac, rel_cutoff
        Passed to `nichenet.component_ligand_scores`.
    output_path : Path, optional
        Parquet destination; defaults to the registry's NicheNet scores filename.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The per-(component, ligand) table, its output path, and its sidecar path.
    """
    factors_path = ensure_decompressed(spec.factors_path())
    if not factors_path.exists():
        raise FileNotFoundError(
            f"{factors_path} not found. Produce it with:\n"
            f"    uv run cccrise-run --dataset {spec.key} "
            "--rise-rank <N> --cp-rank <M>"
        )
    output_path = output_path or (VALIDATION_DIR / spec.nichenet_scores_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== NicheNet validation: {spec.label} ===")
    print(
        f"    top_perc={top_perc}  de_method={de_method!r}  "
        f"min_expr_frac={min_expr_frac}  rel_cutoff={rel_cutoff}"
    )
    print(f"1. Loading factors from {factors_path}...")
    adata = load_factors_to_anndata(factors_path, adata=spec.load())
    lr_pairs = _lr_pairs_from_adata(adata)
    components = list(range(1, adata.uns["D"].shape[1] + 1))

    print("2. Scoring every ligand on each component (one DE test per component)...")
    scores = component_ligand_scores(
        adata,
        lr_pairs,
        load_ligand_target_matrix(),
        components,
        top_perc=top_perc,
        de_method=de_method,
        min_expr_frac=min_expr_frac,
        rel_cutoff=rel_cutoff,
    )
    print("3. Top ligands vs all other ligands:")
    print(top_ligand_tests(scores).round(4).to_string(index=False))

    print(f"4. Writing {len(scores)} rows to {output_path}...")
    scores.to_parquet(output_path, index=False)
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_path": relpath(factors_path),
            "factors_sha256": sha256_file(factors_path),
            "cp_rank": len(components),
            "components": components,
            "top_perc": top_perc,
            "de_method": de_method,
            "min_expr_frac": min_expr_frac,
            "rel_cutoff": rel_cutoff,
            "nichenet_ligand_target_url": (
                "https://zenodo.org/records/7074291/files/"
                "ligand_target_matrix_nsga2r_final.rds"
            ),
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=len(lr_pairs)),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")

    return scores, output_path, sidecar


def _split_symbols(symbols) -> pd.DataFrame:
    """ "LIGAND^RECEPTOR" symbols as ligand/receptor columns, the way
    `_lr_pairs_from_adata` reads cccRISE's."""
    ligand, receptor = zip(*(str(s).split("^", 1) for s in symbols))
    return pd.DataFrame({"ligand": ligand, "receptor": receptor})


def run_comparator_nichenet(
    spec: DatasetSpec,
    top_perc: float = 10.0,
    de_method: DeMethod = "wilcoxon",
    min_expr_frac: float = 0.1,
    rel_cutoff: float = 0.4,
    random_state: int = 42,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Score every ligand on each CP comparator component's receiver ranking.

    Reads ``benchmark_fits_<dataset>.nc`` (`cccrise-benchmark`). Each cell gets
    its type's receiver loading, ties broken at random
    (`nichenet_comparators.comparator_ligand_scores`). Fits already in an
    existing output are skipped, so an interrupted run resumes.
    """
    fits_path = VALIDATION_DIR / spec.benchmark_fits_filename()
    output_path = output_path or (
        VALIDATION_DIR / spec.nichenet_comparator_scores_filename()
    )
    git_sha()
    fits, info, _conditions = read_fits(fits_path)
    lr_pairs = _split_symbols(info["lr_pairs"])
    done = pd.read_parquet(output_path) if output_path.exists() else pd.DataFrame()
    adata = spec.load()
    lt_df = load_ligand_target_matrix()
    for fit in fits:
        if fit.kind != "cp" or fit.method == "cccRISE":
            continue
        if (
            not done.empty
            and (
                (done["method"] == fit.method) & (done["rank_mode"] == fit.rank_mode)
            ).any()
        ):
            print(f"   {fit.method} ({fit.rank_mode}) already scored")
            continue
        print(f"   Scoring {fit.method} ({fit.rank_mode}, rank {fit.rank})...")
        scores = comparator_ligand_scores(
            adata,
            spec.celltype_column,
            info["celltypes"],
            fit.modes["receiver"],
            fit.modes["lr"],
            lr_pairs,
            lt_df,
            random_state=random_state,
            top_perc=top_perc,
            de_method=de_method,
            min_expr_frac=min_expr_frac,
            rel_cutoff=rel_cutoff,
        )
        scores.insert(0, "rank", fit.rank)
        scores.insert(0, "rank_mode", fit.rank_mode)
        scores.insert(0, "method", fit.method)
        done = pd.concat([done, scores], ignore_index=True)
        done.to_parquet(output_path, index=False)
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "fits_path": relpath(fits_path),
            "fits_sha256": sha256_file(fits_path),
            "fits": sorted(
                {f"{m} ({r})" for m, r in zip(done["method"], done["rank_mode"])}
            ),
            "receiver_loading": "cell type's receiver-factor row, column sign "
            "oriented to a positive mean, ties broken by seeded uniform jitter",
            "random_state": random_state,
            "top_perc": top_perc,
            "de_method": de_method,
            "min_expr_frac": min_expr_frac,
            "rel_cutoff": rel_cutoff,
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=len(lr_pairs)),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=COMPARATOR_HEADER)
    print(f"   Wrote {len(done)} rows to {output_path} and provenance to {sidecar}")
    return done, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--top-perc", type=float, default=10.0)
    parser.add_argument(
        "--de-method",
        type=str,
        default="wilcoxon",
        choices=get_args(DeMethod),
    )
    parser.add_argument(
        "--min-expr-frac",
        type=float,
        default=0.1,
        help="Minimum detection fraction in the high or the low receiver group "
        "for a gene to be scored.",
    )
    parser.add_argument(
        "--rel-cutoff",
        type=float,
        default=0.4,
        help="Top-ligand threshold: LR pairs with |loading| >= this fraction of "
        "the component's largest scorable pair.",
    )
    parser.add_argument(
        "--comparators",
        action="store_true",
        help="Score the CP comparator fits cached by cccrise-benchmark instead "
        "of the canonical cccRISE fit.",
    )
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Parquet destination; defaults to data/validation_results/nichenet_scores_<dataset>.parquet.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = resolve_dataset(args)
    settings = {
        "top_perc": args.top_perc,
        "de_method": cast(DeMethod, args.de_method),
        "min_expr_frac": args.min_expr_frac,
        "rel_cutoff": args.rel_cutoff,
    }
    if args.comparators:
        run_comparator_nichenet(
            spec,
            random_state=args.random_state,
            output_path=resolve_output(
                args.output, VALIDATION_DIR, spec.nichenet_comparator_scores_filename()
            ),
            **settings,
        )
        return
    run_nichenet(
        spec,
        output_path=resolve_output(
            args.output, VALIDATION_DIR, spec.nichenet_scores_filename()
        ),
        **settings,
    )


if __name__ == "__main__":
    main()
