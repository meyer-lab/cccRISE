#!/usr/bin/env python
"""
Runner: NicheNet v2 vs SecAct ligand-target priors, each scored with this
project's NicheNet-style pipeline and with SecAct's recommended one.

For every CPD component, two receiver profiles contrast the top and bottom
``top_perc``% of cells by receiver loading:

* ``wilcoxon`` -- this project's (`nichenet.receiver_ranking`): Wilcoxon
  scores on the loader's normalized expression, genes expressed in >=10% of
  either group.
* ``log_tpm_diff`` -- SecAct's (`secact.pseudobulk_log_tpm_diff`): pseudobulk
  log2(TPM + 1) difference of raw counts, all detected genes.

Each profile is scored against each prior with ``auroc`` (top-250 targets,
`nichenet.ligand_activity_auroc`) and ``ridge`` (SecAct's grouped ridge
permutation z, `secact.ridge_ligand_scores`), and each component's top
ligands are drawn either from each prior's own scorable ligands (``own``) or
only from ligands both priors cover (``shared``). The two "native" settings
are wilcoxon+auroc (ours) and log_tpm_diff+ridge (SecAct's); the other two
isolate which step drives any difference. ``ligand_log_tpm_diff`` records the
ligand's own expression change between the receiver groups, a confound for
priors whose "targets" are co-expressed with the ligand itself.

Writes ``nichenet_prior_comparison_<dataset>.parquet``.

    uv run cccrise-prior-comparison --dataset alad
"""

import argparse
import itertools
from typing import cast

import numpy as np
import pandas as pd

from ..factors import load_factors_to_anndata
from ..validation import secact
from ..validation.nichenet import (
    _receiver_population,
    ligand_activity_auroc,
    ligand_weights,
    receiver_ranking,
    top_ligand_tests,
)
from ._cli import add_dataset_argument, dataset_metadata
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata
from .run_nichenet import _lr_pairs_from_adata

HEADER = """\
Per-(prior, profile, scoring, universe, component, ligand) downstream-target
scores comparing the NicheNet v2 and SecAct priors. Generated by
cccrise.runners.run_prior_comparison -- do not hand-edit.
"""
TOP_N_TARGETS = 250
PRIORS: tuple[secact.Prior, ...] = ("nichenet", "secact")


def run_prior_comparison(
    spec: DatasetSpec,
    top_perc: float = 10.0,
    rel_cutoff: float = 0.4,
    nrand: int = secact.N_PERMUTATIONS,
) -> pd.DataFrame:
    factors_path = spec.factors_path()
    git_sha()
    adata = load_factors_to_anndata(factors_path, adata=spec.load())
    counts = spec.loader(**(spec.loader_args | {"normalize": False}))
    counts = counts[adata.obs_names, adata.var_names]
    lr_pairs = _lr_pairs_from_adata(adata)
    D = adata.uns["D"]
    model_ligands = ligand_weights(D, lr_pairs).index
    components = list(range(1, D.shape[1] + 1))

    signatures = {p: secact.signature_matrix(p) for p in PRIORS}
    shared = set(model_ligands).intersection(*(s.columns for s in signatures.values()))
    long = {p: secact.top_targets_long(s, TOP_N_TARGETS) for p, s in signatures.items()}
    grouped = {p: secact.group_signatures(s) for p, s in signatures.items()}
    print(
        "Model ligands covered: "
        + ", ".join(
            f"{p} {model_ligands.isin(s.columns).sum()}" for p, s in signatures.items()
        )
        + f", both {len(shared)} of {len(model_ligands)}"
    )

    rows = []
    for cmp in components:
        profiles = _receiver_profiles(adata, counts, cmp, top_perc)
        ligand_lfc = profiles["log_tpm_diff"]
        for prior, (name, profile) in itertools.product(PRIORS, profiles.items()):
            print(f"  component {cmp}: {prior} x {name}")
            scored = _prior_scores(
                profile, model_ligands, long[prior], grouped[prior], prior, nrand
            )
            for (scoring, scores), (universe, keep) in itertools.product(
                scored.items(), {"own": None, "shared": shared}.items()
            ):
                rows += [
                    r
                    | {
                        "prior": prior,
                        "profile": name,
                        "scoring": scoring,
                        "universe": universe,
                        "ligand_log_tpm_diff": ligand_lfc.get(r["ligand"], np.nan),
                    }
                    for r in secact.score_rows(
                        cmp, scores, D, lr_pairs, rel_cutoff, keep
                    )
                ]
    out = pd.DataFrame(rows)

    path = VALIDATION_DIR / f"nichenet_prior_comparison_{spec.key}.parquet"
    out.to_parquet(path, index=False)
    write_metadata(
        path,
        build_metadata(
            dataset_metadata(spec)
            | {
                "factors_path": relpath(factors_path),
                "factors_sha256": sha256_file(factors_path),
                "top_perc": top_perc,
                "rel_cutoff": rel_cutoff,
                "top_n_targets": TOP_N_TARGETS,
                "nrand": nrand,
                "group_cor": secact.GROUP_COR,
                "ridge_lambda": dict(secact.PRIOR_LAMBDA),
                "prior_urls": dict(secact.PRIOR_URLS),
            }
        ),
        header=HEADER,
    )
    print(f"Wrote {len(out)} rows to {path}")
    return out


def _prior_scores(
    profile: pd.Series,
    ligands: pd.Index,
    top_targets: pd.DataFrame,
    grouped: tuple[pd.DataFrame, pd.Series],
    prior: secact.Prior,
    nrand: int,
) -> dict[str, dict[str, float]]:
    """Ligand -> score under `auroc` (top-target AUROC) and `ridge` (grouped
    ridge permutation z) for one receiver profile and prior."""
    ridge = secact.ridge_ligand_scores(
        profile, *grouped, secact.PRIOR_LAMBDA[prior], nrand
    )
    return {
        "auroc": {
            lig: _nan_if_none(ligand_activity_auroc(profile, lig, top_targets))
            for lig in ligands
        },
        "ridge": ridge.reindex(ligands).to_dict(),
    }


def _receiver_profiles(
    adata, counts, cmp: int, top_perc: float
) -> dict[str, pd.Series]:
    """Component `cmp`'s `wilcoxon` and `log_tpm_diff` receiver profiles."""
    wilcoxon = receiver_ranking(adata, cmp, top_perc)
    assert wilcoxon is not None
    kept, pos_mask = _receiver_population(adata, cmp, top_perc)
    return {
        "wilcoxon": wilcoxon[0],
        "log_tpm_diff": secact.pseudobulk_log_tpm_diff(
            counts[kept.obs_names], pos_mask
        ),
    }


def _nan_if_none(x: float | None) -> float:
    return np.nan if x is None else x


def summarize(out: pd.DataFrame) -> pd.DataFrame:
    """`top_ligand_tests` per (universe, prior, profile, scoring)."""
    keys = ["universe", "prior", "profile", "scoring"]
    return pd.concat(
        [
            top_ligand_tests(g, score="score").assign(
                **dict(zip(keys, cast(tuple, k), strict=True))
            )
            for k, g in out.groupby(keys)
        ],
        ignore_index=True,
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--nrand", type=int, default=secact.N_PERMUTATIONS)
    args = parser.parse_args(argv)
    out = run_prior_comparison(DATASETS[args.dataset], nrand=args.nrand)
    print(summarize(out).round(4).to_string(index=False))


if __name__ == "__main__":
    main()
