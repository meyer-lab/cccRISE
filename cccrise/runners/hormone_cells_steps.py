H1_CUTS = {
    "reference": (0.10, 0.05, 0.20, 0.10),
    "T11 low": (0.05, 0.025, 0.10, 0.05),
    "T11 high": (0.15, 0.075, 0.30, 0.15),
}
H2_CUTS = {
    "reference": (0.01, 0.05, 0.10, 0.10, 0.25),
    "T11 low": (0.005, 0.025, 0.05, 0.05, 0.125),
    "T11 high": (0.015, 0.075, 0.15, 0.15, 0.375),
}


def cells_beyond_chance(types: pd.DataFrame) -> tuple[int, float, bool]:
    """Non-carrier cells scoring above all random directions: observed,
    expected by chance (1 in N_DIRECTIONS + 1 per cell) and whether the
    excess passes a Poisson 99.9% bound (deviation from §5: the literal
    'any cell' rule is met by chance alone)."""
    nc = types[~types.carrier]
    observed = int(nc["n_beyond_all_directions"].sum())
    expected = float(nc["n_cells"].sum() / (N_DIRECTIONS + 1))
    return observed, expected, bool(observed > stats.poisson.ppf(0.999, expected))


def h1_rows(shares, types) -> list[dict]:
    rows = []
    for (k, side, q), s in shares.groupby(["component", "side", "quantity"]):
        tt = types[
            (types.component == k) & (types.side == side) & (types.quantity == q)
        ]
        n_types = int((tt.loc[~tt.carrier, "q"] < Q_CUT).sum())
        observed, expected, excess = cells_beyond_chance(tt)
        for variant, group in (
            ("pos (pre-registered)", "noncarrier"),
            ("beyond null", "noncarrier_beyond_null"),
        ):
            r = s[s.group == group].iloc[0]
            for label, cuts in H1_CUTS.items():
                level = H.h1_level(n_types, int(excess), r["pos"], r["pos_lo"], cuts)
                rows.append(
                    {
                        "hypothesis": "H1",
                        "component": k,
                        "side": side,
                        "quantity": q,
                        "share_variant": variant,
                        "cuts": label,
                        "level": level,
                        "share": r["pos"],
                        "share_lo": r["pos_lo"],
                        "share_hi": r["pos_hi"],
                        "n_types_beyond": n_types,
                        "cells_beyond_observed": observed,
                        "cells_beyond_expected": expected,
                    }
                )
    return rows


def levels(shares, types, psum) -> pd.DataFrame:
    rows = h1_rows(shares, types)
    for _, r in psum[
        (psum.m == 5) & (psum.top == 0.8) & (psum.f_cut == 0.5)
    ].iterrows():
        for label, cuts in H2_CUTS.items():
            rows.append(
                {
                    "hypothesis": "H2",
                    "component": r["component"],
                    "side": "both",
                    "quantity": r["quantity"],
                    "share_variant": "A energy outside V5",
                    "cuts": label,
                    "level": H.h2_level(
                        r["energy_outside"],
                        r["frac_top_f_out"],
                        r["any_top_f_out"],
                        cuts,
                    ),
                    "share": r["energy_outside"],
                }
            )
    return pd.DataFrame(rows)


# --- Orchestration -------------------------------------------------------------------


def run_analysis(dataset: str = "ibd") -> None:
    start = time.time()
    path, tag = factors_tag(dataset)
    cells = Cells(tag, path, dataset)
    t = cells.table
    print(
        f">> {len(t['sample'])} cells loaded ({time.time() - start:.0f} s)", flush=True
    )
    save(composition(cells), "composition", cells)
    order = sorted(set(t["celltype"]))
    onehot = sparse.csr_matrix(
        (
            np.ones(len(t["celltype"])),
            (pd.Index(order).get_indexer(t["celltype"]), np.arange(len(t["celltype"]))),
        ),
        shape=(len(order), len(t["celltype"])),
    )
    directions = H.random_directions(cells.P.shape[1], N_DIRECTIONS)
    out = {
        key: []
        for key in (
            "shares",
            "types",
            "cells",
            "identity",
            "patients",
            "psum",
            "repr",
            "sweeps",
        )
    }
    per_cell = {}
    for k in cells.cfg.carriers:
        both = {}
        for side in H.SIDES:
            print(f">> C{k} {side} ({time.time() - start:.0f} s)", flush=True)
            res = program_side(cells, k, side, directions, onehot, order)
            for key in ("shares", "types", "cells", "identity"):
                out[key].append(res[key])
            both[side] = res["values"]
            for q, v in res["values"].items():
                per_cell[f"C{k}_{side}_{q}"] = v.astype(np.float32)
                per_cell[f"C{k}_{side}_{q}_exceed"] = res["exceed"][q]
            out["repr"].extend(representability_rows(cells, k, side, res["values"]))
            out["sweeps"].extend(
                sweep_rows(cells, k, side, res["values"], res["exceed"])
            )
            carrier = cells.carrier_mask(k, side)
            like = {
                q: ~carrier & (v >= np.percentile(v[carrier], CARRIER_LIKE_Q))
                for q, v in res["values"].items()
            }
            out["sweeps"].extend(t10_rows(cells, k, side, like))
        frame = patients(cells, k, both)
        out["patients"].append(frame)
        out["psum"].extend(dict(r, component=k) for r in patient_summary(frame))
        out["sweeps"].extend(t4_rows(frame, k))
        out["sweeps"].extend(fig2l_sweep(cells, k, both))
        flush_partial(out, cells)
    out["sweeps"].extend(t5_rows(cells))
    out["sweeps"].extend(t12_rows(cells))
    tables = flush_partial(out, cells)
    print(">> Fitted-comparator paint", flush=True)
    sel, paint_values = paint(cells)
    save(sel, "paint", cells)
    for (k, method, side), v in paint_values.items():
        per_cell[f"paint_C{k}_{method.replace(' ', '_')}_{side}"] = v
    psum_full = tables["psum"]
    save(
        levels(tables["shares"], tables["types"], psum_full),
        "levels",
        cells,
    )
    np.savez_compressed(CACHE_DIR / f"{dataset}_values_{tag}.npz", **per_cell)
    print(f">> done ({time.time() - start:.0f} s)", flush=True)


def flush_partial(out: dict, cells: Cells) -> dict:
    """Write every table collected so far, so results appear as each program
    finishes."""
    tables = {}
    for key, parts in out.items():
        if not parts:
            continue
        frame = (
            pd.concat(parts, ignore_index=True)
            if isinstance(parts[0], pd.DataFrame)
            else pd.DataFrame(parts)
        )
        if key == "types":
            # BH over non-carrier types x sides x programs x quantities (§4C)
            frame["q"] = np.nan
            nc = ~frame["carrier"]
            frame.loc[nc, "q"] = H.bh(frame.loc[nc, "p"].to_numpy())
        if key == "sweeps":
            frame["x"] = frame["x"].astype(str)
        tables[key] = frame
        save(
            frame,
            {"repr": "representability", "psum": "patient_summary"}.get(key, key),
            cells,
        )
    return tables


