def run_pacmap(seed: int, dataset: str = "ibd") -> None:
    """PaCMAP of the RISE projections at `seed`. Seed 42 reuses the
    embedding stored in the factors file when there is one (the manuscript's,
    fit by `add_cell_embeddings` at `random_state` 42)."""
    import pacmap

    path, tag = factors_tag(dataset)
    with np.load(cells_path(tag, dataset), allow_pickle=True) as z:
        P = z["projections"]
        stored = z["stored_pacmap"] if "stored_pacmap" in z.files else None
    start = time.time()
    if seed == 42 and stored is not None:
        emb, source = stored, "stored in the factors file (cell_pacmap)"
    else:
        emb = pacmap.PaCMAP(random_state=seed).fit_transform(P)
        source = f"PaCMAP(random_state={seed}) on obsm['projections'], all cells"
    out = CACHE_DIR / f"{dataset}_pacmap_{tag}_seed{seed}.npz"
    np.savez_compressed(out, embedding=emb.astype(np.float32))
    write_metadata(
        out,
        build_metadata(
            {
                "factors_sha256": sha256_file(path),
                "seed": seed,
                "pacmap_version": pacmap.__version__
                if hasattr(pacmap, "__version__")
                else "0.9.1",
                "input": source,
                "seconds": round(time.time() - start),
            }
        ),
    )
    print(f"wrote {out} ({time.time() - start:.0f} s)", flush=True)


# --- Extra checks: PaCMAP seed stability and the tensor's clip ----------------------


def run_stability(dataset: str = "ibd", k_neighbours: int = 30) -> None:
    """For every carrier label, the share of each cell's nearest PaCMAP
    neighbours (seed 42) that are also its neighbours under seeds 0 and 1."""
    from sklearn.neighbors import NearestNeighbors

    path, tag = factors_tag(dataset)
    cells = Cells(tag, path, dataset)
    labels = cells.table["celltype"]
    emb = {
        s: np.load(CACHE_DIR / f"{dataset}_pacmap_{tag}_seed{s}.npz")["embedding"]
        for s in (42, 0, 1)
    }
    carriers = cells.cfg.all_carriers()
    knn = {
        s: NearestNeighbors(n_neighbors=k_neighbours + 1).fit(e) for s, e in emb.items()
    }
    rows = []
    for label in carriers:
        idx = np.flatnonzero(labels == label)
        ref = knn[42].kneighbors(emb[42][idx], return_distance=False)[:, 1:]
        for seed in (0, 1):
            other = knn[seed].kneighbors(emb[seed][idx], return_distance=False)[:, 1:]
            kept = np.mean(
                [
                    len(set(a) & set(b)) / k_neighbours
                    for a, b in zip(ref, other, strict=True)
                ]
            )
            rows.append(
                {
                    "celltype": label,
                    "seed": seed,
                    "kept": kept,
                    "random_expected": k_neighbours / len(labels),
                }
            )
    save(pd.DataFrame(rows), "pacmap_stability", cells)


def run_clip(dataset: str = "ibd") -> None:
    """Share of each program side's (sample, eigenstate) entries, weighted by
    the squared factor loading, that the tensor's clip at zero sets to 0 for
    the side's top-weighted gene: there the per-cell decomposition does not
    reach the tensor."""
    path, tag = factors_tag(dataset)
    cells = Cells(tag, path, dataset)
    t = cells.table
    expr = cells.expression
    rows = []
    for k in cells.cfg.carriers:
        for side in H.SIDES:
            w = H.side_token_weights(cells.ds["cp_D"].values, cells.pairs, k, side)
            f2 = cells.factor(side)[:, k - 1] ** 2
            f2 = f2 / f2.sum()
            for token in w.sort_values(ascending=False).index[:3]:
                genes = H.token_genes(token)
                if not all(g in cells.gene_list for g in genes):
                    continue
                cols = [cells.gene_list.index(g) for g in genes]
                x = expr[:, cols].toarray()
                mu = cells.means[genes].to_numpy()
                clipped_w, n = 0.0, 0
                for s in np.unique(t["sample"]):
                    r = t["sample"] == s
                    M = cells.P[r].T @ (x[r] - mu) + mu
                    clipped = (M < 0).any(axis=1)
                    clipped_w += float(f2[clipped].sum())
                    n += 1
                rows.append(
                    {
                        "component": k,
                        "side": side,
                        "token": token,
                        "token_weight": float(w[token]),
                        "clipped_weighted_share": clipped_w / n,
                    }
                )
    save(pd.DataFrame(rows), "clip", cells)


def run_subset(dataset: str = "ibd", cut: float = 0.1) -> None:
    """Post hoc (not pre-registered): the share of each carrier label's cells
    whose value is below `cut` x the label's 90th percentile, and their share
    of the label's positive weight -- whether a program sits on a subset of
    its carrier label."""
    path, tag = factors_tag(dataset)
    cells = Cells(tag, path, dataset)
    with np.load(CACHE_DIR / f"{dataset}_values_{tag}.npz") as z:
        values = {k: z[k] for k in z.files}
    rows = []
    for k in cells.cfg.carriers:
        for side in H.SIDES:
            mask = cells.carrier_mask(k, side)
            for q in QUANTITIES:
                x = values[f"C{k}_{side}_{q}"][mask].astype(float)
                pos = np.clip(x, 0, None)
                for c in (0.05, cut, 0.2, 0.3):
                    low = x < c * np.percentile(x, 90)
                    rows.append(
                        {
                            "component": k,
                            "side": side,
                            "quantity": q,
                            "cut": c,
                            "n_carrier": int(mask.sum()),
                            "frac_low": float(low.mean()),
                            "low_share_of_positive": float(pos[low].sum() / pos.sum()),
                        }
                    )
    save(pd.DataFrame(rows), "carrier_subset", cells)
