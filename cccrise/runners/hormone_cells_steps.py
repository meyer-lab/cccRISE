# --- Sweeps (§6) ---------------------------------------------------------------------


def sweep_rows(cells: Cells, k, side, vals, exceed) -> list[dict]:
    t = cells.table
    carrier = cells.carrier_mask(k, side)
    rows = []

    def rec(threshold, value, metric, quantity, x):
        rows.append(
            {
                "threshold": threshold,
                "component": k,
                "side": side,
                "quantity": quantity,
                "metric": metric,
                "x": x,
                "value": value,
            }
        )

    # T1: LR-pair cut and weighting for the contribution
    for power in (1, 2):
        for rho in (0.0, 0.05, 0.1, 0.2, 0.3, 0.4, 0.6):
            v = cells.values(k, side, rho, power)["contribution"]
            sh = side_shares(cells, v, carrier)["noncarrier"]
            rec("T1", sh["pos"], f"S_out_pos_power{power}", "contribution", rho)
            rec("T1", sh["net"], f"S_out_net_power{power}", "contribution", rho)
            rec(
                "T1",
                H.representability(v, t["sample"], t["celltype"]),
                f"r2_sample_fine_power{power}",
                "contribution",
                rho,
            )
    for q, v in vals.items():
        pos = np.clip(v, 0, None)
        # T2: carrier set = top-n fine types by positive share
        ranked = (
            pd.Series(pos).groupby(t["celltype"]).sum().sort_values(ascending=False)
        )
        for n in range(1, 5):
            mask = np.isin(t["celltype"], ranked.index[:n])
            sh = side_shares(cells, v, mask)["noncarrier"]
            rec("T2", sh["pos"], "S_out_pos_topn", q, n)
        # T3: carrier-like percentile
        for pct in range(5, 100, 5):
            thr = np.percentile(v[carrier], pct)
            like = ~carrier & (v >= thr)
            rec("T3", int(like.sum()), "n_carrier_like", q, pct)
            rec("T3", float(pos[like].sum() / pos.sum()), "share_carrier_like", q, pct)
        # T6: per-cell null percentile for the beyond-null share
        for pct in (95, 99, 99.9):
            beyond = ~carrier & (exceed[q] <= (1 - pct / 100) * N_DIRECTIONS) & (v > 0)
            rec("T6", float(pos[beyond].sum() / pos.sum()), "share_beyond_null", q, pct)
            rec("T6", int(beyond.sum()), "n_beyond_null", q, pct)
    return rows


def fig2l_sweep(cells: Cells, k, both: dict) -> list[dict]:
    rows = []
    for q in QUANTITIES:
        s, r = both["sender"][q], both["receiver"][q]
        for scale in ("max", "q99.9"):
            sm, rm = (
                (s.max(), r.max())
                if scale == "max"
                else (np.percentile(s, 99.9), np.percentile(r, 99.9))
            )
            for tau in np.round(np.arange(0.1, 0.61, 0.05), 2):
                rs, rr = s / sm, r / rm
                high = (rs >= tau) | (rr >= tau)
                send = high & (rs > rr)
                recv = high & ~(rs > rr)
                for role, mask, side in (
                    ("sender", send, "sender"),
                    ("receiver", recv, "receiver"),
                ):
                    car = cells.carrier_mask(k, side)
                    rows.append(
                        {
                            "threshold": "T7",
                            "component": k,
                            "side": role,
                            "quantity": q,
                            "metric": f"n_{scale}",
                            "x": tau,
                            "value": int(mask.sum()),
                        }
                    )
                    rows.append(
                        {
                            "threshold": "T7",
                            "component": k,
                            "side": role,
                            "quantity": q,
                            "metric": f"carrier_frac_{scale}",
                            "x": tau,
                            "value": float(car[mask].mean()) if mask.any() else np.nan,
                        }
                    )
    return rows


def t5_rows(cells: Cells) -> list[dict]:
    rows = []
    for k in cells.cfg.carriers:
        for side in H.SIDES:
            f = np.abs(cells.factor(side)[:, k - 1])
            for cut in np.round(np.arange(0.1, 0.81, 0.1), 1):
                sel = np.flatnonzero(f >= cut * f.max()) + 1
                rows.append(
                    {
                        "threshold": "T5",
                        "component": k,
                        "side": side,
                        "quantity": "factor",
                        "metric": "eigenstates",
                        "x": cut,
                        "value": len(sel),
                        "detail": ",".join(f"E{a}" for a in sel),
                    }
                )
    return rows


def t12_rows(cells: Cells) -> list[dict]:
    rows = []
    D, A = cells.ds["cp_D"].values, cells.ds["cp_A"].values
    for k in cells.cfg.carriers:
        d2, a2 = D[:, k - 1] ** 2, A[:, k - 1] ** 2
        for metric, value in (
            ("effective_pairs", d2.sum() ** 2 / (d2**2).sum()),
            (
                "pairs_ge_0.4max",
                int((np.abs(D[:, k - 1]) >= 0.4 * np.abs(D[:, k - 1]).max()).sum()),
            ),
            ("effective_samples", a2.sum() ** 2 / (a2**2).sum()),
            (
                "samples_ge_0.4max",
                int((np.abs(A[:, k - 1]) >= 0.4 * np.abs(A[:, k - 1]).max()).sum()),
            ),
        ):
            rows.append(
                {
                    "threshold": "T12",
                    "component": k,
                    "side": "both",
                    "quantity": "factor",
                    "metric": metric,
                    "x": 0,
                    "value": float(value),
                }
            )
    return rows


def t10_rows(cells: Cells, k, side, like_masks) -> list[dict]:
    carrier = cells.carrier_mask(k, side)
    inputs = cells._identity_cache[(k, side)]
    rows = []
    for hi_q in (10, 25, 50):
        for lo_q in (1, 5, 10):
            for ng_q in (90, 95, 99):
                cls = classify(inputs, carrier, cells, hi_q, lo_q, ng_q)
                for q, like in like_masks.items():
                    vc = pd.Series(cls[like]).value_counts(normalize=True)
                    for c in (
                        "doublet-like",
                        "mislabelled-carrier-like",
                        "ambient-like",
                        "other state",
                    ):
                        rows.append(
                            {
                                "threshold": "T10",
                                "component": k,
                                "side": side,
                                "quantity": q,
                                "metric": c,
                                "x": f"{hi_q}/{lo_q}/{ng_q}",
                                "value": float(vc.get(c, 0.0)),
                            }
                        )
    return rows


def t4_rows(frame: pd.DataFrame, k) -> list[dict]:
    rows = []
