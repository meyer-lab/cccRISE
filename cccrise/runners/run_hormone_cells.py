#!/usr/bin/env python
"""
Runner: which cells carry cccRISE's programs, against the fine labels
(`validation.hormone_cells`; `HORMONE_CELLS_PREREGISTRATION.md`, and its ALAD
addendum).

    uv run python -m cccrise.runners.run_hormone_cells cells [--dataset alad]
    uv run python -m cccrise.runners.run_hormone_cells pacmap --seed 42
    uv run python -m cccrise.runners.run_hormone_cells analyze

`cells` loads the cohort once and writes, per cell, the RISE projections,
labels, QC columns, marker scores and the expression of every LR and marker
gene to ``output/cache/hormone_cells/`` (git-ignored). It also runs the
pre-registered gate: the stored communication tensor that CP was fit on is
rebuilt for each program's leading LR pairs, and the per-cell sums are
checked to add up to the eigenstate-level expression. A failing gate stops
the runner.
"""

import argparse
import time
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr
from scipy import sparse

from ..factors import (
    ensure_decompressed,
    load_factors_netcdf,
    load_factors_to_anndata,
)
from ..import_data import iter_condition_matrices
from ..validation import hormone_cells as H
from .datasets import DATASETS
from .provenance import build_metadata, relpath, sha256_file, write_metadata

REPO = Path(__file__).resolve().parents[2]
CACHE_DIR = REPO / "output" / "cache" / "hormone_cells"
TENSOR_DIR = REPO / "output" / "cache" / "story"
#: Gate tolerances (pre-registration §3.2)
ADDITIVITY_TOL = 1e-6
TENSOR_TOL = 1e-6
GATE_PAIRS = 5  # leading LR pairs per component rebuilt from the cells
HEADER = """\
Per-cell table for the carrier analysis. Generated by
cccrise.runners.run_hormone_cells -- do not hand-edit.
"""


def factors_tag(dataset: str = "ibd") -> tuple[Path, str]:
    path = ensure_decompressed(DATASETS[dataset].factors_path())
    return path, sha256_file(path)[:12]


def cells_path(tag: str, dataset: str = "ibd") -> Path:
    return CACHE_DIR / f"{dataset}_cells_{tag}.npz"


def expression_path(tag: str, dataset: str = "ibd") -> Path:
    return CACHE_DIR / f"{dataset}_expression_{tag}.npz"


def table_genes(pairs, var_names, cfg: H.DatasetConfig) -> list[str]:
    genes = {g for p in pairs for t in H.pair_tokens(p) for g in H.token_genes(t)}
    for markers in (*cfg.carrier_markers.values(), *cfg.lineage_markers.values()):
        genes |= set(markers)
    return sorted(genes & set(var_names))


def marker_scores(adata, cfg: H.DatasetConfig) -> pd.DataFrame:
    import scanpy as sc

    scores = {}
    for name, genes in {**cfg.carrier_markers, **cfg.lineage_markers}.items():
        present = [g for g in genes if g in adata.var_names]
        sc.tl.score_genes(adata, present, score_name="_score", random_state=0)
        scores[name] = adata.obs.pop("_score").to_numpy(np.float32)
    return pd.DataFrame(scores)


def gate_pairs(ds: xr.Dataset) -> list[int]:
    D = np.abs(ds["cp_D"].values)
    return sorted(
        {int(i) for k in range(D.shape[1]) for i in np.argsort(-D[:, k])[:GATE_PAIRS]}
    )


def eigen_token(L: np.ndarray, genes: list[str], token: str) -> np.ndarray:
    """A token's eigenstate-level expression after the tensor's clip: the
    min over a complex's subunits."""
    return np.min([L[:, genes.index(g)] for g in H.token_genes(token)], axis=0)


def tensor_gate(adata, ds: xr.Dataset, genes: list[str], dataset: str) -> dict:
    """Rebuild the stored tensor's entries for the leading pairs from the
    cells; also the per-cell additivity check on every LR gene."""
    tensor = np.load(TENSOR_DIR / H.CONFIGS[dataset].tensor_file, mmap_mode="r")
    conditions = list(ds["condition"].values.astype(str))
    pairs = ds["lr_pair"].values.astype(str)
    rows = gate_pairs(ds)
    B, C = ds["cp_B"].values, ds["cp_C"].values
    sub = adata[:, genes].copy()
    means = sub.var["means"].to_numpy()
    cond_idx = adata.obs["condition_unique_idxs"].to_numpy().astype(int)
    names = adata.obs[DATASETS[dataset].condition_column].astype(str).to_numpy()
    worst_tensor, worst_add, clipped = 0.0, 0.0, 0
    for i, X in enumerate(iter_condition_matrices(sub)):
        P = np.asarray(adata.obsm["projections"])[cond_idx == i].astype(float)
        s = conditions.index(names[cond_idx == i][0])
        M = P.T @ X
        clipped += int((M + means < 0).sum())
        L = np.clip(M + means, 0, None)
        stored = np.asarray(tensor[s][:, :, rows])
        rebuilt = np.stack(
            [
                np.outer(*(eigen_token(L, genes, t) for t in H.pair_tokens(pairs[r])))
                for r in rows
            ],
            axis=-1,
        )
        worst_tensor = max(
            worst_tensor, float(np.abs(rebuilt - stored).max() / np.abs(stored).max())
        )
        for F in (B, C):
            eigen, cells = F.T @ M, (P @ F).T @ X
            worst_add = max(
                worst_add, float(np.abs(eigen - cells).max() / np.abs(eigen).max())
            )
    return {
        "pairs_rebuilt": [str(pairs[r]) for r in rows],
        "tensor_max_rel_error": worst_tensor,
        "additivity_max_rel_error": worst_add,
        "clipped_entries": clipped,
        "passed": bool(worst_tensor <= TENSOR_TOL and worst_add <= ADDITIVITY_TOL),
    }


def obs_values(obs: pd.DataFrame, column: str | None) -> np.ndarray:
    """A numeric obs column as float32, NaN where the dataset has none."""
    if column is None or column not in obs:
        return np.full(len(obs), np.nan, dtype=np.float32)
    return pd.to_numeric(obs[column], errors="coerce").to_numpy(np.float32)


def build_cells(dataset: str = "ibd") -> None:
    start = time.time()
    cfg = H.CONFIGS[dataset]
    path, tag = factors_tag(dataset)
    spec = DATASETS[dataset]
    ds = load_factors_netcdf(path)
    print(f">> Loading {dataset} with its CP projections", flush=True)
    adata = load_factors_to_anndata(path, adata=spec.load())
    genes = table_genes(ds["lr_pair"].values.astype(str), adata.var_names, cfg)
    print(f">> Gate on {len(genes)} genes ({time.time() - start:.0f} s)", flush=True)
    gate = tensor_gate(adata, ds, genes, dataset)
    print(f"   {gate}", flush=True)
    print(">> Marker scores", flush=True)
    scores = marker_scores(adata, cfg)
    obs = adata.obs
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    sparse.save_npz(
        expression_path(tag, dataset),
        sparse.csr_matrix(adata[:, genes].X, dtype=np.float32),
    )
    extra = {}
    if "PaCMAP" in adata.obsm:  # the embedding stored in the factors file
        extra["stored_pacmap"] = np.asarray(adata.obsm["PaCMAP"], np.float32)
    np.savez_compressed(
        cells_path(tag, dataset),
        projections=np.asarray(adata.obsm["projections"], np.float32),
        sample=obs[spec.condition_column].astype(str).to_numpy(),
        lineage=obs["broad_cell_type"].astype(str).to_numpy(),
        celltype=obs["celltype"].astype(str).to_numpy(),
        group=obs[cfg.group_column].astype(str).to_numpy(),
        **{field: obs_values(obs, column) for field, column in cfg.qc.items()},
        cell_id=obs.index.astype(str).to_numpy(),
        genes=np.array(genes),
        gene_means=adata[:, genes].var["means"].to_numpy(),
        score_names=np.array(scores.columns),
        scores=scores.to_numpy(np.float32),
        **extra,
    )
    write_metadata(
        cells_path(tag, dataset),
        build_metadata(
            {
                "dataset": dataset,
                "factors_path": relpath(path),
                "factors_sha256": sha256_file(path),
                "tensor_path": relpath(TENSOR_DIR / cfg.tensor_file),
                "n_cells": int(adata.n_obs),
                "n_genes": len(genes),
                "gate": gate,
            }
        ),
        header=HEADER,
    )
    print(
        f"   Wrote {cells_path(tag, dataset)} ({time.time() - start:.0f} s)",
        flush=True,
    )
    if not gate["passed"]:
        raise SystemExit("Gate failed: stop and revise the pre-registration §3.2")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument(
        "step", choices=["cells", "pacmap", "analyze", "stability", "clip", "subset"]
    )
    parser.add_argument("--dataset", choices=sorted(H.CONFIGS), default="ibd")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args(argv)
    if args.step == "cells":
        build_cells(args.dataset)
        return
    from . import hormone_cells_steps as steps

    if args.step == "pacmap":
        steps.run_pacmap(args.seed, args.dataset)
        return
    {
        "analyze": steps.run_analysis,
        "stability": steps.run_stability,
        "clip": steps.run_clip,
        "subset": steps.run_subset,
    }[args.step](args.dataset)


if __name__ == "__main__":
    main()
