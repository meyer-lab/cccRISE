"""
Runner: the IBD tables behind Figure 5's reading of the hormone (C3, C4) and
inflammatory (C1, C5) programs, from the finalized fit and one load of the
cohort's cells. Like `run_cohort`, it does not refit RISE/CPD. Writes, into
`IBD_PROGRAMS_DIR` (one `provenance.yaml` for the folder):

    enteroendocrine_cells_ibd.parquet
        every enteroendocrine (EE), enterochromaffin (EC) and tuft cell: its
        biopsy, status, group (EE cells detecting an L hormone are
        "L-hormone+ EE"), genes detected, unscaled C3/C4 sender and receiver
        weights, the EE/EC/tuft PaCMAP of its RISE projections, and the expression
        of `EE_GENES`
    myeloid_program_cells_ibd.parquet
        every myeloid cell's fine type, unscaled C1/C5 sender weights and the
        expression of `MYELOID_GENES`
    cell_map_ibd.parquet
        a PaCMAP of every cell's RISE projections, keeping every EE, EC and
        tuft cell and `MAP_BACKGROUND` others drawn at `--random-state`
    eigenstate_energy_ibd.parquet
        mean squared RISE projection per eigenstate of EE cells, EC cells and
        the secretory lineage
    eigenstate_celltypes_ibd.parquet
        per eigenstate and cell category (`cell_categories`): the category's
        cells, their mean RISE projection, and their share of the eigenstate's
        squared projection over all cells
    dissociation_ibd.parquet
        each biopsy's mean dissociation score over all its cells
        (`DISSOCIATION_GENES`)
    program_covariation_ibd.parquet
        Figure 3D's test for `PROGRAMS`: the pairwise rank correlations of
        each component's top LR pairs' context scores across biopsies, and of
        `covariation.covariation_baselines`' draws
    program_permutation_ibd.parquet
        Figure 3F's test for `PROGRAMS`: each top pair's CD-inflamed minus
        healthy mean depth-normalized context score, its biopsy-permutation
        null and one-sided p

    uv run cccrise-ibd-programs --dataset ibd
"""

