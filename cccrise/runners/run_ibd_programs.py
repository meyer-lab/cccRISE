def expression(adata: anndata.AnnData, genes: list[str]) -> pd.DataFrame:
    sub = adata[:, [g for g in genes if g in adata.var_names]]
    return pd.DataFrame(
        np.asarray(cast(Any, sub.X).todense()),
        index=adata.obs_names,
        columns=sub.var_names,
    )


def weights(adata: anndata.AnnData, role: str, k: int) -> np.ndarray:
    return np.asarray(adata.obsm["sc_B" if role == "sender" else "rc_C"])[:, k - 1]


def cell_frame(adata: anndata.AnnData, spec: DatasetSpec) -> pd.DataFrame:
    obs = cast(pd.DataFrame, adata.obs)
    return pd.DataFrame(
        {
            "Biopsy": obs[spec.condition_column].astype(str).to_numpy(),
            "Status": obs[spec.group_column].astype(str).to_numpy(),
            "Cell type": obs[spec.fine_celltype_column].astype(str).to_numpy(),
        },
        index=adata.obs_names,
    )


def ee_group(cells: pd.DataFrame, genes: pd.DataFrame) -> np.ndarray:
    """EE cells detecting any L hormone are "L-hormone+ EE", other EE cells
    "Other EE"; EC and tuft cells keep their type."""
    group = cells["Cell type"].map({EE: "Other EE", EC: "EC", TUFT: "Tuft"})
    l_hormone = (genes[L_HORMONES] > 0).any(axis=1) & (cells["Cell type"] == EE)
    return group.where(~l_hormone, "L-hormone+ EE").to_numpy()


def enteroendocrine_cells(adata: anndata.AnnData, spec: DatasetSpec) -> pd.DataFrame:
    sub = adata[adata.obs[spec.fine_celltype_column].isin([EE, EC, TUFT]).to_numpy()]
    cells = cell_frame(sub, spec)
    genes = expression(sub, EE_GENES)
    cells["Group"] = ee_group(cells, genes)
    cells["Genes detected"] = np.asarray((cast(Any, sub.X) > 0).sum(axis=1)).ravel()
    for role in ("sender", "receiver"):
        for k in (3, 4):
            cells[f"C{k} {role} weight"] = weights(sub, role, k)
    projections = np.asarray(sub.obsm["projections"], dtype=np.float32)
    cells[["PaCMAP 1", "PaCMAP 2"]] = PaCMAP(random_state=PACMAP_SEED).fit_transform(
        projections
    )
    return cells.join(genes).rename_axis("Cell").reset_index()


def myeloid_program_cells(adata: anndata.AnnData, spec: DatasetSpec) -> pd.DataFrame:
    sub = adata[(adata.obs[spec.celltype_column] == "Myeloid").to_numpy()]
    cells = cell_frame(sub, spec)
    for k in PROGRAMS:
        cells[f"C{k} sender weight"] = weights(sub, "sender", k)
    return cells.join(expression(sub, MYELOID_GENES)).rename_axis("Cell").reset_index()


def cell_map(
    adata: anndata.AnnData, spec: DatasetSpec, random_state: int
) -> pd.DataFrame:
    cells = cell_frame(adata, spec)
    genes = expression(adata, L_HORMONES)
    group = pd.Series(ee_group(cells, genes), index=cells.index).fillna("Other")
    projections = np.asarray(adata.obsm["projections"], dtype=np.float32)
    coords = PaCMAP(random_state=PACMAP_SEED).fit_transform(projections)
    other = np.flatnonzero(group.to_numpy() == "Other")
    drawn = np.random.default_rng(random_state).choice(
        other, MAP_BACKGROUND, replace=False
    )
    keep = np.sort(np.concatenate([np.flatnonzero(group.to_numpy() != "Other"), drawn]))
    return pd.DataFrame(
        {
            "Group": group.to_numpy()[keep],
            "PaCMAP 1": coords[keep, 0],
            "PaCMAP 2": coords[keep, 1],
        }
    )


def eigenstate_energy(adata: anndata.AnnData, spec: DatasetSpec) -> pd.DataFrame:
    projections = np.asarray(adata.obsm["projections"], dtype=float)
    fine = adata.obs[spec.fine_celltype_column].to_numpy()
    groups = {
        "EE cells": fine == EE,
        "EC cells": fine == EC,
        "Secretory lineage": (adata.obs[spec.celltype_column] == SECRETORY).to_numpy(),
    }
    return pd.DataFrame(
        [
            {"Cells": name, "Eigenstate": j + 1, "Mean squared projection": value}
            for name, mask in groups.items()
            for j, value in enumerate((projections[mask] ** 2).mean(axis=0))
        ]
    )


def cell_categories(adata: anndata.AnnData, spec: DatasetSpec) -> np.ndarray:
    """Each cell's lineage, the secretory lineage split into EE, EC, tuft and
    goblet cells."""
    fine = adata.obs[spec.fine_celltype_column].astype(str)
    named = fine.map({EE: "EE", EC: "EC", TUFT: "Tuft"})
    goblet = fine.str.startswith("Goblet").map({True: "Goblet"})
    lineage = adata.obs[spec.celltype_column].astype(str)
    return named.fillna(goblet).fillna(lineage).to_numpy()


def eigenstate_celltypes(adata: anndata.AnnData, spec: DatasetSpec) -> pd.DataFrame:
    projections = np.asarray(adata.obsm["projections"], dtype=float)
    category = cell_categories(adata, spec)
    squared = (projections**2).sum(axis=0)
    return pd.DataFrame(
        [
            {
                "Category": c,
                "Eigenstate": j + 1,
                "Cells": int(mask.sum()),
                "Mean projection": mean,
                "Squared projection share": share,
            }
            for c in np.unique(category)
            for mask in [category == c]
            for j, (mean, share) in enumerate(
                zip(
                    projections[mask].mean(axis=0),
                    (projections[mask] ** 2).sum(axis=0) / squared,
                    strict=True,
                )
            )
        ]
    )


def dissociation(adata: anndata.AnnData, spec: DatasetSpec) -> pd.DataFrame:
    score = expression(adata, DISSOCIATION_GENES).mean(axis=1)
    biopsy = adata.obs[spec.condition_column].astype(str).to_numpy()
    per = score.groupby(biopsy).agg(["size", "mean"])
    return (
        per.set_axis(["Cells", "Dissociation score"], axis=1)
        .rename_axis("Biopsy")
        .reset_index()
    )


def status_q(scores: np.ndarray, depth: np.ndarray, status: np.ndarray) -> np.ndarray:
    """Benjamini-Hochberg q of each LR pair's one-way ANOVA over status, on
    read-depth-corrected scores (as `figure3.coordinated_changes`)."""
    from scipy.stats import false_discovery_control

    corrected = correct_by_read_depth(scores, depth)
    groups = [corrected[status == s] for s in np.unique(status)]
    p = np.nan_to_num(f_oneway(*groups, axis=0).pvalue, nan=1.0)
    return false_discovery_control(p)


def program_tables(
    tensor: np.ndarray,
    factors,
    depth: np.ndarray,
    status: np.ndarray,
    random_state: int,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    lr = factors["lr_pair"].values.astype(str)
    covariation, permutation = [], []
    for k in PROGRAMS:
        B, C, D = (
            factors[m].values[:, k - 1].astype(float) for m in ("cp_B", "cp_C", "cp_D")
        )
        scores = context_scores(tensor, B, C)
        top = top_pairs(D)
        rng_seed = random_state + k
        covariation.append(
            _covariation(k, scores, top, status_q(scores, depth, status), rng_seed)
        )
        permutation.append(
            _permutation(k, scores / depth[:, None], top, status, lr, rng_seed)
        )
    return pd.concat(covariation), pd.concat(permutation)


def _covariation(k, scores, top, q, seed) -> pd.DataFrame:
    sets = {
        "Top pairs": pairwise_rank_correlations(scores, top)[None]
    } | covariation_baselines(scores, top, q < 0.05, seed=seed)
    return pd.concat(
        pd.DataFrame(draws)
        .rename_axis("Draw")
        .reset_index()
        .melt("Draw", value_name="Rank correlation")
        .assign(Component=k, Set=name)
        for name, draws in sets.items()
    ).drop(columns="variable")


def _permutation(k, scores, top, status, lr, seed) -> pd.DataFrame:
    keep = np.isin(status, [CASE, CONTROL])
    case = status[keep] == CASE
    biopsies = np.arange(keep.sum()).astype(str)  # one biopsy per donor
    observed, null = patient_permutation_differential(
        scores[keep][:, top], case, biopsies, N_PERMS, seed
    )
    p = ((null >= observed).sum(0) + 1) / (N_PERMS + 1)
    return (
        pd.DataFrame(null, columns=lr[top])
        .rename_axis("Permutation")
        .reset_index()
        .melt("Permutation", var_name="LR pair", value_name="Null difference")
        .assign(
            Component=k,
            Rank=lambda d: d["LR pair"].map(
                {name: i + 1 for i, name in enumerate(lr[top])}
            ),
            Observed=lambda d: d["LR pair"].map(
                dict(zip(lr[top], observed, strict=True))
            ),
            P=lambda d: d["LR pair"].map(dict(zip(lr[top], p, strict=True))),
        )
    )


def write(
    spec: DatasetSpec, name: str, table: pd.DataFrame, metadata: dict, command: str
) -> None:
    path = IBD_PROGRAMS_DIR / scores_filename(name, spec.output_key)
    path.parent.mkdir(parents=True, exist_ok=True)
    table.to_parquet(path, index=False)
    record_output(path, metadata, command, header=HEADER)
    print(f"   wrote {path.name} ({len(table)} rows)", flush=True)


def run_ibd_programs(spec: DatasetSpec, random_state: int, command: str) -> None:
    git_sha()  # pin the code version before anything runs (`provenance.git_sha`)
    factors = load_factors_netcdf(spec.factors_path())
    print("1. Loading the cohort and rebuilding its tensor...", flush=True)
    raw = spec.load()
    tensor = cccrise_tensor(spec.factors_path(), raw, spec.condition_column)
    adata = load_factors_to_anndata(spec.factors_path(), adata=raw)
    conditions = np.unique(adata.obs[spec.condition_column].astype(str))
    assert np.array_equal(conditions, factors["condition"].values.astype(str))
    status = (
        cast(pd.DataFrame, adata.obs)
        .groupby(spec.condition_column, observed=True)[spec.group_column]
        .first()
        .astype(str)
        .reindex(conditions)
        .to_numpy()
    )
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_path": relpath(spec.factors_path()),
            "factors_sha256": sha256_file(spec.factors_path()),
            "random_state": random_state,
            "pacmap_random_state": PACMAP_SEED,
            "n_perms": N_PERMS,
            "n_top": N_TOP,
            "programs": list(PROGRAMS),
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=tensor.shape[-1]),
        }
    )
    print("2. Program pair tests (C1, C5)...", flush=True)
    covariation, permutation = program_tables(
        tensor, factors, condition_read_depths(adata), status, random_state
    )
    del tensor
    write(spec, "program_covariation", covariation, metadata, command)
    write(spec, "program_permutation", permutation, metadata, command)
    print("3. Cell tables...", flush=True)
    for name, make in (
        ("enteroendocrine_cells", enteroendocrine_cells),
        ("myeloid_program_cells", myeloid_program_cells),
        ("eigenstate_energy", eigenstate_energy),
        ("eigenstate_celltypes", eigenstate_celltypes),
        ("dissociation", dissociation),
    ):
        write(spec, name, make(adata, spec), metadata, command)
    print("4. All-cell PaCMAP...", flush=True)
    write(spec, "cell_map", cell_map(adata, spec, random_state), metadata, command)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--random-state", type=int, default=0)
    return parser


def main(argv: list[str] | None = None) -> None:
    args, command = parse_command(build_parser(), "cccrise-ibd-programs", argv)
    spec = resolve_dataset(args)
    if spec.key != "ibd":
        raise SystemExit(
            "cccrise-ibd-programs reads IBD's cell types; run it with --dataset ibd"
        )
    run_ibd_programs(spec, args.random_state, command)


if __name__ == "__main__":
    main()
