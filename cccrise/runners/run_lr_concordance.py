#!/usr/bin/env python
"""
Runner: do cccRISE and the tensor comparators agree on top LR pairs?

Reads the comparator fits ``cccrise-benchmark`` cached on the coarse
(``benchmark_fits_<dataset>.nc``) and fine (``..._fine.nc``) annotations and,
per comparator column against every cccRISE component
(`comparators.lr_concordance`):

- the shared count of their top-k LR pairs (k = 5, 10, 25), against an
  abundance-weighted null (pairs drawn in proportion to their mean score in
  the coarse pseudobulk tensor); the k most abundant pairs are added as a
  reference column;
- coverage of each column's top-k by the union of the other fit's top-k;
- pairs in one method's top-k that the other ranks below 50 everywhere;
- per comparator column, its best cccRISE match with the agreement of their
  sender / receiver cell types (cccRISE's sample-scaled per-cell loadings
  averaged per comparator type) and of their condition columns, and its A5
  class (`classify_components`), rank-only as pre-registered and mass-aware
  (the shared pairs must carry >= `MASS_HIT` of the comparator column's
  squared loading; added after the columns proved head-heavy).

Writes, in ``data/validation_results/``:

    lr_concordance_overlap_<dataset>.parquet   (annotation, fit, cccRISE comp, column, k)
    lr_concordance_null_<dataset>.parquet      per k: abundance and uniform nulls
    lr_concordance_coverage_<dataset>.parquet  (annotation, fit, direction, column, k)
    lr_concordance_missed_<dataset>.parquet    (annotation, fit, direction, k, pair)
    lr_concordance_matches_<dataset>.parquet   one row per comparator column
    lr_concordance_columns_<dataset>.parquet   per LR column: head mass, top pairs

    uv run python -m cccrise.runners.run_lr_concordance --dataset alad
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from ..benchmark import ComparatorFit, pseudobulk_tensor, read_fits
from ..comparators.agreement import aligned_modes, sample_scaled
from ..comparators.lr_concordance import (
    KS,
    MASS_HIT,
    PRIMARY_K,
    best_matches,
    classify_components,
    coverage_table,
    head_mass,
    head_spearman,
    missed_pairs,
    mode_agreement,
    null_thresholds,
    overlap_table,
    top_k_sets,
)
from ..factors import load_factors_netcdf, load_factors_to_anndata
from ..import_data import import_ligand_receptor_pairs
from ..validation.program_breadth import participation_ratio
from ._cli import add_dataset_argument, dataset_metadata
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

#: annotation -> (fits suffix, obs column of its cell types)
ANNOTATIONS = {"coarse": ("", "broad_cell_type"), "fine": ("_fine", "celltype")}
N_NULL = 10_000
HEADER = """\
Top-k LR-pair agreement of cccRISE with the tensor comparators, the pairs one
method ranks highly and the other does not, and each comparator column's best
cccRISE match. Generated by cccrise.runners.run_lr_concordance -- do not hand-edit.
"""


def _outputs(spec: DatasetSpec) -> dict[str, Path]:
    names = ("overlap", "null", "coverage", "missed", "matches", "columns")
    return {n: VALIDATION_DIR / f"lr_concordance_{n}_{spec.key}.parquet" for n in names}


def _label(fit: ComparatorFit, annotation: str) -> dict[str, str]:
    return {
        "annotation": annotation,
        "method": fit.method,
        "rank_mode": fit.rank_mode,
        "rank": fit.rank,
    }


def _abundance(adata, spec: DatasetSpec, lr_order: np.ndarray) -> np.ndarray:
    """Each LR pair's mean score over the coarse pseudobulk tensor, in
    `lr_order`."""
    tensor, _types, pairs = pseudobulk_tensor(
        adata,
        spec.condition_column,
        ANNOTATIONS["coarse"][1],
        import_ligand_receptor_pairs(),
    )
    mean = pd.Series(
        tensor.mean(axis=(0, 1, 2)),
        index=pairs["interaction_symbol"].astype(str).to_numpy(),
    )
    return mean.reindex(lr_order).to_numpy(float)


def _type_profile(loadings: np.ndarray, types: np.ndarray, order) -> np.ndarray:
    """``(n_types, rank)`` mean per-cell loading per type, rows in `order`."""
    frame = pd.DataFrame(loadings).groupby(types).mean()
    return frame.reindex([str(t) for t in order]).fillna(0).to_numpy()


def _cell_profiles(adata, spec: DatasetSpec, column: str, celltypes) -> dict:
    """cccRISE's sender / receiver loadings on a comparator's cell types."""
    samples = adata.obs[spec.condition_column].astype(str).to_numpy()
    types = adata.obs[column].astype(str).to_numpy()
    return {
        side: _type_profile(sample_scaled(adata.obsm[key], samples), types, celltypes)
        for side, key in (("sender", "sc_B"), ("receiver", "rc_C"))
    }


def _cp_agreement(fit: ComparatorFit, ref: ComparatorFit, profiles, i, j) -> dict:
    """Sender / receiver / condition agreement of comparator column `j` with
    cccRISE component `i` (CP fits only)."""
    row = {}
    for side in ("sender", "receiver"):
        theirs = fit.modes[side][:, j]
        ours = profiles[side][:, i]
        row[f"{side}_cos"] = float(mode_agreement(ours[:, None], theirs[:, None])[0, 0])
        row[f"{side}_top_match"] = bool(np.argmax(np.abs(theirs)) == np.argmax(ours))
        row[f"{side}_pr"] = float(participation_ratio(theirs[:, None])[0])
    cond = mode_agreement(ref.condition_factor[:, [i]], fit.condition_factor[:, [j]])
    row["condition_cos"] = float(cond[0, 0])
    row["condition_pr"] = float(participation_ratio(fit.condition_factor[:, [j]])[0])
    return row


def _match_rows(fit, ref, lr, ref_lr, overlaps, profiles) -> pd.DataFrame:
    """Each column of `fit` with its best cccRISE match and that pair's
    overlap at every k, head Spearman and (CP) cell-type / sample agreement."""
    best = best_matches(overlaps).set_index("comparator_component")
    per_k = overlaps.set_index(["cccrise_component", "comparator_component", "k"])
    rows = []
    for j, match in best.iterrows():
        i = int(match["cccrise_component"]) - 1
        pair = per_k.loc[(i + 1, j)]
        row = {
            "comparator_component": j,
            "cccrise_component": i + 1,
            "hit": bool(match["hit"]),
            "mass_hit": bool(match["hit"] and match["mass_comparator"] >= MASS_HIT),
            "lr_abs_cos": float(match["lr_abs_cos"]),
            "head_spearman": head_spearman(ref_lr[:, i], lr[:, j - 1]),
        }
        for k in KS:
            row |= {
                f"shared_k{k}": int(pair.loc[k, "shared"]),
                f"mass_comparator_k{k}": float(pair.loc[k, "mass_comparator"]),
                f"mass_cccrise_k{k}": float(pair.loc[k, "mass_cccrise"]),
            }
        if fit.kind == "cp":
            row |= _cp_agreement(fit, ref, profiles, i, j - 1)
        rows.append(row)
    return pd.DataFrame(rows)


def _column_rows(lr: np.ndarray, names, n_top: int = 5) -> pd.DataFrame:
    """Per LR column: its head mass at every k and its top pairs with their
    share of the column's squared loading."""
    table = head_mass(lr, KS).pivot(index="component", columns="k", values="head_mass")
    table.columns = [f"head_mass_k{k}" for k in table.columns]
    sq = np.asarray(lr, float) ** 2
    share = sq / sq.sum(axis=0)
    order = np.argsort(-sq, axis=0)[:n_top]
    table["top_pairs"] = [
        "; ".join(f"{names[p]} {share[p, c]:.2f}" for p in order[:, c])
        for c in range(lr.shape[1])
    ]
    return table.reset_index()


def _missed_rows(ref, ref_lr, fit, lr, names, pathways) -> pd.DataFrame:
    frames = []
    for k in KS:
        for direction, source, target, weights in (
            ("comparator top-k, cccRISE rank", lr, ref_lr, ref.weights),
            ("cccRISE top-k, comparator rank", ref_lr, lr, fit.weights),
        ):
            t = missed_pairs(source, target, weights, k, names)
            frames.append(t.assign(direction=direction))
    out = pd.concat(frames, ignore_index=True)
    out["pathway"] = out["lr_pair"].map(pathways)
    if fit.kind == "cp":
        pr = participation_ratio(fit.condition_factor)
        comparator_source = out["direction"].str.startswith("comparator")
        out.loc[comparator_source, "source_min_condition_pr"] = [
            min(pr[int(c) - 1] for c in s.split(","))
            for s in out.loc[comparator_source, "source_components"]
        ]
    return out


def _annotation_tables(spec, annotation, adata, abundance, thresholds, pathways):
    """Every table's rows for the fits on one annotation."""
    suffix, column = ANNOTATIONS[annotation]
    fits, info, _conditions = read_fits(
        VALIDATION_DIR / spec.benchmark_fits_filename(suffix)
    )
    ref = next(f for f in fits if f.method == "cccRISE")
    lr_names = (
        load_factors_netcdf(spec.factors_path()).coords["lr_pair"].values.astype(str)
    )
    ref_lr = ref.modes["lr"]
    profiles = _cell_profiles(adata, spec, column, info["celltypes"])
    out: dict[str, list[pd.DataFrame]] = {
        n: [] for n in ("overlap", "coverage", "missed", "matches", "columns")
    }
    out["columns"].append(
        _column_rows(ref_lr, lr_names).assign(**_label(ref, annotation))
    )
    for fit in (f for f in fits if f.method != "cccRISE"):
        lr = aligned_modes(fit, info, lr_names)["lr"]
        label = _label(fit, annotation)
        overlaps = overlap_table(ref_lr, lr, KS, thresholds)
        out["overlap"].append(overlaps.assign(**label))
        out["coverage"].append(coverage_table(ref_lr, lr, KS).assign(**label))
        out["missed"].append(
            _missed_rows(ref, ref_lr, fit, lr, lr_names, pathways).assign(**label)
        )
        out["matches"].append(
            _match_rows(fit, ref, lr, ref_lr, overlaps, profiles).assign(**label)
        )
        out["columns"].append(_column_rows(lr, lr_names).assign(**label))
    out["overlap"].append(
        overlap_table(ref_lr, abundance[:, None], KS, thresholds).assign(
            annotation=annotation, method="abundance", rank_mode="reference", rank="1"
        )
    )
    return {n: pd.concat(frames, ignore_index=True) for n, frames in out.items()}


def _with_classes(matches: pd.DataFrame, containment: pd.DataFrame) -> pd.DataFrame:
    """Adds each CP column's A5 class and its LR containment in cccRISE's span."""
    lr = containment[
        (containment["direction"] == "comparator in cccRISE")
        & (containment["mode"] == "lr")
    ][["annotation", "method", "rank_mode", "component", "containment"]]
    lr = lr.rename(
        columns={"component": "comparator_component", "containment": "lr_containment"}
    )
    matches = matches.merge(
        lr, on=["annotation", "method", "rank_mode", "comparator_component"], how="left"
    )
    cp = matches["sender_cos"].notna()
    for column, hit in (("lr_class", "hit"), ("lr_class_mass", "mass_hit")):
        matches[column] = None
        matches.loc[cp, column] = classify_components(matches[cp], hit=hit)
    return matches


def _containment(spec: DatasetSpec) -> pd.DataFrame:
    frames = []
    for annotation, (suffix, _column) in ANNOTATIONS.items():
        path = VALIDATION_DIR / f"comparator_containment_{spec.key}{suffix}.parquet"
        frames.append(pd.read_parquet(path).assign(annotation=annotation))
    return pd.concat(frames, ignore_index=True)


def run_lr_concordance(
    spec: DatasetSpec, random_state: int = 42
) -> dict[str, pd.DataFrame]:
    git_sha()
    lr_names = (
        load_factors_netcdf(spec.factors_path()).coords["lr_pair"].values.astype(str)
    )
    print(">> Loading the dataset and per-cell loadings")
    adata = load_factors_to_anndata(spec.factors_path(), adata=spec.load())
    abundance = _abundance(adata, spec, lr_names)
    rng = np.random.default_rng(random_state)
    thresholds = null_thresholds(abundance, KS, N_NULL, rng)
    pairs = import_ligand_receptor_pairs().drop_duplicates("interaction_symbol")
    pathways = pairs.set_index(pairs["interaction_symbol"].astype(str))["pathway_name"]
    per_annotation = [
        _annotation_tables(spec, a, adata, abundance, thresholds, pathways)
        for a in ANNOTATIONS
    ]
    tables = {
        n: pd.concat([t[n] for t in per_annotation], ignore_index=True)
        for n in per_annotation[0]
    }
    tables["matches"] = _with_classes(tables["matches"], _containment(spec))
    tables["null"] = thresholds
    paths = _outputs(spec)
    for name, table in tables.items():
        table.to_parquet(paths[name], index=False)
        print(f"   Wrote {len(table)} rows to {paths[name]}")
    abundant = [
        lr_names[i] for i in sorted(top_k_sets(abundance[:, None], PRIMARY_K)[0])
    ]
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_path": relpath(spec.factors_path()),
            "factors_sha256": sha256_file(spec.factors_path()),
            "fits": {
                a: relpath(VALIDATION_DIR / spec.benchmark_fits_filename(s))
                for a, (s, _c) in ANNOTATIONS.items()
            },
            "ks": list(KS),
            "primary_k": PRIMARY_K,
            "mass_hit": MASS_HIT,
            "n_null": N_NULL,
            "random_state": random_state,
            "null": "abundance-weighted: k pairs drawn without replacement with "
            "probability proportional to their mean coarse pseudobulk score",
            "abundant_top10": abundant,
            "outputs": {k: relpath(v) for k, v in paths.items()},
        }
    )
    write_metadata(paths["overlap"], metadata, header=HEADER)
    return tables


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--random-state", type=int, default=42)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    run_lr_concordance(DATASETS[args.dataset], random_state=args.random_state)


if __name__ == "__main__":
    main()
