#!/usr/bin/env python
"""
Runner: CPD rank selection on the interaction tensor.

Fits RISE once at a fixed (already-selected) rank, builds the 4D communication
tensor from that single fit, then sweeps CP ranks over it. Every rank in a
sweep therefore sees identical RISE factors.

Each rank is fit once and all three criteria are read off that shared fit:
fit R2X, core consistency (CORCONDIA), and a component-collinearity screen.
The sweep runs on a CANDELINC core by default -- both criteria are invariant
to that, and it is what makes a cohort-scale tensor sweepable at all.

    uv run cccrise-cpdrank --dataset alad --rise-rank 25 --ranks 1:26
    uv run cccrise-cpdrank --dataset ibd --rise-rank 70 --ranks 1:26 --oversample 5
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from tensorly.decomposition import parafac

from ..ccc_rise import validate_cp_rank
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..rank_selection import (
    calculate_r2x,
    candelinc_compress,
    candelinc_r2x,
    cp_core_consistency_sweep,
    cpd_component_collinearity,
)
from ..tensor import calculate_interaction_tensor, rise_store_r2x
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    parse_ranks,
    resolve_output,
    resulting_dims,
)
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, git_sha, write_metadata

DEFAULT_RANKS = list(range(1, 26))

HEADER = """\
CPD rank selection (core consistency + collinearity screen). Generated by
cccrise.runners.run_cpd_rank -- do not hand-edit.
"""


def build_interaction_tensor(
    spec: DatasetSpec,
    rise_rank: int,
    complex_sep: str | None,
    n_iter_max: int,
    tol: float,
    random_state: int | None,
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
) -> tuple[np.ndarray, dict]:
    """Fit RISE at `rise_rank`; return the 4D tensor and sidecar fields."""
    adata = spec.load()
    adata = add_cond_idxs(adata, spec.condition_column)
    lr_pairs = import_ligand_receptor_pairs()

    adata, r2x_pf2 = rise_store_r2x(
        adata,
        rank=rise_rank,
        n_iter_max=n_iter_max,
        tolerance=tol,
        random_state=random_state,
    )
    tensor = calculate_interaction_tensor(
        adata,
        lr_pairs=lr_pairs,
        complex_sep=complex_sep,
        communication_score=communication_score,
        hill_k=hill_k,
    )
    facts = {
        "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=tensor.shape[3]),
        "lr_pairs_annotated": len(lr_pairs),
        "r2x_pf2": float(r2x_pf2),
    }
    return tensor, facts


def cp_fits_by_rank(
    tensor: np.ndarray,
    ranks: list[int],
    n_iter_max: int,
    tol: float,
    init: str,
    random_state: int | None,
) -> dict[int, tuple[np.ndarray, list[np.ndarray], float]]:
    """Fit CP once per rank. Every criterion below reads from this shared fit.

    `tensor` is the CANDELINC core when the sweep is compressed, so the
    returned factors and R2X are in that core's space.

    `randomized_svd` rather than tensorly's default `truncated_svd`: only the
    initialisation needs an SVD, and a full one on a wide mode-0 unfolding
    dominates the fit. On the uncompressed IBDverse tensor at RISE rank 70
    (343 x 2,513,700) that is 410 s against 72 s per fit, for an R2X that
    agrees to 3 decimal places.
    """
    fits = {}
    for rank in ranks:
        weights, factors = parafac(
            tensor,
            rank=rank,
            n_iter_max=n_iter_max,
            tol=tol,
            init=init,
            svd="randomized_svd",
            normalize_factors=True,
            random_state=random_state,
        )
        fits[rank] = (weights, factors, calculate_r2x(weights, factors, tensor))
    return fits


def run_cpd_rank_selection(
    spec: DatasetSpec,
    rise_rank: int,
    ranks: list[int],
    n_iter_max: int = 100,
    tol: float = 1e-3,
    cp_n_iter_max: int = 4000,
    cp_tol: float = 1e-12,
    init: str = "svd",
    compress: bool = True,
    oversample: int = 5,
    complex_sep: str | None = "&",
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
    random_state: int | None = 42,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Sweep CP ranks over one interaction tensor and persist CSV plus sidecar.

    CP rank selection is conditional on the already-selected `rise_rank`.

    `n_iter_max` / `tol` control the RISE fit; `cp_n_iter_max` / `cp_tol` the
    CP fits. They are separate because the two stages want very different
    budgets: CORCONDIA is read off a converged fit, so the CP side is run far
    tighter than the RISE side that produced the tensor.

    Returns the sweep results, the CSV path, and the sidecar path.
    """
    output_path = output_path or (DATA_DIR / spec.cpd_rank_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== CPD rank selection: {spec.label} (RISE rank {rise_rank}) ===")
    print(f"    ranks={ranks}  compress={compress}  oversample={oversample}")

    print("1. Loading data and fitting RISE...")
    tensor, tensor_facts = build_interaction_tensor(
        spec,
        rise_rank=rise_rank,
        complex_sep=complex_sep,
        n_iter_max=n_iter_max,
        tol=tol,
        random_state=random_state,
        communication_score=communication_score,
        hill_k=hill_k,
    )
    print(f"   Interaction tensor shape: {tensor.shape}")
    validate_cp_rank(max(ranks), tensor.shape)

    # Everything downstream runs against `fit_target`: the CANDELINC core when
    # compressing, the tensor itself otherwise. Both criteria are invariant to
    # the choice, and `lost_sq` restates R2X against the original tensor.
    lost_sq = 0.0
    compression_facts: dict = {"compressed": compress}
    fit_target = tensor
    if compress:
        print("2. Compressing the interaction tensor (CANDELINC)...")
        fit_target, _bases, lost_sq = candelinc_compress(
            tensor, max_rank=max(ranks), oversample=oversample
        )
        retained = 1.0 - lost_sq / float(np.sum(tensor**2))
        print(
            f"   Core shape: {fit_target.shape} "
            f"({tensor.size / fit_target.size:.0f}x smaller), "
            f"retaining {retained:.4%} of the sum of squares"
        )
        compression_facts |= {
            "oversample": oversample,
            "core_shape": list(fit_target.shape),
            "compression_ratio": float(tensor.size / fit_target.size),
            "retained_fraction": float(retained),
        }

    print("3. Fitting CP at every rank...")
    fits = cp_fits_by_rank(
        fit_target,
        ranks=ranks,
        n_iter_max=cp_n_iter_max,
        tol=cp_tol,
        init=init,
        random_state=random_state,
    )
    # `candelinc_r2x` is the identity when nothing was discarded, so the
    # uncompressed path reports exactly the R2X the fit returned.
    fit_r2x_df = pd.DataFrame(
        {"Rank": rank, "FitR2X": candelinc_r2x(r2x, fit_target, lost_sq)}
        for rank, (_w, _f, r2x) in sorted(fits.items())
    )
    factors_by_rank = {rank: (w, f) for rank, (w, f, _r2x) in fits.items()}

    print("4. Screening for component collinearity...")
    collinearity_df = cpd_component_collinearity(factors_by_rank)

    print("5. Computing core consistency (CORCONDIA)...")
    core_consistency_df = cp_core_consistency_sweep(fit_target, factors_by_rank)

    df = fit_r2x_df.merge(collinearity_df, on="Rank").merge(
        core_consistency_df, on="Rank"
    )

    print(f"6. Writing {output_path}...")
    df.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "rise_rank": rise_rank,
            "cp_ranks": ranks,
            "n_iter_max": n_iter_max,
            "tol": tol,
            "cp_n_iter_max": cp_n_iter_max,
            "cp_tol": cp_tol,
            "init": init,
            "complex_sep": complex_sep,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "random_state": random_state,
            "interaction_tensor_shape": list(tensor.shape),
        }
        | compression_facts
        | tensor_facts,
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank the interaction tensor is built at.",
    )
    parser.add_argument(
        "--ranks",
        type=str,
        default=f"{DEFAULT_RANKS[0]}:{DEFAULT_RANKS[-1] + 1}",
        help="CP ranks: comma list and/or start:stop[:step] slices (default: 1:26).",
    )
    parser.add_argument(
        "--n-iter-max", type=int, default=100, help="RISE fit iteration cap."
    )
    parser.add_argument("--tol", type=float, default=1e-3, help="RISE fit tolerance.")
    parser.add_argument(
        "--cp-n-iter-max", type=int, default=4000, help="CP fit iteration cap."
    )
    parser.add_argument("--cp-tol", type=float, default=1e-12, help="CP fit tolerance.")
    parser.add_argument("--init", type=str, default="svd", choices=["random", "svd"])
    parser.add_argument(
        "--no-compress",
        dest="compress",
        action="store_false",
        help="Fit CP on the full tensor instead of a CANDELINC core.",
    )
    parser.add_argument(
        "--oversample",
        type=int,
        default=5,
        help="Extra basis columns per mode beyond the largest rank swept.",
    )
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument(
        "--communication-score",
        type=str,
        default="expression_product",
        choices=[
            "expression_product",
            "expression_mean",
            "expression_gmean",
            "expression_hill",
        ],
    )
    parser.add_argument("--hill-k", type=float, default=0.5)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV output path (default: data/cpd_rank_<dataset>.csv).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_cpd_rank_selection(
        spec,
        rise_rank=args.rise_rank,
        ranks=parse_ranks(args.ranks),
        n_iter_max=args.n_iter_max,
        tol=args.tol,
        cp_n_iter_max=args.cp_n_iter_max,
        cp_tol=args.cp_tol,
        init=args.init,
        compress=args.compress,
        oversample=args.oversample,
        complex_sep=args.complex_sep,
        communication_score=args.communication_score,
        hill_k=args.hill_k,
        random_state=args.random_state,
        output_path=resolve_output(args.output, DATA_DIR, spec.cpd_rank_filename()),
    )


if __name__ == "__main__":
    main()
