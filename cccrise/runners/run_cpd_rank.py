#!/usr/bin/env python
"""
Runner: CPD rank selection on the interaction tensor.

Builds the 4D communication tensor from the dataset's canonical RISE fit (its
factors file, written by `run_ccc_rise`; RISE is not refit), then sweeps CP
ranks over it. RISE rank is selected before CP rank and the RISE fit does not
depend on CP rank, so the sweep describes exactly the tensor the canonical CP
factorizes. Run `run_ccc_rise` first, at a provisional CP rank if need be.

Each rank is fit once and we then read off the following three criteria:
1. Fit R2X
2. Core Consistency (CORCONDIA)
3. Component-Collinearity Screen

With `REPLICATE_COMPRESS`, the sweep runs on a CANDELINC core, which is proven
invariant to the three criteria.

A fourth, imputation R2X (`rank_selection.cp_imputation_sweep`), refits every
rank with entries held out. Masks select entries of the original tensor, so it
runs uncompressed, on the GPU when the dataset's backend is 'cupy'. Its masked
fits carry a ridge (`IMPUTATION_OPTIONS["l2_reg"]`) that no other CP fit uses,
so a ridge comparison then refits the full tensor with and without it at every
rank (same backend, uncompressed) and, at the canonical CP rank, compares both
with the saved canonical core fit.

    uv run cccrise-cpdrank --dataset alad
"""

import argparse
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from tensorly.decomposition import parafac

from ..ccc_rise import (
    CP_COMPRESSION_OPTIONS,
    CP_FIT_OPTIONS,
    calculate_interaction_tensor,
    validate_cp_rank,
)
from ..factors import load_factors_netcdf
from ..import_data import import_ligand_receptor_pairs
from ..rank_selection import (
    calculate_r2x,
    candelinc_compress,
    candelinc_r2x,
    cp_core_consistency_sweep,
    cp_imputation_sweep,
    cpd_component_collinearity,
    fit_cp_on_backend,
)
from ..utils import load_rise_reference
from ..validation.stability import per_component_fms
from ._cli import (
    CP_N_ITER_MAX,
    CP_TOL,
    REPLICATE_COMPRESS,
    add_dataset_argument,
    dataset_metadata,
    parse_ranks,
    resolve_output,
)
from .datasets import DATASETS, RANK_SELECTION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, read_metadata, write_metadata

#: Top of the default CP sweep, which is also capped at the RISE rank: a CP
#: rank can't exceed the tensor's smallest mode (`ccc_rise.validate_cp_rank`).
MAX_DEFAULT_RANK = 25

#: Masked fits extrapolate to held-out entries, where nothing anchors a
#: component's scale: a component confined to one condition-sender-receiver
#: fiber is pinned on that fiber's held-out entries only by the EM fill-in, so
#: without a ridge it drifts onto them and imputation R2X goes far negative.
#: The ridge leaves the full-data fit at the selected rank unchanged (the
#: ridge comparison), so it is applied to masked fits only.
IMPUTATION_OPTIONS: dict[str, Any] = {"n_folds": 10, "l2_reg": 0.1}
IMPUTATION_REPEATS = 3

#: Canonical-fit provenance carried into this sweep's sidecar.
CANONICAL_FIELDS = (
    "complex_sep",
    "communication_score",
    "hill_k",
    "resulting_dims",
    "lr_pairs_annotated",
    "r2x_pf2",
)

HEADER = """\
CPD rank selection (core consistency, collinearity screen, imputation, ridge
comparison). Generated by cccrise.runners.run_cpd_rank -- do not hand-edit.
"""


def canonical_tensor(
    spec: DatasetSpec, provenance: dict
) -> tuple[np.ndarray, pd.Index]:
    """The communication tensor the canonical CP was fit on, and its LR labels."""
    adata = load_rise_reference(spec.factors_path(), spec.load(), spec.condition_column)
    tensor, lr_pairs = calculate_interaction_tensor(
        adata,
        import_ligand_receptor_pairs(),
        complex_sep=provenance["complex_sep"],
        communication_score=provenance["communication_score"],
        hill_k=provenance["hill_k"],
    )
    return np.asarray(tensor), pd.Index(lr_pairs["interaction_symbol"].astype(str))


def cp_fits_by_rank(
    tensor: np.ndarray,
    ranks: list[int],
    n_iter_max: int,
    tol: float,
    random_state: int | None,
) -> dict[int, tuple[np.ndarray, list[np.ndarray], float]]:
    """Fit CP once per rank. Every criterion below reads from this shared fit.

    `tensor` is the CANDELINC core when the sweep is compressed, so the
    returned factors and R2X are in that core's space.
    """
    fits = {}
    for rank in ranks:
        weights, factors = parafac(
            tensor,
            rank=rank,
            n_iter_max=n_iter_max,
            tol=tol,
            random_state=random_state,
            **CP_FIT_OPTIONS,
        )
        fits[rank] = (weights, factors, calculate_r2x(weights, factors, tensor))
    return fits


def rank_criteria(
    tensor: np.ndarray, ranks: list[int], compress: bool, **fit_kwargs
) -> tuple[pd.DataFrame, dict]:
    """Fit R2X, collinearity and CORCONDIA per rank, from one CP fit per rank
    of `tensor` (or its CANDELINC core when `compress`), plus the compression's
    sidecar fields."""
    # Everything here runs against `fit_target`: the CANDELINC core when
    # compressing, the tensor itself otherwise. Both criteria are invariant to
    # the choice, and `lost_sq` restates R2X against the original tensor.
    lost_sq = 0.0
    compression_facts: dict = {}
    fit_target = tensor
    if compress:
        fit_target, _bases, lost_sq = candelinc_compress(
            tensor, max_rank=max(ranks), **CP_COMPRESSION_OPTIONS
        )
        retained = 1.0 - lost_sq / float(np.sum(tensor**2))
        print(
            f"   Core shape: {fit_target.shape} "
            f"({tensor.size / fit_target.size:.0f}x smaller), "
            f"retaining {retained:.4%} of the sum of squares"
        )
        compression_facts = {
            "core_shape": list(fit_target.shape),
            "compression_ratio": float(tensor.size / fit_target.size),
            "retained_fraction": float(retained),
        }

    fits = cp_fits_by_rank(fit_target, ranks=ranks, **fit_kwargs)
    # `candelinc_r2x` is the identity when nothing was discarded, so the
    # uncompressed path reports exactly the R2X the fit returned.
    fit_r2x_df = pd.DataFrame(
        {"Rank": rank, "FitR2X": candelinc_r2x(r2x, fit_target, lost_sq)}
        for rank, (_w, _f, r2x) in sorted(fits.items())
    )
    factors_by_rank = {rank: (w, f) for rank, (w, f, _r2x) in fits.items()}
    df = fit_r2x_df.merge(cpd_component_collinearity(factors_by_rank), on="Rank").merge(
        cp_core_consistency_sweep(fit_target, factors_by_rank), on="Rank"
    )
    return df, compression_facts


def ridge_comparison(
    tensor: np.ndarray, ranks: list[int], l2_reg: float, backend: str, **parafac_kwargs
) -> tuple[pd.DataFrame, dict[int, list]]:
    """Unregularized and `l2_reg` CP fits of the full `tensor` at each rank.

    Returns one row per (rank, unregularized component): its matched ridge
    component and their congruence product ('RidgeComponentFMS'), plus each
    rank's 'NoRidgeFitR2X', 'RidgeFitR2X' and 'RidgeFMS' (the mean of
    'RidgeComponentFMS'); and the [unregularized, ridge] (weights, factors)
    fits by rank.
    """
    frames, fits_by_rank = [], {}
    for rank in ranks:
        fits = [
            fit_cp_on_backend(tensor, rank, backend, l2_reg=reg, **parafac_kwargs)
            for reg in (0.0, l2_reg)
        ]
        fits_by_rank[rank] = fits
        matched = per_component_fms(fits[0][1], fits[1][1])
        frames.append(
            matched[["Component", "MatchedComponent"]].assign(
                Rank=rank,
                RidgeComponentFMS=matched["FMS"],
                NoRidgeFitR2X=calculate_r2x(*fits[0], tensor),
                RidgeFitR2X=calculate_r2x(*fits[1], tensor),
                RidgeFMS=matched["FMS"].mean(),
            )
        )
        print(f"   rank {rank}: FMS {frames[-1]['RidgeFMS'].iloc[0]:.4f}")
    return pd.concat(frames, ignore_index=True), fits_by_rank


def core_comparison(
    spec: DatasetSpec, tensor: np.ndarray, lr_labels: pd.Index, fits: list
) -> dict[str, float]:
    """The saved canonical (CPU) core fit's R2X against `tensor`, and its FMS
    to the unregularized and ridge fits in `fits` (from `ridge_comparison`)."""
    ds = load_factors_netcdf(spec.factors_path())
    order = pd.Index(ds["lr_pair"].values.astype(str)).get_indexer(lr_labels)
    core = [ds[f"cp_{mode}"].values for mode in "ABC"] + [ds["cp_D"].values[order]]
    fms = [per_component_fms(core, f)["FMS"].mean() for _, f in fits]
    return {
        "CoreFitR2X": calculate_r2x(ds["cp_weights"].values, core, tensor),
        "CoreFMS": fms[0],
        "CoreRidgeFMS": fms[1],
    }


def run_cpd_rank_selection(
    spec: DatasetSpec,
    ranks: list[int] | None = None,
    cp_n_iter_max: int = CP_N_ITER_MAX,
    cp_tol: float = CP_TOL,
    compress: bool = REPLICATE_COMPRESS,
    imputation_repeats: int = IMPUTATION_REPEATS,
    compare_ridge: bool = True,
    random_state: int | None = 42,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Sweep CP ranks over the canonical interaction tensor and persist the
    table plus sidecar.

    The criteria fits run on the CPU (`compress` fits a CANDELINC core);
    imputation and the ridge comparison run uncompressed, on CuPy when
    `spec.backend` is 'cupy'. `imputation_repeats=0` skips imputation and
    `compare_ridge=False` the ridge comparison. `ranks` defaults to 1 through
    min(`MAX_DEFAULT_RANK`, the canonical RISE rank).

    The table has one row per (rank, component) when the ridge comparison runs,
    with per-rank columns repeated, and one row per rank otherwise; the 'Core*'
    columns are filled at the canonical CP rank only.

    Returns the sweep results, the output path, and the sidecar path.
    """
    output_path = output_path or (RANK_SELECTION_DIR / spec.cpd_rank_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)
    git_sha()

    provenance = read_metadata(spec.factors_path())
    rise_rank = provenance["rank_selection"]["rise"]["rank"]
    cp_rank = provenance["rank_selection"]["cpd"]["rank"]
    ranks = ranks or list(range(1, min(MAX_DEFAULT_RANK, rise_rank) + 1))
    backend = "cupy" if spec.backend == "cupy" else "numpy"
    fit_kwargs: dict[str, Any] = {"n_iter_max": cp_n_iter_max, "tol": cp_tol}

    print(f"=== CPD rank selection: {spec.label} (RISE rank {rise_rank}) ===")
    print(f"    ranks={ranks}  compress={compress}")

    print("1. Rebuilding the canonical interaction tensor...")
    tensor, lr_labels = canonical_tensor(spec, provenance)
    print(f"   Interaction tensor shape: {tensor.shape}")
    validate_cp_rank(max(ranks), tensor.shape)

    print("2. Fitting CP at every rank (fit R2X, collinearity, CORCONDIA)...")
    df, compression_facts = rank_criteria(
        tensor, ranks, compress, random_state=random_state, **fit_kwargs
    )

    if imputation_repeats:
        print(f"3. Imputation R2X ({imputation_repeats} repeats)...")
        imputation_df = cp_imputation_sweep(
            tensor,
            ranks,
            n_repeats=imputation_repeats,
            random_state=random_state or 0,
            backend=backend,
            **fit_kwargs,
            **IMPUTATION_OPTIONS,
            **CP_FIT_OPTIONS,
        )
        df = df.merge(imputation_df, on="Rank")

    if compare_ridge:
        print("4. Fitting CP with and without the imputation ridge...")
        ridge_df, fits = ridge_comparison(
            tensor,
            ranks,
            IMPUTATION_OPTIONS["l2_reg"],
            backend,
            random_state=random_state,
            **fit_kwargs,
            **CP_FIT_OPTIONS,
        )
        df = df.merge(ridge_df, on="Rank")
        if cp_rank in fits:
            core = core_comparison(spec, tensor, lr_labels, fits[cp_rank])
            print(f"   Canonical core fit at rank {cp_rank}: {core}")
            df.loc[df["Rank"] == cp_rank, list(core)] = list(core.values())

    print(f"5. Writing {output_path}...")
    df.to_parquet(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_file": spec.factors_filename,
            "rise_rank": rise_rank,
            "canonical_cp_rank": cp_rank,
            "cp_ranks": ranks,
            "cp_n_iter_max": cp_n_iter_max,
            "cp_tol": cp_tol,
            "cp_fit_options": CP_FIT_OPTIONS,
            "compress": compress,
            "cp_compression_options": CP_COMPRESSION_OPTIONS,
            "criteria_backend": "numpy",
            "backend": backend,
            "imputation_repeats": imputation_repeats,
            "imputation_options": IMPUTATION_OPTIONS,
            "compare_ridge": compare_ridge,
            "random_state": random_state,
            "interaction_tensor_shape": list(tensor.shape),
        }
        | {field: provenance[field] for field in CANONICAL_FIELDS}
        | compression_facts,
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--ranks",
        type=str,
        default=None,
        help="CP ranks: comma list and/or start:stop[:step] slices "
        f"(default: 1 to min({MAX_DEFAULT_RANK}, the canonical RISE rank)).",
    )
    parser.add_argument(
        "--cp-n-iter-max", type=int, default=CP_N_ITER_MAX, help="CP fit iteration cap."
    )
    parser.add_argument(
        "--cp-tol", type=float, default=CP_TOL, help="CP fit tolerance."
    )
    parser.add_argument(
        "--imputation-repeats",
        type=int,
        default=IMPUTATION_REPEATS,
        help="K-fold imputation repeats per rank (0 skips imputation).",
    )
    parser.add_argument(
        "--no-ridge-comparison",
        action="store_true",
        help="Skip the full-data fits with and without the imputation ridge.",
    )
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Parquet output path (default: data/rank_selection_results/cpd_rank_<dataset>.parquet).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_cpd_rank_selection(
        spec,
        ranks=parse_ranks(args.ranks) if args.ranks else None,
        cp_n_iter_max=args.cp_n_iter_max,
        cp_tol=args.cp_tol,
        imputation_repeats=args.imputation_repeats,
        compare_ridge=not args.no_ridge_comparison,
        random_state=args.random_state,
        output_path=resolve_output(
            args.output, RANK_SELECTION_DIR, spec.cpd_rank_filename()
        ),
    )


if __name__ == "__main__":
    main()
