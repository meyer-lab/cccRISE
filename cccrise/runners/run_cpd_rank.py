#!/usr/bin/env python
"""
Runner: CP rank selection on the interaction tensor.

Builds the 4D communication tensor from the dataset's canonical RISE fit (its
factors file, written by `run_ccc_rise`; RISE is not refit), then sweeps CP
ranks over it. RISE rank is selected before CP rank and the RISE fit does not
depend on CP rank, so the sweep describes exactly the tensor the canonical CP
factorizes. Run `run_ccc_rise` first, at a provisional CP rank if need be.

Every rank is fit from `N_STARTS` seeded starts of the production
initialization (`CP_FIT_OPTIONS`; seeds `random_state`, `random_state + 1`,
...), uncompressed, on the GPU in float32 unless `--cp-device` and
`--cp-dtype` say otherwise. Per fit, the sweep table records the fit R2X and
each mode's largest |cosine| between two components; per pair of a rank's
starts, `cpd_start_fms_<dataset>.parquet` records their factor match score,
from which `rank_selection.distinct_minima` groups the starts into the distinct
minima they reach.

Imputation R2X (`rank_selection.cp_imputation_sweep`) refits every rank with
entries held out, once per fold split (`cpd_imputation_<dataset>.parquet`),
in float64 (`rank_selection.MASKED_CP_DTYPE`).
Its masked fits carry a ridge (`IMPUTATION_OPTIONS["l2_reg"]`) that no other
CP fit uses, so a ridge comparison refits the full tensor with and without it
at every rank and, at the canonical CP rank, compares both with the saved
canonical core fit (`cpd_ridge_<dataset>.parquet`).

    uv run cccrise-cpdrank --dataset alad
"""

import argparse
import time
from itertools import combinations
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from ..ccc_rise import (
    CP_DTYPE,
    CP_FIT_OPTIONS,
    calculate_interaction_tensor,
    validate_cp_rank,
)
from ..factors import clean_memory, load_factors_netcdf
from ..import_data import import_ligand_receptor_pairs
from ..rank_selection import (
    MASKED_CP_DTYPE,
    Factors,
    calculate_r2x,
    cp_imputation_sweep,
    fit_cp_on_device,
    max_mode_cosines,
)
from ..utils import load_rise_reference
from ..validation.stability import per_component_fms
from ._cli import (
    CP_N_ITER_MAX,
    CP_TOL,
    add_cp_device_arguments,
    add_dataset_argument,
    cp_device_metadata,
    dataset_metadata,
    parse_ranks,
    resolve_dataset,
    resolve_output,
)
from .datasets import RANK_SELECTION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, read_metadata, write_metadata

#: Top of the default CP sweep, which is also capped at the RISE rank: a CP
#: rank can't exceed the tensor's smallest mode (`ccc_rise.validate_cp_rank`).
MAX_DEFAULT_RANK = 25

#: Seeded starts of the production initialization fit at every rank.
N_STARTS = 10

#: Factor modes, in the sweep table's per-mode column names.
MODES = "ABCD"

#: Masked fits extrapolate to held-out entries, where nothing anchors a
#: component's scale: a component confined to one condition-sender-receiver
#: fiber is pinned on that fiber's held-out entries only by the EM fill-in, so
#: without a ridge it drifts onto them and imputation R2X goes far negative.
#: The ridge leaves the full-data fit at the selected rank unchanged (the
#: ridge comparison), so it is applied to masked fits only.
IMPUTATION_OPTIONS: dict[str, Any] = {"n_folds": 10, "l2_reg": 0.1}
IMPUTATION_REPEATS = 10

#: Canonical-fit provenance carried into this sweep's sidecar.
CANONICAL_FIELDS = (
    "complex_sep",
    "communication_score",
    "hill_k",
    "resulting_dims",
    "lr_pairs_annotated",
    "r2x_pf2",
)

HEADER = """\
CP rank selection (seeded starts per rank, imputation, ridge comparison).
Generated by cccrise.runners.run_cpd_rank -- do not hand-edit.
"""


def canonical_tensor(
    spec: DatasetSpec, provenance: dict
) -> tuple[np.ndarray, pd.Index]:
    """The communication tensor the canonical CP was fit on, and its LR labels."""
    adata = load_rise_reference(spec.factors_path(), spec.load(), spec.condition_column)
    tensor, lr_pairs = calculate_interaction_tensor(
        adata,
        import_ligand_receptor_pairs(),
        complex_sep=provenance["complex_sep"],
        communication_score=provenance["communication_score"],
        hill_k=provenance["hill_k"],
    )
    return np.asarray(tensor), pd.Index(lr_pairs["interaction_symbol"].astype(str))


def start_sweep(
    tensor: np.ndarray, ranks: list[int], seeds: list[int], **fit_kwargs
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Fit CP at every rank from each seeded start in `seeds`.

    Returns one row per fit ('Rank', 'Start', 'Seed', 'FitR2X', 'MaxCosA' to
    'MaxCosD', 'Seconds'; start 0 is the production fit), and one row per pair
    of a rank's starts ('Rank', 'SeedA', 'SeedB', 'FMS').
    """
    fits, agreement = [], []
    for rank in ranks:
        factors_by_seed: dict[int, Factors] = {}
        for start, seed in enumerate(seeds):
            began = time.perf_counter()
            weights, factors = fit_cp_on_device(
                tensor, rank, random_state=seed, **fit_kwargs, **CP_FIT_OPTIONS
            )
            factors_by_seed[seed] = factors
            # Each fit moves its own copy of the tensor to the device; without
            # releasing the pool, IBD's 6 GB copies fragment it past 24 GB.
            clean_memory()
            fits.append(
                {
                    "Rank": rank,
                    "Start": start,
                    "Seed": seed,
                    "FitR2X": calculate_r2x(weights, factors, tensor),
                    **dict(
                        zip(
                            [f"MaxCos{m}" for m in MODES],
                            max_mode_cosines(factors),
                            strict=True,
                        )
                    ),
                    "Seconds": time.perf_counter() - began,
                }
            )
        agreement += start_agreement(rank, factors_by_seed)
        r2x = [f["FitR2X"] for f in fits[-len(seeds) :]]
        print(
            f"   rank {rank}: R2X {min(r2x):.4f}-{max(r2x):.4f} over {len(seeds)} starts"
        )
    return pd.DataFrame(fits), pd.DataFrame(agreement)


def start_agreement(rank: int, factors_by_seed: dict[int, Factors]) -> list[dict]:
    """FMS between every pair of one rank's starts."""
    return [
        {
            "Rank": rank,
            "SeedA": a,
            "SeedB": b,
            "FMS": per_component_fms(factors_by_seed[a], factors_by_seed[b])[
                "FMS"
            ].mean(),
        }
        for a, b in combinations(sorted(factors_by_seed), 2)
    ]


def ridge_comparison(
    tensor: np.ndarray, ranks: list[int], l2_reg: float, **fit_kwargs
) -> tuple[pd.DataFrame, dict[int, list]]:
    """Unregularized and `l2_reg` CP fits of the full `tensor` at each rank.

    Returns one row per (rank, unregularized component): its matched ridge
    component and their congruence product ('RidgeComponentFMS'), plus each
    rank's 'NoRidgeFitR2X', 'RidgeFitR2X' and 'RidgeFMS' (the mean of
    'RidgeComponentFMS'); and the [unregularized, ridge] (weights, factors)
    fits by rank.
    """
    frames, fits_by_rank = [], {}
    for rank in ranks:
        fits = [
            fit_cp_on_device(tensor, rank, l2_reg=reg, **fit_kwargs)
            for reg in (0.0, l2_reg)
        ]
        fits_by_rank[rank] = fits
        matched = per_component_fms(fits[0][1], fits[1][1])
        frames.append(
            matched[["Component", "MatchedComponent"]].assign(
                Rank=rank,
                RidgeComponentFMS=matched["FMS"],
                NoRidgeFitR2X=calculate_r2x(*fits[0], tensor),
                RidgeFitR2X=calculate_r2x(*fits[1], tensor),
                RidgeFMS=matched["FMS"].mean(),
            )
        )
        print(f"   rank {rank}: FMS {frames[-1]['RidgeFMS'].iloc[0]:.4f}")
    return pd.concat(frames, ignore_index=True), fits_by_rank


def core_comparison(
    spec: DatasetSpec, tensor: np.ndarray, lr_labels: pd.Index, fits: list
) -> dict[str, float]:
    """The saved canonical (CPU) core fit's R2X against `tensor`, and its FMS
    to the unregularized and ridge fits in `fits` (from `ridge_comparison`)."""
    ds = load_factors_netcdf(spec.factors_path())
    order = pd.Index(ds["lr_pair"].values.astype(str)).get_indexer(lr_labels)
    core = [ds[f"cp_{mode}"].values for mode in "ABC"] + [ds["cp_D"].values[order]]
    fms = [per_component_fms(core, f)["FMS"].mean() for _, f in fits]
    return {
        "CoreFitR2X": calculate_r2x(ds["cp_weights"].values, core, tensor),
        "CoreFMS": fms[0],
        "CoreRidgeFMS": fms[1],
    }


def ridge_table(
    spec: DatasetSpec,
    tensor: np.ndarray,
    lr_labels: pd.Index,
    ranks: list[int],
    cp_rank: int,
    **fit_kwargs,
) -> pd.DataFrame:
    """`ridge_comparison` at `ranks`, with the canonical core fit's
    comparison ('Core*' columns, `core_comparison`) at `cp_rank`."""
    ridge, fits = ridge_comparison(
        tensor, ranks, IMPUTATION_OPTIONS["l2_reg"], **fit_kwargs, **CP_FIT_OPTIONS
    )
    if cp_rank in fits:
        core = core_comparison(spec, tensor, lr_labels, fits[cp_rank])
        print(f"   Canonical core fit at rank {cp_rank}: {core}")
        ridge.loc[ridge["Rank"] == cp_rank, list(core)] = list(core.values())
    return ridge


def run_cpd_rank_selection(
    spec: DatasetSpec,
    ranks: list[int] | None = None,
    n_starts: int = N_STARTS,
    cp_n_iter_max: int = CP_N_ITER_MAX,
    cp_tol: float = CP_TOL,
    cp_device: str | None = None,
    cp_dtype: str = CP_DTYPE,
    imputation_repeats: int = IMPUTATION_REPEATS,
    compare_ridge: bool = True,
    random_state: int = 42,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Sweep CP ranks over the canonical interaction tensor and persist the
    tables plus sidecars.

    Every CP fit runs on `cp_device` in `cp_dtype` (`ccc_rise.fit_cp`).
    `imputation_repeats=0` skips imputation and `compare_ridge=False` the
    ridge comparison. `ranks` defaults to 1 through min(`MAX_DEFAULT_RANK`,
    the canonical RISE rank).

    Writes the sweep table (one row per rank and start; see `start_sweep`) to
    `output_path`, and beside it the starts' pairwise FMS
    (`spec.cpd_start_fms_filename()`), imputation R2X, one row per (rank, fold
    split) (`spec.cpd_imputation_filename()`), and the ridge comparison
    (`spec.cpd_ridge_filename()`; its 'Core*' columns are filled at the
    canonical CP rank only).

    Returns the sweep table, the output path, and the sidecar path.
    """
    output_path = output_path or (RANK_SELECTION_DIR / spec.cpd_rank_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)
    git_sha()

    provenance = read_metadata(spec.factors_path())
    rise_rank = provenance["rank_selection"]["rise"]["rank"]
    cp_rank = provenance["rank_selection"]["cpd"]["rank"]
    ranks = ranks or list(range(1, min(MAX_DEFAULT_RANK, rise_rank) + 1))
    seeds = list(range(random_state, random_state + n_starts))
    fit_kwargs: dict[str, Any] = {
        "n_iter_max": cp_n_iter_max,
        "tol": cp_tol,
        "device": cp_device,
        "dtype": cp_dtype,
    }

    print(f"=== CP rank selection: {spec.label} (RISE rank {rise_rank}) ===")
    print(
        f"    ranks={ranks}  starts={n_starts}  {cp_device_metadata(cp_device, cp_dtype)}"
    )

    print("1. Rebuilding the canonical interaction tensor...")
    tensor, lr_labels = canonical_tensor(spec, provenance)
    print(f"   Interaction tensor shape: {tensor.shape}")
    validate_cp_rank(max(ranks), tensor.shape)

    print(f"2. Fitting CP from {n_starts} seeded starts at every rank...")
    df, agreement = start_sweep(tensor, ranks, seeds, **fit_kwargs)
    paths = {"sweep": output_path.name, "start_fms": spec.cpd_start_fms_filename()}
    agreement.to_parquet(output_path.with_name(paths["start_fms"]), index=False)

    if imputation_repeats:
        print(f"3. Imputation R2X ({imputation_repeats} repeats)...")
        paths["imputation"] = spec.cpd_imputation_filename()
        cp_imputation_sweep(
            tensor,
            ranks,
            n_repeats=imputation_repeats,
            random_state=random_state,
            # Masked fits keep their own precision (`MASKED_CP_DTYPE`)
            **{k: v for k, v in fit_kwargs.items() if k != "dtype"},
            **IMPUTATION_OPTIONS,
            **CP_FIT_OPTIONS,
        ).to_parquet(output_path.with_name(paths["imputation"]), index=False)

    if compare_ridge:
        print("4. Fitting CP with and without the imputation ridge...")
        paths["ridge"] = spec.cpd_ridge_filename()
        ridge_table(
            spec,
            tensor,
            lr_labels,
            ranks,
            cp_rank,
            random_state=random_state,
            **fit_kwargs,
        ).to_parquet(output_path.with_name(paths["ridge"]), index=False)

    print(f"5. Writing {output_path}...")
    df.to_parquet(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_file": spec.factors_filename,
            "rise_rank": rise_rank,
            "canonical_cp_rank": cp_rank,
            "cp_ranks": ranks,
            "n_starts": n_starts,
            "start_seeds": seeds,
            "cp_n_iter_max": cp_n_iter_max,
            "cp_tol": cp_tol,
            "cp_fit_options": CP_FIT_OPTIONS,
            **cp_device_metadata(cp_device, cp_dtype),
            "imputation_repeats": imputation_repeats,
            "imputation_options": IMPUTATION_OPTIONS,
            "imputation_dtype": MASKED_CP_DTYPE,
            "compare_ridge": compare_ridge,
            "random_state": random_state,
            "files": {key: Path(name).name for key, name in paths.items()},
            "interaction_tensor_shape": list(tensor.shape),
        }
        | {field: provenance[field] for field in CANONICAL_FIELDS},
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    for name in list(paths.values())[1:]:
        write_metadata(output_path.with_name(name), metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--ranks",
        type=str,
        default=None,
        help="CP ranks: comma list and/or start:stop[:step] slices "
        f"(default: 1 to min({MAX_DEFAULT_RANK}, the canonical RISE rank)).",
    )
    parser.add_argument(
        "--n-starts",
        type=int,
        default=N_STARTS,
        help="Seeded starts of the production initialization per rank.",
    )
    parser.add_argument(
        "--cp-n-iter-max", type=int, default=CP_N_ITER_MAX, help="CP fit iteration cap."
    )
    parser.add_argument(
        "--cp-tol", type=float, default=CP_TOL, help="CP fit tolerance."
    )
    add_cp_device_arguments(parser)
    parser.add_argument(
        "--imputation-repeats",
        type=int,
        default=IMPUTATION_REPEATS,
        help="K-fold imputation repeats per rank (0 skips imputation).",
    )
    parser.add_argument(
        "--no-ridge-comparison",
        action="store_true",
        help="Skip the full-data fits with and without the imputation ridge.",
    )
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Parquet output path (default: data/rank_selection_results/cpd_rank_<dataset>.parquet).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = resolve_dataset(args)
    run_cpd_rank_selection(
        spec,
        ranks=parse_ranks(args.ranks) if args.ranks else None,
        n_starts=args.n_starts,
        cp_n_iter_max=args.cp_n_iter_max,
        cp_tol=args.cp_tol,
        cp_device=args.cp_device,
        cp_dtype=args.cp_dtype,
        imputation_repeats=args.imputation_repeats,
        compare_ridge=not args.no_ridge_comparison,
        random_state=args.random_state,
        output_path=resolve_output(
            args.output, RANK_SELECTION_DIR, spec.cpd_rank_filename()
        ),
    )


if __name__ == "__main__":
    main()
