#!/usr/bin/env python
"""
Runner: CPD rank selection on the interaction tensor.

Fits RISE once at a fixed (already-selected) rank, builds the 4D communication
tensor from that single fit, then sweeps CP ranks over it. Every rank in a
sweep therefore sees identical RISE factors.

Each rank is fit once and we then read off the following three criteria:
1. Fit R2X
2. Core Consistency (CORCONDIA)
3. Component-Collinearity Screen

With `REPLICATE_COMPRESS`, RISE is fit compressed and the sweep runs on a
CANDELINC core, which is proven invariant to the three criteria.

A fourth, imputation R2X (`rank_selection.cp_imputation_sweep`), refits every
rank with entries held out. Masks select entries of the original tensor, so it
runs uncompressed, on the GPU when the dataset's backend is 'cupy'.

    uv run cccrise-cpdrank --dataset alad --rise-rank 17
    uv run cccrise-cpdrank --dataset ibd --rise-rank 70
"""

import argparse
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from tensorly.decomposition import parafac

from ..ccc_rise import (
    CP_COMPRESSION_OPTIONS,
    CP_FIT_OPTIONS,
    RISE_COMPRESSION_OPTIONS,
    calculate_interaction_tensor,
    fit_rise,
    validate_cp_rank,
)
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..rank_selection import (
    calculate_r2x,
    candelinc_compress,
    candelinc_r2x,
    cp_core_consistency_sweep,
    cp_imputation_sweep,
    cpd_component_collinearity,
)
from ._cli import (
    CP_N_ITER_MAX,
    CP_TOL,
    REPLICATE_COMPRESS,
    RISE_N_ITER_MAX,
    RISE_TOL,
    add_dataset_argument,
    add_scoring_arguments,
    dataset_metadata,
    parse_ranks,
    resolve_output,
    resulting_dims,
)
from .datasets import DATASETS, RANK_SELECTION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, write_metadata

#: Top of the default CP sweep, which is also capped at the RISE rank: a CP
#: rank can't exceed the tensor's smallest mode (`ccc_rise.validate_cp_rank`).
MAX_DEFAULT_RANK = 25

#: Masked fits extrapolate to held-out entries, where nothing anchors a
#: component's scale; without a ridge, components grow onto the held-out
#: entries of this heavy-tailed tensor and imputation R2X goes far negative.
IMPUTATION_OPTIONS: dict[str, Any] = {"n_folds": 10, "l2_reg": 0.1}
IMPUTATION_REPEATS = 3

HEADER = """\
CPD rank selection (core consistency, collinearity screen, imputation). Generated by
cccrise.runners.run_cpd_rank -- do not hand-edit.
"""


def build_interaction_tensor(
    spec: DatasetSpec,
    rise_rank: int,
    complex_sep: str | None,
    n_iter_max: int,
    tol: float,
    random_state: int | None,
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
    backend: str | None = None,
    compress: bool = False,
) -> tuple[np.ndarray, dict]:
    """Fit RISE at `rise_rank`; return the 4D tensor and sidecar fields."""
    adata = spec.load()
    adata = add_cond_idxs(adata, spec.condition_column)
    lr_pairs = import_ligand_receptor_pairs()

    adata, r2x_pf2 = fit_rise(
        adata,
        rank=rise_rank,
        n_iter_max=n_iter_max,
        tolerance=tol,
        random_state=random_state,
        backend=backend,
        compress=compress,
    )
    tensor, _ = calculate_interaction_tensor(
        adata,
        lr_pairs=lr_pairs,
        complex_sep=complex_sep,
        communication_score=communication_score,
        hill_k=hill_k,
    )
    facts = {
        "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=tensor.shape[3]),
        "lr_pairs_annotated": len(lr_pairs),
        "r2x_pf2": float(r2x_pf2),
    }
    return tensor, facts


def cp_fits_by_rank(
    tensor: np.ndarray,
    ranks: list[int],
    n_iter_max: int,
    tol: float,
    random_state: int | None,
) -> dict[int, tuple[np.ndarray, list[np.ndarray], float]]:
    """Fit CP once per rank. Every criterion below reads from this shared fit.

    `tensor` is the CANDELINC core when the sweep is compressed, so the
    returned factors and R2X are in that core's space.
    """
    fits = {}
    for rank in ranks:
        weights, factors = parafac(
            tensor,
            rank=rank,
            n_iter_max=n_iter_max,
            tol=tol,
            random_state=random_state,
            **CP_FIT_OPTIONS,
        )
        fits[rank] = (weights, factors, calculate_r2x(weights, factors, tensor))
    return fits


def run_cpd_rank_selection(
    spec: DatasetSpec,
    rise_rank: int,
    ranks: list[int],
    rise_n_iter_max: int = RISE_N_ITER_MAX,
    rise_tol: float = RISE_TOL,
    cp_n_iter_max: int = CP_N_ITER_MAX,
    cp_tol: float = CP_TOL,
    compress: bool = REPLICATE_COMPRESS,
    imputation_repeats: int = IMPUTATION_REPEATS,
    complex_sep: str | None = "&",
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
    random_state: int | None = 42,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Sweep CP ranks over one interaction tensor and persist the table plus sidecar.

        CP rank selection is conditional on the already-selected `rise_rank`.

    RISE runs on `spec.backend`; the CP stage is CPU-only, except imputation,
    which also runs on CuPy when `spec.backend` does. `compress` compresses
    RISE and every CP fit but imputation's. `imputation_repeats=0` skips
    imputation.

        Returns the sweep results, the output path, and the sidecar path.
    """
    output_path = output_path or (RANK_SELECTION_DIR / spec.cpd_rank_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    git_sha()

    print(f"=== CPD rank selection: {spec.label} (RISE rank {rise_rank}) ===")
    print(f"    ranks={ranks}  compress={compress}")

    print("1. Loading data and fitting RISE...")
    tensor, tensor_facts = build_interaction_tensor(
        spec,
        rise_rank=rise_rank,
        complex_sep=complex_sep,
        n_iter_max=rise_n_iter_max,
        tol=rise_tol,
        random_state=random_state,
        communication_score=communication_score,
        hill_k=hill_k,
        backend=spec.backend,
        compress=compress,
    )
    print(f"   Interaction tensor shape: {tensor.shape}")
    validate_cp_rank(max(ranks), tensor.shape)

    # Everything downstream runs against `fit_target`: the CANDELINC core when
    # compressing, the tensor itself otherwise. Both criteria are invariant to
    # the choice, and `lost_sq` restates R2X against the original tensor.
    lost_sq = 0.0
    compression_facts: dict = {}
    fit_target = tensor
    if compress:
        print("2. Compressing the interaction tensor (CANDELINC)...")
        fit_target, _bases, lost_sq = candelinc_compress(
            tensor, max_rank=max(ranks), **CP_COMPRESSION_OPTIONS
        )
        retained = 1.0 - lost_sq / float(np.sum(tensor**2))
        print(
            f"   Core shape: {fit_target.shape} "
            f"({tensor.size / fit_target.size:.0f}x smaller), "
            f"retaining {retained:.4%} of the sum of squares"
        )
        compression_facts = {
            "core_shape": list(fit_target.shape),
            "compression_ratio": float(tensor.size / fit_target.size),
            "retained_fraction": float(retained),
        }

    print("3. Fitting CP at every rank...")
    fits = cp_fits_by_rank(
        fit_target,
        ranks=ranks,
        n_iter_max=cp_n_iter_max,
        tol=cp_tol,
        random_state=random_state,
    )
    # `candelinc_r2x` is the identity when nothing was discarded, so the
    # uncompressed path reports exactly the R2X the fit returned.
    fit_r2x_df = pd.DataFrame(
        {"Rank": rank, "FitR2X": candelinc_r2x(r2x, fit_target, lost_sq)}
        for rank, (_w, _f, r2x) in sorted(fits.items())
    )
    factors_by_rank = {rank: (w, f) for rank, (w, f, _r2x) in fits.items()}

    print("4. Screening for component collinearity...")
    collinearity_df = cpd_component_collinearity(factors_by_rank)

    print("5. Computing core consistency (CORCONDIA)...")
    core_consistency_df = cp_core_consistency_sweep(fit_target, factors_by_rank)

    df = fit_r2x_df.merge(collinearity_df, on="Rank").merge(
        core_consistency_df, on="Rank"
    )

    if imputation_repeats:
        print(f"6. Imputation R2X ({imputation_repeats} repeats)...")
        imputation_df = cp_imputation_sweep(
            tensor,
            ranks,
            n_repeats=imputation_repeats,
            random_state=random_state or 0,
            backend="cupy" if spec.backend == "cupy" else "numpy",
            n_iter_max=cp_n_iter_max,
            tol=cp_tol,
            **IMPUTATION_OPTIONS,
            **CP_FIT_OPTIONS,
        )
        df = df.merge(imputation_df, on="Rank")

    print(f"7. Writing {output_path}...")
    df.to_parquet(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "rise_rank": rise_rank,
            "cp_ranks": ranks,
            "rise_n_iter_max": rise_n_iter_max,
            "rise_tol": rise_tol,
            "cp_n_iter_max": cp_n_iter_max,
            "cp_tol": cp_tol,
            "cp_fit_options": CP_FIT_OPTIONS,
            "backend": spec.backend or "auto",
            "compress": compress,
            "imputation_repeats": imputation_repeats,
            "imputation_options": IMPUTATION_OPTIONS,
            "rise_compression_options": RISE_COMPRESSION_OPTIONS,
            "cp_compression_options": CP_COMPRESSION_OPTIONS,
            "complex_sep": complex_sep,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "random_state": random_state,
            "interaction_tensor_shape": list(tensor.shape),
        }
        | compression_facts
        | tensor_facts,
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank the interaction tensor is built at.",
    )
    parser.add_argument(
        "--ranks",
        type=str,
        default=None,
        help="CP ranks: comma list and/or start:stop[:step] slices "
        f"(default: 1 to min({MAX_DEFAULT_RANK}, --rise-rank)).",
    )
    parser.add_argument(
        "--rise-n-iter-max",
        type=int,
        default=RISE_N_ITER_MAX,
        help="RISE fit iteration cap.",
    )
    parser.add_argument(
        "--rise-tol", type=float, default=RISE_TOL, help="RISE fit tolerance."
    )
    parser.add_argument(
        "--cp-n-iter-max", type=int, default=CP_N_ITER_MAX, help="CP fit iteration cap."
    )
    parser.add_argument(
        "--cp-tol", type=float, default=CP_TOL, help="CP fit tolerance."
    )
    parser.add_argument(
        "--imputation-repeats",
        type=int,
        default=IMPUTATION_REPEATS,
        help="K-fold imputation repeats per rank (0 skips imputation).",
    )
    parser.add_argument("--complex-sep", type=str, default="&")
    add_scoring_arguments(parser)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Parquet output path (default: data/rank_selection_results/cpd_rank_<dataset>.parquet).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_cpd_rank_selection(
        spec,
        rise_rank=args.rise_rank,
        ranks=parse_ranks(args.ranks)
        if args.ranks
        else list(range(1, min(MAX_DEFAULT_RANK, args.rise_rank) + 1)),
        rise_n_iter_max=args.rise_n_iter_max,
        rise_tol=args.rise_tol,
        cp_n_iter_max=args.cp_n_iter_max,
        cp_tol=args.cp_tol,
        imputation_repeats=args.imputation_repeats,
        complex_sep=args.complex_sep,
        communication_score=args.communication_score,
        hill_k=args.hill_k,
        random_state=args.random_state,
        output_path=resolve_output(
            args.output, RANK_SELECTION_DIR, spec.cpd_rank_filename()
        ),
    )


if __name__ == "__main__":
    main()
