#!/usr/bin/env python
"""
Runner: on IBD, how much of inflammation is a shift in cell composition, and
what is left of each method's association with it once composition is
accounted for.

From the pseudobulk cache's per-(sample, fine type) cell counts
(``run_pseudobulk_cache``):

- per fine type and per lineage, the Spearman correlation of its share (of
  all cells, and for fine types also of its lineage's cells) with inflamed
  (1) vs healthy (0), BH-corrected within each level and share;
- how well composition alone separates inflamed from healthy samples:
  cross-validated AUROC of an L2 logistic regression on the first
  `N_PCS` principal components of the centred-log-ratio composition, and on
  every CLR coordinate;
- the association of every unit -- each cccRISE component and every
  condition-factor column of every own-rank comparator fit -- with four
  contrasts, by OLS on ranks, unadjusted and adjusted for the composition
  PCs, with maxT over every unit of every fit (``N_PERMUTATIONS`` label
  permutations per contrast). Design fixed 2026-10-16 (story check S6b).

Writes, in ``data/validation_results/``:

    composition_celltypes_ibd.parquet    one row per (level, share, type)
    composition_association_ibd.parquet  one row per (contrast, adjusted, unit)

    uv run python -m cccrise.runners.run_ibd_composition --dataset ibd --max-cells-per-condition 2000 --cell-cap-seed 0
"""

import argparse

import numpy as np
import pandas as pd
from scipy.stats import rankdata, spearmanr
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import RepeatedStratifiedKFold, cross_val_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from statsmodels.stats.multitest import multipletests

from ..benchmark import read_fits
from ..factors import load_factors_netcdf
from ._cli import add_dataset_argument, dataset_metadata, resolve_dataset
from .datasets import VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, relpath, sha256_file, write_metadata
from .run_pseudobulk_cache import cache_path

STATUS = "inflammation_status"
INFLAMED, UNINFLAMED, HEALTHY = "CD_inflamed", "CD_uninflamed", "Healthy"
CONTRASTS = {
    "inflamed vs healthy": (INFLAMED, HEALTHY),
    "uninflamed vs healthy": (UNINFLAMED, HEALTHY),
    "inflamed vs uninflamed": (INFLAMED, UNINFLAMED),
    "three-way": (INFLAMED, UNINFLAMED, HEALTHY),
}
N_PCS = 5
PSEUDOCOUNT = 0.5  # cells
N_PERMUTATIONS = 2000
CV_SEEDS = 20
HEADER = """\
# IBD composition and inflammation. Generated by
# cccrise.runners.run_ibd_composition -- do not hand-edit.
"""


def clr_composition(counts: np.ndarray) -> np.ndarray:
    """Centred-log-ratio composition (samples x types), centred over samples."""
    logs = np.log(counts + PSEUDOCOUNT)
    clr = logs - logs.mean(axis=1, keepdims=True)
    return clr - clr.mean(axis=0)


def composition_pcs(counts: np.ndarray, n: int = N_PCS) -> np.ndarray:
    u, s, _ = np.linalg.svd(clr_composition(counts), full_matrices=False)
    return u[:, :n] * s[:n]


def cv_auroc(features: np.ndarray, labels: np.ndarray) -> tuple[float, float]:
    """Mean and SE over `CV_SEEDS` 5-fold splits of an L2 logistic regression's
    held-out AUROC (as for the CP-rank condition check, S4b)."""
    model = make_pipeline(StandardScaler(), LogisticRegression(C=1.0, max_iter=5000))
    scores = [
        cross_val_score(model, features, labels, scoring="roc_auc",
                        cv=RepeatedStratifiedKFold(n_splits=5, n_repeats=1, random_state=s)).mean()
        for s in range(CV_SEEDS)
    ]  # fmt: skip
    return float(np.mean(scores)), float(np.std(scores, ddof=1) / np.sqrt(CV_SEEDS))


def celltype_table(counts, fine, lineage_of, status) -> pd.DataFrame:
    """Per level and share, each type's Spearman rho with inflamed vs healthy."""
    keep = np.isin(status, (INFLAMED, HEALTHY))
    inflamed = (status[keep] == INFLAMED).astype(float)
    fine_counts = pd.DataFrame(counts, columns=fine)
    lineage_counts = fine_counts.T.groupby(lineage_of).sum().T
    lineage_totals = lineage_counts[[lineage_of[t] for t in fine]].to_numpy()
    shares = {
        ("fine", "all cells"): fine_counts.div(fine_counts.sum(axis=1), axis=0),
        ("fine", "lineage"): fine_counts / np.maximum(lineage_totals, 1),
        ("lineage", "all cells"): lineage_counts.div(lineage_counts.sum(axis=1), axis=0),
    }
    frames = []
    for (level, share), table in shares.items():
        rows = []
        for celltype in table.columns:
            values = table[celltype].to_numpy()
            rho, p = spearmanr(values[keep], inflamed)
            rows.append({"level": level, "share": share, "celltype": celltype,
                         "lineage": lineage_of.get(celltype, celltype), "rho": rho, "p": p,
                         **{f"median {s}": float(np.median(values[status == s]))
                            for s in (HEALTHY, UNINFLAMED, INFLAMED)}})  # fmt: skip
        frame = pd.DataFrame(rows)
        frame["q"] = multipletests(frame["p"].fillna(1), method="fdr_bh")[1]
        frames.append(frame)
    return pd.concat(frames, ignore_index=True)


def units(spec: DatasetSpec, conditions: np.ndarray) -> tuple[list[dict], np.ndarray]:
    """Every unit tested and its sample profile, in `conditions` order."""
    ds = load_factors_netcdf(spec.factors_path())
    lr = ds.coords["lr_pair"].values.astype(str)
    out, profiles = [], []
    for k in range(ds.sizes["cp_component"]):
        out.append({"method": "cccRISE", "labelling": "-", "rank": f"CP {ds.sizes['cp_component']}",
                    "unit": f"C{k + 1} {lr[np.argmax(ds['cp_D'].values[:, k])]}"})  # fmt: skip
        profiles.append(ds["cp_A"].values[:, k])
    for path in sorted(VALIDATION_DIR.glob(f"benchmark_fits_{spec.output_key}*.nc")):
        fits, _info, fit_conditions = read_fits(path)
        index = pd.Index(np.asarray(fit_conditions).astype(str)).get_indexer(conditions)
        if (index < 0).any():
            raise ValueError(f"{path.name} lacks some samples")
        label = path.stem.removeprefix(f"benchmark_fits_{spec.output_key}") or "_coarse"
        for fit in (f for f in fits if f.method != "cccRISE" and f.rank_mode == "own"):
            for j in range(fit.condition_factor.shape[1]):
                out.append({"method": fit.method, "labelling": label, "rank": fit.rank,
                            "unit": f"col{j + 1}"})  # fmt: skip
                profiles.append(fit.condition_factor[index, j])
    return out, np.column_stack(profiles)


def _residualise(matrix: np.ndarray, covariates: np.ndarray) -> np.ndarray:
    q, _ = np.linalg.qr(covariates)
    return matrix - q @ (q.T @ matrix)


def _group_stat(ranks: np.ndarray, groups: np.ndarray, df: int) -> np.ndarray:
    """|t| of the one group dummy, or the F of several, per column of the
    residualised `ranks`."""
    q, _ = np.linalg.qr(groups)
    explained = np.sum((q.T @ ranks) ** 2, axis=0)
    rss = np.sum(ranks**2, axis=0) - explained
    if groups.shape[1] == 1:
        g = groups[:, 0]
        beta = (g @ ranks) / (g @ g)
        return np.abs(beta / np.sqrt(rss / df / (g @ g)))
    return (explained / groups.shape[1]) / (rss / df)


def _dummies(labels: np.ndarray, levels: tuple[str, ...]) -> np.ndarray:
    return np.column_stack([(labels == level).astype(float) for level in levels[:-1]])


def maxt(profiles, status, pcs, levels, adjusted, rng) -> pd.DataFrame:
    """One contrast's observed statistic, permutation p and maxT p per unit."""
    keep = np.isin(status, levels)
    labels = status[keep]
    ranks = np.apply_along_axis(rankdata, 0, profiles[keep])
    covariates = np.column_stack([np.ones(keep.sum())] + ([pcs[keep]] if adjusted else []))
    residual = _residualise(ranks, covariates)
    df = keep.sum() - covariates.shape[1] - (len(levels) - 1)

    def stat(groups):
        return _group_stat(residual, _residualise(_dummies(groups, levels), covariates), df)

    observed = stat(labels)
    exceed, maxima = np.zeros(profiles.shape[1]), np.empty(N_PERMUTATIONS)
    for b in range(N_PERMUTATIONS):
        permuted = stat(rng.permutation(labels))
        maxima[b] = permuted.max()
        exceed += permuted >= observed
    return pd.DataFrame({
        "stat": observed,
        "p_raw": (1 + exceed) / (N_PERMUTATIONS + 1),
        "p_maxT": (1 + (maxima[None, :] >= observed[:, None]).sum(axis=1)) / (N_PERMUTATIONS + 1),
    })  # fmt: skip


def association_table(spec, conditions, status, pcs) -> pd.DataFrame:
    tested, profiles = units(spec, conditions)
    rng = np.random.default_rng(0)
    frames = []
    for name, levels in CONTRASTS.items():
        for adjusted in (False, True):
            result = maxt(profiles, status, pcs, levels, adjusted, rng)
            frames.append(pd.concat([pd.DataFrame(tested), result], axis=1)
                          .assign(contrast=name, adjusted=adjusted))  # fmt: skip
            print(f"   {name}, adjusted={adjusted}: {(result['p_maxT'] < 0.05).sum()} units pass maxT",
                  flush=True)  # fmt: skip
    return pd.concat(frames, ignore_index=True)


def run(spec: DatasetSpec) -> None:
    cache = np.load(cache_path(spec.key))
    conditions = cache["samples"].astype(str)
    obs = spec.load().obs.drop_duplicates(spec.condition_column).set_index(spec.condition_column)
    status = obs.reindex(conditions)[STATUS].astype(str).to_numpy()
    counts = cache["counts"].astype(float)
    fine = list(cache["fine_types"].astype(str))
    lineage_of = dict(zip(fine, cache["fine_to_coarse"].astype(str), strict=True))
    pcs = composition_pcs(counts)
    keep = np.isin(status, (INFLAMED, HEALTHY))
    inflamed = (status[keep] == INFLAMED).astype(int)
    factors = load_factors_netcdf(spec.factors_path())["cp_A"].values
    aurocs = {
        f"composition, {N_PCS} CLR PCs": cv_auroc(pcs[keep], inflamed),
        "composition, all CLR coordinates": cv_auroc(clr_composition(counts)[keep], inflamed),
        "cccRISE sample factors": cv_auroc(factors[keep], inflamed),
    }
    celltypes = celltype_table(counts, fine, lineage_of, status)
    associations = association_table(spec, conditions, status, pcs)
    metadata = build_metadata(dataset_metadata(spec) | {
        "pseudobulk_cache": relpath(cache_path(spec.key)), "factors_sha256": sha256_file(spec.factors_path()),
        "n_pcs": N_PCS, "pseudocount": PSEUDOCOUNT, "n_permutations": N_PERMUTATIONS,
        "auroc_inflamed_vs_healthy": {k: {"mean": m, "se": se} for k, (m, se) in aurocs.items()},
    })  # fmt: skip
    for name, table in (("composition_celltypes", celltypes), ("composition_association", associations)):
        out = VALIDATION_DIR / f"{name}_{spec.output_key}.parquet"
        table.to_parquet(out, index=False)
        write_metadata(out, metadata, header=HEADER)
        print(f"wrote {out}")
    print(aurocs)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    add_dataset_argument(parser)
    run(resolve_dataset(parser.parse_args()))


if __name__ == "__main__":
    main()
