"""
Runner: upstream NICHES on a dataset's production cccRISE fit, and cccRISE's
sender and receiver populations against it (`comparators.niches_programs`).
Runs NICHES on each component's carrying pairs through
`comparators/niches_system.R`. Writes, into `NICHES_DIR` (one `provenance.yaml`
for the folder):

    populations_<dataset>.parquet
        per component and side, the population's cells, samples, NICHES+
        cells and NICHES concordance, and what cell type predicts within
        sample (`niches_programs.population_table`)
    tau_<dataset>.parquet
        the same at every tau (`niches_programs.tau_table`)
    cells_<dataset>.parquet
        per cell, its sample, coarse and fine label and its unscaled sender and
        receiver weight on each component (`cell_frame`), so figures plotting
        per-cell weights read them instead of loading and projecting the cohort

NICHES needs R with Seurat, and the package's source at `NICHES_COMMIT`:

    git clone https://github.com/msraredon/NICHES <source>
    git -C <source> checkout 5d932b8

    uv run cccrise-niches --dataset ibd --niches-source <source> --r-library <lib>

`--cells-only` writes only the per-cell table (no R, no NICHES; the other
tables and their records are left as they are):

    uv run cccrise-niches --dataset ibd --cells-only
"""

import argparse
import subprocess
import tempfile
from pathlib import Path
from typing import Any, cast

import anndata
import numpy as np
import pandas as pd
import scipy.io
import xarray as xr
import yaml
from scipy.sparse import csr_matrix

from ..comparators.niches_programs import (
    MODES,
    TAUS,
    Cohort,
    pair_tokens,
    population_table,
    program_score,
    tau_table,
    token_expression,
)
from ..covariation import CARRYING_CAP, carrying_pairs
from ..factors import load_factors_netcdf, load_factors_to_anndata
from ..figures.figure2._common import GROUP_TAU
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    parse_command,
    resolve_dataset,
    resulting_dims,
)
from .datasets import NICHES_DIR, DatasetSpec, scores_filename
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_table

HEADER = """\
Upstream NICHES on the production cccRISE fits, and cccRISE's sender and
receiver populations against it. Generated by cccrise.runners.run_niches --
do not hand-edit.
"""
NICHES_COMMIT = "5d932b8"
R_SCRIPT = Path(__file__).parent.parent / "comparators" / "niches_system.R"


def source_commit(source: Path) -> str:
    """The NICHES source's commit; it must be `NICHES_COMMIT`."""
    commit = subprocess.run(
        ["git", "-C", str(source), "rev-parse", "--short=7", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    if commit != NICHES_COMMIT:
        raise SystemExit(f"NICHES source is at {commit}, not {NICHES_COMMIT}")
    return commit


def known_pairs(pairs: pd.DataFrame, genes: pd.Index) -> pd.DataFrame:
    """The rows of `pairs` whose every subunit is in `genes`."""
    known = set(genes)
    tokens = pairs["ligand"] + "&" + pairs["receptor"]
    return pairs[[set(t.split("&")) <= known for t in tokens]]


def run_upstream(
    expression: np.ndarray,
    tokens: list[str],
    pairs: pd.DataFrame,
    cells: pd.DataFrame,
    args: argparse.Namespace,
) -> tuple[dict[str, tuple[Any, pd.Index, pd.Index]], dict[str, str]]:
    """NICHES' (LR pair x cell) matrix, its pair and cell names per side, and
    the R package versions."""
    with tempfile.TemporaryDirectory(prefix="cccrise-niches-") as folder:
        work = Path(folder)
        scipy.io.mmwrite(work / "expression.mtx", csr_matrix(expression.T).tocoo())
        (work / "tokens.txt").write_text("\n".join(tokens) + "\n")
        cells.to_csv(work / "cells.csv", index=False)
        pairs.to_csv(work / "pairs.csv", index=False)
        subprocess.run(
            [
                "Rscript",
                str(R_SCRIPT),
                folder,
                str(args.niches_source),
                str(args.r_library),
                str(args.r_workers),
            ],
            check=True,
        )
        matrices = {
            side: (
                scipy.io.mmread(work / f"{mode}.mtx").tocsr(),
                pd.Index((work / f"{mode}_rows.txt").read_text().splitlines()),
                pd.Index((work / f"{mode}_cells.txt").read_text().splitlines()),
            )
            for side, mode in MODES.items()
        }
        return matrices, yaml.safe_load((work / "versions.yaml").read_text())


def cell_frame(adata: anndata.AnnData, spec: DatasetSpec) -> pd.DataFrame:
    """Each cell's name, sample, labels and unscaled per-cell weights."""
    obs = cast(pd.DataFrame, adata.obs)
    labels = spec.labellings
    frame = {
        "Cell": adata.obs_names.astype(str),
        "Sample": obs[spec.condition_column].astype(str).to_numpy(),
        "Coarse": obs[labels["coarse"]].astype(str).to_numpy(),
        "Fine": obs[labels["fine"]].astype(str).to_numpy(),
    }
    for side, key in (("Sender", "sc_B"), ("Receiver", "rc_C")):
        for k, column in enumerate(np.asarray(adata.obsm[key]).T):
            frame[f"{side} C{k + 1}"] = column
    return pd.DataFrame(frame)


def add_program_scores(
    frame: pd.DataFrame,
    matrices: dict[str, tuple[Any, pd.Index, pd.Index]],
    loadings: np.ndarray,
    lr_pairs: np.ndarray,
) -> pd.DataFrame:
    """`frame` with each side and component's NICHES program score, NaN where
    NICHES has no such cell."""
    columns = {}
    for side, (matrix, rows, names) in matrices.items():
        position = names.get_indexer(frame["Cell"])
        have = position >= 0
        for k in range(loadings.shape[1]):
            score = program_score(matrix, rows, loadings[:, k], lr_pairs)
            aligned = np.full(len(frame), np.nan)
            aligned[have] = score[position[have]]
            columns[f"NICHES {side.title()} C{k + 1}"] = aligned
    return pd.concat([frame, pd.DataFrame(columns)], axis=1)


def niches_scores(
    frame: pd.DataFrame,
    adata: anndata.AnnData,
    spec: DatasetSpec,
    loadings: np.ndarray,
    lr_pairs: np.ndarray,
    args: argparse.Namespace,
) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, str]]:
    """`frame` with NICHES' program scores, the pairs NICHES ran on, and the R
    package versions."""
    carrying = sorted(
        {i for k in range(loadings.shape[1]) for i in carrying_pairs(loadings[:, k])}
    )
    genes = pd.Index(adata.var_names.astype(str))
    pairs = known_pairs(pair_tokens(lr_pairs).iloc[carrying], genes)
    tokens = sorted(set(pairs["ligand"]) | set(pairs["receptor"]))
    cells = pd.DataFrame(
        {
            "cell": frame["Cell"],
            "sample": cast(pd.DataFrame, adata.obs)[spec.condition_column]
            .astype(str)
            .to_numpy(),
            "celltype": frame["Coarse"],
        }
    )
    expression = token_expression(adata.X, genes, tokens)
    matrices, versions = run_upstream(expression, tokens, pairs, cells, args)
    return add_program_scores(frame, matrices, loadings, lr_pairs), pairs, versions


def write(
    spec: DatasetSpec, name: str, table: pd.DataFrame, metadata: dict, command: str
) -> None:
    path = NICHES_DIR / scores_filename(name, spec.output_key)
    write_table(path, table, metadata, command, HEADER)


def fit_metadata(spec: DatasetSpec, dims: dict) -> dict:
    """The settings every table's record shares: the dataset and its fit."""
    return dataset_metadata(spec) | {
        "factors_path": relpath(spec.factors_path()),
        "factors_sha256": sha256_file(spec.factors_path()),
        "resulting_dims": dims,
    }


def write_cells(
    spec: DatasetSpec, frame: pd.DataFrame, metadata: dict, command: str
) -> None:
    """`cell_frame`'s columns of `frame` (not the NICHES columns added later),
    sample and labels as categories."""
    columns = ["Cell", "Sample", "Coarse", "Fine"] + [
        c for c in frame.columns if c.startswith(("Sender C", "Receiver C"))
    ]
    cells = frame[columns].astype(
        {"Sample": "category", "Coarse": "category", "Fine": "category"}
    )
    write(spec, "cells", cells, metadata, command)


def run_niches(spec: DatasetSpec, args: argparse.Namespace, command: str) -> None:
    git_sha()  # pin the code version before anything runs (`provenance.git_sha`)
    commit = None if args.cells_only else source_commit(args.niches_source)
    factors: xr.Dataset = load_factors_netcdf(spec.factors_path())
    lr_pairs = factors["lr_pair"].to_numpy().astype(str)
    loadings = factors["cp_D"].to_numpy()
    print("1. Loading the cohort and projecting its cells...", flush=True)
    adata = load_factors_to_anndata(spec.factors_path(), adata=spec.load())
    frame = cell_frame(adata, spec)
    dims = resulting_dims(spec, adata, n_lr_pairs=len(lr_pairs))
    if args.cells_only:
        write_cells(spec, frame, build_metadata(fit_metadata(spec, dims)), command)
        return
    print("2. NICHES...", flush=True)
    frame, pairs, versions = niches_scores(frame, adata, spec, loadings, lr_pairs, args)
    del adata
    scored = frame["NICHES Sender C1"].notna().to_numpy()
    cohort = Cohort(frame[scored].reset_index(drop=True))
    print("3. Populations...", flush=True)
    metadata = build_metadata(
        fit_metadata(spec, dims)
        | {
            "niches_commit": commit,
            "r_versions": versions,
            "niches_pairs": (pairs["ligand"] + "^" + pairs["receptor"]).tolist(),
            "cells_without_niches_score": int((~scored).sum()),
            "group_tau": GROUP_TAU,
            "carrying_cap": CARRYING_CAP,
            "taus": list(TAUS),
        }
    )
    write(spec, "populations", population_table(cohort), metadata, command)
    write(spec, "tau", tau_table(cohort), metadata, command)
    write_cells(spec, frame, metadata, command)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--niches-source",
        type=Path,
        help=f"Clone of msraredon/NICHES at {NICHES_COMMIT} (not with --cells-only).",
    )
    parser.add_argument(
        "--r-library",
        type=Path,
        help="R library holding Seurat (not with --cells-only).",
    )
    parser.add_argument(
        "--cells-only",
        action="store_true",
        help="Write only the per-cell table (cells_<dataset>); skips R and NICHES.",
    )
    parser.add_argument("--r-workers", type=int, default=8)
    return parser


def main(argv: list[str] | None = None) -> None:
    parser = build_parser()
    args, command = parse_command(parser, "cccrise-niches", argv)
    if not args.cells_only and None in (args.niches_source, args.r_library):
        parser.error("--niches-source and --r-library are needed without --cells-only")
    run_niches(resolve_dataset(args), args, command)


if __name__ == "__main__":
    main()
