#!/usr/bin/env python
"""
Runner: generate CPD factors for all four communication-scoring methods,
sharing one RISE fit between them.

Fits RISE once (`ccc_rise.fit_rise`), then CP per method on that shared RISE
basis (`ccc_rise.fit_ccc_cp`), so the four methods differ only in CP fit and
everything built from it. Each method's full-cohort fit is written as a
factors.nc. Every fit uses `run_ccc_rise`'s settings (`_cli` tolerances,
`spec.backend`, no compression). One `--random-state` seeds the RISE fit and
every CP fit.

Outputs land under `VALIDATION_DIR/alt_score_methods/<communication-score>/`,
separate from the default score's canonical results. Always
regenerates and overwrites; does not check for existing output first.

    uv run cccrise-altcommscore --dataset alad --rise-rank 17 --cp-rank 5
"""

import argparse
from pathlib import Path
from typing import Any

import anndata

from ..ccc_rise import CP_DTYPE, CP_FIT_OPTIONS, fit_ccc_cp, fit_rise
from ..factors import load_factors_netcdf, save_ccc_rise_fit
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..validation.stability import relabel_cp_fit, relabel_rise
from ._cli import (
    CP_N_ITER_MAX,
    CP_TOL,
    RISE_N_ITER_MAX,
    RISE_TOL,
    add_dataset_argument,
    component_numbering,
    core_numbering_reference,
    cp_device_metadata,
    dataset_metadata,
    resolve_dataset,
)
from .datasets import (
    COMMUNICATION_SCORES,
    DatasetSpec,
    comparison_output_dir,
)
from .provenance import build_metadata, git_sha, relpath, write_metadata

FACTORS_HEADER = """\
One method's full-cohort CP fit on the shared RISE fit. Generated by
cccrise.runners.run_alt_comm_score -- do not hand-edit.
"""

#: Fit settings of the shared RISE fit and every CP fit, recorded under the
#: same keys `run_ccc_rise`'s sidecar uses.
FIT_PROVENANCE = {
    "rise_n_iter_max": RISE_N_ITER_MAX,
    "rise_tol": RISE_TOL,
    "cp_n_iter_max": CP_N_ITER_MAX,
    "cp_tol": CP_TOL,
    "cp_fit_options": CP_FIT_OPTIONS,
}


def _save_factors(
    spec: DatasetSpec,
    rise_adata: anndata.AnnData,
    cp_fit: dict[str, Any],
    metadata: dict[str, Any],
    output_path: Path,
) -> Path:
    """Write one method's full-cohort fit as a factors.nc in `run_ccc_rise`'s
    format (`factors.save_ccc_rise_fit`)."""
    save_ccc_rise_fit(
        output_path,
        rise_adata,
        cp_fit,
        spec.condition_column,
        attrs={
            "dataset_name": spec.key,
            "dataset_label": spec.label,
            "complex_sep": "&",
        },
    )
    write_metadata(
        output_path,
        build_metadata(
            dataset_metadata(spec)
            | metadata
            | {
                "r2x_pf2": float(rise_adata.uns["r2x_pf2"]),
                "r2x_cp": float(cp_fit["r2x_cp"]),
            }
        ),
        header=FACTORS_HEADER,
    )
    return output_path


def run_alt_comm_score(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    hill_k: float = 0.5,
    random_state: int = 42,
) -> dict[str, Path]:
    """Generate CPD factors for all four scoring methods.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank, cp_rank : int
        Ranks used for the shared RISE fit and every method's CP fit.
    hill_k : float, default=0.5
        Half-saturation constant, used only for `expression_hill`.
    random_state : int, default=42
        Seed for the shared RISE fit and every method's CP fit.

    Returns
    -------
    dict[str, Path]
        Each method's factors.nc path, keyed by `communication_score`.
    """
    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== Alt communication-score generation: {spec.label} ===")
    print(
        f"    RISE rank={rise_rank}  CPD rank={cp_rank}  "
        f"scores={COMMUNICATION_SCORES}  random_state={random_state}  "
        f"backend={spec.backend or 'auto'}"
    )

    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()

    print("\n--- 1. Fitting the shared RISE model on the full cohort ---")
    rise_adata, r2x_rise = fit_rise(
        add_cond_idxs(adata.copy(), spec.condition_column),
        rank=rise_rank,
        n_iter_max=RISE_N_ITER_MAX,
        tolerance=RISE_TOL,
        random_state=random_state,
        backend=spec.backend,
    )
    print(f"   RISE R2X {r2x_rise:.4f}")
    core = core_numbering_reference(spec, rise_rank, cp_rank)
    core_ds = load_factors_netcdf(core) if core else None
    if core_ds is not None:
        relabel_rise(rise_adata, core_ds, spec.condition_column)

    factors_paths: dict[str, Path] = {}
    for method in COMMUNICATION_SCORES:
        output_dir = comparison_output_dir(method)

        print(f"\n--- 2. CP fit for {method!r} on the shared RISE fit ---")
        cp_fit = fit_ccc_cp(
            rise_adata,
            lr_pairs,
            cp_rank,
            communication_score=method,
            hill_k=hill_k,
            random_state=random_state,
            cp_n_iter_max=CP_N_ITER_MAX,
            cp_tol=CP_TOL,
        )
        if core_ds is not None:
            relabel_cp_fit(cp_fit, core_ds, rise_order=None)
        print(f"   CP R2X {cp_fit['r2x_cp']:.4f}")
        factors_path = _save_factors(
            spec,
            rise_adata,
            cp_fit,
            {
                "communication_score": method,
                "hill_k": hill_k,
                "random_state": random_state,
                "rise_rank": rise_rank,
                "cp_rank": cp_rank,
                "backend": spec.backend or "auto",
                # CP fits use `ccc_rise.fit_cp`'s defaults
                **cp_device_metadata(None, CP_DTYPE),
                "component_numbering": component_numbering(core),
            }
            | FIT_PROVENANCE,
            output_dir / spec.factors_filename,
        )
        factors_paths[method] = factors_path

    print("\n=== Done. Wrote outputs under:")
    for method, factors_path in factors_paths.items():
        print(f"    {method}: {relpath(factors_path.parent)}")
    return factors_paths


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank of the shared RISE fit.",
    )
    parser.add_argument(
        "--cp-rank", type=int, required=True, help="CPD rank every method is fit at."
    )
    parser.add_argument(
        "--hill-k",
        type=float,
        default=0.5,
        help="Hill function half-saturation constant (default: 0.5).",
    )
    parser.add_argument(
        "--random-state",
        type=int,
        default=42,
        help="Seed for the RISE fit and every CP fit.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = resolve_dataset(args)
    run_alt_comm_score(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        hill_k=args.hill_k,
        random_state=args.random_state,
    )


if __name__ == "__main__":
    main()
