#!/usr/bin/env python
"""
Runner: generate every result `figureScoringComparison` compares, for one
communication-scoring method (issue #143 / PR #157).

A thin wrapper around three existing runners' own CLIs -- `run_ccc_rise`
(CPD factors), `run_significance` (permutation significance), and
`run_component_stability` (CP component stability) -- plus a new ANOVA point
estimate (no existing runner covers that; `run_anova_bootstrap` only reports
one alongside a bootstrap). Calling each runner's own `main()` rather than
its underlying function means every fitting control this runner does not
expose (iteration caps, tolerances, the complex-subunit separator, seeds)
is decided by that runner's own CLI default, not a second copy of it kept
here -- so the two can't drift out of sync with each other.

Every output lands under `DATA_DIR/alt_score_methods/<communication-score>/`
(see `datasets.comparison_output_dir`) -- including for the default score.
Comparing scoring methods fairly means running all four at the same,
comparison-scale settings, so this runner is also the one that (re)generates
the default score's comparison-scope copy. That copy is deliberately
separate from the default's comprehensive, canonical results in `DATA_DIR`
(produced by `run_ccc_rise` / `run_significance` / `run_anova_bootstrap` /
`run_component_stability` directly, at whatever scale and ranks those were
last run at) -- this runner never touches those.

Like every other runner, this one always (re)generates and overwrites its
output; it does not check whether a result already exists first.

    uv run cccrise-altcommscore --dataset alad --rise-rank 19 --cp-rank 3 \
        --communication-score expression_mean --n-perms 3 --n-replicates 3
"""

import argparse
from pathlib import Path

from ..import_data import import_ligand_receptor_pairs
from ..stability.anova_stability import fit_anova_pipeline, top_lr_pairs
from . import run_ccc_rise, run_component_stability, run_significance
from ._cli import add_dataset_argument, dataset_metadata, resolve_group_labels
from .datasets import DATASETS, DatasetSpec, comparison_output_dir
from .provenance import build_metadata, relpath, write_metadata

HEADER = """\
ANOVA point estimate for one communication-scoring method.
Generated by cccrise.runners.run_alt_comm_score -- do not hand-edit.
"""

# Skips the expensive `conditions` cohort-resampling axis by default; see
# `run_component_stability`'s module docstring for what each axis measures.
DEFAULT_STABILITY_AXES = ("cells", "lr_pairs", "permuted")


def _run_anova_point_estimate(
    spec: DatasetSpec,
    communication_score: str,
    rise_rank: int,
    cp_rank: int,
    hill_k: float,
    output_path: Path,
) -> Path:
    """A single ANOVA fit -- no patient-resampling bootstrap -- against
    `spec.group_column`, for the cross-method comparison in
    `figureScoringComparison`. `run_anova_bootstrap` reports the same
    reference fit's `anova` table, but only alongside a bootstrap; this is
    that fit alone. No standalone runner covers this, so unlike the other
    three steps it is implemented here directly."""
    group_column, control_label, other_label = resolve_group_labels(
        spec, None, None, None
    )
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()

    reference = fit_anova_pipeline(
        adata,
        condition_column=spec.condition_column,
        group_column=group_column,
        control_label=control_label,
        other_label=other_label,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        lr_pairs=lr_pairs,
        communication_score=communication_score,
        hill_k=hill_k,
    )
    df = reference["anova"].copy()
    labels = top_lr_pairs(reference["factors"][3], reference["lr_symbols"], top_n=1)
    df = df.merge(
        labels[["Component", "LRPair"]].rename(columns={"LRPair": "TopLRPair"}),
        on="Component",
        how="left",
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "rise_rank": rise_rank,
            "cp_rank": cp_rank,
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "reference_r2x_cp": float(reference["r2x_cp"]),
        }
    )
    write_metadata(output_path, metadata, header=HEADER)
    return output_path


def run_alt_comm_score(
    spec: DatasetSpec,
    communication_score: str,
    rise_rank: int,
    cp_rank: int,
    hill_k: float = 0.5,
    n_perms: int = 3,
    stability_axes: tuple[str, ...] = DEFAULT_STABILITY_AXES,
    n_replicates: int = 3,
) -> Path:
    """Generate CPD factors, permutation significance, an ANOVA point
    estimate, and CP component stability at one scoring method, for
    `figureScoringComparison` to load. Every fitting control besides these
    core parameters -- iteration caps, tolerances, seeds, the
    complex-subunit separator -- is each called runner's own CLI default;
    see the module docstring.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    communication_score : str
        The scoring method to generate results for; see
        `ccc_rise.calc_communication_score`. Every output is written under
        `comparison_output_dir(communication_score)`, even for the default
        score -- see module docstring.
    rise_rank, cp_rank : int
        The already-selected ranks every analysis is fit at.
    hill_k : float, default=0.5
        Half-saturation constant, used only when
        `communication_score="expression_hill"`.
    n_perms : int, default=3
        Permutations for the significance test.
    stability_axes : tuple[str, ...], default=("cells", "lr_pairs", "permuted")
        Resampling axes for the stability run; see `run_component_stability`.
    n_replicates : int, default=3
        Replicates per stability axis.

    Returns
    -------
    Path
        The directory every output was written under.
    """
    output_dir = comparison_output_dir(communication_score)
    print(f"=== Alt communication-score generation: {spec.label} ===")
    print(
        f"    score={communication_score!r}  RISE rank={rise_rank}  CP rank={cp_rank}  "
        f"-> {output_dir}"
    )

    print("\n--- 1. CPD factors (cccrise-run) ---")
    run_ccc_rise.main(
        [
            "--dataset", spec.key,
            "--rise-rank", str(rise_rank),
            "--cp-rank", str(cp_rank),
            "--communication-score", communication_score,
            "--hill-k", str(hill_k),
            "--output", str(output_dir / spec.factors_filename),
        ]
    )  # fmt: skip

    print("\n--- 2. Permutation significance (cccrise-significance) ---")
    run_significance.main(
        [
            "--dataset", spec.key,
            "--rise-rank", str(rise_rank),
            "--n-perms", str(n_perms),
            "--communication-score", communication_score,
            "--hill-k", str(hill_k),
            "--output-root", str(output_dir),
        ]
    )  # fmt: skip

    print("\n--- 3. ANOVA point estimate ---")
    _run_anova_point_estimate(
        spec,
        communication_score=communication_score,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        hill_k=hill_k,
        output_path=output_dir / spec.anova_point_estimate_filename(),
    )

    print("\n--- 4. CP component stability (cccrise-stability) ---")
    run_component_stability.main(
        [
            "--dataset", spec.key,
            "--rise-rank", str(rise_rank),
            "--cp-rank", str(cp_rank),
            "--axes", ",".join(stability_axes),
            "--n-replicates", str(n_replicates),
            "--communication-score", communication_score,
            "--hill-k", str(hill_k),
            "--output", str(output_dir / spec.stability_filename()),
        ]
    )  # fmt: skip

    print(f"\n=== Done. Wrote outputs under {relpath(output_dir)} ===")
    return output_dir


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--communication-score",
        type=str,
        required=True,
        choices=[
            "expression_product",
            "expression_mean",
            "expression_gmean",
            "expression_hill",
        ],
        help="Scoring method to generate every result for.",
    )
    parser.add_argument("--rise-rank", type=int, required=True, help="RISE rank.")
    parser.add_argument("--cp-rank", type=int, required=True, help="CP (CPD) rank.")
    parser.add_argument(
        "--hill-k",
        type=float,
        default=0.5,
        help="Hill function half-saturation constant (default: 0.5).",
    )
    parser.add_argument(
        "--n-perms", type=int, default=3, help="Significance-test permutations."
    )
    parser.add_argument(
        "--stability-axes",
        type=str,
        default=",".join(DEFAULT_STABILITY_AXES),
        help="Comma-separated stability resampling axes.",
    )
    parser.add_argument(
        "--n-replicates", type=int, default=3, help="Stability replicates per axis."
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_alt_comm_score(
        spec,
        communication_score=args.communication_score,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        hill_k=args.hill_k,
        n_perms=args.n_perms,
        stability_axes=tuple(
            axis.strip() for axis in args.stability_axes.split(",") if axis.strip()
        ),
        n_replicates=args.n_replicates,
    )


if __name__ == "__main__":
    main()
