#!/usr/bin/env python
"""
Runner: generate every result `figureScoringComparison` compares, for one
alternate communication-scoring method (issue #143 / PR #157).

Bundles the four analyses the comparison figure reads -- CPD factors,
permutation significance, an ANOVA point estimate against the dataset's
phenotype, and CP component stability -- into one invocation per
`--communication-score`, each fit at the same (already-selected) RISE/CP
ranks. Results land under `DATA_DIR/alt_score_methods/<communication-score>/`
(see `datasets.scoring_output_dir`); the default score's results are never
touched by this runner -- they are produced by `run_ccc_rise` /
`run_significance` / `run_anova_bootstrap` / `run_component_stability`
directly, and are the ones every other figure and the manuscript's
interpretation reads.

Like every other runner, this one always (re)generates and overwrites its
output; it does not check whether a result already exists first.

    uv run cccrise-altcommscore --dataset alad --rise-rank 19 --cp-rank 3 \
        --communication-score expression_mean --n-perms 3 --n-replicates 3
"""

import argparse
from pathlib import Path
from typing import Any

from ..import_data import import_ligand_receptor_pairs
from ..stability.anova_stability import fit_anova_pipeline, top_lr_pairs
from ._cli import (
    add_dataset_argument,
    add_group_arguments,
    dataset_metadata,
    resolve_group_labels,
)
from .datasets import DATASETS, DatasetSpec, scoring_output_dir
from .provenance import build_metadata, relpath, write_metadata
from .run_ccc_rise import run_pipeline as run_ccc_rise_pipeline
from .run_component_stability import run_component_stability as run_stability_pipeline
from .run_significance import run_significance as run_significance_pipeline

HEADER = """\
ANOVA point estimate for one alternate communication-scoring method.
Generated by cccrise.runners.run_alt_comm_score -- do not hand-edit.
"""

# Skips the expensive `conditions` cohort-resampling axis by default; see
# `run_component_stability`'s module docstring for what each axis measures.
DEFAULT_STABILITY_AXES = ("cells", "lr_pairs", "permuted")


def _run_anova_point_estimate(
    spec: DatasetSpec,
    communication_score: str,
    rise_rank: int,
    cp_rank: int,
    hill_k: float,
    group_column: str | None,
    control_label: str | None,
    other_label: str | None,
    complex_sep: str | None,
    random_state: int,
    output_path: Path,
) -> Path:
    """A single ANOVA fit -- no patient-resampling bootstrap -- against
    `spec.group_column`, for the cross-method comparison in
    `figureScoringComparison`. `run_anova_bootstrap` reports the same
    reference fit's `anova` table, but only alongside a bootstrap; this is
    that fit alone."""
    group_column, control_label, other_label = resolve_group_labels(
        spec, group_column, control_label, other_label
    )
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()

    reference = fit_anova_pipeline(
        adata,
        condition_column=spec.condition_column,
        group_column=group_column,
        control_label=control_label,
        other_label=other_label,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        lr_pairs=lr_pairs,
        complex_sep=complex_sep,
        communication_score=communication_score,
        hill_k=hill_k,
        random_state=random_state,
    )
    df = reference["anova"].copy()
    labels = top_lr_pairs(reference["factors"][3], reference["lr_symbols"], top_n=1)
    df = df.merge(
        labels[["Component", "LRPair"]].rename(columns={"LRPair": "TopLRPair"}),
        on="Component",
        how="left",
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "rise_rank": rise_rank,
            "cp_rank": cp_rank,
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "complex_sep": complex_sep,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "random_state": random_state,
            "reference_r2x_cp": float(reference["r2x_cp"]),
        }
    )
    write_metadata(output_path, metadata, header=HEADER)
    return output_path


def run_alt_comm_score(
    spec: DatasetSpec,
    communication_score: str,
    rise_rank: int,
    cp_rank: int,
    hill_k: float = 0.5,
    group_column: str | None = None,
    control_label: str | None = None,
    other_label: str | None = None,
    n_perms: int = 3,
    stability_axes: tuple[str, ...] = DEFAULT_STABILITY_AXES,
    n_replicates: int = 3,
    n_iter_max: int = 100,
    tol: float = 1e-3,
    complex_sep: str | None = "&",
    svd_init: str = "svd",
    random_state: int = 42,
    stability_random_state: int = 0,
) -> dict[str, Any]:
    """Generate CPD factors, permutation significance, an ANOVA point
    estimate, and CP component stability at one scoring method, for
    `figureScoringComparison` to load.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    communication_score : str
        The scoring method to generate results for; see
        `ccc_rise.calc_communication_score`. Every output is written under
        `scoring_output_dir(communication_score)`.
    rise_rank, cp_rank : int
        The already-selected ranks every analysis is fit at.
    hill_k : float, default=0.5
        Half-saturation constant, used only when
        `communication_score="expression_hill"`.
    group_column, control_label, other_label : str, optional
        The ANOVA point estimate's phenotype encoding; see
        `_cli.resolve_group_labels`.
    n_perms : int, default=3
        Permutations for the significance test.
    stability_axes : tuple[str, ...], default=("cells", "lr_pairs", "permuted")
        Resampling axes for the stability run; see `run_component_stability`.
    n_replicates : int, default=3
        Replicates per stability axis.
    n_iter_max, tol, complex_sep, svd_init
        Fitting controls shared across the CPD/significance/stability fits.
    random_state : int, default=42
        Seed for the CPD factors, significance test, and ANOVA fit.
    stability_random_state : int, default=0
        Separate seed for the stability run, matching its own runner's
        default rather than the others' `random_state=42`.

    Returns
    -------
    dict[str, Any]
        Output paths, keyed "factors", "significance_lr",
        "significance_differential", "anova_point_estimate", "stability".
    """
    output_dir = scoring_output_dir(communication_score)
    print(f"=== Alt communication-score generation: {spec.label} ===")
    print(
        f"    score={communication_score!r}  RISE rank={rise_rank}  CP rank={cp_rank}  "
        f"-> {output_dir}"
    )

    print("\n--- 1. CPD factors (cccrise-run) ---")
    _, _, factors_path, _ = run_ccc_rise_pipeline(
        spec,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        n_iter_max=n_iter_max,
        tol=tol,
        random_state=random_state,
        complex_sep=complex_sep,
        svd_init=svd_init,
        communication_score=communication_score,
        hill_k=hill_k,
        output_path=output_dir / spec.factors_filename,
    )

    print("\n--- 2. Permutation significance (cccrise-significance) ---")
    _, significance_paths = run_significance_pipeline(
        spec,
        rise_rank=rise_rank,
        n_perms=n_perms,
        group_column=group_column,
        control_label=control_label,
        other_label=other_label,
        communication_score=communication_score,
        complex_sep=complex_sep,
        hill_k=hill_k,
        n_iter_max=n_iter_max,
        tol=tol,
        random_state=random_state,
        output_root=output_dir,
    )

    print("\n--- 3. ANOVA point estimate ---")
    anova_path = _run_anova_point_estimate(
        spec,
        communication_score=communication_score,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        hill_k=hill_k,
        group_column=group_column,
        control_label=control_label,
        other_label=other_label,
        complex_sep=complex_sep,
        random_state=random_state,
        output_path=output_dir / spec.anova_point_estimate_filename(),
    )

    print("\n--- 4. CP component stability (cccrise-stability) ---")
    _, stability_path, _ = run_stability_pipeline(
        spec,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        axes=stability_axes,
        n_replicates=n_replicates,
        rise_n_iter_max=n_iter_max,
        n_iter_max=n_iter_max,
        tol=tol,
        complex_sep=complex_sep,
        communication_score=communication_score,
        hill_k=hill_k,
        random_state=stability_random_state,
        output_path=output_dir / spec.stability_filename(),
    )

    print(f"\n=== Done. Wrote outputs under {relpath(output_dir)} ===")
    return {
        "factors": factors_path,
        "significance_lr": significance_paths["lr"],
        "significance_differential": significance_paths["differential"],
        "anova_point_estimate": anova_path,
        "stability": stability_path,
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--communication-score",
        type=str,
        required=True,
        choices=[
            "expression_product",
            "expression_mean",
            "expression_gmean",
            "expression_hill",
        ],
        help="Scoring method to generate every result for.",
    )
    parser.add_argument("--rise-rank", type=int, required=True, help="RISE rank.")
    parser.add_argument("--cp-rank", type=int, required=True, help="CP (CPD) rank.")
    parser.add_argument("--hill-k", type=float, default=0.5)
    add_group_arguments(parser)
    parser.add_argument(
        "--n-perms", type=int, default=3, help="Significance-test permutations."
    )
    parser.add_argument(
        "--stability-axes",
        type=str,
        default=",".join(DEFAULT_STABILITY_AXES),
        help="Comma-separated stability resampling axes.",
    )
    parser.add_argument(
        "--n-replicates", type=int, default=3, help="Stability replicates per axis."
    )
    parser.add_argument("--n-iter-max", type=int, default=100)
    parser.add_argument("--tol", type=float, default=1e-3)
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument(
        "--svd-init", type=str, default="svd", choices=["svd", "random"]
    )
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument("--stability-random-state", type=int, default=0)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_alt_comm_score(
        spec,
        communication_score=args.communication_score,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        hill_k=args.hill_k,
        group_column=args.group_column,
        control_label=args.control_label,
        other_label=args.other_label,
        n_perms=args.n_perms,
        stability_axes=tuple(
            axis.strip() for axis in args.stability_axes.split(",") if axis.strip()
        ),
        n_replicates=args.n_replicates,
        n_iter_max=args.n_iter_max,
        tol=args.tol,
        complex_sep=args.complex_sep,
        svd_init=args.svd_init,
        random_state=args.random_state,
        stability_random_state=args.stability_random_state,
    )


if __name__ == "__main__":
    main()
