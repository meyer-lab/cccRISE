#!/usr/bin/env python
"""
Runner: generate CPD factors, permutation significance, an ANOVA point
estimate, and CP component stability for all four communication-scoring
methods, sharing one RISE fit between them.

Fits RISE once, at the same settings `run_component_stability` refits it at
(backend included), then fits CP per method on that shared RISE basis, so the
four methods differ only in CP fit and everything built from it. Each
method's full-cohort fit is written as a factors.nc and reused as the
reference for its significance test, ANOVA point estimate, and stability
run. One `--random-state` seeds the RISE fit, every CP fit, the permutations,
and the stability replicates.

Outputs land under `DATA_DIR/alt_score_methods/<communication-score>/`,
separate from the default score's canonical results in `DATA_DIR`. Always
regenerates and overwrites; does not check for existing output first.

    uv run cccrise-altcommscore --dataset alad --rise-rank 19 --cp-rank 3 \
        --n-perms 3 --n-replicates 3
"""

import argparse
from pathlib import Path
from typing import Any

import anndata
import numpy as np

from ..anova import anova_component_associations, prepare_anova_inputs
from ..factors import factors_to_xarray, save_factors_netcdf
from ..import_data import import_ligand_receptor_pairs
from ..validation.component_stability import SEED_AXIS, fit_cp_stage, fit_rise_stage
from . import run_component_stability, run_significance
from ._cli import add_dataset_argument, dataset_metadata, resolve_anova_labels
from .datasets import DATASETS, DatasetSpec, comparison_output_dir
from .provenance import (
    build_metadata,
    read_metadata,
    relpath,
    write_metadata,
    write_metadata_at,
)

FACTORS_HEADER = """\
One method's full-cohort CP fit on the shared RISE fit. Generated by
cccrise.runners.run_alt_comm_score -- do not hand-edit.
"""

ANOVA_HEADER = """\
ANOVA point estimate of one method's full-cohort CP fit. Generated by
cccrise.runners.run_alt_comm_score -- do not hand-edit.
"""

CONSOLIDATED_HEADER = """\
One method's CPD factors, permutation significance, ANOVA point estimate,
and CP component stability provenance, merged from their individual sidecars.
Generated by cccrise.runners.run_alt_comm_score -- do not hand-edit.
"""

ALL_SCORES = (
    "expression_product",
    "expression_mean",
    "expression_gmean",
    "expression_hill",
)

# Skips the expensive `conditions` cohort-resampling axis by default; see
# `run_component_stability`'s module docstring for what each axis measures.
DEFAULT_STABILITY_AXES = ("cells", "lr_pairs", SEED_AXIS)


def _save_factors(
    spec: DatasetSpec,
    rise_adata: anndata.AnnData,
    reference: dict[str, Any],
    metadata: dict[str, Any],
    output_path: Path,
) -> Path:
    """Write one method's full-cohort fit as a factors.nc in `run_ccc_rise`'s
    format, per-cell RISE projections included so `run_significance` can
    load the shared RISE fit from it."""
    ds = factors_to_xarray(
        cpd_factors=reference["cp_factors"],
        cpd_weights=reference["cp_weights"],
        filtered_lr_pairs=reference["lr_symbols"],
        condition_names=reference["condition_labels"],
        gene_names=list(rise_adata.var_names),
        pf2_factors=reference["rise_factors"],
        pf2_weights=rise_adata.uns["Pf2_weights"],
        pf2_projections=np.asarray(rise_adata.obsm["projections"]),
        cell_ids=rise_adata.obs_names.to_numpy(),
        r2x_cp=reference["r2x_cp"],
        r2x_pf2=float(reference["r2x_rise"]),
        attrs={
            "dataset_name": spec.key,
            "dataset_label": spec.label,
            "condition_key": spec.condition_column,
            "complex_sep": "&",
        },
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    save_factors_netcdf(ds, output_path)
    write_metadata(
        output_path,
        build_metadata(
            dataset_metadata(spec)
            | metadata
            | {
                "r2x_pf2": float(reference["r2x_rise"]),
                "r2x_cp": float(reference["r2x_cp"]),
            }
        ),
        header=FACTORS_HEADER,
    )
    return output_path


def _anova_point_estimate(
    spec: DatasetSpec,
    rise_adata: anndata.AnnData,
    reference: dict[str, Any],
    output_path: Path,
) -> Path:
    """Test one method's full-cohort CP fit against `spec`'s outcome with a
    one-way ANOVA, and write the point-estimate table."""
    group_column, control_label, other_label = resolve_anova_labels(
        spec, None, None, None
    )
    X, sample_to_group = prepare_anova_inputs(
        rise_adata,
        reference["cp_factors"],
        spec.condition_column,
        group_column,
        control_label,
        other_label,
    )
    df = anova_component_associations(X, sample_to_group, control_label=control_label)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "reference_r2x_cp": float(reference["r2x_cp"]),
        }
    )
    write_metadata(output_path, metadata, header=ANOVA_HEADER)
    return output_path


#: Trailer fields every individual sidecar carries with its own generation
#: time; never hoisted even when equal, and dropped from every section since
#: the consolidated file gets its own single trailer instead.
_TRAILER_KEYS = ("git_sha", "generated")


def _consolidate_provenance(output_dir: Path, section_paths: dict[str, Path]) -> Path:
    """Merge one method's four individual provenance sidecars into a single
    `provenance.yaml` for `output_dir`.

    A field is hoisted to the top level once if it has the same value in
    more than one section; otherwise it stays nested under that section's
    own key.

    Parameters
    ----------
    output_dir : Path
        Directory to write `provenance.yaml` into.
    section_paths : dict[str, Path]
        Each section's own output path, keyed by section name, e.g.
        `{"factors": ..., "significance": ..., "anova_point_estimate": ...,
        "stability": ...}`.
    """
    sections = {name: read_metadata(path) for name, path in section_paths.items()}

    all_keys: set[str] = set()
    for meta in sections.values():
        all_keys.update(meta.keys())

    shared: dict[str, object] = {}
    for key in sorted(all_keys - set(_TRAILER_KEYS)):
        values = [meta[key] for meta in sections.values() if key in meta]
        if len(values) > 1 and all(v == values[0] for v in values[1:]):
            shared[key] = values[0]

    consolidated: dict[str, object] = dict(shared)
    for name, meta in sections.items():
        consolidated[name] = {
            k: v for k, v in meta.items() if k not in shared and k not in _TRAILER_KEYS
        }

    metadata = build_metadata(consolidated)
    path = output_dir / "provenance.yaml"
    write_metadata_at(path, metadata, header=CONSOLIDATED_HEADER)
    return path


def run_alt_comm_score(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    hill_k: float = 0.5,
    n_perms: int = 3,
    stability_axes: tuple[str, ...] = DEFAULT_STABILITY_AXES,
    n_replicates: int = 3,
    random_state: int = 42,
    backend: str | None = None,
    compress: bool = True,
    oversample: int = 5,
) -> dict[str, Path]:
    """Generate CPD factors, permutation significance, an ANOVA point
    estimate, and CP component stability for all four scoring methods.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank, cp_rank : int
        Ranks used for the shared RISE fit and every method's CP fit.
    hill_k : float, default=0.5
        Half-saturation constant, used only for `expression_hill`.
    n_perms : int, default=3
        Permutations for each method's significance test.
    stability_axes : tuple[str, ...], default=DEFAULT_STABILITY_AXES
        Resampling axes for each method's stability run.
    n_replicates : int, default=3
        Replicates per stability axis.
    random_state : int, default=42
        Seed for the shared RISE fit, every method's CP fit and permutations,
        and the base seed of every stability replicate.
    backend : str | None, default=None
        Backend the shared RISE fit and each stability replicate's RISE refit
        run on ('cpu', 'cupy', 'mlx', or None to auto-detect).
    compress : bool, default=True
        Fit every CP stage inside a CANDELINC core; see
        `validation.component_stability._fit_cp`.
    oversample : int, default=5
        Extra basis columns per mode beyond the CP rank, when `compress`.

    Returns
    -------
    dict[str, Path]
        Each method's factors.nc path, keyed by `communication_score`.
    """
    print(f"=== Alt communication-score generation: {spec.label} ===")
    print(
        f"    RISE rank={rise_rank}  CP rank={cp_rank}  scores={ALL_SCORES}  "
        f"random_state={random_state}  backend={backend or 'auto'}  "
        f"compress={compress}"
    )

    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()

    # Controls not exposed here (iteration caps, tolerances, CP init) are
    # `fit_rise_stage`/`fit_cp_stage`'s defaults, which are also
    # `run_component_stability`'s, so references and replicates match.
    print("\n--- 1. Fitting the shared RISE model on the full cohort ---")
    rise_adata, r2x_rise = fit_rise_stage(
        adata.copy(),
        spec.condition_column,
        rise_rank,
        random_state=random_state,
        backend=backend,
    )
    print(f"   RISE R2X {r2x_rise:.4f}")

    factors_paths: dict[str, Path] = {}
    for method in ALL_SCORES:
        output_dir = comparison_output_dir(method)

        print(f"\n--- 2. CP fit for {method!r} on the shared RISE fit ---")
        reference = fit_cp_stage(
            rise_adata,
            r2x_rise,
            lr_pairs,
            spec.condition_column,
            cp_rank,
            communication_score=method,
            hill_k=hill_k,
            random_state=random_state,
            keep_tensor=True,
            compress=compress,
            oversample=oversample,
        )
        print(f"   CP R2X {reference['r2x_cp']:.4f}")
        factors_path = _save_factors(
            spec,
            rise_adata,
            reference,
            {
                "communication_score": method,
                "hill_k": hill_k,
                "random_state": random_state,
                "backend": backend or "auto",
                "compress": compress,
                "oversample": oversample,
                "rise_rank": rise_rank,
                "cp_rank": cp_rank,
            },
            output_dir / spec.factors_filename,
        )
        factors_paths[method] = factors_path

        print(f"\n--- 3. Permutation significance for {method!r} ---")
        run_significance.main(
            [
                "--dataset", spec.key,
                "--reference-source", str(factors_path),
                "--n-perms", str(n_perms),
                "--communication-score", method,
                "--hill-k", str(hill_k),
                "--random-state", str(random_state),
                "--output-root", str(output_dir),
            ]
        )  # fmt: skip

        print(f"\n--- 4. ANOVA point estimate for {method!r} ---")
        _anova_point_estimate(
            spec,
            rise_adata,
            reference,
            output_dir / spec.anova_point_estimate_filename(),
        )

        print(f"\n--- 5. CP component stability for {method!r} ---")
        run_component_stability.run_component_stability(
            spec,
            rise_rank=rise_rank,
            cp_rank=cp_rank,
            axes=stability_axes,
            n_replicates=n_replicates,
            communication_score=method,
            hill_k=hill_k,
            random_state=random_state,
            backend=backend,
            compress=compress,
            oversample=oversample,
            output_path=output_dir / spec.stability_filename(),
            reference=reference,
        )

        print(f"\n--- 6. Consolidating {method!r}'s provenance ---")
        consolidated_path = _consolidate_provenance(
            output_dir,
            {
                "factors": factors_path,
                "significance": output_dir / spec.significance_lr_filename(),
                "anova_point_estimate": output_dir
                / spec.anova_point_estimate_filename(),
                "stability": output_dir / spec.stability_filename(),
            },
        )
        print(f"   Wrote {consolidated_path}")

    print("\n=== Done. Wrote outputs under:")
    for method, factors_path in factors_paths.items():
        print(f"    {method}: {relpath(factors_path.parent)}")
    return factors_paths


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank of the shared RISE fit and every stability refit.",
    )
    parser.add_argument(
        "--cp-rank", type=int, required=True, help="CP rank every method is fit at."
    )
    parser.add_argument(
        "--hill-k",
        type=float,
        default=0.5,
        help="Hill function half-saturation constant (default: 0.5).",
    )
    parser.add_argument(
        "--n-perms", type=int, default=3, help="Significance-test permutations."
    )
    parser.add_argument(
        "--stability-axes",
        type=str,
        default=",".join(DEFAULT_STABILITY_AXES),
        help="Comma-separated stability resampling axes.",
    )
    parser.add_argument(
        "--n-replicates", type=int, default=3, help="Stability replicates per axis."
    )
    parser.add_argument(
        "--random-state",
        type=int,
        default=42,
        help="Seed for every fit and permutation; base seed for stability replicates.",
    )
    parser.add_argument(
        "--backend",
        type=str,
        default=None,
        choices=["cpu", "cupy", "mlx"],
        help="Backend every RISE fit runs on (default: auto-detect).",
    )
    parser.add_argument(
        "--no-compress",
        dest="compress",
        action="store_false",
        help="Fit every CP stage on the full tensor instead of a CANDELINC core.",
    )
    parser.add_argument(
        "--oversample",
        type=int,
        default=5,
        help="Extra basis columns per mode beyond the CP rank, when compressing.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_alt_comm_score(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        hill_k=args.hill_k,
        n_perms=args.n_perms,
        stability_axes=tuple(
            axis.strip() for axis in args.stability_axes.split(",") if axis.strip()
        ),
        n_replicates=args.n_replicates,
        random_state=args.random_state,
        backend=args.backend,
        compress=args.compress,
        oversample=args.oversample,
    )


if __name__ == "__main__":
    main()
