FACTORS_HEADER = """\
One method's full-cohort CP fit on the shared RISE fit. Generated by
cccrise.runners.run_alt_comm_score -- do not hand-edit.
"""

ANOVA_HEADER = """\
ANOVA point estimate of one method's full-cohort CP fit. Generated by
cccrise.runners.run_alt_comm_score -- do not hand-edit.
"""

CONSOLIDATED_HEADER = """\
One method's CPD factors, permutation significance, ANOVA point estimate,
and CP component stability provenance, merged from their individual sidecars
(which are then removed).
Generated by cccrise.runners.run_alt_comm_score -- do not hand-edit.
"""

#: Fit settings of the shared RISE fit and every CP fit, recorded under the
#: same keys `run_stability`'s sidecar uses.
FIT_PROVENANCE = {
    "rise_n_iter_max": RISE_N_ITER_MAX,
    "rise_tol": RISE_TOL,
    "cp_n_iter_max": CP_N_ITER_MAX,
    "cp_tol": CP_TOL,
    "cp_fit_options": CP_FIT_OPTIONS,
    "compress": REPLICATE_COMPRESS,
    "rise_compression_options": RISE_COMPRESSION_OPTIONS,
    "cp_compression_options": CP_COMPRESSION_OPTIONS,
}


def _save_factors(
    spec: DatasetSpec,
    rise_adata: anndata.AnnData,
    cp_fit: dict[str, Any],
    metadata: dict[str, Any],
    output_path: Path,
) -> Path:
    """Write one method's full-cohort fit as a factors.nc in `run_ccc_rise`'s
    format (`factors.save_ccc_rise_fit`), so `run_significance` can load the
    shared RISE fit from it."""
    save_ccc_rise_fit(
        output_path,
        rise_adata,
        cp_fit,
        spec.condition_column,
        attrs={
            "dataset_name": spec.key,
            "dataset_label": spec.label,
            "complex_sep": "&",
        },
    )
    write_metadata(
        output_path,
        build_metadata(
            dataset_metadata(spec)
            | metadata
            | {
                "r2x_pf2": float(rise_adata.uns["r2x_pf2"]),
                "r2x_cp": float(cp_fit["r2x_cp"]),
            }
        ),
        header=FACTORS_HEADER,
    )
    return output_path


def _anova_point_estimate(
    spec: DatasetSpec,
    rise_adata: anndata.AnnData,
    reference: dict[str, Any],
    output_path: Path,
) -> Path:
    """Test one method's full-cohort CP fit against `spec`'s outcome with a
    one-way ANOVA, and write the point-estimate table."""
    group_column, control_label, other_label = resolve_anova_labels(
        spec, None, None, None
    )
    X, sample_to_group = prepare_anova_inputs(
        rise_adata,
        reference["cp_factors"],
        spec.condition_column,
        group_column,
        control_label,
        other_label,
    )
    df = anova_component_associations(X, sample_to_group, control_label=control_label)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_parquet(output_path, index=False)
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "reference_r2x_cp": float(reference["r2x_cp"]),
        }
    )
    write_metadata(output_path, metadata, header=ANOVA_HEADER)
    return output_path


#: Trailer fields every individual sidecar carries with its own generation
#: time; never hoisted even when equal, and dropped from every section since
#: the consolidated file gets its own single trailer instead.
_TRAILER_KEYS = ("git_sha", "generated")


def _consolidate_provenance(output_dir: Path, section_paths: dict[str, Path]) -> Path:
    """Merge one method's four individual provenance sidecars into a single
    `COMPARISON_PROVENANCE_FILENAME` for `output_dir`, then delete them, so
    each method directory holds one provenance file.

    A field is hoisted to the top level once if it has the same value in
    more than one section; otherwise it stays nested under that section's
    own key.

    Parameters
    ----------
    output_dir : Path
        Directory to write the consolidated provenance into.
    section_paths : dict[str, Path]
        Each section's own output path, keyed by section name, e.g.
        `{"factors": ..., "significance": ..., "anova_point_estimate": ...,
        "stability": ...}`.
    """
    sections = {name: read_metadata(path) for name, path in section_paths.items()}
    shared = _shared_fields(sections)

    consolidated: dict[str, object] = dict(shared)
    for name, meta in sections.items():
        consolidated[name] = {
            k: v for k, v in meta.items() if k not in shared and k not in _TRAILER_KEYS
        }

    metadata = build_metadata(consolidated)
    path = output_dir / COMPARISON_PROVENANCE_FILENAME
    write_metadata_at(path, metadata, header=CONSOLIDATED_HEADER)
    for section_path in section_paths.values():
        sidecar_path(section_path).unlink()
    return path


def _shared_fields(sections: dict[str, dict]) -> dict[str, object]:
    """Non-trailer fields with the same value in more than one section."""
    shared: dict[str, object] = {}
    for key in sorted(set().union(*sections.values()) - set(_TRAILER_KEYS)):
        values = [meta[key] for meta in sections.values() if key in meta]
        if len(values) > 1 and all(v == values[0] for v in values[1:]):
            shared[key] = values[0]
    return shared


def run_alt_comm_score(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    hill_k: float = 0.5,
    n_perms: int = 200,
    stability_axes: tuple[str, ...] = DEFAULT_AXES,
    n_replicates: int = 20,
    random_state: int = 42,
) -> dict[str, Path]:
    """Generate CPD factors, permutation significance, an ANOVA point
    estimate, and CP component stability for all four scoring methods.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank, cp_rank : int
        Ranks used for the shared RISE fit and every method's CP fit.
    hill_k : float, default=0.5
        Half-saturation constant, used only for `expression_hill`.
    n_perms : int, default=200
        Permutations for each method's significance test.
    stability_axes : tuple[str, ...], default=DEFAULT_AXES
        Stability axes for each method's stability run.
    n_replicates : int, default=20
        Seed-only stability replicates; the jackknife runs one per patient.
    random_state : int, default=42
        Seed for the shared RISE fit, every method's CP fit and permutations,
        and the base seed of every stability replicate.

    Returns
    -------
    dict[str, Path]
        Each method's factors.nc path, keyed by `communication_score`.
    """
    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== Alt communication-score generation: {spec.label} ===")
    print(
        f"    RISE rank={rise_rank}  CP rank={cp_rank}  "
        f"scores={COMMUNICATION_SCORES}  random_state={random_state}  "
        f"backend={spec.backend or 'auto'}  compress={REPLICATE_COMPRESS}"
    )

    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()

    print("\n--- 1. Fitting the shared RISE model on the full cohort ---")
    rise_adata, r2x_rise = fit_rise(
        add_cond_idxs(adata.copy(), spec.condition_column),
        rank=rise_rank,
        n_iter_max=RISE_N_ITER_MAX,
        tolerance=RISE_TOL,
        random_state=random_state,
        backend=spec.backend,
        compress=REPLICATE_COMPRESS,
    )
    print(f"   RISE R2X {r2x_rise:.4f}")
    core = core_numbering_reference(spec, rise_rank, cp_rank)
    core_ds = load_factors_netcdf(core) if core else None
    if core_ds is not None:
        relabel_rise(rise_adata, core_ds, spec.condition_column)

    factors_paths: dict[str, Path] = {}
    for method in COMMUNICATION_SCORES:
        output_dir = comparison_output_dir(method)

        print(f"\n--- 2. CP fit for {method!r} on the shared RISE fit ---")
        cp_fit = fit_ccc_cp(
            rise_adata,
            lr_pairs,
            cp_rank,
            communication_score=method,
            hill_k=hill_k,
            random_state=random_state,
            compress=REPLICATE_COMPRESS,
            cp_n_iter_max=CP_N_ITER_MAX,
            cp_tol=CP_TOL,
        )
        if core_ds is not None:
            relabel_cp_fit(cp_fit, core_ds, rise_order=None)
        reference = stability_fit(
            rise_adata,
            cp_fit,
            spec.condition_column,
            *resolve_anova_labels(spec, None, None, None),
        )
        print(f"   CP R2X {reference['r2x_cp']:.4f}")
        factors_path = _save_factors(
            spec,
            rise_adata,
            cp_fit,
            {
                "communication_score": method,
                "hill_k": hill_k,
                "random_state": random_state,
                "rise_rank": rise_rank,
                "cp_rank": cp_rank,
                "backend": spec.backend or "auto",
                "component_numbering": component_numbering(core),
            }
            | FIT_PROVENANCE,
            output_dir / spec.factors_filename,
        )
        factors_paths[method] = factors_path

        print(f"\n--- 3. Permutation significance for {method!r} ---")
        run_significance.main(
            [
                "--dataset", spec.key,
                "--reference-source", str(factors_path),
                "--n-perms", str(n_perms),
                "--communication-score", method,
                "--hill-k", str(hill_k),
                "--random-state", str(random_state),
                "--output-root", str(output_dir),
            ]
        )  # fmt: skip

        print(f"\n--- 4. ANOVA point estimate for {method!r} ---")
        _anova_point_estimate(
            spec,
            rise_adata,
            reference,
            output_dir / spec.anova_point_estimate_filename(),
        )

        print(f"\n--- 5. CP component stability for {method!r} ---")
        run_stability.run_stability(
            spec,
            rise_rank=rise_rank,
            cp_rank=cp_rank,
            axes=stability_axes,
            n_replicates=n_replicates,
            rise_n_iter_max=RISE_N_ITER_MAX,
            rise_tol=RISE_TOL,
            cp_n_iter_max=CP_N_ITER_MAX,
            cp_tol=CP_TOL,
            communication_score=method,
            hill_k=hill_k,
            random_state=random_state,
            output_path=output_dir / spec.stability_filename(),
            reference=reference,
        )

        print(f"\n--- 6. Consolidating {method!r}'s provenance ---")
        consolidated_path = _consolidate_provenance(
            output_dir,
            {
                "factors": factors_path,
                "significance": output_dir / spec.significance_lr_filename(),
                "anova_point_estimate": output_dir
                / spec.anova_point_estimate_filename(),
                "stability": output_dir / spec.stability_filename(),
            },
        )
        print(f"   Wrote {consolidated_path}")

    print("\n=== Done. Wrote outputs under:")
    for method, factors_path in factors_paths.items():
        print(f"    {method}: {relpath(factors_path.parent)}")
    return factors_paths


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank of the shared RISE fit and every stability refit.",
    )
    parser.add_argument(
        "--cp-rank", type=int, required=True, help="CP rank every method is fit at."
    )
    parser.add_argument(
        "--hill-k",
        type=float,
        default=0.5,
        help="Hill function half-saturation constant (default: 0.5).",
    )
    parser.add_argument(
        "--n-perms", type=int, default=200, help="Significance-test permutations."
    )
    parser.add_argument(
        "--stability-axes",
        type=str,
        default=",".join(DEFAULT_AXES),
        help="Comma-separated stability axes.",
    )
    parser.add_argument(
        "--n-replicates",
        type=int,
        default=20,
        help="Seed-only stability replicates (the jackknife runs one per patient).",
    )
    parser.add_argument(
        "--random-state",
        type=int,
        default=42,
        help="Seed for every fit and permutation; base seed for stability replicates.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_alt_comm_score(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        hill_k=args.hill_k,
        n_perms=args.n_perms,
        stability_axes=tuple(
            axis.strip() for axis in args.stability_axes.split(",") if axis.strip()
        ),
        n_replicates=args.n_replicates,
        random_state=args.random_state,
    )


if __name__ == "__main__":
    main()
