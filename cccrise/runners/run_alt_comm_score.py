#!/usr/bin/env python
"""
Runner: generate CPD factors, permutation significance, an ANOVA point
estimate, and CP component stability for all four communication-scoring
methods, sharing one RISE fit between them.

Fits RISE once (`ccc_rise.fit_rise`), then CP per method on that shared RISE
basis (`ccc_rise.fit_ccc_cp`), so the four methods differ only in CP fit and
everything built from it. Each method's full-cohort fit is written as a
factors.nc and reused as the reference for its significance test (RISE),
ANOVA point estimate (CP), and stability run (RISE and CP). Every fit uses the
settings `run_stability` refits its replicates at (`_cli`
tolerances, `spec.backend`, `REPLICATE_COMPRESS`), so references and
replicates match. One `--random-state` seeds the RISE fit, every CP fit, the
permutations, and the stability replicates.

Outputs land under `VALIDATION_DIR/alt_score_methods/<communication-score>/`,
separate from the default score's canonical results. Always
regenerates and overwrites; does not check for existing output first.

    uv run cccrise-altcommscore --dataset alad --rise-rank 17 --cp-rank 5 \
        --n-perms 200 --n-replicates 20
"""

