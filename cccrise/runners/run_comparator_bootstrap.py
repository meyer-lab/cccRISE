#!/usr/bin/env python
"""
Runner: patient-resampled bootstrap of the tensor comparators' ANOVA.

For each CP comparator (pseudobulk CPD, Tensor-cell2cell) at the rank its own
procedure selected (``cccrise-benchmark``'s cached fits), fits the full
cohort once, then repeats pseudobulk tensor + fit + ANOVA on ``--n-boot``
stratified patient resamples (`validation.comparator_bootstrap`), as
``cccrise-anovaboot`` does for cccRISE: same group column, stratification,
paired-sample carry, seeds and LR-mode matching.

Every replicate is checkpointed as its own file under
``output/cache/comparator_bootstrap/<settings digest>/``; a rerun skips the
replicates already there. ``--limit N`` runs at most N new replicates per method and
stops (for timing pilots); the combined table is written once every
replicate exists:

    comparator_anova_bootstrap_<dataset>.parquet  one row per (method, replicate, component)

    uv run cccrise-comparator-bootstrap --dataset alad --n-boot 100
"""

import argparse
import hashlib
import json
import time

import numpy as np
import pandas as pd

from ..benchmark import read_fits
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..utils import replicate_seed
from ..validation.comparator_bootstrap import (
    comparator_fitter,
    comparator_replicate,
    fit_and_test,
)
from ._cli import add_dataset_argument, dataset_metadata
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec
from .provenance import REPO_ROOT, build_metadata, git_sha, write_metadata

METHODS = ("Pseudobulk CPD", "Tensor-cell2cell")
CHECKPOINT_DIR = REPO_ROOT / "output" / "cache" / "comparator_bootstrap"
HEADER = """\
Patient-resampled bootstrap of the tensor comparators' ANOVA effect sizes.
Generated by cccrise.runners.run_comparator_bootstrap -- do not hand-edit.
"""


def _own_ranks(spec: DatasetSpec) -> dict[str, int]:
    fits, _info, _conditions = read_fits(
        VALIDATION_DIR / spec.benchmark_fits_filename()
    )
    return {
        f.method: int(f.rank)
        for f in fits
        if f.rank_mode == "own" and f.method in METHODS
    }


def _replicates(
    adata, method, rank, settings, columns, lr_pairs, limit
) -> tuple[pd.DataFrame | None, dict]:
    """Every replicate of one method, from its checkpoints where they exist;
    None if `limit` stopped the loop first."""
    fit = comparator_fitter(method, settings["tc2c_backend"])
    reference = fit_and_test(
        adata, fit, rank, settings["random_state"], columns, lr_pairs
    )
    # n_boot is left out: more replicates extend the same directory.
    fixed = {k: v for k, v in settings.items() if k != "n_boot"}
    key = json.dumps(fixed | {"method": method, "rank": rank}, sort_keys=True)
    directory = CHECKPOINT_DIR / hashlib.sha256(key.encode()).hexdigest()[:16]
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "settings.json").write_text(key)
    seconds, run = [], 0
    for b in range(settings["n_boot"]):
        path = directory / f"replicate_{b:03d}.parquet"
        if path.exists():
            continue
        if limit is not None and run >= limit:
            return None, reference
        start = time.time()
        table = comparator_replicate(
            adata,
            reference,
            fit,
            rank,
            replicate_seed(settings["random_state"], b),
            columns,
            lr_pairs,
            settings["patient_column"],
        )
        table.insert(0, "Replicate", b)
        table.to_parquet(path.with_suffix(".partial"), index=False)
        path.with_suffix(".partial").replace(path)
        seconds.append(time.time() - start)
        run += 1
        left = sum(
            not (directory / f"replicate_{i:03d}.parquet").exists()
            for i in range(settings["n_boot"])
        )
        print(
            f"   {method} replicate {b + 1}/{settings['n_boot']}: "
            f"{seconds[-1]:.0f} s; ~{np.median(seconds) * left / 60:.0f} min left"
        )
    frames = [
        pd.read_parquet(directory / f"replicate_{b:03d}.parquet")
        for b in range(settings["n_boot"])
    ]
    return pd.concat(frames, ignore_index=True), reference


def run_comparator_bootstrap(
    spec: DatasetSpec, settings: dict, limit: int | None = None
) -> pd.DataFrame | None:
    git_sha()
    adata = add_cond_idxs(spec.load(), spec.condition_column)
    lr_pairs = import_ligand_receptor_pairs()
    columns = {
        "condition": spec.condition_column,
        "celltype": spec.celltype_column,
        "group": settings["group_column"],
    }
    frames, references = [], {}
    for method, rank in _own_ranks(spec).items():
        print(f">> {method} (rank {rank})")
        table, reference = _replicates(
            adata, method, rank, settings, columns, lr_pairs, limit
        )
        if table is None:
            print(f"   {method}: stopped after --limit {limit} new replicates")
            continue
        frames.append(table.assign(Method=method, Rank=rank))
        references[method] = {
            "rank": rank,
            **{
                f"reference_{c.lower()}": reference["anova"][c].tolist()
                for c in ("EtaSquared", "F", "P", "GroupMeanDiff")
            },
        }
    if len(references) < len(_own_ranks(spec)):
        return None
    out = pd.concat(frames, ignore_index=True)
    path = VALIDATION_DIR / f"comparator_anova_bootstrap_{spec.key}.parquet"
    out.to_parquet(path, index=False)
    write_metadata(
        path,
        build_metadata(
            dataset_metadata(spec)
            | settings
            | {"match_modes": [3], "references": references}
        ),
        header=HEADER,
    )
    print(f"   Wrote {len(out)} rows to {path}")
    return out


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--n-boot", type=int, default=100)
    parser.add_argument("--group-column", default="6monthcondition")
    parser.add_argument("--patient-column", default="patient_id")
    parser.add_argument("--tc2c-backend", choices=("numpy", "cupy"), default="numpy")
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--limit", type=int, default=None, help="Run at most this many new replicates."
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    settings = {
        "n_boot": args.n_boot,
        "group_column": args.group_column,
        "patient_column": args.patient_column,
        "tc2c_backend": args.tc2c_backend,
        "random_state": args.random_state,
        "stratify": True,
    }
    run_comparator_bootstrap(DATASETS[args.dataset], settings, limit=args.limit)


if __name__ == "__main__":
    main()
