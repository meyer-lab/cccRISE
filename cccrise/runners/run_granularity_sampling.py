#!/usr/bin/env python
"""
Runner: the granularity sampling's per-labelling metrics.

Reads every labelling's fits written by `run_comparator_fits`
(``benchmark_fits_<dataset>.nc`` for the coarse annotation, ``_fine``,
``_s<n>r<k>`` for `n` fine types broken out of their coarse type at random,
and the targeted labellings, e.g. ``_lin+ee+ec``) and scores each with
`comparators.granularity_sampling.labelling_metrics`.

Writes, in ``data/validation_results/``:

    granularity_sampling_components_<dataset>.parquet  (labelling, method, cccRISE component)
    granularity_sampling_columns_<dataset>.parquet     (labelling, method, comparator column)
    granularity_targeted_components_<dataset>.parquet  (the same, targeted labellings)
    granularity_targeted_columns_<dataset>.parquet
    granularity_isolation_<dataset>.parquet            (labelling, fine type)

each metrics row carrying the labelling's suffix, its number of cell types,
the number of fine types broken out, the repeat, and the fit's rank. The
isolation table gives, per labelling and fine type, the share of its group's
cells that are of that type (1: the type has a group of its own).

    uv run python -m cccrise.runners.run_granularity_sampling --dataset ibd
"""

import argparse
import re

import numpy as np
import pandas as pd

from ..benchmark import read_fits
from ..comparators.granularity_sampling import labelling_metrics
from ..factors import ensure_decompressed, load_factors_netcdf
from ._cli import add_dataset_argument, dataset_metadata, resolve_dataset
from .datasets import VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, write_metadata
from .run_pseudobulk_cache import cache_path

HEADER = """\
Granularity sampling: what each labelling lets the comparators recover.
Generated by cccrise.runners.run_granularity_sampling -- do not hand-edit.
"""
SUFFIX = re.compile(r"^(?:|_fine|_s(\d+)r(\d+))$")
TARGETED_SUFFIX = re.compile(r"^_(?:lin|fine-\w+|s\d+r\d+)(?:[+-]\w+)+$|^_fine-\w+$")


def labelling_files(spec: DatasetSpec, pattern=SUFFIX) -> dict[str, object]:
    """Every labelling's fits file whose suffix matches `pattern`, keyed by
    suffix."""
    prefix = spec.benchmark_fits_filename("").removesuffix(".nc")
    out = {}
    for path in sorted(VALIDATION_DIR.glob(f"{prefix}*.nc")):
        suffix = path.stem.removeprefix(prefix)
        if pattern.match(suffix):
            out[suffix] = path
    return out


def _labelling_fields(suffix: str, info: dict) -> dict:
    match = SUFFIX.match(suffix)
    repeat = match.group(2) if match else None
    return {
        "labelling": suffix or "_coarse",
        "n_types": len(info["celltypes"]),
        "n_broken_out": len(info.get("broken_out", [])),
        "repeat": int(repeat) if repeat else 0,
    }


def _isolation(suffix: str, info: dict, cache: dict) -> pd.DataFrame:
    """Per fine type: the share of its group's cells that are of that type
    in this labelling (1 when the type has a group of its own)."""
    fine = cache["fine_types"].astype(str)
    coarse = cache["fine_to_coarse"].astype(str)
    group = np.where(np.isin(fine, info.get("broken_out", [])), fine, coarse)
    cells = cache["counts"].sum(axis=0)
    group_cells = pd.Series(cells).groupby(group).transform("sum").to_numpy()
    return pd.DataFrame(
        {
            "labelling": suffix or "_coarse",
            "celltype": fine,
            "coarse": coarse,
            "share_of_group": cells / group_cells,
        }
    )


def _score(files: dict, lr_names) -> dict[str, list[pd.DataFrame]]:
    tables: dict[str, list[pd.DataFrame]] = {"components": [], "columns": []}
    for suffix, path in files.items():
        fits, info, _ = read_fits(path)
        fields = _labelling_fields(suffix, info)
        components, columns = labelling_metrics(fits, info, lr_names)
        tables["components"].append(components.assign(**fields))
        tables["columns"].append(columns.assign(**fields))
        print(f"   {fields['labelling']}: {fields['n_types']} types")
    return tables


def run(spec: DatasetSpec) -> dict[str, pd.DataFrame]:
    git_sha()
    lr_names = (
        load_factors_netcdf(ensure_decompressed(spec.factors_path()))
        .coords["lr_pair"]
        .values.astype(str)
    )
    cache = dict(np.load(cache_path(spec.output_key), allow_pickle=False))
    files = labelling_files(spec)
    targeted = labelling_files(spec, TARGETED_SUFFIX)
    out = {}
    for kind, kind_files in (("sampling", files), ("targeted", targeted)):
        for name, tables in _score(kind_files, lr_names).items():
            if tables:
                out[f"{kind}_{name}"] = pd.concat(tables, ignore_index=True)
    out["isolation"] = pd.concat(
        [
            _isolation(suffix, read_fits(path)[1], cache)
            for suffix, path in (files | targeted).items()
        ],
        ignore_index=True,
    )
    for name, table in out.items():
        path = VALIDATION_DIR / f"granularity_{name}_{spec.output_key}.parquet"
        table.to_parquet(path, index=False)
        print(f"   Wrote {len(table)} rows to {path}")
    write_metadata(
        path,
        build_metadata(
            dataset_metadata(spec)
            | {
                "labellings": {
                    s: relpath(p) for s, p in (files | targeted).items()
                }
            }
        ),
        header=HEADER,
    )
    return out


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    add_dataset_argument(parser)
    run(resolve_dataset(parser.parse_args(argv)))


if __name__ == "__main__":
    main()
