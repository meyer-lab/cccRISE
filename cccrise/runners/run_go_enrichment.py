#!/usr/bin/env python
"""
Runner: gene-set (GO) enrichment of CPD components over the LR mode.

Loads an already-finalized factor fit (``spec.factors_path()``, produced by
``cccrise-run``) and tests each component's LR loadings against each gene-set
library with `cccrise.validation.go_enrichment`.

Writes:

    go_enrichment_<dataset>.parquet   one row per (library, component, term)

    uv run cccrise-go --dataset alad
    uv run cccrise-go --dataset alad --libraries GOBP KEGG Reactome
"""

import argparse

import pandas as pd

from ..factors import load_factors_netcdf
from ..validation.go_enrichment import (
    LIBRARIES,
    PERMUTATIONS,
    Library,
    generate_lr_geneset,
    load_pathway_per_gene,
    lr_gsea,
    lr_resource_interactions,
)
from ._cli import add_dataset_argument
from .datasets import DATASETS, VALIDATION_DIR
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

HEADER = """\
GO enrichment of CPD components. Generated by
cccrise.runners.run_go_enrichment -- do not hand-edit.
"""


def run_go_enrichment(dataset: str, libraries: list[Library], permutations: int):
    spec = DATASETS[dataset]
    factors_path = spec.factors_path()
    output_path = VALIDATION_DIR / spec.go_enrichment_filename()
    git_sha()

    factors = load_factors_netcdf(factors_path)
    loadings = pd.DataFrame(
        factors["cp_D"].values,
        index=factors["lr_pair"].values.astype(str),
        columns=factors["cp_component"].values,
    )

    results = []
    for library in libraries:
        print(f"Testing {library}...")
        lr_set = generate_lr_geneset(
            lr_resource_interactions(), load_pathway_per_gene(library)
        )
        result = lr_gsea(loadings, lr_set, permutations=permutations)
        enriched = result[result["padj"] < 0.05]
        print(f"  {len(enriched)} enriched terms with adjusted p < 0.05")
        results.append(result.assign(library=library))
    results = pd.concat(results, ignore_index=True)

    results.to_parquet(output_path, index=False)
    print(f"Wrote {len(results)} rows to {output_path}")

    metadata = build_metadata(
        {
            "dataset": dataset,
            "factors_path": relpath(factors_path),
            "factors_sha256": sha256_file(factors_path),
            "libraries": libraries,
            "permutations": permutations,
        }
    )
    write_metadata(output_path, metadata, header=HEADER)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--libraries", nargs="+", choices=LIBRARIES, default=["GOBP"])
    parser.add_argument("--permutations", type=int, default=PERMUTATIONS)
    args = parser.parse_args(argv)
    run_go_enrichment(args.dataset, args.libraries, args.permutations)


if __name__ == "__main__":
    main()
