"""
Runner: the Scriabin paper's own robustness analyses (Wilk et al. 2024, Nat
Biotechnol 42:470), rerun on its panc8 data with its stated settings
(`figureR_scriabin_reproduced`).

Writes one table per analysis to ``data/scriabin_reproduction/`` (each
recorded in the folder's ``provenance.yaml``), from upstream R runs
(git-ignored, under `RUNS_DIR`):

- ``downsampling_panc8`` (Fig. 2d-e): per random 300-cell subsample of the
  Fluidigm C1 islets and arm (``raw``, ``alra``), the fraction of
  ground-truth cell-cell pairs with LISI > 1 after integrating the
  downsampled CCIM with the full-depth one, their mean LISI, and the fold
  downsampling to inDrop depth (``rcheck/authors/panc8_paper_noise.R``).
- ``soft_power_panc8`` (Extended Data Fig. 8f): per random inDrop subsample
  (300 and 1,000 cells) and R^2 threshold, WGCNA's recommended soft power,
  the power used, and the programs' size, composition and significance
  (``rcheck/authors/panc8_paper_r2_sweep.R``). The power is the one the
  paper's panel plots, uncapped (1 where no power reaches the threshold);
  upstream today falls back to 1 above power 3 as well.
- ``downsampling_programs_panc8`` (added to Fig. 2d-e): per C1 subsample,
  best-match Jaccard of the interaction programs (upstream
  InteractionPrograms, its default power) between the ground truth and a
  downsampled draw, raw or ALRA, and between two independent downsampling
  draws of the same cells (`COMPARISONS`).
- ``soft_power_programs_panc8`` (added to ED Fig. 8f): best-match Jaccard of
  the programs between every pair of inDrop subsamples of one size, per R^2
  threshold and power rule (`POWER_RULES`).

Inputs: ``Rscript rcheck/authors/panc8_paper_prep.R``, then the jobs of
``rcheck/out/authors/panc8_paper/jobs.tsv`` through ``rcheck/shared/loadq.py``.

Usage:

    uv run cccrise-scriabin-reproduction --analysis downsampling
    uv run cccrise-scriabin-reproduction --analysis soft_power
    uv run cccrise-scriabin-reproduction --analysis downsampling_programs
    uv run cccrise-scriabin-reproduction --analysis soft_power_programs
"""

import argparse
import itertools
import json
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd

from ._cli import parse_command
from .datasets import SCRIABIN_REPRODUCTION_DIR
from .provenance import REPO_ROOT, build_metadata, record_output
from .run_scriabin_stability import best_match

HEADER = """\
The Scriabin paper's robustness analyses rerun on panc8 (figureR_scriabin_reproduced).
Generated by cccrise.runners.run_scriabin_reproduction -- do not hand-edit.
"""

RUNS_DIR = REPO_ROOT / "rcheck" / "out" / "authors" / "panc8_paper"
#: Each analysis' run folder under `RUNS_DIR` and its R script
RUNS = {
    "downsampling": ("noise", "rcheck/authors/panc8_paper_noise.R"),
    "soft_power": ("r2_sweep", "rcheck/authors/panc8_paper_r2_sweep.R"),
}
RUNS["downsampling_programs"] = RUNS["downsampling"]
RUNS["soft_power_programs"] = RUNS["soft_power"]
#: Fig. 2e's inDrop coverage, UMIs per cell
INDROP_UMI = 5828
#: InteractionProgramSignificance: a program is non-significant when more
#: than this fraction of its random-set tests have p > 0.05
FAILURE_FRACTION = 0.05
#: The downsampled arms the CCIM integration scores, and their names here
ARMS = {"down1": "raw", "down1_alra": "alra"}
#: The program comparisons of each C1 subsample: (arm, arm) -> name; GT is
#: the full depth, down1 and down2 independent downsampling draws
COMPARISONS = {
    ("gt", "down1"): "gt_vs_downsampled",
    ("gt", "down1_alra"): "gt_vs_downsampled_alra",
    ("down1", "down2"): "two_draws",
    ("down1_alra", "down2_alra"): "two_draws_alra",
}
#: The soft power each rule uses at an R^2 threshold: upstream's (1 where
#: no power reaches it or the power is above 3), or uncapped (1 where none)
POWER_RULES = {"default": "capped", "uncapped": "uncapped"}
_R_DUMP = """
.libPaths(c(normalizePath("rcheck/lib"), .libPaths()))
for (f in list.files(commandArgs(TRUE)[1], "\\\\.rds$", full.names = TRUE))
  jsonlite::write_json(readRDS(f), sub("\\\\.rds$", ".json", f), auto_unbox = TRUE,
                       na = "null", digits = NA, dataframe = "rows")
"""


def load_runs(folder: Path) -> dict[str, dict]:
    """Every R run (``.rds``) in `folder`, by file stem, through a JSON dump
    written beside it."""
    subprocess.run(["Rscript", "-e", _R_DUMP, str(folder)], check=True, cwd=REPO_ROOT)
    return {f.stem: json.loads(f.read_text()) for f in sorted(folder.glob("*.json"))}


def program_pairs(modules: dict) -> list[list[str]]:
    """Each program's LR pairs (``ligand=receptor``); jsonlite unboxes a
    one-element list."""
    return [v if isinstance(v, list) else [v] for v in modules.values()]


def composition(modules: dict) -> pd.DataFrame:
    """Each program's numbers of LR pairs, ligands and receptors."""
    rows = []
    for pairs in program_pairs(modules):
        ligands = {p.split("=")[0] for p in pairs}
        receptors = {p.split("=")[1] for p in pairs}
        rows.append(
            {"pairs": len(pairs), "ligands": len(ligands), "receptors": len(receptors)}
        )
    return pd.DataFrame(rows, columns=["pairs", "ligands", "receptors"])


def downsampling(runs: dict[str, dict]) -> pd.DataFrame:
    rows = []
    for run in runs.values():
        for row in run["lisi"]:
            rows.append(
                {
                    "Subsample": run["index"],
                    "Arm": ARMS[row["arm"]],
                    "Pairs": row["n_pairs"],
                    "FractionLisiAbove1": row["frac_lisi_gt_1"],
                    "MeanLisi": row["lisi_mean"],
                    "FoldDownsampled": 1 / run["prop"],
                    "DownsampledMeanUmis": run["downsampled_mean_counts"][0],
                }
            )
    return pd.DataFrame(rows)


def _sweep_row(run: dict, power: dict) -> dict:
    key = str(int(power["uncapped"]))
    comp = composition(run["modules"][key])
    failure = np.asarray(run["failure"][key], float)
    single = (comp.ligands == 1) | (comp.receptors == 1)
    return {
        "Cells": run["n_cells"],
        "Subsample": run["index"],
        "R2": power["r2"],
        "RecommendedPower": power["recommended"],
        "Power": int(power["uncapped"]),
        "Programs": len(comp),
        "PercentNonSignificant": 100 * float(np.mean(failure > FAILURE_FRACTION)),
        "MeanPairsPerProgram": float(comp.pairs.mean()),
        "PercentSingleLigandOrReceptor": 100 * float(single.mean()),
    }


def soft_power(runs: dict[str, dict]) -> pd.DataFrame:
    table = pd.DataFrame(
        [_sweep_row(run, p) for run in runs.values() for p in run["powers"]]
    )
    table["RecommendedPower"] = table.RecommendedPower.astype("Int64")
    return table.sort_values(["Cells", "Subsample", "R2"], ignore_index=True)


def downsampling_programs(runs: dict[str, dict]) -> pd.DataFrame:
    rows = []
    for run in runs.values():
        programs = run["programs"]
        for (a, b), name in COMPARISONS.items():
            sa, sb = (_sets(programs[x]["modules"]) for x in (a, b))
            rows.append(
                {
                    "Subsample": run["index"],
                    "Comparison": name,
                    "ProgramsA": len(sa),
                    "ProgramsB": len(sb),
                    "Agreement": best_match(sa, sb),
                }
            )
    return pd.DataFrame(rows)


def _sets(modules: dict) -> list[set]:
    return [set(p) for p in program_pairs(modules)]


def _pair_rows(group: list[dict], r2_index: int, rule: str, memo: dict) -> list[dict]:
    """Agreement between every pair of `group`'s subsamples at one R^2
    threshold and power rule; `memo` keeps each (run, power, run, power)."""
    power = {r["index"]: int(r["powers"][r2_index][POWER_RULES[rule]]) for r in group}
    sets = {r["index"]: r["modules"] for r in group}
    rows = []
    for a, b in itertools.combinations(sorted(sets), 2):
        key = (a, power[a], b, power[b])
        if key not in memo:
            memo[key] = best_match(
                _sets(sets[a][str(power[a])]), _sets(sets[b][str(power[b])])
            )
        rows.append(
            {
                "SubsampleA": a,
                "SubsampleB": b,
                "Rule": rule,
                "Agreement": memo[key],
            }
        )
    return rows


def soft_power_programs(runs: dict[str, dict]) -> pd.DataFrame:
    parts = []
    for cells in sorted({r["n_cells"] for r in runs.values()}):
        group = [r for r in runs.values() if r["n_cells"] == cells]
        memo: dict = {}
        for i, power in enumerate(group[0]["powers"]):
            for rule in POWER_RULES:
                rows = pd.DataFrame(_pair_rows(group, i, rule, memo))
                parts.append(rows.assign(Cells=cells, R2=power["r2"]))
    columns = ["Cells", "R2", "Rule", "SubsampleA", "SubsampleB", "Agreement"]
    return pd.concat(parts, ignore_index=True)[columns]


def _run_settings(analysis: str, runs: dict[str, dict]) -> dict:
    folder, script = RUNS[analysis]
    return {
        "runs": f"rcheck/out/authors/panc8_paper/{folder}",
        "script": script,
        "subsamples": len(runs),
    }


def _downsampling_settings(first: dict) -> dict:
    return {"indrop_umi": INDROP_UMI, "pairs": first["lisi"][0]["n_pairs"]}


def _sweep_settings(first: dict) -> dict:
    return {
        "r2_cuts": [p["r2"] for p in first["powers"]],
        "significance_replicates": first["n_replicate"],
        "failure_fraction": FAILURE_FRACTION,
        "power": "uncapped: WGCNA's recommended power, 1 if none",
    }


def _downsampling_programs_settings(first: dict) -> dict:
    return {
        "comparisons": {f"{a} vs {b}": n for (a, b), n in COMPARISONS.items()},
        "power": "upstream InteractionPrograms' own (R^2 0.6; 1 if none or above 3)",
    }


def _sweep_programs_settings(first: dict) -> dict:
    return {
        "r2_cuts": [p["r2"] for p in first["powers"]],
        "power_rules": {
            "default": "upstream: recommended power, 1 if none or above 3",
            "uncapped": "recommended power, 1 if none",
        },
    }


def _settings(analysis: str, runs: dict[str, dict]) -> dict:
    first = next(iter(runs.values()))
    settings = _run_settings(analysis, runs)
    if "n_cells" in first:
        settings["cells"] = sorted({r["n_cells"] for r in runs.values()})
    return settings | SETTINGS[analysis](first)


ANALYSES = {
    "downsampling": downsampling,
    "soft_power": soft_power,
    "downsampling_programs": downsampling_programs,
    "soft_power_programs": soft_power_programs,
}
SETTINGS = {
    "downsampling": _downsampling_settings,
    "soft_power": _sweep_settings,
    "downsampling_programs": _downsampling_programs_settings,
    "soft_power_programs": _sweep_programs_settings,
}


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--analysis", choices=tuple(ANALYSES), required=True)
    return parser


def main(argv: list[str] | None = None) -> None:
    args, command = parse_command(build_parser(), "cccrise-scriabin-reproduction", argv)
    runs = load_runs(RUNS_DIR / RUNS[args.analysis][0])
    table = ANALYSES[args.analysis](runs)
    SCRIABIN_REPRODUCTION_DIR.mkdir(parents=True, exist_ok=True)
    path = SCRIABIN_REPRODUCTION_DIR / f"{args.analysis}_panc8.parquet"
    table.to_parquet(path, index=False)
    metadata = build_metadata(
        {"analysis": args.analysis, "dataset": "panc8"} | _settings(args.analysis, runs)
    )
    record_output(path, metadata, command, header=HEADER)
    print(f"wrote {path.name} ({len(table)} rows)")


if __name__ == "__main__":
    main()
