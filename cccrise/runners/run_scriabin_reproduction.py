"""
Runner: the Scriabin paper's technical-noise analysis (Wilk et al. 2024, Nat
Biotechnol 42:470, Fig. 2d-e) rerun on its Fluidigm C1 pancreas islets
(panc8) with upstream Scriabin (`figureR_scriabin`), from PR #275's
`run_scriabin_reproduction` (cut to what the figure and its check read).

Writes to ``data/scriabin_reproduction/``, recorded in the folder's
``provenance.yaml``, from upstream R runs (git-ignored, under `RUNS_DIR`;
``comparators/scriabin/README.md`` has the commands):

- ``downsampling_panc8`` (panel A): per random 300-cell subsample and arm
  (``raw``, ``alra``), the fraction of ground-truth (GT) cell-cell pairs
  with LISI > 1 after integrating the downsampled CCIM with the GT one,
  their mean LISI, and the GT-vs-downsampled CCIM Spearman correlation
  (``panc8_noise.R``).
- ``downsampling_programs_panc8`` (panel B): per subsample, best-match
  Jaccard (`best_match`) of upstream InteractionPrograms' significant
  programs (upstream's significance test as the vignette applies it) between
  GT and a downsampled draw, raw or ALRA, and between two independent
  downsampling draws of the same cells (`COMPARISONS`); and of all their
  programs, before the test (``panc8_programs.R``).
- ``lisi_checks_panc8`` (why PR #275's panel A sat above the paper): panel
  A's read-out on subsample 1 with one setting changed at a time: the
  hard-coded seeds, the cap on GT pairs, or no integration
  (``panc8_lisi_checks.R``, `CHECK_GROUPS`).

Usage:

    uv run cccrise-scriabin-reproduction --analysis downsampling
    uv run cccrise-scriabin-reproduction --analysis downsampling_programs
    uv run cccrise-scriabin-reproduction --analysis lisi_checks
"""

import argparse
import json
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd

from ._cli import parse_command
from .datasets import SCRIABIN_REPRODUCTION_DIR
from .provenance import REPO_ROOT, build_metadata, git_sha, write_table
from .run_scriabin_seeds import best_match

HEADER = """\
The Scriabin paper's Fig. 2d-e rerun on panc8 (figureR_scriabin).
Generated by cccrise.runners.run_scriabin_reproduction -- do not hand-edit.
"""
RUNS_DIR = REPO_ROOT / "rcheck" / "out" / "scriabin_reproduction"
SCRIPTS = "cccrise/comparators/scriabin"
#: Each analysis' run folder under `RUNS_DIR` and its R script
RUNS = {
    "downsampling": ("noise", f"{SCRIPTS}/panc8_noise.R"),
    "downsampling_programs": ("programs", f"{SCRIPTS}/panc8_programs.R"),
    "lisi_checks": ("lisi_checks", f"{SCRIPTS}/panc8_lisi_checks.R"),
}
#: Fig. 2e's inDrop coverage, UMIs per cell
INDROP_UMI = 5828
#: The paper's read-out: a GT pair is "recapitulated" at LISI > 1 (above
#: rounding)
LISI_ABOVE = 1 + 1e-6
#: The downsampled arms the CCIM integration scores, and their names here
ARMS = {"down1": "raw", "down1_alra": "alra"}
#: The program comparisons of each subsample: (run, run) -> name; GT is the
#: full depth, down1 and down2 independent downsampling draws
COMPARISONS = {
    ("gt", "down1"): "gt_vs_downsampled",
    ("gt", "down1_alra"): "gt_vs_downsampled_alra",
    ("down1", "down2"): "two_draws",
    ("down1_alra", "down2_alra"): "two_draws_alra",
}
#: panc8_lisi_checks.R's settings by what they change (setting-name prefix)
CHECK_GROUPS = {
    "base": "PR #275's setting: 10,000 sampled GT pairs",
    "gt_sct_seed": "GT CCIM's hard-coded SCTransform seed",
    "hardcoded": "every hard-coded seed R reaches (SCTransform, RunPCA)",
    "cca_": "GT pairs entering integration (90,000: all)",
    "none_": "no integration",
}
_R_DUMP = """
.libPaths(c(normalizePath("rcheck/lib"), .libPaths()))
for (f in list.files(commandArgs(TRUE)[1], "\\\\.rds$", full.names = TRUE, recursive = TRUE))
  jsonlite::write_json(readRDS(f), sub("\\\\.rds$", ".json", f), auto_unbox = TRUE,
                       na = "null", digits = NA, dataframe = "rows")
"""


def load_runs(folder: Path) -> dict[str, dict]:
    """Every R run (``.rds``) under `folder`, by path relative to it, through
    a JSON dump written beside it."""
    if not any(folder.rglob("*.rds")):
        raise FileNotFoundError(f"no R runs under {folder}; see {SCRIPTS}/README.md")
    subprocess.run(["Rscript", "-e", _R_DUMP, str(folder)], check=True, cwd=REPO_ROOT)
    return {
        str(f.relative_to(folder).with_suffix("")): json.loads(f.read_text())
        for f in sorted(folder.rglob("*.json"))
    }


def _sets(modules: dict) -> list[set]:
    """A run's programs as sets of LR pairs; jsonlite unboxes a one-pair
    program to a string."""
    return [set(v) if isinstance(v, list) else {v} for v in modules.values()]


def downsampling(runs: dict[str, dict]) -> pd.DataFrame:
    return pd.DataFrame(
        [
            {
                "Subsample": run["index"],
                "Arm": ARMS[row["arm"]],
                "Pairs": row["n_pairs"],
                "FractionLisiAbove1": row["frac_lisi_gt_1"],
                "MeanLisi": row["lisi_mean"],
                "CcimSpearman": row["ccim_spearman"],
                "FoldDownsampled": 1 / run["prop"],
                # both draws' means in the figure's runs, draw 1's alone since
                "DownsampledMeanUmis": np.atleast_1d(run["downsampled_mean_counts"])[0],
            }
            for run in runs.values()
            for row in run["lisi"]
        ]
    )


def _significant(arm: dict) -> list[set]:
    """An arm's programs that pass the significance test (`kept`; jsonlite
    unboxes a single name)."""
    kept = arm["kept"] if isinstance(arm["kept"], list) else [arm["kept"]]
    return [s for k, s in zip(arm["modules"], _sets(arm["modules"])) if k in kept]


def downsampling_programs(runs: dict[str, dict]) -> pd.DataFrame:
    rows = []
    for run in runs.values():
        programs = run["programs"]
        for (a, b), name in COMPARISONS.items():
            sa, sb = (_significant(programs[x]) for x in (a, b))
            aa, ab = (_sets(programs[x]["modules"]) for x in (a, b))
            rows.append(
                {
                    "Subsample": run["index"],
                    "Comparison": name,
                    "ProgramsA": len(sa),
                    "ProgramsB": len(sb),
                    "Agreement": best_match(sa, sb),
                    "AllProgramsA": len(aa),
                    "AllProgramsB": len(ab),
                    "AgreementAllPrograms": best_match(aa, ab),
                }
            )
    return pd.DataFrame(rows)


def _check_group(setting: str) -> str:
    return next(g for g in CHECK_GROUPS if setting.startswith(g))


def lisi_checks(runs: dict[str, dict]) -> pd.DataFrame:
    rows = []
    for run in runs.values():
        lisi = np.asarray(run["lisi"], float)
        rows.append(
            {
                "Subsample": run["index"],
                "Arm": ARMS[run["arm"]],
                "Group": _check_group(run["setting"]),
                "Setting": run["setting"],
                "Integration": run["reduction"],
                "Pairs": run["cap"],
                "FractionLisiAbove1": float(np.mean(lisi > LISI_ABOVE)),
                "MeanLisi": float(lisi.mean()),
                "Minutes": run["minutes"],
            }
        )
    return pd.DataFrame(rows).sort_values(
        ["Subsample", "Arm", "Group", "Pairs"], ignore_index=True
    )


ANALYSES = {
    "downsampling": downsampling,
    "downsampling_programs": downsampling_programs,
    "lisi_checks": lisi_checks,
}
SETTINGS = {
    "downsampling": {"indrop_umi": INDROP_UMI, "lisi_above": LISI_ABOVE},
    "downsampling_programs": {
        "comparisons": {f"{a} vs {b}": n for (a, b), n in COMPARISONS.items()},
        "power": "upstream InteractionPrograms' own (R^2 0.6; 1 if none or above 3)",
    },
    "lisi_checks": {"lisi_above": LISI_ABOVE, "groups": CHECK_GROUPS},
}


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--analysis", choices=tuple(ANALYSES), required=True)
    return parser


def main(argv: list[str] | None = None) -> None:
    args, command = parse_command(build_parser(), "cccrise-scriabin-reproduction", argv)
    git_sha()  # pin the code version before anything runs (`provenance.git_sha`)
    folder, script = RUNS[args.analysis]
    runs = load_runs(RUNS_DIR / folder)
    table = ANALYSES[args.analysis](runs)
    metadata = build_metadata(
        {
            "analysis": args.analysis,
            "dataset": "panc8",
            "runs": f"rcheck/out/scriabin_reproduction/{folder}",
            "script": script,
            "subsamples": sorted({int(v) for v in table.Subsample}),
        }
        | SETTINGS[args.analysis]
    )
    path = SCRIABIN_REPRODUCTION_DIR / f"{args.analysis}_panc8.parquet"
    write_table(path, table, metadata, command, HEADER)


if __name__ == "__main__":
    main()
