HEADER = """\
The ALAD tables behind Figure 2's component 5 groups and Figure 3's program
tests, from the finalized factor fit and the cohort's cells. Generated by
cccrise.runners.run_alad_programs -- do not hand-edit.
"""
#: Figure 2's differential expression: (groups, reference) per scanpy call
#: Figure 2's differential expression: (groups, reference, cutoffs) per scanpy
#: call; "rest" is every other cell. Sender against receiver is also swept over
#: the group cutoff for the component 5 identity supplement (`DE_TAUS`).
DE_TAUS = tuple(float(tau) for tau in np.round(np.arange(0.1, 0.61, 0.05), 2))
GROUP_TESTS: tuple[tuple[tuple[str, ...], str, tuple[float, ...]], ...] = (
    (DE_GROUPS, "rest", (GROUP_TAU,)),
    (("sender",), "receiver", DE_TAUS),
)
#: Figure 3G-H's contrast: the 6-month outcome collapsed to CLAD/Died vs.
#: Stable/Recovered (no CLAD)
CONTRAST_COLUMN = "6monthcondition"
CASE_LABEL = "CLAD/Died"
CONTROL_LABEL = "Stable/Recovered"
CONTRAST_MAPPING = {
    "CLAD": CASE_LABEL,
    "Died": CASE_LABEL,
    "No CLAD/Stable": CONTROL_LABEL,
    "No CLAD/Recovered": CONTROL_LABEL,
}
N_PERMS = 10_000
SIG_ALPHA = 0.05


def cell_groups(adata: anndata.AnnData, tau: float = GROUP_TAU) -> np.ndarray:
    """Each cell's Figure 2 group at `tau` (`split_cells` on the granularity
    component's per-cell weights), "rest" if in none."""
    k = GRANULARITY_COMPONENT - 1
    groups = split_cells(adata.obsm["sc_B"][:, k], adata.obsm["rc_C"][:, k], tau)
    labels = np.full(adata.n_obs, "rest", dtype=object)
    for group, mask in groups.items():
        labels[mask] = group
    assert set(labels) <= set(GROUPS)
    return labels


def group_de(adata: anndata.AnnData) -> pd.DataFrame:
    """scanpy's Wilcoxon test of each `GROUP_TESTS` comparison at each of its
    cutoffs, one row per comparison, cutoff and gene; each call on its own
    copy of the cells."""
    frames = []
    for groups, reference, taus in GROUP_TESTS:
        for tau in taus:
            labels = cell_groups(adata, tau)
            test = anndata.AnnData(
                X=adata.X,
                obs=pd.DataFrame({"group": labels}, index=adata.obs_names),
                var=pd.DataFrame(index=adata.var_names),
            )
            sc.tl.rank_genes_groups(
                test,
                "group",
                groups=list(groups),
                reference=reference,
                method="wilcoxon",
            )
            result = test.uns["rank_genes_groups"]
            frames += [
                comparison_rows(adata, labels, result, group, reference, tau)
                for group in groups
            ]
    return pd.concat(frames, ignore_index=True)


def comparison_rows(
    adata: anndata.AnnData,
    labels: np.ndarray,
    result: Any,
    group: str,
    reference: str,
    tau: float,
) -> pd.DataFrame:
    """One comparison's genes, in scanpy's order, with the fraction of the
    group's and of the reference's cells detecting each ('rest': every cell
    outside `group`, as scanpy tests it)."""
    genes = pd.Index(result["names"][group])
    position = adata.var_names.get_indexer(genes)
    in_reference = labels != group if reference == "rest" else labels == reference
    return pd.DataFrame(
        {
            "Tau": tau,
            "Group": group,
            "Reference": reference,
            "Gene": genes,
            "Score": result["scores"][group],
            "P": result["pvals"][group],
            "Q": result["pvals_adj"][group],
            "Group detected": detected_fraction(adata, labels == group)[position],
            "Reference detected": detected_fraction(adata, in_reference)[position],
        }
    )


def detected_fraction(adata: anndata.AnnData, cells: np.ndarray) -> np.ndarray:
    """Per gene, the fraction of `cells` with positive expression; sparse-safe,
    never densifying the cells."""
    X = cast(Any, adata.X)
    return np.asarray((X[cells] > 0).sum(axis=0)).ravel() / cells.sum()


def contrast(adata: anndata.AnnData, spec: DatasetSpec) -> pd.DataFrame:
    """Per condition (np.unique order, as the CP condition factor): its
    patient, CLAD/Died vs. No CLAD group and read depth (total normalized
    expression over its cells)."""
    obs = cast(pd.DataFrame, adata.obs)
    cond = spec.condition_column
    labels = prepare_group_labels(
        get_sample_to_group(adata, cond, CONTRAST_COLUMN), mapping=CONTRAST_MAPPING
    )
    patients = obs.drop_duplicates(cond).set_index(cond).loc[labels.index]
    depth = np.bincount(
        obs["condition_unique_idxs"].astype(int),
        weights=np.asarray(cast(Any, adata.X).sum(axis=1)).ravel(),
    )
    return pd.DataFrame(
        {
            "Condition": labels.index.to_numpy(),
            "Patient": patients[spec.patient_column].astype(str).to_numpy(),
            "Group": labels.to_numpy(),
            "Read depth": depth,
        }
    )


def lr_association(scores: np.ndarray, adata: anndata.AnnData, spec) -> pd.DataFrame:
    """The component ANOVA against `OUTCOME` on each column of `scores`
    (conditions x LR pairs) in place of the condition loadings."""
    tested = copy.copy(adata)
    tested.uns = {**adata.uns, "A": scores}
    return run_multiple_factors_anova(
        tested,
        [association(OUTCOME)],
        condition_column=spec.condition_column,
        correction="fdr_bh",
    )


def covariation_table(
    scores: np.ndarray, top: np.ndarray, associated: np.ndarray, seed: int, genes
) -> pd.DataFrame:
    """`COMPONENT`'s top pairs' pairwise rank correlations (one draw) and the
    baselines' draws, those sharing a gene of `genes` averaged into one, long,
    keeping each draw's pair-of-pairs index."""
    sets = {
        "Top pairs": pairwise_rank_correlations(scores, top, genes, merge=True)[None]
    } | covariation_baselines(scores, top, associated, seed, genes, merge=True)
    return pd.concat(
        pd.DataFrame(draws)
        .rename_axis(index="Draw", columns="Pair of pairs")
        .stack()
        .dropna()  # a draw's padding, past its merged pairs' correlations
        .rename("Rank correlation")
        .reset_index()
        .assign(Component=COMPONENT, Set=name)
        for name, draws in sets.items()
    )


def pair_tests(
    tensor: np.ndarray, factors, groups: pd.DataFrame, seed: int
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Per component, every LR pair's permutation test in its own context
    (`program_pair_tests`), and `COMPONENT`'s top pairs' nulls
    (`program_permutation`)."""
    lr = factors["lr_pair"].values.astype(str)
    case = (groups["Group"] == CASE_LABEL).to_numpy()
    depth = groups["Read depth"].to_numpy()
    tests, permutation = [], None
    for k in range(1, factors["cp_D"].shape[1] + 1):
        B, C, D = (
            factors[m].values[:, k - 1].astype(float) for m in ("cp_B", "cp_C", "cp_D")
        )
        scores = context_scores(tensor, B, C) / depth[:, None]
        observed, null = patient_permutation_differential(
            scores, case, groups["Patient"].to_numpy(), N_PERMS, seed
        )
        p = ((null >= observed).sum(0) + 1) / (N_PERMS + 1)
        rank = np.empty(len(lr), dtype=int)
        rank[np.argsort(-np.abs(D))] = np.arange(1, len(lr) + 1)
        test = pd.DataFrame(
            {
                "Component": k,
                "LR pair": lr,
                "Rank": rank,
                "Observed": observed,
                "P": p,
                f"{CASE_LABEL} mean": scores[case].mean(0),
                f"{CONTROL_LABEL} mean": scores[~case].mean(0),
            }
        )
        tests.append(test)
        if k == COMPONENT:
            permutation = permutation_table(test, null, top_pairs(D))
    assert permutation is not None
    return pd.concat(tests, ignore_index=True), permutation


def permutation_table(
    test: pd.DataFrame, null: np.ndarray, top: np.ndarray
) -> pd.DataFrame:
    """The `top` pairs' nulls (permutations x LR pairs, every pair's column of
    `null`), long, with each pair's `test` row (component, rank, observed
    difference, p)."""
    return (
        pd.DataFrame(null[:, top], columns=test["LR pair"].to_numpy()[top])
        .rename_axis("Permutation")
        .reset_index()
        .melt("Permutation", var_name="LR pair", value_name="Null difference")
        .merge(
            test[["Component", "LR pair", "Rank", "Observed", "P"]],
            on="LR pair",
            how="left",
            validate="many_to_one",
        )
    )


def run_alad_programs(spec: DatasetSpec, random_state: int, command: str) -> None:
    git_sha()  # pin the code version before anything runs (`provenance.git_sha`)
    factors = load_factors_netcdf(spec.factors_path())
    lr = factors["lr_pair"].values.astype(str)
    print("1. Loading the cohort, projecting it, rebuilding its tensor...", flush=True)
    raw = spec.load()
    adata, _, _ = _resolve_factors_and_metadata(
        spec.factors_path(), adata=raw, condition_column=spec.condition_column
    )
    tensor = cccrise_tensor(spec.factors_path(), raw, spec.condition_column)
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_path": relpath(spec.factors_path()),
            "factors_sha256": sha256_file(spec.factors_path()),
            "random_state": random_state,
            "n_perms": N_PERMS,
            "n_top": N_TOP,
            "component": COMPONENT,
            "outcome": OUTCOME,
            "granularity_component": GRANULARITY_COMPONENT,
            "group_tests": [[list(g), r, list(taus)] for g, r, taus in GROUP_TESTS],
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=len(lr)),
        }
    )

    def write(name: str, table: pd.DataFrame) -> None:
        path = ALAD_PROGRAMS_DIR / scores_filename(name, spec.output_key)
        write_table(path, table, metadata, command, HEADER)

    print("2. Figure 2 group tests...", flush=True)
    write("group_de", group_de(adata))
    print("3. Figure 3 program tests...", flush=True)
    groups = contrast(adata, spec)
    B, C, D = (
        factors[m].values[:, COMPONENT - 1].astype(float)
        for m in ("cp_B", "cp_C", "cp_D")
    )
    scores = context_scores(tensor, B, C)
    association_table = lr_association(scores, adata, spec)
    write(
        "program_context_scores",
        pd.DataFrame(scores, columns=lr)
        .assign(**groups.to_dict("series"))
        .melt(id_vars=list(groups.columns), var_name="LR pair", value_name="Score")
        .assign(Component=COMPONENT),
    )
    write(
        "program_lr_association",
        association_table[["F", "P", "PAdj", "EtaSquared"]]
        .reset_index(drop=True)
        .assign(Component=COMPONENT, **{"LR pair": lr}),
    )
    associated = association_table["PAdj"].to_numpy() < SIG_ALPHA
    write(
        "program_covariation",
        covariation_table(
            scores,
            top_pairs(D),
            associated,
            random_state,
            lr_pair_genes(lr, factors.attrs["complex_sep"]),
        ),
    )
    tests, permutation = pair_tests(tensor, factors, groups, random_state)
    write("program_pair_tests", tests)
    write("program_permutation", permutation)


def build_parser() -> argparse.ArgumentParser:
    return seeded_dataset_parser(__doc__)


def main(argv: list[str] | None = None) -> None:
    args, command = parse_command(build_parser(), "cccrise-alad-programs", argv)
    spec = resolve_dataset(args)
    if spec.key != "alad":
        raise SystemExit(
            "cccrise-alad-programs reads ALAD's outcomes; run it with --dataset alad"
        )
    run_alad_programs(spec, args.random_state, command)


if __name__ == "__main__":
    main()
