"""
Runner: the ALAD tables behind Figure 2's component 5 groups and Figure 3's
tests of the outcome program, from the finalized fit and one load of the
cohort's cells. The ALAD counterpart of `run_ibd_programs`; it does not refit
RISE/CPD. Writes, into `ALAD_PROGRAMS_DIR` (one `provenance.yaml` for the
folder):

    group_de_alad.parquet
        Figure 2M and the component 5 identity supplement: per comparison
        (`GROUP_TESTS`: each of the component's sender and receiver groups
        against every other cell, and sender against receiver, the latter also
        at each cutoff of `DE_TAUS`), cutoff and gene,
        scanpy's two-sided Wilcoxon rank-sum score, p and Benjamini-Hochberg q
        across genes, in scanpy's order (highest score first), and the
        fraction of each side's cells detecting the gene
    program_context_scores_alad.parquet
        Figure 3E-G: each LR pair's raw score per condition in `COMPONENT`'s
        sender/receiver context (`covariation.context_scores`), with the
        condition's patient, CLAD/Died vs. No CLAD group and read depth
    program_lr_association_alad.parquet
        Figure 3E: each LR pair's one-way ANOVA of its read-depth-corrected
        context scores over the 6-month outcome (F, p, Benjamini-Hochberg q
        across pairs, eta^2), as the component's loadings are tested
    program_covariation_alad.parquet
        Figure 3F: the pairwise rank correlations across conditions of
        `COMPONENT`'s top LR pairs, and of `covariation_baselines`' draws
        (random, expression-matched, other outcome-associated), each set's
        pairs sharing a ligand or receptor gene first averaged into one
        (`pairwise_rank_correlations` with `merge`), each draw's pairs of
        pairs indexed as it orders them
    program_permutation_alad.parquet
        Figure 3G: `COMPONENT`'s top pairs' CLAD/Died minus No CLAD mean
        depth-normalized context score, its patient-block permutation null and
        one-sided p (as `program_permutation_ibd`)
    program_pair_tests_alad.parquet
        Figure 3G-H: per component and LR pair, its rank by |loading|, the
        observed difference, both group means and the one-sided permutation p,
        each pair scored in its own component's context

    uv run cccrise-alad-programs --dataset alad

Both random draws use `--random-state` as the figure code they replace did:
the baselines' draws, and one set of patient-block permutations shared by
every component.
"""

