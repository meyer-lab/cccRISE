#!/usr/bin/env python
"""
Runner: Per-component stability during patient jackknifing and seed-refitting.

This runner measures whether the components recovered at fixed ranks survive leaving
each patient out: per replicate, each reference component's factor match score against
its best-matching replicate component, and that replicate component's one-way ANOVA
against the outcome.

One replicate loop serves all three analyses. A replicate refits RISE once,
scores RISE stability from that fit, then builds the communication tensor
from the *same* fit, scores CPD stability, and re-runs the ANOVA on that same
CP fit -- so a replicate's RISE, CPD and ANOVA rows describe the same data,
and the expensive PARAFAC2 fit is paid for once instead of once per analysis.

Axes, and what each one asks:

  jackknife   One patient (all of its conditions) left out per replicate,
              every patient in turn, so it always runs one replicate per
              patient whatever --n-replicates is. The influence of each
              patient on every component and association.
  seed_only   Identical data refit end to end (RISE -> communication tensor
              -> CP) from a different random seed: the reproducibility
              ceiling the jackknife is read against.

Components are matched, and the FMS computed, on the non-eigen-state modes,
holding out the condition mode on the jackknife (`validation.axis_skip_modes`).
Writes one row per (axis, replicate, stage, component); CPD rows also carry
the matched component's ANOVA statistics:

    component_stability_<dataset>.parquet

    uv run cccrise-stability --dataset alad --rise-rank 17 --cp-rank 5 \
        --n-replicates 47
"""

