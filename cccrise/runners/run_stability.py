HEADER = """\
Per-component RISE and CPD stability, and CP component--outcome ANOVA
stability, at fixed ranks under patient jackknifing and seed refitting.
Generated by cccrise.runners.run_stability -- do not hand-edit.
"""


def run_stability(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    axes: tuple[str, ...] = DEFAULT_AXES,
    n_replicates: int = 100,
    group_column: str | None = None,
    control_label: str | None = None,
    other_label: str | None = None,
    ci_level: float = 95.0,
    alpha: float = 0.05,
    rise_n_iter_max: int = RISE_N_ITER_MAX,
    rise_tol: float = RISE_TOL,
    cp_n_iter_max: int = CP_N_ITER_MAX,
    cp_tol: float = CP_TOL,
    complex_sep: str | None = "&",
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
    random_state: int = 42,
    cp_device: str | None = None,
    cp_dtype: str = CP_DTYPE,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Score per-component RISE, CPD and ANOVA stability at fixed ranks.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank, cp_rank : int
        The already-selected ranks. Stability is a claim about the chosen
        model, so both are fixed rather than swept.
    axes : tuple[str, ...], default=DEFAULT_AXES
        Axes to run; see the module docstring.
    n_replicates : int, default=100
        Replicates on the seed axis; the jackknife runs one per patient.
    group_column : str, optional
        Column in `adata.obs` carrying the outcome the CP components are
        tested against. Defaults to `spec.outcome_column` (every level tested), else
        `spec.group_column`.
    control_label, other_label : str, optional
        Values of `group_column` mapped to the reference and other class.
        Default to `_cli.DEFAULT_GROUP_LABELS[spec.key]` when not given.
    ci_level : float, default=95.0
        Central percentile interval width on eta-squared in the printed summary.
    alpha : float, default=0.05
        Significance threshold for the printed summary's `FracSignificant`.
    rise_n_iter_max, rise_tol, cp_n_iter_max, cp_tol
        Fitting controls for the RISE and CP fits.
    complex_sep, communication_score, hill_k
        Communication-tensor options; see `ccc_rise.calc_communication_score`.
    random_state : int, default=42
        Base seed for the reference fit and the replicates.
    cp_device, cp_dtype
        Device and precision of every CP fit; see `ccc_rise.fit_cp`.
    output_path : Path, optional
        Parquet destination; defaults to the registry's stability filename under
        `VALIDATION_DIR` for `communication_score="expression_product"`, or
        `comparison_output_dir(communication_score)`
        (under `validation_results/alt_score_methods/`) for any other score.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The long per-component table, the output path, and the sidecar path.
    """
    group_column, control_label, other_label = resolve_anova_labels(
        spec, group_column, control_label, other_label
    )
    output_path = output_path or (
        scoring_output_dir(communication_score, VALIDATION_DIR)
        / spec.stability_filename()
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== Component and association stability: {spec.label} ===")
    print(f"    RISE rank {rise_rank}, CP rank {cp_rank}, {n_replicates} replicates")
    print(f"    Axes: {', '.join(axes)}")
    print(
        f"    alpha={alpha}  group_column={group_column!r}  "
        f"control={control_label!r}  other={other_label!r}"
    )
    print(
        f"    backend={spec.backend or 'auto'}  compress (RISE)={REPLICATE_COMPRESS}"
        f"  cp_device={cp_device or 'auto'}  cp_dtype={cp_dtype}"
    )

    print("1. Loading data...")
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()
    print(f"   AnnData shape: {adata.shape}")
    print(f"   Ligand-receptor pairs: {len(lr_pairs)}")
    per_axis = _replicates_per_axis(adata, spec, axes, n_replicates)

    anova_kwargs: dict[str, Any] = {
        "group_column": group_column,
        "control_label": control_label,
        "other_label": other_label,
    }
    fit_kwargs: dict[str, Any] = {
        "condition_column": spec.condition_column,
        "rise_rank": rise_rank,
        "cp_rank": cp_rank,
        "rise_n_iter_max": rise_n_iter_max,
        "rise_tol": rise_tol,
        "cp_n_iter_max": cp_n_iter_max,
        "cp_tol": cp_tol,
        "complex_sep": complex_sep,
        "communication_score": communication_score,
        "hill_k": hill_k,
        "backend": spec.backend,
        "compress": REPLICATE_COMPRESS,
        "cp_device": cp_device,
        "cp_dtype": cp_dtype,
    } | anova_kwargs

    core = core_numbering_reference(spec, rise_rank, cp_rank)
    print("2. Fitting the reference model on the full cohort...")
    reference = fit_stability_pipeline(
        adata.copy(),
        lr_pairs,
        **fit_kwargs,
        random_state=random_state,
        numbering_reference=core,
    )
    assert reference["anova"] is not None
    tensor_shape = tuple(int(f.shape[0]) for f in reference["cp_factors"])
    print(f"   Interaction tensor shape: {tensor_shape}")
    print(f"   RISE R2X {reference['r2x_rise']:.4f}, CP R2X {reference['r2x_cp']:.4f}")

    print("3. Running replicates...")
    df = stability_replicates(
        adata,
        reference,
        lr_pairs,
        **fit_kwargs,
        patient_column=spec.patient_column,
        axes=axes,
        n_replicates=n_replicates,
        random_state=random_state,
    )

    # Label each component by the LR pair it loads onto hardest in the
    # reference fit, so the summary can name components clearly.
    labels = top_lr_pairs(
        reference["cp_factors"][3], reference["lr_symbols"], top_n=1
    ).set_index("Component")
    print("4. Summaries:")
    _print_summaries(df, reference["anova"], labels["LRPair"], ci_level, alpha)

    print(f"5. Writing {len(df)} rows to {output_path}...")
    df.to_parquet(output_path, index=False)

    reference_anova = reference["anova"]
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "rise_rank": rise_rank,
            "cp_rank": cp_rank,
            "axes": list(axes),
            "n_replicates": n_replicates,
            "n_replicates_per_axis": per_axis,
            "jackknife_unit": _jackknife_unit(spec),
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "ci_level": ci_level,
            "alpha": alpha,
            "patient_column": spec.patient_column,
            "rise_n_iter_max": rise_n_iter_max,
            "rise_tol": rise_tol,
            "cp_n_iter_max": cp_n_iter_max,
            "cp_tol": cp_tol,
            "cp_fit_options": CP_FIT_OPTIONS,
            "complex_sep": complex_sep,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "random_state": random_state,
            "backend": spec.backend or "auto",
            "compress": REPLICATE_COMPRESS,
            **cp_device_metadata(cp_device, cp_dtype),
            "rise_compression_options": RISE_COMPRESSION_OPTIONS,
            "seed_formula": (
                "random_state * 1000 + replicate + 1 seeds a replicate's RISE "
                "and CP fits (see validation.replicate_seed). On the seed_only "
                "axis the seed is the only thing that differs from the "
                "reference: same cells, same conditions, same ligand-receptor "
                "pairs"
            ),
            "replicates": _replicate_description(spec),
            "fms_definition": (
                "congruence product across compared modes, weights ignored (see "
                "validation.per_component_fms); components matched on the same "
                "modes"
            ),
            "fms_modes": _fms_modes(axes),
            "anova_alignment": (
                "each replicate's ANOVA statistics carried onto the reference "
                "component its CP component was matched to by the CPD FMS; "
                "GroupMeanDiff sign-corrected by the condition mode's signed "
                "cosine, or the LR mode's where the condition mode is held out "
                "(see validation._attach_anova); a group left with one condition "
                "stays in the test as a group of one"
            ),
            "component_numbering": component_numbering(core),
            "lr_roster_stable": True,
            "interaction_tensor_shape": list(tensor_shape),
            "r2x_pf2": float(reference["r2x_rise"]),
            "r2x_cp": float(reference["r2x_cp"]),
            "reference_eta_squared": reference_anova["EtaSquared"].tolist(),
            "reference_f": reference_anova["F"].tolist(),
            "reference_p": reference_anova["P"].tolist(),
            "reference_p_adj": reference_anova["PAdj"].tolist(),
            "reference_group_mean_diff": reference_anova["GroupMeanDiff"].tolist(),
            "reference_top_lr_pair": labels["LRPair"].tolist(),
            "reference_top_lr_loading": labels["DLoading"].astype(float).tolist(),
            "n_components_significant": int((reference_anova["PAdj"] < alpha).sum()),
            "reference_seed": random_state,
            "first_replicate_seed": replicate_seed(random_state, 0),
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=tensor_shape[3]),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")

    return df, output_path, sidecar


def _fms_modes(axes: tuple[str, ...]) -> dict[str, dict[str, list[int]]]:
    """The modes each stage's FMS compares on each axis, for the sidecar."""
    return {
        stage: {
            axis: [m for m in range(n_modes) if m not in axis_skip_modes(stage, axis)]
            for axis in axes
        }
        for stage, n_modes in ((STAGE_RISE, 3), (STAGE_CPD, 4))
    }


def _jackknife_unit(spec: DatasetSpec) -> str:
    """The column the jackknife leaves one value of out per replicate."""
    return spec.patient_column or spec.condition_column


def _replicates_per_axis(
    adata, spec: DatasetSpec, axes: tuple[str, ...], n_replicates: int
) -> dict[str, int]:
    """Replicates each axis runs -- one per patient on the jackknife -- with
    the fit counts they cost printed."""
    n_patients = len(jackknife_units(adata, _jackknife_unit(spec)))
    per_axis = {a: n_patients if a == JACKKNIFE_AXIS else n_replicates for a in axes}
    print(f"   Replicates per axis: {per_axis}")
    print(f"   {1 + sum(per_axis.values())} PARAFAC2 and CP fits")
    return per_axis


def _print_summaries(
    df: pd.DataFrame,
    reference_anova: pd.DataFrame,
    top_lr_pair: pd.Series,
    ci_level: float,
    alpha: float,
) -> None:
    """Print the aggregate and per-component FMS, and the per-component ANOVA
    stability on every axis that was run."""
    print("   Aggregate FMS across replicates, per stage and axis:")
    print(metric_interval(df, "FMS", by=("Stage", "Axis")).to_string(index=False))
    print("   Per-component stability:")
    print(summarize_component_stability(df).to_string(index=False))
    for axis in df["Axis"].unique():
        print(f"   Per-component ANOVA stability on the {axis!r} axis:")
        summary = summarize_anova_stability(
            df, reference_anova, axis, ci_level=ci_level, alpha=alpha
        )
        print(summary.join(top_lr_pair, on="Component").to_string(index=False))


def _replicate_description(spec: DatasetSpec) -> dict[str, str]:
    """The sidecar's per-axis description of what each replicate refits."""
    return {
        SEED_AXIS: (
            "identical data refit end to end (RISE -> communication "
            "tensor -> CP) under a different random seed"
        ),
        JACKKNIFE_AXIS: (
            f"one {_jackknife_unit(spec)} left out per replicate (all of its "
            "conditions), every one in turn in sorted order "
            "(utils.jackknife_units); refit end to end; the left-out patient "
            "is the 'LeftOut' column"
        ),
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank every fit uses; see rank_selection.select_rise_rank.",
    )
    parser.add_argument(
        "--cp-rank",
        type=int,
        required=True,
        help="CP rank every fit uses; see rank_selection.select_cpd_rank.",
    )
    parser.add_argument(
        "--axes",
        type=str,
        default=",".join(DEFAULT_AXES),
        help=(
            "Comma-separated axes: jackknife leaves one patient out per "
            "replicate; seed_only varies only the fits' starting point. "
            f"Options: {', '.join(DEFAULT_AXES)}."
        ),
    )
    parser.add_argument(
        "--n-replicates",
        type=int,
        default=100,
        help="Seed-only replicates; the jackknife always runs one per patient.",
    )
    add_group_arguments(parser)
    parser.add_argument(
        "--ci-level",
        type=float,
        default=95.0,
        help="Central percentile interval width on eta-squared, in percent (default: 95).",
    )
    parser.add_argument(
        "--alpha",
        type=float,
        default=0.05,
        help="Significance threshold for FracSignificant (default: 0.05).",
    )
    parser.add_argument("--rise-n-iter-max", type=int, default=RISE_N_ITER_MAX)
    parser.add_argument("--rise-tol", type=float, default=RISE_TOL)
    parser.add_argument("--cp-n-iter-max", type=int, default=CP_N_ITER_MAX)
    parser.add_argument("--cp-tol", type=float, default=CP_TOL)
    add_cp_device_arguments(parser)
    parser.add_argument("--complex-sep", type=str, default="&")
    add_scoring_arguments(parser)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Parquet destination; defaults to component_stability_<dataset>.parquet in "
        "data/validation_results/ (its alt_score_methods/<score>/ for a "
        "non-default score).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = resolve_dataset(args)
    run_stability(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        axes=tuple(axis.strip() for axis in args.axes.split(",") if axis.strip()),
        n_replicates=args.n_replicates,
        group_column=args.group_column,
        control_label=args.control_label,
        other_label=args.other_label,
        ci_level=args.ci_level,
        alpha=args.alpha,
        rise_n_iter_max=args.rise_n_iter_max,
        rise_tol=args.rise_tol,
        cp_n_iter_max=args.cp_n_iter_max,
        cp_tol=args.cp_tol,
        complex_sep=args.complex_sep,
        communication_score=args.communication_score,
        hill_k=args.hill_k,
        random_state=args.random_state,
        cp_device=args.cp_device,
        cp_dtype=args.cp_dtype,
        output_path=resolve_output(
            args.output,
            scoring_output_dir(args.communication_score, VALIDATION_DIR),
            spec.stability_filename(),
        ),
    )


if __name__ == "__main__":
    main()
