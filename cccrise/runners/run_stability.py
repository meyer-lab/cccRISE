#!/usr/bin/env python
"""
Runner: are the components CCC-RISE reports, and their phenotype associations,
reproducible under resampling?

Both ranks are already chosen (see `rank_selection.select_rise_rank` and
`select_cpd_rank` for the rules, and issue #168 for the pinned values), so this
runner takes them as inputs rather than producing them. What it measures is
whether the components recovered at those ranks survive resampling the data:
per replicate, each reference component's factor match score against its
best-matching replicate component, and that replicate component's one-way
ANOVA against the outcome.

One replicate loop serves all three analyses. A replicate resamples the
AnnData once, refits RISE once, scores RISE stability from that fit, then
builds the communication tensor from the *same* fit, scores CPD stability, and
re-runs the ANOVA on that same CP fit -- so a replicate's RISE, CPD and ANOVA
rows describe the same resampled dataset, and the expensive PARAFAC2 fit is
paid for once instead of once per analysis.

Axes, and what each one asks:

  cells       Cells bootstrapped with replacement within each condition, the
              cohort held fixed. Robustness to which cells were captured and
              to sequencing depth. Refits RISE.
  conditions  Whole conditions bootstrapped with replacement, drawn within
              outcome strata, keeping every cell of a drawn condition.
              Robustness to which patients were enrolled -- the axis the
              manuscript's claims rest on, and the patient bootstrap of the
              ANOVA effect sizes. Refits RISE.
  lr_pairs    The reference tensor's ligand-receptor mode bootstrapped.
              Robustness to which interactions the database contains. Costs
              no PARAFAC2 fit.
  seed_only   Identical data refit end to end (RISE -> communication tensor
              -> CP) from a different random seed. Refits RISE.

Writes one row per (axis, replicate, stage, component); CPD rows also carry
the matched component's ANOVA statistics:

    component_stability_<dataset>.parquet

    uv run cccrise-stability --dataset alad --rise-rank 17 --cp-rank 5 \
        --n-replicates 100
"""

import argparse
from pathlib import Path
from typing import Any

import pandas as pd

from ..ccc_rise import (
    CP_COMPRESSION_OPTIONS,
    CP_FIT_OPTIONS,
    RISE_COMPRESSION_OPTIONS,
)
from ..import_data import import_ligand_receptor_pairs
from ..validation.stability import (
    DEFAULT_AXES,
    RISE_REFIT_AXES,
    SEED_AXIS,
    fit_stability_pipeline,
    metric_interval,
    replicate_seed,
    stability_replicates,
    summarize_anova_stability,
    summarize_component_stability,
    top_lr_pairs,
)
from ._cli import (
    CP_N_ITER_MAX,
    CP_TOL,
    REPLICATE_COMPRESS,
    RISE_N_ITER_MAX,
    RISE_TOL,
    add_dataset_argument,
    add_group_arguments,
    add_scoring_arguments,
    component_numbering,
    core_numbering_reference,
    dataset_metadata,
    resolve_anova_labels,
    resolve_output,
    resulting_dims,
)
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec, scoring_output_dir
from .provenance import build_metadata, git_sha, write_metadata

HEADER = """\
Per-component RISE and CPD stability, and CP component--outcome ANOVA
stability, at fixed ranks under resampling.
Generated by cccrise.runners.run_stability -- do not hand-edit.
"""


def run_stability(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    axes: tuple[str, ...] = DEFAULT_AXES,
    n_replicates: int = 100,
    group_column: str | None = None,
    control_label: str | None = None,
    other_label: str | None = None,
    ci_level: float = 95.0,
    alpha: float = 0.05,
    stratify: bool = True,
    rise_n_iter_max: int = RISE_N_ITER_MAX,
    rise_tol: float = RISE_TOL,
    cp_n_iter_max: int = CP_N_ITER_MAX,
    cp_tol: float = CP_TOL,
    complex_sep: str | None = "&",
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
    random_state: int = 42,
    output_path: Path | None = None,
    reference: dict[str, Any] | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Score per-component RISE, CPD and ANOVA stability at fixed ranks.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank, cp_rank : int
        The already-selected ranks. Stability is a claim about the chosen
        model, so both are fixed rather than swept.
    axes : tuple[str, ...], default=DEFAULT_AXES
        Resampling axes to run; see the module docstring.
    n_replicates : int, default=100
        Replicates per axis.
    group_column : str, optional
        Column in `adata.obs` carrying the outcome the CP components are
        tested against, and that the 'conditions' draw is stratified within.
        Defaults to `spec.outcome_column` (every level tested), else
        `spec.group_column`.
    control_label, other_label : str, optional
        Values of `group_column` mapped to the reference and other class.
        Default to `_cli.DEFAULT_GROUP_LABELS[spec.key]` when not given.
    ci_level : float, default=95.0
        Central percentile interval width on eta-squared in the printed summary.
    alpha : float, default=0.05
        Significance threshold for the printed summary's `FracSignificant`.
    stratify : bool, default=True
        Draw conditions within each `group_column` stratum, holding the class
        balance fixed; see `utils.resample_conditions`.
    rise_n_iter_max, rise_tol, cp_n_iter_max, cp_tol
        Fitting controls for the RISE and CP fits.
    complex_sep, communication_score, hill_k
        Communication-tensor options; see `ccc_rise.calc_communication_score`.
    random_state : int, default=42
        Base seed for the reference fit and the replicates.
    output_path : Path, optional
        Parquet destination; defaults to the registry's stability filename under
        `VALIDATION_DIR` for `communication_score="expression_product"`, or
        `comparison_output_dir(communication_score)`
        (under `validation_results/alt_score_methods/`) for any other score.
    reference : dict[str, Any], optional
        A full-cohort fit already built with this call's settings (including
        the resolved group labels), as `fit_stability_pipeline(...,
        keep_tensor=True)` returns, and already relabeled to
        `core_numbering_reference`; fit here when None. Lets
        `run_alt_comm_score` share one RISE fit between scores.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The long per-component table, the output path, and the sidecar path.
    """
    group_column, control_label, other_label = resolve_anova_labels(
        spec, group_column, control_label, other_label
    )
    output_path = output_path or (
        scoring_output_dir(communication_score, VALIDATION_DIR)
        / spec.stability_filename()
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    rise_axes = [axis for axis in axes if axis in RISE_REFIT_AXES]
    print(f"=== Component and association stability: {spec.label} ===")
    print(f"    RISE rank {rise_rank}, CP rank {cp_rank}, {n_replicates} replicates")
    print(f"    Axes: {', '.join(axes)}")
    print(
        f"    stratify={stratify}  alpha={alpha}  group_column={group_column!r}  "
        f"control={control_label!r}  other={other_label!r}"
    )
    print(f"    backend={spec.backend or 'auto'}  compress={REPLICATE_COMPRESS}")
    print(
        f"    {1 + len(rise_axes) * n_replicates} PARAFAC2 fits, "
        f"{1 + len(axes) * n_replicates} CP fits"
    )

    print("1. Loading data...")
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()
    print(f"   AnnData shape: {adata.shape}")
    print(f"   Ligand-receptor pairs: {len(lr_pairs)}")

    anova_kwargs: dict[str, Any] = {
        "group_column": group_column,
        "control_label": control_label,
        "other_label": other_label,
    }
    fit_kwargs: dict[str, Any] = {
        "condition_column": spec.condition_column,
        "rise_rank": rise_rank,
        "cp_rank": cp_rank,
        "rise_n_iter_max": rise_n_iter_max,
        "rise_tol": rise_tol,
        "cp_n_iter_max": cp_n_iter_max,
        "cp_tol": cp_tol,
        "complex_sep": complex_sep,
        "communication_score": communication_score,
        "hill_k": hill_k,
        "backend": spec.backend,
        "compress": REPLICATE_COMPRESS,
    } | anova_kwargs

    core = core_numbering_reference(spec, rise_rank, cp_rank)
    if reference is None:
        print("2. Fitting the reference model on the full cohort...")
        reference = fit_stability_pipeline(
            adata.copy(),
            lr_pairs,
            **fit_kwargs,
            random_state=random_state,
            keep_tensor=True,
            numbering_reference=core,
        )
    else:
        print("2. Using the supplied full-cohort reference fit...")
    assert reference["tensor"] is not None and reference["anova"] is not None
    tensor_shape = tuple(int(dim) for dim in reference["tensor"].shape)
    print(f"   Interaction tensor shape: {tensor_shape}")
    print(f"   RISE R2X {reference['r2x_rise']:.4f}, CP R2X {reference['r2x_cp']:.4f}")

    print("3. Running resampled replicates...")
    df = stability_replicates(
        adata,
        reference,
        lr_pairs,
        **fit_kwargs,
        stratify=stratify,
        patient_column=spec.patient_column,
        axes=axes,
        n_replicates=n_replicates,
        random_state=random_state,
    )

    print("4. Aggregate FMS across replicates, per stage and axis:")
    aggregate = metric_interval(df, "FMS", by=("Stage", "Axis"))
    print(aggregate.to_string(index=False))
    print("   Per-component stability:")
    print(summarize_component_stability(df).to_string(index=False))

    # Label each component by the LR pair it loads onto hardest in the
    # reference fit, so the summary can name components clearly.
    labels = top_lr_pairs(
        reference["cp_factors"][3], reference["lr_symbols"], top_n=1
    ).set_index("Component")
    if "conditions" in axes:
        print("   Per-component ANOVA stability under the patient bootstrap:")
        summary = summarize_anova_stability(
            df, reference["anova"], "conditions", ci_level=ci_level, alpha=alpha
        )
        print(summary.join(labels["LRPair"], on="Component").to_string(index=False))

    print(f"5. Writing {len(df)} rows to {output_path}...")
    df.to_parquet(output_path, index=False)

    reference_anova = reference["anova"]
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "rise_rank": rise_rank,
            "cp_rank": cp_rank,
            "axes": list(axes),
            "n_replicates": n_replicates,
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "ci_level": ci_level,
            "alpha": alpha,
            "stratify": stratify,
            "patient_column": spec.patient_column,
            "rise_n_iter_max": rise_n_iter_max,
            "rise_tol": rise_tol,
            "cp_n_iter_max": cp_n_iter_max,
            "cp_tol": cp_tol,
            "cp_fit_options": CP_FIT_OPTIONS,
            "complex_sep": complex_sep,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "random_state": random_state,
            "backend": spec.backend or "auto",
            "compress": REPLICATE_COMPRESS,
            "rise_compression_options": RISE_COMPRESSION_OPTIONS,
            "cp_compression_options": CP_COMPRESSION_OPTIONS,
            "seed_formula": (
                "random_state * 1000 + replicate + 1; one seed drives the "
                "resample, the RISE refit and the CP fit, so a "
                "replicate's RISE, CPD and ANOVA rows are the same resampled "
                "dataset (see validation.replicate_seed). On the seed_only axis "
                "the seed is the only thing that differs from the reference: "
                "same cells, same conditions, same ligand-receptor pairs"
            ),
            "resampling": _resampling_description(spec, group_column, stratify),
            "condition_mode_alignment": (
                "reference condition-mode rows expanded onto the replicate's "
                "roster by draw (see validation.reference_condition_rows)"
            ),
            "lr_mode_alignment": (
                "reference ligand-receptor mode rows expanded by the drawn LR indices"
            ),
            "fms_definition": (
                "congruence product across compared modes (Modes 0 and 2 for RISE, "
                "with Mode 1 held out; Modes 0 and 3 for CPD, with Modes 1 and 2 "
                "held out), weights ignored (see validation.per_component_fms)"
            ),
            "anova_alignment": (
                "each replicate's ANOVA statistics carried onto the reference "
                "component its CP component was matched to by the CPD FMS; "
                "GroupMeanDiff sign-corrected by the condition mode's signed "
                "cosine (see validation._attach_anova)"
            ),
            "component_numbering": component_numbering(core),
            "lr_roster_stable": True,
            "interaction_tensor_shape": list(tensor_shape),
            "r2x_pf2": float(reference["r2x_rise"]),
            "r2x_cp": float(reference["r2x_cp"]),
            "reference_eta_squared": reference_anova["EtaSquared"].tolist(),
            "reference_f": reference_anova["F"].tolist(),
            "reference_p": reference_anova["P"].tolist(),
            "reference_group_mean_diff": reference_anova["GroupMeanDiff"].tolist(),
            "reference_top_lr_pair": labels["LRPair"].tolist(),
            "reference_top_lr_loading": labels["DLoading"].astype(float).tolist(),
            "n_components_significant": int((reference_anova["P"] < alpha).sum()),
            "reference_seed": random_state,
            "first_replicate_seed": replicate_seed(random_state, 0),
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=tensor_shape[3]),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")

    return df, output_path, sidecar


def _resampling_description(
    spec: DatasetSpec, group_column: str, stratify: bool
) -> dict[str, str]:
    """The sidecar's per-axis description of what each replicate resamples."""
    return {
        "cells": "cells bootstrapped with replacement within each condition",
        "conditions": (
            "whole conditions bootstrapped with replacement"
            + (f", stratified by {group_column}" if stratify else ", unstratified")
            + (
                f"; paired by {spec.patient_column}: drawing one of a "
                "patient's conditions carries its sibling in and drops "
                "one other random draw from the sibling's stratum to "
                "keep every stratum's size fixed"
                if spec.patient_column
                else ""
            )
        ),
        "lr_pairs": (
            "reference tensor's ligand-receptor mode bootstrapped "
            "with replacement; no PARAFAC2 refit; ANOVA on the reference cohort"
        ),
        SEED_AXIS: (
            "identical data refit end to end (RISE -> communication "
            "tensor -> CP) under a different random seed; one "
            "PARAFAC2 refit per replicate"
        ),
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank every fit uses; see rank_selection.select_rise_rank.",
    )
    parser.add_argument(
        "--cp-rank",
        type=int,
        required=True,
        help="CP rank every fit uses; see rank_selection.select_cpd_rank.",
    )
    parser.add_argument(
        "--axes",
        type=str,
        default=",".join(DEFAULT_AXES),
        help=(
            "Comma-separated axes. The cohort axes draw with replacement; "
            "seed_only draws nothing and varies only the fits' starting "
            f"point. Options: {', '.join(DEFAULT_AXES)}."
        ),
    )
    parser.add_argument("--n-replicates", type=int, default=100)
    add_group_arguments(parser)
    parser.add_argument(
        "--ci-level",
        type=float,
        default=95.0,
        help="Central percentile interval width on eta-squared, in percent (default: 95).",
    )
    parser.add_argument(
        "--alpha",
        type=float,
        default=0.05,
        help="Significance threshold for FracSignificant (default: 0.05).",
    )
    parser.add_argument(
        "--no-stratify",
        action="store_false",
        dest="stratify",
        help="Draw conditions from the whole cohort instead of within each "
        "outcome group, letting the class balance vary between replicates.",
    )
    parser.add_argument("--rise-n-iter-max", type=int, default=RISE_N_ITER_MAX)
    parser.add_argument("--rise-tol", type=float, default=RISE_TOL)
    parser.add_argument("--cp-n-iter-max", type=int, default=CP_N_ITER_MAX)
    parser.add_argument("--cp-tol", type=float, default=CP_TOL)
    parser.add_argument("--complex-sep", type=str, default="&")
    add_scoring_arguments(parser)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Parquet destination; defaults to component_stability_<dataset>.parquet in "
        "data/validation_results/ (its alt_score_methods/<score>/ for a "
        "non-default score).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_stability(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        axes=tuple(axis.strip() for axis in args.axes.split(",") if axis.strip()),
        n_replicates=args.n_replicates,
        group_column=args.group_column,
        control_label=args.control_label,
        other_label=args.other_label,
        ci_level=args.ci_level,
        alpha=args.alpha,
        stratify=args.stratify,
        rise_n_iter_max=args.rise_n_iter_max,
        rise_tol=args.rise_tol,
        cp_n_iter_max=args.cp_n_iter_max,
        cp_tol=args.cp_tol,
        complex_sep=args.complex_sep,
        communication_score=args.communication_score,
        hill_k=args.hill_k,
        random_state=args.random_state,
        output_path=resolve_output(
            args.output,
            scoring_output_dir(args.communication_score, VALIDATION_DIR),
            spec.stability_filename(),
        ),
    )


if __name__ == "__main__":
    main()
