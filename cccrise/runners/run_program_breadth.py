#!/usr/bin/env python
"""
Runner: are the programs the comparators find general ("basal") or specific?

For every component of cccRISE and of each comparator fit at its own rank
(``cccrise-benchmark``'s cached fits), describes each mode
(`validation.program_breadth`): how prevalent its LR pairs are across samples
and cell-type pairs, how many samples and cell types carry it, and its
strongest clinical association (from the benchmark ANOVA). Each comparator
component is labelled recovered or not by cccRISE (contained in cccRISE's
span, ``cccrise-comparator-agreement``: on both condition and LR modes for a
CP fit, on the mode itself for a Tucker fit). cccRISE's sender and receiver
modes are its per-cell loadings averaged per cell type.

Then tests the pre-registered hypothesis H-G3: comparator components cccRISE
does not recover have higher LR prevalence, higher sample breadth and lower
disease association than cccRISE's (one-sided Mann-Whitney, descriptive).

LR prevalence always uses the coarse cell types; the cell-type breadth uses
the fits' own types.

Writes, in ``data/validation_results/``:

    program_breadth_<dataset><suffix>.parquet        (fit, mode, component, statistic)
    program_breadth_tests_<dataset><suffix>.parquet  one row per H-G3 statistic

    uv run cccrise-program-breadth --dataset alad [--celltype-column celltype --suffix _fine]
"""

import argparse
from dataclasses import replace

import numpy as np
import pandas as pd
from scipy.stats import mannwhitneyu

from ..benchmark import ComparatorFit, read_fits
from ..comparators.agreement import celltype_profiles, shared_calls
from ..factors import load_factors_netcdf, load_factors_to_anndata
from ..import_data import import_ligand_receptor_pairs
from ..validation.program_breadth import (
    detection_table,
    lr_prevalence,
    mode_statistics,
)
from ._cli import add_dataset_argument, dataset_metadata
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

COMPLEX_SEP = "&"
#: (statistic, alternative for "comparator not recovered" vs cccRISE).
HYPOTHESES = (
    ("lr_prevalence", "greater"),
    ("sample_breadth", "greater"),
    ("max_eta_squared", "less"),
)
HEADER = """\
How general or specific each component of cccRISE and of the comparators is,
mode by mode, with whether cccRISE recovers each comparator component.
Generated by cccrise.runners.run_program_breadth -- do not hand-edit.
"""


def _prevalence(adata, spec: DatasetSpec, coarse_column: str) -> pd.DataFrame:
    """Every LR pair's prevalence (coarse types), with its pathway, indexed by
    its interaction symbol."""
    pairs = import_ligand_receptor_pairs().drop_duplicates("interaction_symbol")
    genes = {
        g
        for col in ("ligand", "receptor")
        for name in pairs[col].astype(str)
        for g in name.split(COMPLEX_SEP)
    } & set(adata.var_names)
    genes = sorted(genes)
    det = detection_table(
        adata[:, genes].X,
        genes,
        adata.obs[spec.condition_column],
        adata.obs[coarse_column],
    )
    prevalence = lr_prevalence(det, pairs["ligand"], pairs["receptor"], COMPLEX_SEP)
    return pd.DataFrame(
        {"prevalence": prevalence, "pathway": pairs["pathway_name"].to_numpy()},
        index=pairs["interaction_symbol"].astype(str).to_numpy(),
    )


def _fit_modes(
    fit: ComparatorFit, adata, spec: DatasetSpec, celltypes
) -> dict[str, np.ndarray]:
    """A fit's condition / lr / sender / receiver modes, on cell types."""
    modes = {"condition": fit.condition_factor, **fit.modes}
    if fit.method == "cccRISE":
        types = adata.obs[spec.celltype_column].astype(str).to_numpy()
        modes["sender"] = celltype_profiles(adata.obsm["sc_B"], types, celltypes)
        modes["receiver"] = celltype_profiles(adata.obsm["rc_C"], types, celltypes)
    return modes


def _mode_rows(fits, info, adata, spec: DatasetSpec, prevalence) -> list[pd.DataFrame]:
    """`mode_statistics` of every fit, LR rows matched to their prevalence."""
    cccrise_lr = load_factors_netcdf(spec.factors_path()).coords["lr_pair"].values
    frames = []
    for fit in fits:
        names = cccrise_lr if fit.method == "cccRISE" else np.asarray(info["lr_pairs"])
        modes = _fit_modes(fit, adata, spec, info["celltypes"])
        pairs = prevalence.reindex(names.astype(str))
        stats = mode_statistics(
            modes, pairs["prevalence"].fillna(0).to_numpy(), pairs["pathway"]
        )
        frames.append(
            stats.assign(method=fit.method, rank_mode=fit.rank_mode, rank=fit.rank)
        )
    return frames


def _association(anova: pd.DataFrame, fits: list[ComparatorFit]) -> pd.DataFrame:
    """Per (method, component) of `fits`: max eta-squared and min maxT perm p
    over the associations, as condition-mode statistics."""
    keys = ["Method", "RankMode", "Component"]
    agg = anova.groupby(keys).agg(
        max_eta_squared=("EtaSquared", "max"), min_perm_p=("PermPAdj", "min")
    )
    long = agg.reset_index().melt(id_vars=keys, var_name="statistic")
    long = long.rename(
        columns={"Method": "method", "RankMode": "rank_mode", "Component": "component"}
    ).assign(mode="condition", top_pathways="")
    ranks = {(f.method, f.rank_mode): f.rank for f in fits}
    fit_keys = list(zip(long["method"], long["rank_mode"], strict=True))
    long = long[[k in ranks for k in fit_keys]]
    return long.assign(rank=[ranks[k] for k in fit_keys if k in ranks])


def _recovered(containment: pd.DataFrame, fits: list[ComparatorFit]) -> pd.DataFrame:
    """Per (method, rank_mode, mode, component): contained in cccRISE's span
    (CP fits: on both condition and LR; Tucker: on the mode itself)."""
    reverse = containment[containment["direction"] == "comparator in cccRISE"]
    both = shared_calls(reverse, ["condition", "lr"])
    kinds = {(f.method, f.rank_mode): f.kind for f in fits}
    rows = reverse[["method", "rank_mode", "mode", "component", "contained"]]
    rows = rows.merge(both, on=["method", "rank_mode", "component"], how="left")
    cp = rows.apply(lambda r: kinds.get((r["method"], r["rank_mode"])) == "cp", axis=1)
    rows["recovered"] = np.where(cp, rows["contained_all_modes"], rows["contained"])
    return rows[["method", "rank_mode", "mode", "component", "recovered"]]


def _tests(table: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for statistic, alternative in HYPOTHESES:
        sub = table[table["statistic"] == statistic]
        ours = sub.loc[sub["method"] == "cccRISE", "value"].to_numpy(float)
        theirs = sub.loc[
            (sub["method"] != "cccRISE") & sub["recovered"].eq(False),
            "value",
        ].to_numpy(float)
        test = mannwhitneyu(theirs, ours, alternative=alternative)
        rows.append(
            {
                "statistic": statistic,
                "alternative": f"not-recovered comparator {alternative} than cccRISE",
                "n_comparator": len(theirs),
                "n_cccrise": len(ours),
                "median_comparator": float(np.median(theirs)),
                "median_cccrise": float(np.median(ours)),
                "cles": float(test.statistic) / (len(theirs) * len(ours)),
                "p": float(test.pvalue),
            }
        )
    return pd.DataFrame(rows)


def run_program_breadth(
    spec: DatasetSpec, coarse_column: str, suffix: str = ""
) -> dict[str, pd.DataFrame]:
    git_sha()
    fits_path = VALIDATION_DIR / spec.benchmark_fits_filename(suffix)
    anova_path = VALIDATION_DIR / spec.benchmark_anova_filename(suffix)
    containment_path = (
        VALIDATION_DIR / f"comparator_containment_{spec.key}{suffix}.parquet"
    )
    fits, info, _conditions = read_fits(fits_path)
    fits = [f for f in fits if f.rank_mode in ("own", "published")]
    adata = load_factors_to_anndata(spec.factors_path(), adata=spec.load())
    print(">> LR prevalence")
    prevalence = _prevalence(adata, spec, coarse_column)
    frames = _mode_rows(fits, info, adata, spec, prevalence)
    assoc = _association(pd.read_parquet(anova_path), fits)
    table = pd.concat([*frames, assoc], ignore_index=True)
    table = table.merge(
        _recovered(pd.read_parquet(containment_path), fits),
        on=["method", "rank_mode", "mode", "component"],
        how="left",
    )
    tables = {"breadth": table.assign(celltype_column=spec.celltype_column)}
    # Association rows sit on the condition mode and share its recovery call.
    tables["tests"] = _tests(tables["breadth"])
    paths = {
        "breadth": VALIDATION_DIR / f"program_breadth_{spec.key}{suffix}.parquet",
        "tests": VALIDATION_DIR / f"program_breadth_tests_{spec.key}{suffix}.parquet",
    }
    for name, frame in tables.items():
        frame.to_parquet(paths[name], index=False)
        print(f"   Wrote {len(frame)} rows to {paths[name]}")
    write_metadata(
        paths["breadth"],
        build_metadata(
            dataset_metadata(spec)
            | {
                "fits_path": relpath(fits_path),
                "fits_sha256": sha256_file(fits_path),
                "anova_path": relpath(anova_path),
                "containment_path": relpath(containment_path),
                "factors_sha256": sha256_file(spec.factors_path()),
                "prevalence_celltype_column": coarse_column,
                "min_detected": 0.1,
                "hypotheses": [list(h) for h in HYPOTHESES],
                "outputs": {k: relpath(v) for k, v in paths.items()},
            }
        ),
        header=HEADER,
    )
    return tables


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--celltype-column", default=None)
    parser.add_argument("--suffix", default="")
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    coarse_column = spec.celltype_column
    if args.celltype_column:
        spec = replace(spec, celltype_column=args.celltype_column)
    run_program_breadth(spec, coarse_column, suffix=args.suffix)


if __name__ == "__main__":
    main()
