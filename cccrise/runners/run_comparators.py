"""
Runner: the annotation-pooled comparators' own rank selection and fits.

For each labelling of the dataset (`DatasetSpec.labellings`: its coarse and
fine cell types) it builds the comparators' communication tensors
(`comparators.tensors`) and runs each method's own rank selection and fit
(`comparators.methods`), writing to ``data/comparators/`` (one file per
method, dataset and labelling; `datasets.comparator_filename`), each file
recorded in its folder's ``provenance.yaml`` (`provenance.record_output`):

- **pb** (pseudobulk CPD): ``rank_selection/pb_rank_*`` and ``pb_start_fms_*``,
  cccRISE's own sweep (`run_cpd_rank.start_sweep`: seeded SVD starts per rank,
  up to the tensor's smallest mode). The rank is chosen from these by hand;
  ``--pb-rank <labelling>=<rank>`` writes the best start (highest fit R2X)
  of the minimum most of that rank's saved starts reach (f_max;
  `rank_selection.distinct_minima`) as ``fits/pb_*``.
- **tc2c** (Tensor-cell2cell): ``rank_selection/tc2c_elbow_*`` (every run's
  error at every rank), ``tc2c_start_fms_*`` (the FMS
  between every pair of a rank's runs), ``tc2c_starts_*.nc`` (every run's
  factors) and ``fits/tc2c_*``, the lowest-error start at the elbow rank,
  on the masked tensor. Its fits run with pseudobulk CPD's tolerance, device
  and precision, for at most `methods.TC2C_N_ITER_MAX` iterations, up to the
  labelling's `methods.TC2C_UPPER_RANKS`.
- **tc2c_inner** (Tensor-cell2cell as published, a sensitivity check): the
  same tables on the paper's tensor, only the cell types present in every
  sample and no mask, its fit one SVD start at the elbow rank.
- **stac** (STACCato): ``rank_selection/stac_shares_*`` (each mode's
  eigenvalue shares) and ``fits/stac_*`` at the 1% core.

Usage:

    uv run cccrise-comparators --dataset alad
    uv run cccrise-comparators --dataset alad --methods pb --pb-rank coarse=4
    uv run cccrise-comparators --dataset alad --methods tc2c --tc2c-from-sweep
    uv run cccrise-comparators --dataset alad --methods tc2c --cp-device cpu --workers 10
"""

