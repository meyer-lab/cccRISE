METHODS = ("pb", "tc2c", "tc2c_inner", "stac")
HEADER = """\
Annotation-pooled comparator rank selection and fit.
Generated by cccrise.runners.run_comparators -- do not hand-edit.
"""


def labelled_tensors(adata, spec: DatasetSpec, labelling: str, lr_pairs):
    """Each comparator's tensor for one labelling, their LR pairs checked
    against the cccRISE fit's, so every method's LR mode is indexed alike."""
    column = spec.labellings[labelling]
    pooled = {
        "pb": pseudobulk_tensor(adata, spec.condition_column, column, lr_pairs),
        "tc2c": tensor_cell2cell_tensor(adata, spec.condition_column, column, lr_pairs),
        "tc2c_inner": tensor_cell2cell_tensor(
            adata, spec.condition_column, column, lr_pairs, how="inner"
        ),
        "stac": staccato_tensor(adata, spec.condition_column, column, lr_pairs),
    }
    cccrise_pairs = load_factors_netcdf(spec.factors_path())["lr_pair"].values
    for tensor in pooled.values():
        if not np.array_equal(tensor.lr_pairs, cccrise_pairs.astype(str)):
            raise ValueError("The comparator tensors' LR pairs differ from cccRISE's.")
    return pooled


def tensor_metadata(pooled: PooledTensor) -> dict:
    observed = 1.0 if pooled.mask is None else float(pooled.mask.mean())
    return {
        "tensor_shape": list(pooled.values.shape),
        "observed_share": observed,
        "celltypes": pooled.celltypes.tolist(),
    }


def fmax_best_seed(sweep: dict[str, Path], rank: int) -> int:
    """The seed of the best start (highest fit R2X) of the minimum most of
    `rank`'s starts reach (f_max) in pseudobulk CPD's saved `sweep`."""
    r2x = pd.read_parquet(sweep["rank"]).set_index(["Rank", "Seed"])["FitR2X"]
    fms = pd.read_parquet(sweep["start_fms"])
    minima = distinct_minima(fms[fms["Rank"] == rank], r2x.loc[[rank]])
    seeds = list(minima.loc[minima["Order"] == 1, "Seeds"].item())
    return int(r2x.loc[rank].loc[seeds].idxmax())


def run_pb(pooled: PooledTensor, rank, random_state, fit_kwargs, sweep) -> dict:
    """Pseudobulk CPD's start sweep (tables) and, at `rank`, its fit: the
    best f_max start of the saved `sweep` (`fmax_best_seed`)."""
    ranks = list(range(1, min(MAX_DEFAULT_RANK, *pooled.values.shape) + 1))
    seeds = list(range(random_state, random_state + N_STARTS))
    out = {
        "settings": {
            "ranks": ranks,
            "start_seeds": seeds,
            "cp_fit_options": CP_FIT_OPTIONS,
            **fit_kwargs,
        }
    }
    if rank is None:
        out["rank"], out["start_fms"] = start_sweep(
            pooled.values, ranks, seeds, **fit_kwargs
        )
        return out
    out["settings"]["rank"] = rank
    out["settings"]["fit_seed"] = seed = fmax_best_seed(sweep, rank)
    weights, factors = fit_cp_on_device(
        pooled.values, rank, random_state=seed, **fit_kwargs, **CP_FIT_OPTIONS
    )
    out["fit"] = methods.fit_dataset(pooled, factors, weights, rank=str(rank))
    return out


def tc2c_fit(
    pooled: PooledTensor, elbow, factors_by_rank, random_state, fit_kwargs
) -> tuple[xr.Dataset, dict]:
    """Tensor-cell2cell's fit at the elbow rank of its sweep: the
    lowest-error run on a masked tensor, one SVD start on an unmasked one
    (module docstring); and its settings."""
    rank = methods.tensor_cell2cell_rank(elbow)
    if rank is None:
        raise ValueError("Kneedle found no elbow in Tensor-cell2cell's error curve.")
    if pooled.mask is None:
        weights, factors = methods.tensor_cell2cell_fit(
            pooled.values, None, rank, random_state, init="svd", **fit_kwargs
        )
        fit = {"init": "svd"}
    else:
        seed, weights, factors = methods.best_start(elbow, factors_by_rank, rank)
        fit = {"init": "random", "best_of_runs_seed": seed}
    dataset = methods.fit_dataset(pooled, factors, weights, rank=str(rank))
    return dataset, {"elbow_rank": rank, "fit": fit}


def run_tc2c(
    pooled: PooledTensor, upper_rank, random_state, fit_kwargs, workers: int = 1
) -> dict:
    """Tensor-cell2cell's elbow (its fits over `workers` processes), the
    agreement of each rank's runs, and its fit (`tc2c_fit`)."""
    elbow, factors_by_rank = methods.tensor_cell2cell_elbow(
        pooled.values,
        pooled.mask,
        range(1, upper_rank + 1),
        random_state=random_state,
        workers=workers,
        **fit_kwargs,
    )
    fit, fit_settings = tc2c_fit(
        pooled, elbow, factors_by_rank, random_state, fit_kwargs
    )
    settings = {
        "upper_rank": upper_rank,
        "runs": methods.TC2C_RUNS,
        "init": "random",
        "first_seed": random_state,
        **fit_settings,
        **fit_kwargs,
    }
    return {
        "elbow": elbow,
        "start_fms": pd.DataFrame(
            [
                row
                for rank, by_seed in factors_by_rank.items()
                for row in start_agreement(rank, by_seed)
            ]
        ),
        "starts": methods.starts_dataset(pooled, factors_by_rank),
        "settings": settings,
        "fit": fit,
    }


def run_tc2c_from_sweep(
    pooled: PooledTensor, sweep: dict, random_state, fit_kwargs
) -> dict:
    """Tensor-cell2cell's fit (`tc2c_fit`) from its saved sweep, the paths of
    its "elbow" table and "starts", without rerunning the sweep."""
    path, starts_path = sweep["elbow"], sweep["starts"]
    elbow = pd.read_parquet(path)
    with xr.open_dataset(starts_path, engine="h5netcdf") as starts:
        factors_by_rank = methods.starts_factors(starts.load())
    fit, fit_settings = tc2c_fit(
        pooled, elbow, factors_by_rank, random_state, fit_kwargs
    )
    shas = {f"{what}_sha256": sha256_file(p) for what, p in sweep.items()}
    return {"fit": fit, "settings": fit_settings | {"from_sweep": shas, **fit_kwargs}}


def run_stac(pooled: PooledTensor, random_state) -> dict:
    """STACCato's eigenvalue shares and its fit at the 1% core."""
    shares = methods.eigenvalue_shares(pooled.values)
    core_shape = methods.staccato_core_shape(shares)
    core, factors = methods.staccato_fit(pooled.values, core_shape, random_state)
    rank = "x".join(str(core_shape[m]) for m in methods.MODES)
    return {
        "shares": shares,
        "fit": methods.fit_dataset(pooled, factors, core=core, rank=rank),
        "settings": {
            "varexp_percent": methods.STACCATO_VAREXP,
            "core_shape": core_shape,
            "random_state": random_state,
        },
    }


def write_outputs(
    result: dict,
    method: str,
    spec: DatasetSpec,
    labelling: str,
    metadata: dict,
    command: str,
) -> None:
    """Each table and the fit of one method's `result`, each recorded in its
    folder's provenance file as written by `command`."""
    metadata = build_metadata(
        metadata
        | {"method": method, "labelling": labelling, method: result["settings"]}
    )
    for what, value in result.items():
        if what == "settings":
            continue
        name = comparator_filename(method, what, spec.output_key, labelling)
        folder = COMPARATOR_FITS_DIR if what == "fit" else COMPARATOR_RANKS_DIR
        path = folder / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(value, xr.Dataset):
            value.to_netcdf(path, engine="h5netcdf")
        else:
            value.to_parquet(path, index=False)
        record_output(path, metadata, command, header=HEADER)
        print(f"   wrote {path.name}")


def saved_sweep(method: str, spec: DatasetSpec, labelling: str, whats) -> dict:
    """The paths of `method`'s saved sweep tables `whats` for one labelling."""
    return {
        what: COMPARATOR_RANKS_DIR
        / comparator_filename(method, what, spec.output_key, labelling)
        for what in whats
    }


def run_tensor_cell2cell(
    pooled: PooledTensor,
    method: str,
    spec: DatasetSpec,
    labelling: str,
    random_state,
    fit_kwargs,
    workers: int | None,
) -> dict:
    """A Tensor-cell2cell variant's sweep and fit (`run_tc2c`, its fits over
    `workers` processes), or with `workers` None only its fit from the saved
    sweep (`run_tc2c_from_sweep`)."""
    if workers is not None:
        upper_rank = methods.TC2C_UPPER_RANKS[labelling]
        return run_tc2c(pooled, upper_rank, random_state, fit_kwargs, workers)
    sweep = saved_sweep(method, spec, labelling, ("elbow", "starts"))
    return run_tc2c_from_sweep(pooled, sweep, random_state, fit_kwargs)


def run_comparators(
    spec: DatasetSpec,
    labellings,
    method_names,
    pb_ranks: dict[str, int],
    cp_device: str | None = None,
    cp_dtype: str = CP_DTYPE,
    random_state: int = 42,
    tc2c_from_sweep: bool = False,
    workers: int = 1,
    command: str = "uv run cccrise-comparators",
) -> None:
    """Rank selection and fits of `method_names` on each of `labellings`
    (module docstring); with `pb_ranks`, only pseudobulk CPD's fit at each
    given labelling's rank; with `tc2c_from_sweep`, Tensor-cell2cell's fit
    from its saved sweep. `workers` processes share Tensor-cell2cell's elbow
    fits. `command` is recorded as what wrote the outputs."""
    git_sha()
    print(f"=== Comparators: {spec.label}; {', '.join(labellings)} ===")
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()
    fit_kwargs = {
        "n_iter_max": CP_N_ITER_MAX,
        "tol": CP_TOL,
        "device": cp_device,
        "dtype": cp_dtype,
    }
    head = dataset_metadata(spec) | cp_device_metadata(cp_device, cp_dtype)
    for labelling in labellings:
        pooled = labelled_tensors(adata, spec, labelling, lr_pairs)
        for method in method_names:
            if pb_ranks and (method != "pb" or labelling not in pb_ranks):
                continue
            print(f"-- {labelling}: {method} on {pooled[method].values.shape}")
            if method == "pb":
                result = run_pb(
                    pooled["pb"],
                    pb_ranks.get(labelling),
                    random_state,
                    fit_kwargs,
                    saved_sweep("pb", spec, labelling, ("rank", "start_fms")),
                )
            elif method == "stac":
                result = run_stac(pooled["stac"], random_state)
            else:
                result = run_tensor_cell2cell(
                    pooled[method],
                    method,
                    spec,
                    labelling,
                    random_state,
                    fit_kwargs | {"n_iter_max": methods.TC2C_N_ITER_MAX},
                    workers=None if tc2c_from_sweep else workers,
                )
            metadata = head | {
                "celltype_key": spec.labellings[labelling],
                "tensor": tensor_metadata(pooled[method]),
            }
            write_outputs(result, method, spec, labelling, metadata, command)


def _pb_rank(text: str) -> tuple[str, int]:
    labelling, rank = text.split("=")
    return labelling, int(rank)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--labellings",
        nargs="+",
        default=None,
        help="Labellings to run (default: every one the dataset has).",
    )
    parser.add_argument("--methods", nargs="+", choices=METHODS, default=list(METHODS))
    parser.add_argument(
        "--pb-rank",
        type=_pb_rank,
        action="append",
        default=[],
        metavar="LABELLING=RANK",
        help="Write pseudobulk CPD's fit at this rank (no sweeps run).",
    )
    add_cp_device_arguments(parser)
    parser.add_argument(
        "--tc2c-from-sweep",
        action="store_true",
        help="Write Tensor-cell2cell's fit from its saved sweep (no sweep run).",
    )
    parser.add_argument(
        "--workers",
        type=int,
        default=1,
        help="Processes sharing Tensor-cell2cell's elbow fits (default 1). Pays on "
        "small tensors, best with --cp-device cpu; each worker uses the BLAS "
        "threads set in the environment.",
    )
    parser.add_argument("--random-state", type=int, default=42)
    return parser


def main(argv: list[str] | None = None) -> None:
    args, command = parse_command(build_parser(), "cccrise-comparators", argv)
    spec = resolve_dataset(args)
    pb_ranks = dict(args.pb_rank)
    run_comparators(
        spec,
        args.labellings or list(pb_ranks) or list(spec.labellings),
        args.methods,
        pb_ranks,
        cp_device=args.cp_device,
        cp_dtype=args.cp_dtype,
        random_state=args.random_state,
        tc2c_from_sweep=args.tc2c_from_sweep,
        workers=args.workers,
        command=command,
    )


if __name__ == "__main__":
    main()
