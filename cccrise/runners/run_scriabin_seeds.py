"""
Runner: whether Scriabin's interaction programs and cccRISE's LR sets
reproduce between random seeds (`figureS_comparator_single_cell` A), from PR #275's
`run_scriabin_stability` (its ``seed_agreement`` analysis, cut to what the
figure reads).

Writes ``seed_agreement_<dataset>.parquet`` (alad, ibd) to ``data/scriabin/``,
recorded in the folder's ``provenance.yaml``, one row per pair of seeds:

- ``Method`` Scriabin, ``Stage`` programs: best-match Jaccard (`best_match`)
  of the interaction programs merged over every subsampled sample
  (`scriabin_programs.merge_programs`, Jaccard `SIM_THRESHOLD`; upstream's
  merge, exactly), between upstream R runs at seeds `SEEDS` (1111,
  upstream's own, and 2-10) on cccRISE's inputs. Only samples of more than
  `ITERATE_THRESHOLD` cells are subsampled; smaller ones use the full
  cell-cell interaction matrix, identical across seeds, so they are left out.
- ``Method`` cccRISE, ``Stage`` lr_sets: best-match Jaccard of each
  component's carrying LR pairs (`covariation.carrying_pairs`) between
  cccRISE refits at seeds `CCCRISE_REFITS`.

Inputs (git-ignored, under ``rcheck/out/``): the R runs, one folder per seed
holding each sample's ``<sample>.json`` (its modules and cell count) and
``.rds``; the refits, ``cccrise/<dataset>/s1/seed<seed>.npz`` (``cp_D``,
``lr_symbols``). PR #275 made both (``rcheck/faithful/ip_runs.R``,
``rcheck/shared/cccrise_refits.py``).

    uv run cccrise-scriabin-seeds --dataset alad
"""

import argparse
import itertools
import json
from pathlib import Path

import numpy as np
import pandas as pd

from ..comparators.scriabin_programs import (
    ITERATE_THRESHOLD,
    SIM_THRESHOLD,
    merge_programs,
)
from ..covariation import CARRIED_SHARE, CARRYING_CAP, carrying_pairs
from ._cli import parse_command
from .datasets import SCRIABIN_DIR, scores_filename
from .provenance import REPO_ROOT, build_metadata, git_sha, write_table

HEADER = """\
Scriabin's interaction programs and cccRISE's LR sets between seeds
(Appendix Figure S8A, figureS_comparator_single_cell).
Generated by cccrise.runners.run_scriabin_seeds -- do not hand-edit.
"""
RUNS_DIR = REPO_ROOT / "rcheck" / "out"
SEEDS = (1111, 2, 3, 4, 5, 6, 7, 8, 9, 10)
#: Each dataset's R runs (under `RUNS_DIR`), on cccRISE's inputs by sample
SCRIABIN_RUNS = {"alad": "shared/alad/s1", "ibd": "shared/ibd/s1"}
#: cccRISE refit seeds per dataset (ALAD: seed 42's replicates; IBD: all five)
CCCRISE_REFITS = {
    "alad": tuple(range(42001, 42011)),
    "ibd": (42, 42001, 42002, 42003, 42004),
}


def best_match(a: list[set], b: list[set]) -> float:
    """Mean best-match Jaccard of two collections of sets, in both
    directions, averaged (1 if both are empty)."""
    if not a or not b:
        return float(a == b)
    universe = {x: i for i, x in enumerate(sorted(set().union(*a, *b)))}
    ma, mb = (
        np.array(
            [np.isin(np.arange(len(universe)), [universe[x] for x in s]) for s in sets],
            float,
        )
        for sets in (a, b)
    )
    inter = ma @ mb.T
    j = inter / (ma.sum(1)[:, None] + mb.sum(1)[None, :] - inter)
    return float((j.max(axis=1).mean() + j.max(axis=0).mean()) / 2)


def _modules(modules: dict) -> dict[str, list]:
    """A run's modules, a one-pair module (a JSON scalar) as a list."""
    return {k: v if isinstance(v, list) else [v] for k, v in modules.items()}


def _run_json(run: Path, sample: str) -> dict:
    return json.loads((run / f"{sample}.json").read_text())


def subsampled_samples(root: Path) -> list[str]:
    """The samples a run subsamples, after checking every seed's run is
    complete."""
    first = root / f"seed{SEEDS[0]}"
    samples = sorted(
        f.stem for f in first.glob("*.json") if f.stem not in ("merged", "kept")
    )
    missing = [
        f"seed{s}/{g}"
        for s in SEEDS
        for g in samples
        if not (root / f"seed{s}" / f"{g}.rds").exists()
    ]
    if missing:
        raise FileNotFoundError(
            f"{root}: {len(missing)} runs missing, e.g. {missing[0]}"
        )
    return [g for g in samples if _run_json(first, g)["n_cells"] > ITERATE_THRESHOLD]


def scriabin_rows(root: Path) -> pd.DataFrame:
    """Best-match Jaccard of the merged programs between every pair of seeds."""
    samples = subsampled_samples(root)
    merged = {
        s: [
            set(v)
            for v in merge_programs(
                {
                    g: _modules(_run_json(root / f"seed{s}", g)["modules"])
                    for g in samples
                },
                SIM_THRESHOLD,
            ).values()
        ]
        for s in SEEDS
    }
    print(f"   {root.relative_to(RUNS_DIR)}: {len(samples)} subsampled samples")
    return pd.DataFrame(
        [
            {"SeedA": a, "SeedB": b, "Value": best_match(merged[a], merged[b])}
            for a, b in itertools.combinations(SEEDS, 2)
        ]
    ).assign(Method="Scriabin", Stage="programs")


def cccrise_rows(dataset: str) -> pd.DataFrame:
    """Best-match Jaccard of cccRISE's carrying LR sets between seed refits."""
    sets = {}
    for seed in CCCRISE_REFITS[dataset]:
        fit = np.load(
            RUNS_DIR / "cccrise" / dataset / "s1" / f"seed{seed}.npz", allow_pickle=True
        )
        D, symbols = fit["cp_D"], fit["lr_symbols"]
        sets[seed] = [set(symbols[carrying_pairs(D[:, c])]) for c in range(D.shape[1])]
    return pd.DataFrame(
        [
            {"SeedA": a, "SeedB": b, "Value": best_match(sets[a], sets[b])}
            for a, b in itertools.combinations(CCCRISE_REFITS[dataset], 2)
        ]
    ).assign(Method="cccRISE", Stage="lr_sets")


def seed_agreement(dataset: str) -> pd.DataFrame:
    table = pd.concat(
        [scriabin_rows(RUNS_DIR / SCRIABIN_RUNS[dataset]), cccrise_rows(dataset)],
        ignore_index=True,
    )
    return table[["Method", "Stage", "SeedA", "SeedB", "Value"]]


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--dataset", required=True, choices=list(SCRIABIN_RUNS))
    return parser


def main(argv: list[str] | None = None) -> None:
    args, command = parse_command(build_parser(), "cccrise-scriabin-seeds", argv)
    git_sha()  # pin the code version before anything runs (`provenance.git_sha`)
    dataset = args.dataset
    print(f"=== Scriabin and cccRISE seed agreement: {dataset} ===", flush=True)
    table = seed_agreement(dataset)
    metadata = build_metadata(
        {
            "dataset": dataset,
            "seeds": list(SEEDS),
            "scriabin_runs": f"rcheck/out/{SCRIABIN_RUNS[dataset]}",
            "merge_threshold": SIM_THRESHOLD,
            "iterate_threshold": ITERATE_THRESHOLD,
            "cccrise_refits": {
                "dir": f"rcheck/out/cccrise/{dataset}/s1",
                "seeds": list(CCCRISE_REFITS[dataset]),
            },
            "carried_share": CARRIED_SHARE,
            "carrying_cap": CARRYING_CAP,
        }
    )
    path = SCRIABIN_DIR / scores_filename("seed_agreement", dataset)
    path.parent.mkdir(parents=True, exist_ok=True)
    write_table(path, table, metadata, command, HEADER)
    print(f"   wrote {path.name}")


if __name__ == "__main__":
    main()
