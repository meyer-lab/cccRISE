HEADER = """\
cccRISE ANOVA benchmark against tensor comparators. Generated by
cccrise.runners.run_benchmark_anova -- do not hand-edit.
"""


def _published_cccrise(
    factors_path: Path, conditions: np.ndarray
) -> tuple[ComparatorFit, int]:
    """cccRISE's published condition factor, and its CP rank."""
    ds = load_factors_netcdf(factors_path)
    stored = np.asarray(ds.coords["condition"].values).astype(str)
    if not np.array_equal(stored, conditions.astype(str)):
        raise ValueError(
            f"{factors_path} was fit on different conditions than the loaded "
            f"dataset ({len(stored)} stored vs {len(conditions)} loaded). "
            "Regenerate it with `uv run cccrise-run` before benchmarking."
        )
    rise_rank, cp_rank = int(ds.attrs["rise_rank"]), int(ds.attrs["cp_rank"])
    fit = ComparatorFit(
        method="cccRISE",
        rank_mode="published",
        rank=f"{rise_rank}/{cp_rank}",
        condition_factor=np.asarray(ds["cp_A"].values),
        details={"rise_rank": rise_rank, "cp_rank": cp_rank},
    )
    return fit, cp_rank


def _condition_patients(adata, spec: DatasetSpec, conditions: np.ndarray) -> pd.Series:
    """Patient per condition, in `conditions` order; each condition is its own
    patient when the dataset registers no `patient_column`."""
    if spec.patient_column is None:
        return pd.Series(conditions, index=conditions)
    obs = adata.obs.drop_duplicates(subset=[spec.condition_column])
    return obs.set_index(spec.condition_column)[spec.patient_column].reindex(conditions)


def run_benchmark_anova(
    spec: DatasetSpec,
    rank_modes: Sequence[str] = RANK_MODES,
    shared_rank: int | None = None,
    associations: Sequence[dict[str, Any] | str] = DEFAULT_ASSOCIATIONS,
    correction: str | None = "fdr_bh",
    alpha: float = 0.05,
    tc2c_upper_rank: int = TC2C_UPPER_RANK,
    tc2c_elbow_runs: int = TC2C_ELBOW_RUNS,
    staccato_varexp: float = STACCATO_VAREXP,
    complex_sep: str | None = "&",
    random_state: int = 42,
    n_permutations: int = N_PERMUTATIONS,
    factors_path: Path | None = None,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame, Path, Path]:
    """Run the cccRISE ANOVA on cccRISE and every comparator.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rank_modes : Sequence[str], default=("own", "shared")
        Comparator rank modes to run; see `benchmark.fit_comparators`.
    shared_rank : int, optional
        Rank for the ``shared`` mode. Defaults to the published cccRISE CP rank.
    associations : Sequence[dict | str], default=figureAnova.DEFAULT_ASSOCIATIONS
        Association specifications, as `anova.run_multiple_factors_anova` takes.
    correction : str | None, default="fdr_bh"
        Per-association multiple-testing correction across components.
    alpha : float, default=0.05
        Threshold `Significant` is reported against.
    tc2c_upper_rank, tc2c_elbow_runs : int
        Tensor-cell2cell elbow sweep controls (``own`` mode only).
    staccato_varexp : float
        STACCato's per-mode explained-variance cut, in percent (``own`` only).
    complex_sep : str, optional
        Communication-tensor option; see `ccc_rise.calc_communication_score`.
    random_state : int, default=42
        Seed for every comparator fit and for the permutations.
    n_permutations : int, default=N_PERMUTATIONS
        Label permutations per association, shared by every fit.
    factors_path : Path, optional
        Published cccRISE model. Defaults to the dataset's canonical factors file.
    output_path : Path, optional
        CSV destination. Defaults to ``data/benchmark_anova_<dataset>.csv``.
    """
    if spec.celltype_column is None:
        raise ValueError(f"Dataset {spec.key!r} has no celltype_column to pseudobulk.")
    factors_path = factors_path or spec.factors_path()
    output_path = output_path or DATA_DIR / spec.benchmark_anova_filename()

    print(f">> Loading {spec.label}")
    adata = add_cond_idxs(spec.load(), spec.condition_column)
    conditions = np.unique(adata.obs[spec.condition_column])

    cccrise_fit, cp_rank = _published_cccrise(factors_path, conditions)
    shared_rank = shared_rank or cp_rank

    print(">> Building the cell-type pseudobulk tensor")
    tensor, celltypes, lr_pairs = pseudobulk_tensor(
        adata,
        spec.condition_column,
        spec.celltype_column,
        import_ligand_receptor_pairs(),
        complex_sep=complex_sep,
    )
    print(f"   Tensor shape {tensor.shape}")

    fits = [cccrise_fit]
    for mode in rank_modes:
        print(f">> Fitting comparators, rank mode {mode!r}")
        fits += fit_comparators(
            tensor,
            rank_mode=mode,
            shared_rank=shared_rank,
            tc2c_upper_rank=tc2c_upper_rank,
            tc2c_elbow_runs=tc2c_elbow_runs,
            staccato_varexp=staccato_varexp,
            random_state=random_state,
        )

    print(f">> Drawing {n_permutations} label permutations per association")
    patients = _condition_patients(adata, spec, conditions)
    streams = np.random.SeedSequence(random_state).spawn(len(associations))
    null_plans = {}
    for association, stream in zip(associations, streams):
        name = association_config(association)["name"]
        labels = association_labels(adata, spec.condition_column, association)
        null_plans[name] = association_permutations(
            labels, patients, n_permutations, np.random.default_rng(stream)
        )

    tables, summaries = [], []
    for fit in fits:
        print(f"   {fit.method} ({fit.rank_mode}, rank {fit.rank})")
        adata.uns["A"] = fit.condition_factor
        adata.uns["A"] = correct_conditions(adata)
        corrected = np.asarray(adata.uns["A"], dtype=float)
        table = run_multiple_factors_anova(
            adata,
            associations=associations,
            condition_column=spec.condition_column,
            alpha=alpha,
            correction=correction,
        )
        table["PermPAdj"] = np.nan
        for name, (kept, codes, perms) in null_plans.items():
            observed, p_adj, null_max = maxt_null(corrected, kept, codes, perms)
            rows = table["Association"] == name
            # The null must be the ANOVA's own statistic, or its p is meaningless
            if not np.allclose(
                observed, table.loc[rows, "EtaSquared"], equal_nan=True, atol=1e-10
            ):
                raise RuntimeError(f"Null eta-squared disagrees with the ANOVA: {name}")
            table.loc[rows, "PermPAdj"] = p_adj
            summaries.append(
                {
                    "Method": fit.method,
                    "RankMode": fit.rank_mode,
                    "Rank": fit.rank,
                    "Association": name,
                    "NComponents": corrected.shape[1],
                    **summarize_null(observed, p_adj, null_max),
                }
            )
        table.insert(0, "Rank", fit.rank)
        table.insert(0, "RankMode", fit.rank_mode)
        table.insert(0, "Method", fit.method)
        tables.append(table)
    results = pd.concat(tables, ignore_index=True)
    results.to_csv(output_path, index=False)
    print(f"   Wrote {len(results)} rows to {output_path}")

    summary = pd.DataFrame(summaries)
    summary["PermPBH"] = bh_across_associations(summary, ["Method", "RankMode"])
    null_path = output_path.with_name(spec.benchmark_null_filename())
    summary.to_csv(null_path, index=False)
    print(f"   Wrote {len(summary)} rows to {null_path}")

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_file": relpath(factors_path),
            "rank_modes": list(rank_modes),
            "shared_rank": shared_rank,
            "correction": correction,
            "alpha": alpha,
            "read_depth_corrected": True,
            "complex_sep": complex_sep,
            "random_state": random_state,
            "null": {
                "n_permutations": n_permutations,
                "statistic": "max eta-squared across components (Westfall-Young maxT)",
                "output": relpath(null_path),
                "permutation_digests": {
                    name: permutation_digest(perms)
                    for name, (_kept, _codes, perms) in null_plans.items()
                },
            },
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=len(lr_pairs)),
            "pseudobulk_tensor_shape": list(tensor.shape),
            "celltypes": [str(c) for c in celltypes],
            "tensor_cell2cell": {
                "upper_rank": tc2c_upper_rank,
                "elbow_runs": tc2c_elbow_runs,
            },
            "fits": [
                {
                    "method": fit.method,
                    "rank_mode": fit.rank_mode,
                    "rank": fit.rank,
                    **fit.details,
                }
                for fit in fits
            ],
        },
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return results, summary, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rank-mode",
        choices=[*RANK_MODES, "both"],
        default="both",
        help="How comparator ranks are chosen (default: both).",
    )
    parser.add_argument(
        "--shared-rank",
        type=int,
        default=None,
        help="Rank every comparator uses in the shared mode "
        "(default: the published cccRISE CP rank).",
    )
    parser.add_argument("--tc2c-upper-rank", type=int, default=TC2C_UPPER_RANK)
    parser.add_argument("--tc2c-elbow-runs", type=int, default=TC2C_ELBOW_RUNS)
    parser.add_argument("--staccato-varexp", type=float, default=STACCATO_VAREXP)
    parser.add_argument("--alpha", type=float, default=0.05)
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--n-permutations",
        type=int,
        default=N_PERMUTATIONS,
        help="Label permutations per association for the null (default: 10000).",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV destination; defaults to data/benchmark_anova_<dataset>.csv.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_benchmark_anova(
        spec,
        rank_modes=RANK_MODES if args.rank_mode == "both" else (args.rank_mode,),
        shared_rank=args.shared_rank,
        alpha=args.alpha,
        tc2c_upper_rank=args.tc2c_upper_rank,
        tc2c_elbow_runs=args.tc2c_elbow_runs,
        staccato_varexp=args.staccato_varexp,
        complex_sep=args.complex_sep,
        random_state=args.random_state,
        n_permutations=args.n_permutations,
        output_path=resolve_output(
            args.output, DATA_DIR, spec.benchmark_anova_filename()
        ),
    )


if __name__ == "__main__":
    main()
