from collections.abc import Sequence
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from ..anova import run_multiple_factors_anova
from ..benchmark import (
    RANK_MODES,
    STACCATO_VAREXP,
    TC2C_ELBOW_RUNS,
    TC2C_UPPER_RANK,
    ComparatorFit,
    fit_comparators,
    pseudobulk_tensor,
)
from ..benchmark_null import (
    N_PERMUTATIONS,
    association_config,
    association_labels,
    association_permutations,
    bh_across_associations,
    maxt_null,
    permutation_digest,
    summarize_null,
)
from ..factors import load_factors_netcdf
from ..figures.figureAnova import DEFAULT_ASSOCIATIONS
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..utils import correct_conditions
