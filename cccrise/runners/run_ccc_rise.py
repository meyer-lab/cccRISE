#!/usr/bin/env python
"""
Runner: the end-to-end cccRISE pipeline.

Loads a registered dataset, runs RISE at ``--rise-rank`` followed by CP
decomposition of the interaction tensor at ``--cp-rank``, and serializes the
factor model to NetCDF alongside a provenance sidecar. The ``.nc`` is written in
the format the figure modules read via `factors.load_factors_to_anndata`.

The ``.nc`` also carries per-cell projections, sender/receiver weights and a
PaCMAP embedding, so the Shiny explorer can read it directly (``--no-embedding``
skips the PaCMAP fit for cohorts where it is too slow).

The sidecar's ``rank_selection`` block records which sweep justifies each chosen
rank -- the sweep CSVs written by `run_rise_rank` / `run_cpd_rank`, plus a
free-text rationale from ``--rise-rank-notes`` / ``--cpd-rank-notes``.

    uv run cccrise-run --dataset alad --rise-rank 25 --cp-rank 14
"""

import argparse
from pathlib import Path
from typing import Any

import anndata
import numpy as np
import xarray as xr

from ..ccc_rise import validate_cp_rank
from ..factors import add_cell_projections, factors_to_xarray, save_factors_netcdf
from ..import_data import import_ligand_receptor_pairs
from ..tensor import run_ccc_rise_workflow
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    resolve_output,
    resulting_dims,
)
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, write_metadata

HEADER = """\
cccRISE pipeline provenance. Generated by
cccrise.runners.run_ccc_rise -- do not hand-edit, except for
`rank_selection.rise.notes` and `rank_selection.cpd.notes`, which document why
these ranks were chosen.
"""


def _rank_selection_block(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    rise_notes: str | None,
    cpd_notes: str | None,
) -> dict[str, Any]:
    """Record, per stage, the chosen rank, the sweep CSV that justifies it, and
    a free-text rationale."""

    def stage(rank: int, csv: Path, notes: str | None) -> dict[str, Any]:
        return {
            "rank": rank,
            "sweep_csv": relpath(csv) if csv.exists() else None,
            "notes": notes,
        }

    return {
        "rise": stage(rise_rank, DATA_DIR / spec.rise_rank_filename(), rise_notes),
        "cpd": stage(cp_rank, DATA_DIR / spec.cpd_rank_filename(), cpd_notes),
    }


def run_pipeline(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    n_iter_max: int = 100,
    tol: float = 1e-3,
    random_state: int | None = 42,
    complex_sep: str | None = "&",
    svd_init: str = "svd",
    output_path: Path | None = None,
    rise_rank_notes: str | None = None,
    cpd_rank_notes: str | None = None,
    do_embedding: bool = True,
) -> tuple[anndata.AnnData, xr.Dataset, Path, Path]:
    """Run cccRISE end to end and serialize the factor model plus provenance.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank : int
        Rank for the RISE / PARAFAC2 stage.
    cp_rank : int
        Rank for the CP decomposition of the interaction tensor.
    n_iter_max : int, default=100
        Maximum iterations for both fits.
    tol : float, default=1e-3
        Convergence tolerance for both fits.
    random_state : int, optional, default=42
        Seed for the decompositions.
    complex_sep : str, optional, default="&"
        Separator for multimeric complexes in the ligand-receptor annotation.
    svd_init : str, default="svd"
        Initialization for the CP fit.
    output_path : Path, optional
        NetCDF destination. Defaults to the dataset's canonical factors path,
        which is what the figure modules load.
    rise_rank_notes, cpd_rank_notes : str, optional
        Rationale for each chosen rank, written into the provenance file.
    do_embedding : bool, default=True
        Fit a PaCMAP embedding of the per-cell projections and store it with
        them, for the Shiny explorer's cell projection views.

    Returns
    -------
    tuple[anndata.AnnData, xr.Dataset, Path, Path]
        The fitted AnnData, the factor Dataset, the ``.nc`` path, and the
        sidecar path.
    """
    output_path = output_path or spec.factors_path()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== cccRISE pipeline: {spec.label} ===")
    print(f"    RISE rank={rise_rank}  CP rank={cp_rank}  seed={random_state}")

    print("1. Loading data and ligand-receptor pairs...")
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()
    print(f"   AnnData shape: {adata.shape}, LR pairs: {len(lr_pairs)}")

    # Fail in seconds rather than after the RISE fit. `ccc_rise` re-checks
    # against the real tensor; this predicts its shape from what we know.
    n_conditions = int(adata.obs[spec.condition_column].nunique())
    validate_cp_rank(cp_rank, (n_conditions, rise_rank, rise_rank))

    print("2. Running cccRISE workflow...")
    adata, r2x_cp = run_ccc_rise_workflow(
        adata=adata,
        rise_rank=rise_rank,
        lr_pairs=lr_pairs,
        cp_rank=cp_rank,
        condition_column=spec.condition_column,
        n_iter_max=n_iter_max,
        tol=tol,
        random_state=random_state,
        complex_sep=complex_sep,
        doEmbedding=do_embedding,
        svd_init=svd_init,
    )
    r2x_pf2 = adata.uns.get("r2x_pf2")
    print(f"   CP R2X: {r2x_cp:.4f}")

    print("3. Converting factors to xarray...")
    condition_names = np.unique(adata.obs[spec.condition_column].unique())
    ds = factors_to_xarray(
        cpd_factors=[adata.uns["A"], adata.uns["B"], adata.uns["C"], adata.uns["D"]],
        cpd_weights=adata.uns["weights"],
        filtered_lr_pairs=adata.uns["lr_pairs"],
        condition_names=condition_names,
        gene_names=list(adata.var_names),
        pf2_factors=[adata.uns["Pf2_A"], adata.uns["Pf2_B"], adata.uns["Pf2_C"]],
        pf2_weights=adata.uns["Pf2_weights"],
        r2x_cp=r2x_cp,
        r2x_pf2=r2x_pf2,
        attrs={
            "dataset_name": spec.key,
            "dataset_label": spec.label,
            "condition_key": spec.condition_column,
            "complex_sep": complex_sep or "",
        },
    )

    print("4. Attaching per-cell projections...")
    ds = add_cell_projections(ds, adata, obs_columns=spec.cell_obs_columns())

    print(f"5. Saving factor model to {output_path}...")
    save_factors_netcdf(ds, output_path)

    rank_selection = _rank_selection_block(
        spec, rise_rank, cp_rank, rise_rank_notes, cpd_rank_notes
    )
    n_lr_used = len(adata.uns["lr_pairs"])
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "n_iter_max": n_iter_max,
            "tol": tol,
            "random_state": random_state,
            "complex_sep": complex_sep,
            "svd_init": svd_init,
            "pacmap_embedding": do_embedding,
            "lr_pairs_annotated": len(lr_pairs),
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=n_lr_used),
            "interaction_tensor_shape": [
                len(condition_names),
                rise_rank,
                rise_rank,
                n_lr_used,
            ],
            "r2x_pf2": None if r2x_pf2 is None else float(r2x_pf2),
            "r2x_cp": float(r2x_cp),
            "rank_selection": rank_selection,
        },
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return adata, ds, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--rise-rank", type=int, required=True, help="RISE rank.")
    parser.add_argument("--cp-rank", type=int, required=True, help="CP (CPD) rank.")
    parser.add_argument("--n-iter-max", type=int, default=100)
    parser.add_argument("--tol", type=float, default=1e-3)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument(
        "--svd-init", type=str, default="svd", choices=["svd", "random"]
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="NetCDF output path (default: the dataset's canonical factors file, "
        "which the figure modules load).",
    )
    parser.add_argument(
        "--no-embedding",
        dest="do_embedding",
        action="store_false",
        help="Skip the PaCMAP embedding of per-cell projections.",
    )
    parser.add_argument(
        "--rise-rank-notes",
        type=str,
        default=None,
        help="Rationale for the chosen RISE rank, recorded in the provenance file.",
    )
    parser.add_argument(
        "--cpd-rank-notes",
        type=str,
        default=None,
        help="Rationale for the chosen CP rank, recorded in the provenance file.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_pipeline(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        n_iter_max=args.n_iter_max,
        tol=args.tol,
        random_state=args.random_state,
        complex_sep=args.complex_sep,
        svd_init=args.svd_init,
        output_path=resolve_output(args.output, DATA_DIR, spec.factors_filename),
        rise_rank_notes=args.rise_rank_notes,
        cpd_rank_notes=args.cpd_rank_notes,
        do_embedding=args.do_embedding,
    )


if __name__ == "__main__":
    main()
