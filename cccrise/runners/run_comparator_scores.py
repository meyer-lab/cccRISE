METHODS = {"pb": "PB", "tc2c": "TC2C", "stac": "STAC"}
N_NULL = 1000
HEADER = """\
cccRISE against the annotation-pooled comparators (Figure 5).
Generated by cccrise.runners.run_comparator_scores -- do not hand-edit.
"""


def load_fits(spec: DatasetSpec, labelling: str) -> dict[str, xr.Dataset]:
    fits = {}
    for key, method in METHODS.items():
        path = COMPARATOR_FITS_DIR / comparator_filename(
            key, "fit", spec.output_key, labelling
        )
        with xr.open_dataset(path, engine="h5netcdf") as fit:
            fits[method] = fit.load()
    return fits


def containment_rows(
    cccrise: Components, comparators: list[Components], rng
) -> pd.DataFrame:
    """cccRISE's LR columns in each comparator fit's LR span."""
    frames = [
        scores.containment(span.modes["lr"], cccrise.modes["lr"], N_NULL, rng).assign(
            In=span.method
        )
        for span in comparators
    ]
    return pd.concat(frames, ignore_index=True)


def column_profiles(
    fit: xr.Dataset, components: Components, column: int
) -> dict[str, pd.Series]:
    """A comparator LR column's sample, sender and receiver profiles, signed
    so the largest entry is positive."""
    if "core" in fit:
        raw = scores.tucker_column_profiles(fit, column)
        labels = {m: fit[m].to_numpy().astype(str) for m in raw}
        frames = {m: pd.DataFrame({column: raw[m]}, index=labels[m]) for m in raw}
    else:
        frames = {
            m: components.modes[m][[column]] for m in ("sample", "sender", "receiver")
        }
    return {m: scores.oriented(f)[column] for m, f in frames.items()}


def fit_rank_rows(fits: dict[str, xr.Dataset]) -> pd.DataFrame:
    """The rank each CP fit was written at (a Tucker fit has a core instead)."""
    return pd.DataFrame(
        [
            {"Method": method, "Rank": int(fit.attrs["rank"])}
            for method, fit in fits.items()
            if "core" not in fit
        ]
    )


def start_congruence_rows(spec: DatasetSpec, labelling: str) -> pd.DataFrame:
    """Tensor-cell2cell's `methods.start_congruence`."""
    path = COMPARATOR_RANKS_DIR / comparator_filename(
        "tc2c", "starts", spec.output_key, labelling
    )
    with xr.open_dataset(path, engine="h5netcdf") as starts:
        return methods.start_congruence(starts).assign(Method=METHODS["tc2c"])


def inner_loss_rows(
    cells, column: str, tensors: dict[str, PooledTensor]
) -> pd.DataFrame:
    """What the published Tensor-cell2cell construction drops (module
    docstring), from `context_tensors`' masked and published tensors."""
    kept = tensors[PUBLISHED].celltypes
    dropped = ~cells.obs[column].astype(str).isin(list(kept)).to_numpy()
    cell_share = {"Measure": "cells", "Dropped": dropped.sum(), "Total": dropped.size}
    return pd.concat(
        [
            scores.inner_losses(tensors["TC2C"], kept),
            pd.DataFrame([cell_share | {"Share": dropped.mean()}]),
        ],
        ignore_index=True,
    )


#: Each cohort's associations, as its own figure tests them.
ASSOCIATIONS = {"alad": ALAD_ASSOCIATIONS, "ibd": IBD_ASSOCIATIONS}


#: `context_tensors`' key for the published Tensor-cell2cell tensor (only the
#: cell types in every sample), built only for `inner_loss_rows`.
PUBLISHED = "TC2C published"


def context_tensors(spec: DatasetSpec, adata, column: str) -> dict[str, PooledTensor]:
    """Each comparator's own tensor on `column`'s cell types, and the
    published Tensor-cell2cell tensor (`PUBLISHED`)."""
    lr_pairs = import_ligand_receptor_pairs()
    sample = spec.condition_column
    return {
        "PB": pseudobulk_tensor(adata, sample, column, lr_pairs),
        "STAC": staccato_tensor(adata, sample, column, lr_pairs),
        "TC2C": tensor_cell2cell_tensor(adata, sample, column, lr_pairs),
        PUBLISHED: tensor_cell2cell_tensor(
            adata, sample, column, lr_pairs, how="inner"
        ),
    }


def lr_genes(adata) -> list[set[str]]:
    """Each scored LR pair's genes (every subunit), in the tensors' LR order."""
    pairs = scored_lr_pairs(import_ligand_receptor_pairs(), adata.var_names)
    return [
        set(subunits(ligand)) | set(subunits(receptor))
        for ligand, receptor in zip(pairs["ligand"], pairs["receptor"], strict=True)
    ]


def component_contexts(fits, comparators, cccrise_context, tensors) -> list[dict]:
    """Every component's scoring context: its method's tensor, its sender and
    receiver loadings and its LR column. cccRISE's are on its eigen-state
    tensor (`cccrise_context`: the tensor and its sender, receiver and LR
    loadings), each comparator's on its own tensor."""
    tensor, sender, receiver, lr = cccrise_context
    contexts = [
        {
            "Method": "cccRISE",
            "Component": k + 1,
            "tensor": tensor,
            "sender": sender[:, k],
            "receiver": receiver[:, k],
            "lr": lr[:, k],
        }
        for k in range(lr.shape[1])
    ]
    for other in comparators:
        for component in other.modes["lr"].columns:
            profiles = column_profiles(fits[other.method], other, component)
            contexts.append(
                {
                    "Method": other.method,
                    "Component": component,
                    "tensor": tensors[other.method].values,
                    "sender": profiles["sender"].to_numpy(),
                    "receiver": profiles["receiver"].to_numpy(),
                    "lr": other.modes["lr"][component].to_numpy(),
                }
            )
    return contexts


def covariation_summary(context: dict, top: np.ndarray, genes) -> dict:
    """The mean pairwise rank correlation of the LR pairs `top` scored in
    `context` (`covariation`), those sharing a gene (`genes`) merged into one
    in it and in every draw, and the mean and 95th percentile of that mean
    over each baseline's draws, with its one-sided empirical p: one plus the
    draws whose mean reaches the observed, over one plus the draws with a
    mean. All NaN when `top` leaves no two groups to correlate."""
    if len(top) < 2:  # nothing to co-vary with
        return {"Observed": np.nan}
    scored = covariation.context_scores(
        context["tensor"], context["sender"], context["receiver"]
    )
    observed = covariation.pairwise_rank_correlations(scored, top, genes, merge=True)
    if np.isnan(observed).all():  # every pair merged into one group
        return {"Observed": np.nan}
    summary = {"Observed": np.nanmean(observed)}
    for name, draws in covariation.covariation_baselines(
        scored, top, genes=genes, merge=True
    ).items():
        means = np.nanmean(draws, axis=1)
        means = means[~np.isnan(means)]
        if not means.size:  # every draw merged into one group
            continue
        summary |= {
            f"{name}_mean": means.mean(),
            f"{name}_q95": np.quantile(means, 0.95),
            f"{name}_p": (1 + (means >= summary["Observed"]).sum()) / (1 + means.size),
        }
    return summary


def covariation_rows(contexts: list[dict], genes: list[set[str]]) -> pd.DataFrame:
    """Every component's top-pair co-variation (`covariation.carrying_pairs`),
    pairs sharing a gene merged (`covariation_summary`)."""
    rows = []
    for context in contexts:
        top = covariation.carrying_pairs(context["lr"])
        rows.append(
            {"Method": context["Method"], "Component": context["Component"]}
            | {
                "PairsUsed": len(top),
                "GeneGroups": len(set(covariation.shared_gene_labels(top, genes))),
            }
            | covariation_summary(context, top, genes)
        )
    return pd.DataFrame(rows)


def sample_profiles(fits, comparators, cccrise: Components) -> dict:
    """Every component's sample profile, keyed (method, component): cccRISE's
    sample loadings, each comparator LR column's `column_profiles`."""
    profiles = {
        ("cccRISE", c): cccrise.modes["sample"][c]
        for c in cccrise.modes["sample"].columns
    }
    for other in comparators:
        for c in other.modes["lr"].columns:
            profiles[(other.method, c)] = column_profiles(fits[other.method], other, c)[
                "sample"
            ]
    return profiles


def sample_obs(spec: DatasetSpec, adata) -> pd.DataFrame:
    """Per sample: its depth (median genes detected per cell)."""
    sample = adata.obs[spec.condition_column].astype(str).to_numpy()
    detected = pd.Series(np.asarray((adata.X > 0).sum(axis=1)).ravel(), index=sample)
    return pd.DataFrame({"Depth": detected.groupby(level=0).median()})


def depth_rows(profiles: dict, obs: pd.DataFrame) -> pd.DataFrame:
    """|Spearman ρ| of every component's |sample profile| with depth."""
    rows = []
    for (m, c), v in profiles.items():
        rho = spearmanr(
            np.abs(v.to_numpy(float)), obs["Depth"].loc[v.index.astype(str)]
        ).statistic
        rows.append({"Method": m, "Component": c, "AbsRho": abs(float(rho))})
    return pd.DataFrame(rows)


def lr_loading_rows(components: list[Components]) -> pd.DataFrame:
    """Every fit's LR columns, long: one row per LR pair and component."""
    return pd.concat(
        [
            comp.modes["lr"]
            .rename_axis(index="LRPair", columns="Component")
            .stack()
            .rename("Loading")
            .reset_index()
            .assign(Method=comp.method)
            for comp in components
        ],
        ignore_index=True,
    )[["Method", "Component", "LRPair", "Loading"]]


def association_rows(spec: DatasetSpec, fits, comparators) -> pd.DataFrame:
    """Every component's outcome associations, cccRISE's (its own fit, as
    Figure 3) and each comparator's (module docstring)."""
    reference, _, _ = _resolve_factors_and_metadata(
        spec.factors_path(), condition_column=spec.condition_column
    )
    conditions = np.unique(reference.obs[spec.condition_column]).astype(str)
    frames = [_associations(reference, spec).assign(Method="cccRISE")]
    for other in comparators:
        loadings = pd.DataFrame(
            {
                component: column_profiles(fits[other.method], other, component)[
                    "sample"
                ]
                for component in other.modes["lr"].columns
            }
        )
        if not np.array_equal(loadings.index.to_numpy(), conditions):
            raise ValueError(f"{other.method}'s samples differ from cccRISE's.")
        adata = copy.copy(reference)
        adata.uns = {**adata.uns, "A": loadings.to_numpy()}
        frames.append(_associations(adata, spec).assign(Method=other.method))
    return pd.concat(frames, ignore_index=True)


def _associations(adata, spec: DatasetSpec) -> pd.DataFrame:
    """Figure 3's test of `adata`'s condition loadings (``uns["A"]``) against
    every association of the cohort's figure."""
    return run_multiple_factors_anova(
        adata,
        ASSOCIATIONS[spec.key],
        condition_column=spec.condition_column,
        correction="fdr_bh",
        global_correction=True,
    )


def labelling_components(spec: DatasetSpec, cells, labelling: str) -> tuple:
    """One labelling's fits, their `Components` and cccRISE's (its sender and
    receiver only with `cells`)."""
    fits = load_fits(spec, labelling)
    comparators = [
        scores.comparator_components(method, fit) for method, fit in fits.items()
    ]
    celltypes = fits["PB"]["sender"].to_numpy().astype(str)
    cccrise = scores.cccrise_components(
        load_factors_netcdf(spec.factors_path()),
        cells,
        spec.labellings[labelling],
        celltypes,
    )
    return fits, comparators, cccrise


#: `fit_tables`' tables that read only the fits and cccRISE's factors, never
#: the dataset or its per-cell weights.
DATA_FREE = ("containment", "fit_ranks", "start_congruence", "lr_loadings")


def fit_tables(
    spec: DatasetSpec,
    adata,
    labelling: str,
    random_state: int,
    components,
    only: list[str] | None = None,
) -> dict:
    """The tables of one labelling that need no tensors, or only those named
    in `only`, from `labelling_components`' `components` (depth from
    `adata`'s genes detected). Containment's draws come first from the
    labelling's generator, so they don't depend on `only`."""
    fits, comparators, cccrise = components
    rng = np.random.default_rng(random_state)
    builders = {
        "containment": lambda: containment_rows(cccrise, comparators, rng),
        "fit_ranks": lambda: fit_rank_rows(fits),
        "start_congruence": lambda: start_congruence_rows(spec, labelling),
        "lr_loadings": lambda: lr_loading_rows([cccrise, *comparators]),
        "associations": lambda: association_rows(spec, fits, comparators),
        "depth": lambda: depth_rows(
            sample_profiles(fits, comparators, cccrise), sample_obs(spec, adata)
        ),
    }
    unknown = set(only or ()) - set(builders)
    if unknown:
        raise ValueError(f"Not fit tables: {sorted(unknown)}")
    return {
        what: build() for what, build in builders.items() if not only or what in only
    }


def score_labelling(
    spec: DatasetSpec, adata, cells, labelling: str, random_state: int, cccrise_context
) -> dict:
    """The tables of one labelling (module docstring)."""
    column = spec.labellings[labelling]
    components = labelling_components(spec, cells, labelling)
    fits, comparators, _ = components
    tensors = context_tensors(spec, adata, column)
    contexts = component_contexts(fits, comparators, cccrise_context, tensors)
    return {
        **fit_tables(spec, adata, labelling, random_state, components),
        "inner_loss": inner_loss_rows(cells, column, tensors),
        "covariation": covariation_rows(contexts, lr_genes(adata)),
    }


def merged_labellings(tables: dict) -> dict:
    """Each table of `tables` (keyed by labelling), every labelling's rows
    in it under a ``Labelling`` column."""
    first = next(iter(tables.values()))
    return {
        what: pd.concat(
            {lab: t[what] for lab, t in tables.items()}, names=["Labelling"]
        )
        .reset_index(level="Labelling")
        .reset_index(drop=True)
        for what in first
    }


def _load(spec: DatasetSpec) -> tuple:
    """The dataset and its cells with cccRISE's per-cell weights."""
    adata = spec.load()
    return adata, load_factors_to_anndata(spec.factors_path(), adata=adata)


def _fit_only_tables(
    spec: DatasetSpec, labellings, random_state: int, only: list[str] | None
) -> dict:
    """`fit_tables`' tables (or `only` those) of every labelling, loading the
    dataset only when one of them needs it (not all `DATA_FREE`)."""
    if only and set(only) <= set(DATA_FREE):
        adata = cells = None
    else:
        adata, cells = _load(spec)
    return {
        lab: fit_tables(
            spec,
            adata,
            lab,
            random_state,
            labelling_components(spec, cells, lab),
            only,
        )
        for lab in labellings
    }


def _all_tables(spec: DatasetSpec, labellings, random_state: int) -> dict:
    """Every table of every labelling (`score_labelling`)."""
    adata, cells = _load(spec)
    factors = load_factors_netcdf(spec.factors_path())
    cccrise_context = (
        covariation.cccrise_tensor(spec.factors_path(), adata, spec.condition_column),
        *(factors[k].to_numpy().astype(float) for k in ("cp_B", "cp_C", "cp_D")),
    )
    return {
        labelling: score_labelling(
            spec, adata, cells, labelling, random_state, cccrise_context
        )
        for labelling in labellings
    }


def run_comparator_scores(
    spec: DatasetSpec,
    random_state: int,
    command: str = "uv run cccrise-comparator-scores",
    fits_only: bool = False,
    only: list[str] | None = None,
) -> None:
    """Every table (module docstring) of `spec`, or with `fits_only` only
    `fit_tables`', or those named in `only`, their provenance recorded as
    written by `command`."""
    git_sha()
    labellings = list(spec.labellings)
    print(f"=== Comparator scores: {spec.label}; {', '.join(labellings)} ===")
    metadata = _metadata(spec, labellings, random_state)
    if fits_only:
        tables = _fit_only_tables(spec, labellings, random_state, only)
    else:
        tables = _all_tables(spec, labellings, random_state)
    merged = merged_labellings(tables)
    write_tables(
        spec,
        {what: t for what, t in merged.items() if not only or what in only},
        metadata,
        command,
    )


def _metadata(spec: DatasetSpec, labellings, random_state: int) -> dict:
    inputs = {
        f"{method} {labelling}": sha256_file(
            COMPARATOR_FITS_DIR
            / comparator_filename(key, "fit", spec.output_key, labelling)
        )
        for key, method in METHODS.items()
        for labelling in labellings
    }
    return build_metadata(
        dataset_metadata(spec)
        | {
            "labelling": " and ".join(labellings),
            "celltype_key": " and ".join(spec.labellings[lab] for lab in labellings),
            "fit_sha256": inputs,
            "n_null": N_NULL,
            "random_state": random_state,
        }
    )


def write_tables(spec: DatasetSpec, tables: dict, metadata: dict, command: str) -> None:
    for what, table in tables.items():
        path = COMPARATOR_SCORES_DIR / scores_filename(what, spec.output_key)
        path.parent.mkdir(parents=True, exist_ok=True)
        table.to_parquet(path, index=False)
        record_output(path, metadata, command, header=HEADER)
        print(f"   wrote {path.name}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--fits-only",
        action="store_true",
        help="Write only the tables that need no tensors (module docstring).",
    )
    parser.add_argument(
        "--tables",
        nargs="+",
        help="Score everything but write only these tables, so a cohort keeps "
        "only the tables a figure reads; with --fits-only, score only these "
        "(without loading the dataset when all are DATA_FREE).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args, command = parse_command(build_parser(), "cccrise-comparator-scores", argv)
    spec = resolve_dataset(args)
    run_comparator_scores(
        spec,
        args.random_state,
        command,
        args.fits_only,
        args.tables,
    )


if __name__ == "__main__":
    main()
