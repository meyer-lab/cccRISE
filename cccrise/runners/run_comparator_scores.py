def load_fits(spec: DatasetSpec, labelling: str) -> dict[str, xr.Dataset]:
    fits = {}
    for key, method in METHODS.items():
        path = COMPARATOR_FITS_DIR / comparator_filename(
            key, "fit", spec.output_key, labelling
        )
        with xr.open_dataset(path, engine="h5netcdf") as fit:
            fits[method] = fit.load()
    return fits


def containment_rows(fits: list[Components], rng) -> pd.DataFrame:
    """Every fit's sample and LR columns in every other fit's span."""
    frames = [
        scores.containment(span.modes[mode], of.modes[mode], N_NULL, rng).assign(
            Of=of.method, In=span.method, Mode=mode
        )
        for of, span in permutations(fits, 2)
        for mode in ("sample", "lr")
    ]
    return pd.concat(frames, ignore_index=True)


def breadth_rows(components: list[Components]) -> pd.DataFrame:
    """Every component's effective number, top share and top label per mode."""
    frames = []
    for fit in components:
        for mode, columns in fit.modes.items():
            frames.append(
                pd.DataFrame(
                    {
                        "Method": fit.method,
                        "Mode": mode,
                        "Component": columns.columns,
                        "Effective": scores.effective_number(columns).to_numpy(),
                        "TopShare": scores.top_share(columns).to_numpy(),
                        "Top": scores.oriented(columns).idxmax().to_numpy(),
                    }
                )
            )
    return pd.concat(frames, ignore_index=True)


def column_profiles(
    fit: xr.Dataset, components: Components, column: int
) -> dict[str, pd.Series]:
    """A comparator LR column's sample, sender and receiver profiles, signed
    so the largest entry is positive."""
    if "core" in fit:
        raw = scores.tucker_column_profiles(fit, column)
        labels = {m: fit[m].to_numpy().astype(str) for m in raw}
        frames = {m: pd.DataFrame({column: raw[m]}, index=labels[m]) for m in raw}
    else:
        frames = {
            m: components.modes[m][[column]] for m in ("sample", "sender", "receiver")
        }
    return {m: scores.oriented(f)[column] for m, f in frames.items()}


def audit_rows(
    fits: dict[str, xr.Dataset],
    comparators: list[Components],
    containment: pd.DataFrame,
    adata,
    spec: DatasetSpec,
    celltype_column: str,
) -> pd.DataFrame:
    """Every comparator LR column outside cccRISE's LR span, classed."""
    missed = containment[
        (containment["In"] == "cccRISE")
        & (containment["Mode"] == "lr")
        & ~containment["Contained"]
    ]
    pairs = scored_lr_pairs(import_ligand_receptor_pairs(), adata.var_names)
    pairs = pairs.set_index("lr_pair")
    records = []
    for other in comparators:
        for _, row in missed[missed["Of"] == other.method].iterrows():
            column = row["Component"]
            lr = scores.oriented(other.modes["lr"][[column]])[column]
            profiles = column_profiles(fits[other.method], other, column)
            records.append(
                {
                    "Method": other.method,
                    "Component": column,
                    "Containment": row["Containment"],
                    "LRPair": lr.idxmax(),
                    "Ligand": pairs.loc[lr.idxmax(), "ligand"],
                    "Receptor": pairs.loc[lr.idxmax(), "receptor"],
                    "TopSender": profiles["sender"].idxmax(),
                    "TopReceiver": profiles["receiver"].idxmax(),
                    "EffectiveLR": scores.effective_number(lr.to_frame()).iloc[0],
                    "EffectiveSamples": scores.effective_number(
                        profiles["sample"].to_frame()
                    ).iloc[0],
                    "SampleProfile": profiles["sample"],
                }
            )
    genes = [
        g
        for r in records
        for side in ("Ligand", "Receptor")
        for g in subunits(str(r[side]))
    ]
    fold, detected = scores.marker_stats(adata, celltype_column, genes)
    fractions = pd.crosstab(
        adata.obs[spec.condition_column].astype(str),
        adata.obs[celltype_column].astype(str),
        normalize="index",
    )
    for record in records:
        record["Class"] = scores.classify(record, fold, detected, fractions)
    return pd.DataFrame(records).drop(columns="SampleProfile")


def inner_loss_tables(cells, column: str, tensors: dict[str, PooledTensor]) -> dict:
    """What the published Tensor-cell2cell construction drops (module
    docstring), from `context_tensors`' masked and published tensors."""
    masked = tensors["TC2C"]
    kept = tensors["TC2C inner"].celltypes
    dropped = ~cells.obs[column].astype(str).isin(list(kept)).to_numpy()
    names = np.arange(1, cells.obsm["sc_B"].shape[1] + 1)
    programs = pd.concat(
        [
            scores.weight_share(pd.DataFrame(cells.obsm[key], columns=names), dropped)
            .rename_axis("Component")
            .rename("Share")
            .reset_index()
            .assign(Side=side)
            for side, key in (("sender", "sc_B"), ("receiver", "rc_C"))
        ],
        ignore_index=True,
    )
    cell_share = {"Measure": "cells", "Dropped": dropped.sum(), "Total": dropped.size}
    losses = pd.concat(
        [
            scores.inner_losses(masked, kept),
            pd.DataFrame([cell_share | {"Share": dropped.mean()}]),
        ],
        ignore_index=True,
    )
    return {"inner_loss": losses, "inner_program_loss": programs}


def representability_rows(cells, spec: DatasetSpec, column: str, rng) -> pd.DataFrame:
    """`scores.representability` of cccRISE's sender and receiver weights."""
    samples = cells.obs[spec.condition_column].astype(str).to_numpy()
    celltypes = cells.obs[column].astype(str).to_numpy()
    names = np.arange(1, cells.obsm["sc_B"].shape[1] + 1)
    return pd.concat(
        [
            scores.representability(
                pd.DataFrame(cells.obsm[key], columns=names),
                samples,
                celltypes,
                N_SPLITS,
                rng,
            ).assign(Side=side)
            for side, key in (("sender", "sc_B"), ("receiver", "rc_C"))
        ],
        ignore_index=True,
    )


def context_tensors(spec: DatasetSpec, adata, column: str) -> dict[str, PooledTensor]:
    """Each comparator's own tensor on `column`'s cell types."""
    lr_pairs = import_ligand_receptor_pairs()
    sample = spec.condition_column
    return {
        "PB": pseudobulk_tensor(adata, sample, column, lr_pairs),
        "STAC": staccato_tensor(adata, sample, column, lr_pairs),
        "TC2C": tensor_cell2cell_tensor(adata, sample, column, lr_pairs),
        "TC2C inner": tensor_cell2cell_tensor(
            adata, sample, column, lr_pairs, how="inner"
        ),
    }


def lr_genes(adata) -> list[set[str]]:
    """Each scored LR pair's genes (every subunit), in the tensors' LR order."""
    pairs = scored_lr_pairs(import_ligand_receptor_pairs(), adata.var_names)
    return [
        set(subunits(ligand)) | set(subunits(receptor))
        for ligand, receptor in zip(pairs["ligand"], pairs["receptor"], strict=True)
    ]


def component_contexts(fits, comparators, cccrise_context, tensors) -> list[dict]:
    """Every component's scoring context: its method's tensor, its sender and
    receiver loadings and its LR column. cccRISE's are on its eigen-state
    tensor (`cccrise_context`: the tensor and its sender, receiver and LR
    loadings), each comparator's on its own tensor."""
    tensor, sender, receiver, lr = cccrise_context
    contexts = [
        {
            "Method": "cccRISE",
            "Component": k + 1,
            "tensor": tensor,
            "sender": sender[:, k],
            "receiver": receiver[:, k],
            "lr": lr[:, k],
        }
        for k in range(lr.shape[1])
    ]
    for other in comparators:
        for component in other.modes["lr"].columns:
            profiles = column_profiles(fits[other.method], other, component)
            contexts.append(
                {
                    "Method": other.method,
                    "Component": component,
                    "tensor": tensors[other.method].values,
                    "sender": profiles["sender"].to_numpy(),
                    "receiver": profiles["receiver"].to_numpy(),
                    "lr": other.modes["lr"][component].to_numpy(),
                }
            )
    return contexts


def covariation_summary(context: dict, top: np.ndarray, genes=None) -> dict:
    """The mean pairwise rank correlation of the LR pairs `top` scored in
    `context` (`covariation`), and the mean and 95th percentile of that mean
    over each baseline's draws; with `genes`, over gene-disjoint pairs only.
    All NaN when `top` leaves no pair of pairs to correlate."""
    if len(top) < 2:  # nothing to co-vary with
        return {"Observed": np.nan}
    scored = covariation.context_scores(
        context["tensor"], context["sender"], context["receiver"]
    )
    observed = covariation.pairwise_rank_correlations(scored, top, genes)
    if np.isnan(observed).all():  # every pair of pairs shares a gene
        return {"Observed": np.nan}
    summary = {"Observed": np.nanmean(observed)}
    for name, draws in covariation.covariation_baselines(
        scored, top, genes=genes
    ).items():
        means = np.nanmean(draws, axis=1)
        summary |= {
            f"{name}_mean": np.nanmean(means),
            f"{name}_q95": np.nanquantile(means, 0.95),
        }
    return summary


def covariation_rows(contexts: list[dict], genes: list[set[str]]) -> pd.DataFrame:
    """Every component's top-pair co-variation (`covariation.carrying_pairs`)
    over all pairs of its top pairs and, suffixed ``_disjoint``, over those
    sharing no gene."""
    rows = []
    for context in contexts:
        top = covariation.carrying_pairs(context["lr"])
        disjoint = covariation_summary(context, top, genes)
        lr = pd.DataFrame(context["lr"])
        rows.append(
            {"Method": context["Method"], "Component": context["Component"]}
            | {
                "EffectiveLR": scores.effective_number(lr).iloc[0],
                "TopShare": scores.top_share(lr).iloc[0],
                "PairsUsed": len(top),
            }
            | covariation_summary(context, top)
            | {f"{k}_disjoint": v for k, v in disjoint.items()}
        )
    return pd.DataFrame(rows)


def _cosine(a: np.ndarray, b: np.ndarray) -> float:
    return abs(a @ b) / (np.linalg.norm(a) * np.linalg.norm(b))


def best_matches(program: dict, contexts: list[dict]) -> list[dict]:
    """`program` (a cccRISE context) and, per comparator, its LR column of
    greatest |cosine| with the program's."""
    methods = dict.fromkeys(c["Method"] for c in contexts if c["Method"] != "cccRISE")
    return [program] + [
        max(
            (c for c in contexts if c["Method"] == method),
            key=lambda c: _cosine(program["lr"], c["lr"]),
        )
        for method in methods
    ]


def program_capture_tables(contexts: list[dict], pairs: np.ndarray) -> dict:
    """How each comparator captures each cccRISE program: its best-matching
    LR column (`best_matches`), that column's loadings on the program's top
    pairs relative to its heaviest (``program_capture``), and whether the
    program's top pairs co-vary when scored in that column's context
    (``program_covariation``; the program's own context for cccRISE)."""
    loadings, coordination = [], []
    for program in (c for c in contexts if c["Method"] == "cccRISE"):
        top = covariation.top_pairs(program["lr"])
        for candidate in best_matches(program, contexts):
            key = {
                "Program": program["Component"],
                "Method": candidate["Method"],
                "Column": candidate["Component"],
                "Cosine": _cosine(program["lr"], candidate["lr"]),
            }
            relative = np.abs(candidate["lr"]) / np.abs(candidate["lr"]).max()
            loadings += [
                key
                | {"Pair": pairs[p], "PairRank": i + 1, "RelativeLoading": relative[p]}
                for i, p in enumerate(top)
            ]
            coordination.append(key | covariation_summary(candidate, top))
    return {
        "program_capture": pd.DataFrame(loadings),
        "program_covariation": pd.DataFrame(coordination),
    }


def sample_profiles(fits, comparators, cccrise: Components) -> dict:
    """Every component's sample profile, keyed (method, component): cccRISE's
    sample loadings, each comparator LR column's `column_profiles`."""
    profiles = {
        ("cccRISE", c): cccrise.modes["sample"][c]
        for c in cccrise.modes["sample"].columns
    }
    for other in comparators:
        for c in other.modes["lr"].columns:
            profiles[(other.method, c)] = column_profiles(fits[other.method], other, c)[
                "sample"
            ]
    return profiles


def sample_obs(spec: DatasetSpec, adata) -> pd.DataFrame:
    """Per sample: its depth (median genes detected per cell) and, where the
    dataset has it, its 6-month outcome."""
    sample = adata.obs[spec.condition_column].astype(str).to_numpy()
    detected = pd.Series(np.asarray((adata.X > 0).sum(axis=1)).ravel(), index=sample)
    obs = adata.obs.drop_duplicates(spec.condition_column)
    obs = obs.set_index(obs[spec.condition_column].astype(str))
    out = pd.DataFrame({"Depth": detected.groupby(level=0).median()})
    if OUTCOME_COLUMN in obs:
        out["Outcome"] = obs[OUTCOME_COLUMN].astype(str)
    return out


def profile_rows(profiles: dict, obs: pd.DataFrame) -> pd.DataFrame:
    """`sample_profiles` long, one row per component and sample."""
    return pd.concat(
        [
            v.rename("Loading")
            .rename_axis("Sample")
            .reset_index()
            .assign(Method=m, Component=c)
            for (m, c), v in profiles.items()
        ],
        ignore_index=True,
    ).merge(
        obs.drop(columns="Depth").rename_axis("Sample").reset_index(),
        on="Sample",
        how="left",
    )


def depth_rows(profiles: dict, obs: pd.DataFrame) -> pd.DataFrame:
    """|Spearman ρ| of every component's |sample profile| with depth."""
    rows = []
    for (m, c), v in profiles.items():
        rho = spearmanr(
            np.abs(v.to_numpy(float)), obs["Depth"].loc[v.index.astype(str)]
        ).statistic
        rows.append({"Method": m, "Component": c, "AbsRho": abs(float(rho))})
    return pd.DataFrame(rows)


def homophily_rows(components: list[Components], adata) -> pd.DataFrame:
    """Every component's share of squared LR loading on homophilic pairs."""
    pairs = scored_lr_pairs(import_ligand_receptor_pairs(), adata.var_names).set_index(
        "lr_pair"
    )
    homophilic = pd.Series(
        [
            scores.is_homophilic(lig, rec)
            for lig, rec in zip(pairs["ligand"], pairs["receptor"], strict=True)
        ],
        index=pairs.index,
    )
    rows = []
    for comp in components:
        lr = comp.modes["lr"]
        squared = lr.to_numpy(float) ** 2
        mask = homophilic.loc[lr.index.astype(str)].to_numpy()
        share = squared[mask].sum(axis=0) / squared.sum(axis=0)
        rows += [
            {"Method": comp.method, "Component": c, "HomophilicShare": float(v)}
            for c, v in zip(lr.columns, share, strict=True)
        ]
    return pd.DataFrame(rows)


def input_rows(
    tensors: dict[str, PooledTensor], cccrise_tensor, obs: pd.DataFrame
) -> pd.DataFrame:
    """Each method's input tensor, its per-sample mean over observed
    entries, with each sample's depth."""
    samples = tensors["PB"].samples.astype(str)
    means = {"cccRISE": cccrise_tensor.mean(axis=(1, 2, 3))}
    for method in ("PB", "TC2C", "STAC"):
        t = tensors[method]
        mask = np.ones_like(t.values) if t.mask is None else t.mask
        means[method] = (t.values * mask).sum(axis=(1, 2, 3)) / mask.sum(axis=(1, 2, 3))
    return (
        pd.DataFrame(means)
        .assign(Sample=samples, Depth=obs["Depth"].loc[samples].to_numpy())
        .melt(id_vars=["Sample", "Depth"], var_name="Method", value_name="Mean")
    )


def _context_pool(contexts: dict) -> dict:
    """Every context of `contexts` (keyed by labelling) keyed (method,
    labelling, component), cccRISE's once and the published Tensor-cell2cell
    left out."""
    first = next(iter(contexts))
    return {
        (c["Method"], lab, int(c["Component"])): c
        for lab, cs in contexts.items()
        for c in cs
        if c["Method"] != "TC2C inner" and (c["Method"] != "cccRISE" or lab == first)
    }


def _is_associated(associations: dict, key) -> bool:
    method, lab, comp = key
    a = associations[lab]
    return (
        a[(a["Method"] == method) & (a["Component"] == comp)]["PAdj"].min() < SIG_ALPHA
    )


def _reference_rows(pool: dict, key) -> list[dict]:
    """`key`'s top pairs scored in its own context and in its `CLOSEST`
    columns of other fits."""
    ref = pool[key]
    top = covariation.top_pairs(ref["lr"])
    others = sorted(
        (k for k in pool if k[:2] != key[:2]),
        key=lambda k: -_cosine(pool[k]["lr"], ref["lr"]),
    )
    names = ("Method", "Labelling", "Column")
    return [
        dict(zip(("RefMethod", "RefLabelling", "RefColumn"), key, strict=True))
        | dict(zip(names, other, strict=True))
        | {"Cosine": _cosine(pool[other]["lr"], ref["lr"])}
        | covariation_summary(pool[other], top)
        for other in [key, *others[:CLOSEST]]
    ]


def pair_covariation_rows(contexts: dict, associations: dict) -> pd.DataFrame:
    """Every component with an association below `SIG_ALPHA`: its top pairs'
    `covariation_summary` in its own context and in those of the `CLOSEST`
    LR columns of other fits (another method, or its own at the other
    labelling) of greatest |cosine| with it. `contexts` and `associations`
    are keyed by labelling."""
    pool = _context_pool(contexts)
    rows = [
        row
        for key in pool
        if _is_associated(associations, key)
        for row in _reference_rows(pool, key)
    ]
    return pd.DataFrame(rows)


def association_rows(spec: DatasetSpec, fits, comparators) -> pd.DataFrame:
    """Every component's outcome associations, cccRISE's (its own fit, as
    Figure 3) and each comparator's (module docstring)."""
    reference, _, _ = _resolve_factors_and_metadata(
        spec.factors_path(), condition_column=spec.condition_column
    )
    conditions = np.unique(reference.obs[spec.condition_column]).astype(str)
    frames = [_associations(reference, spec).assign(Method="cccRISE")]
    for other in comparators:
        loadings = pd.DataFrame(
            {
                component: column_profiles(fits[other.method], other, component)[
                    "sample"
                ]
                for component in other.modes["lr"].columns
            }
        )
        if not np.array_equal(loadings.index.to_numpy(), conditions):
            raise ValueError(f"{other.method}'s samples differ from cccRISE's.")
        adata = copy.copy(reference)
        adata.uns = {**adata.uns, "A": loadings.to_numpy()}
        frames.append(_associations(adata, spec).assign(Method=other.method))
    return pd.concat(frames, ignore_index=True)


def _associations(adata, spec: DatasetSpec) -> pd.DataFrame:
    """Figure 3's test of `adata`'s condition loadings (``uns["A"]``) against
    every ALAD association."""
    return run_multiple_factors_anova(
        adata,
        ASSOCIATIONS,
        condition_column=spec.condition_column,
        correction="fdr_bh",
        global_correction=True,
    )


def score_labelling(
    spec: DatasetSpec, adata, cells, labelling: str, rng, cccrise_context
) -> tuple[dict, list[dict]]:
    """The tables of one labelling (module docstring), and its components'
    scoring contexts."""
    column = spec.labellings[labelling]
    fits = load_fits(spec, labelling)
    comparators = [
        scores.comparator_components(method, fit) for method, fit in fits.items()
    ]
    celltypes = fits["PB"]["sender"].to_numpy().astype(str)
    cccrise = scores.cccrise_components(
        load_factors_netcdf(spec.factors_path()), cells, column, celltypes
    )
    containment = containment_rows([cccrise, *comparators], rng)
    tensors = context_tensors(spec, adata, column)
    contexts = component_contexts(fits, comparators, cccrise_context, tensors)
    profiles = sample_profiles(fits, comparators, cccrise)
    obs = sample_obs(spec, adata)
    tables = {
        "containment": containment,
        "breadth": breadth_rows([cccrise, *comparators]),
        "audit": audit_rows(fits, comparators, containment, adata, spec, column),
        "representability": representability_rows(cells, spec, column, rng),
        **inner_loss_tables(cells, column, tensors),
        "associations": association_rows(spec, fits, comparators),
        "covariation": covariation_rows(contexts, lr_genes(adata)),
        **program_capture_tables(contexts, cccrise.modes["lr"].index.to_numpy()),
        "profiles": profile_rows(profiles, obs),
        "homophily": homophily_rows([cccrise, *comparators], adata),
        "depth": depth_rows(profiles, obs),
        "inputs": input_rows(tensors, cccrise_context[0], obs),
    }
    return tables, contexts


def run_comparator_scores(spec: DatasetSpec, labellings, random_state: int) -> None:
    git_sha()
    print(f"=== Comparator scores: {spec.label}; {', '.join(labellings)} ===")
    adata = spec.load()
    cells = load_factors_to_anndata(spec.factors_path(), adata=adata)
    rng = np.random.default_rng(random_state)
    factors = load_factors_netcdf(spec.factors_path())
    cccrise_context = (
        covariation.cccrise_tensor(spec.factors_path(), adata, spec.condition_column),
        *(factors[k].to_numpy().astype(float) for k in ("cp_B", "cp_C", "cp_D")),
    )
    contexts, associations = {}, {}
    for labelling in labellings:
        tables, contexts[labelling] = score_labelling(
            spec, adata, cells, labelling, rng, cccrise_context
        )
        associations[labelling] = tables["associations"]
        write_tables(
            spec, labelling, tables, _metadata(spec, [labelling], random_state)
        )
    if len(labellings) > 1:
        write_tables(
            spec,
            "both",
            {"pair_covariation": pair_covariation_rows(contexts, associations)},
            _metadata(spec, labellings, random_state),
        )


def _metadata(spec: DatasetSpec, labellings, random_state: int) -> dict:
    inputs = {
        f"{method} {labelling}": sha256_file(
            COMPARATOR_FITS_DIR
            / comparator_filename(key, "fit", spec.output_key, labelling)
        )
        for key, method in METHODS.items()
        for labelling in labellings
    }
    return build_metadata(
        dataset_metadata(spec)
        | {
            "labelling": " and ".join(labellings),
            "celltype_key": " and ".join(spec.labellings[lab] for lab in labellings),
            "fit_sha256": inputs,
            "n_null": N_NULL,
            "n_random_splits": N_SPLITS,
            "random_state": random_state,
            "contained": scores.CONTAINED,
            "diffuse_lr_pairs": scores.DIFFUSE_LR,
        }
    )


def write_tables(
    spec: DatasetSpec, labelling: str, tables: dict, metadata: dict
) -> None:
    for what, table in tables.items():
        path = COMPARATOR_SCORES_DIR / scores_filename(what, spec.output_key, labelling)
        path.parent.mkdir(parents=True, exist_ok=True)
        table.to_parquet(path, index=False)
        write_metadata(path, metadata, header=HEADER)
        print(f"   wrote {path.name}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--labellings", nargs="+", default=None)
    parser.add_argument("--random-state", type=int, default=42)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = resolve_dataset(args)
    run_comparator_scores(
        spec, args.labellings or list(spec.labellings), args.random_state
    )


if __name__ == "__main__":
    main()
