"""
Runner: the cohort a finalized fit was made on, summarized per sample and per
cell type, so figures can describe a large cohort without loading its cells.

Like `run_nichenet`, this does not refit RISE/CPD: it loads the dataset and
its already-finalized factor fit (``spec.factors_path()``), whose fingerprint
(cell IDs, genes and gene centering) `factors.load_factors_to_anndata`
checks before projecting the cells. Writes four tables:

    cohort_samples_<dataset>.parquet
        one row per condition, in the fit's condition order: every `obs`
        column constant within a condition, its cell count and read depth
        (`utils.condition_read_depths`, so any condition factor can be
        corrected as `utils.correct_conditions` does), and its raw and
        read-depth-corrected (as the ANOVA tests) CP condition loadings
    cohort_celltype_counts_<dataset>.parquet
        cells per condition x lineage (the registry's cell type column) x fine
        cell type (`--fine-celltype-column`)
    celltype_component_weights_<dataset>.parquet
        each lineage's and fine cell type's mean per-cell sender and receiver
        weight on every CP component (`utils.celltype_component_association`)
    carrier_expression_<dataset>.parquet
        mean normalized expression and fraction of cells detecting each gene
        of every component's `TOP_PAIRS` highest-loading LR pairs, per
        condition x fine cell type

    uv run cccrise-cohort --dataset ibd
"""

import argparse
from pathlib import Path
from typing import Any, cast

import anndata
import numpy as np
import pandas as pd

from ..factors import load_factors_netcdf, load_factors_to_anndata
from ..utils import (
    celltype_component_association,
    condition_read_depths,
    correct_conditions,
)
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    resolve_dataset,
    resulting_dims,
)
from .datasets import VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

HEADER = """\
The cohort a finalized factor fit was made on, summarized per condition and
per cell type. Generated by cccrise.runners.run_cohort -- do not hand-edit.
"""
ROLES = {"sender": "sc_B", "receiver": "rc_C"}
#: LR pairs per CP component whose genes `carrier_expression` summarizes
TOP_PAIRS = 3


def sample_table(adata: anndata.AnnData, spec: DatasetSpec, conditions) -> pd.DataFrame:
    """One row per condition (in `conditions` order): every `obs` column
    constant within a condition, its cell count, and its raw (`loading_C<k>`)
    and read-depth-corrected (`loading_corrected_C<k>`) CP condition loadings."""
    obs = cast(pd.DataFrame, adata.obs)
    by_condition = obs.groupby(spec.condition_column, observed=True)
    constant = [
        col
        for col in obs.columns
        if col not in (spec.condition_column, "condition_unique_idxs")
        and by_condition[col].nunique().max() <= 1
    ]
    table = by_condition[constant].first().reindex(conditions)
    table.insert(0, "n_cells", by_condition.size().reindex(conditions))
    table.insert(1, "read_depth", condition_read_depths(adata))
    raw, corrected = np.asarray(adata.uns["A"]), correct_conditions(adata)
    for k in range(raw.shape[1]):
        table[f"loading_C{k + 1}"] = raw[:, k]
    for k in range(raw.shape[1]):
        table[f"loading_corrected_C{k + 1}"] = corrected[:, k]
    return table.rename_axis(spec.condition_column).reset_index()


def celltype_counts(
    adata: anndata.AnnData, spec: DatasetSpec, fine_column: str
) -> pd.DataFrame:
    """Cells per condition x lineage x fine cell type (nonzero only)."""
    columns = [spec.condition_column, spec.celltype_column, fine_column]
    obs = cast(pd.DataFrame, adata.obs)[columns].astype(str)
    counts = obs.value_counts().rename("n_cells").reset_index()
    return counts.rename(
        columns={spec.celltype_column: "lineage", fine_column: "celltype"}
    ).sort_values(columns[:1] + ["lineage", "celltype"], ignore_index=True)


def celltype_weights(
    adata: anndata.AnnData, spec: DatasetSpec, fine_column: str
) -> pd.DataFrame:
    """Each lineage's and fine cell type's mean per-cell sender and receiver
    weight on every CP component, long: level, celltype, lineage, n_cells,
    role, component, mean_weight."""
    obs = cast(pd.DataFrame, adata.obs)
    lineage_of = obs.groupby(fine_column, observed=True)[spec.celltype_column].first()
    frames = []
    for level, column in (("lineage", spec.celltype_column), ("fine", fine_column)):
        n_cells = obs[column].astype(str).value_counts()
        for role in ROLES:
            table = celltype_component_association(
                adata, factor_type=role, celltype_col=column, stat="mean"
            )
            long = table.rename_axis("celltype").melt(
                ignore_index=False, var_name="component", value_name="mean_weight"
            )
            long = long.reset_index().assign(level=level, role=role)
            long["n_cells"] = long["celltype"].map(n_cells).to_numpy()
            long["lineage"] = (
                long["celltype"]
                if level == "lineage"
                else long["celltype"].map(lineage_of.astype(str))
            )
            frames.append(long)
    columns = ["level", "celltype", "lineage", "n_cells", "role", "component"]
    return pd.concat(frames, ignore_index=True)[[*columns, "mean_weight"]]


def top_pair_genes(adata: anndata.AnnData, n_pairs: int = TOP_PAIRS) -> list[str]:
    """The ligand and receptor genes (complex subunits split) of each CP
    component's `n_pairs` LR pairs of largest |loading|, in first-seen order."""
    loadings = np.abs(np.asarray(adata.uns["D"]))
    top = np.argsort(-loadings, axis=0)[:n_pairs].T.ravel()
    pairs = np.asarray(adata.uns["lr_pairs"])[top]
    genes = [g for pair in pairs for part in pair.split("^") for g in part.split("&")]
    return list(dict.fromkeys(genes))


def carrier_expression(
    adata: anndata.AnnData, spec: DatasetSpec, fine_column: str, genes: list[str]
) -> pd.DataFrame:
    """Mean normalized expression and fraction of cells with nonzero
    expression of each of `genes`, per condition x fine cell type, long:
    condition, celltype, n_cells, gene, mean_expression, fraction_detected."""
    missing = set(genes) - set(adata.var_names)
    assert not missing, f"LR genes absent from the data: {sorted(missing)}"
    expression = pd.DataFrame(
        cast(Any, adata[:, genes].X).toarray(), columns=pd.Index(genes, name="gene")
    )
    keys = [
        adata.obs[spec.condition_column].astype(str).to_numpy(),
        adata.obs[fine_column].astype(str).to_numpy(),
    ]
    grouped = expression.groupby(keys)
    names = {"level_0": "condition", "level_1": "celltype"}
    means = cast(pd.Series, grouped.mean().stack()).rename("mean_expression")
    detected = (expression > 0).groupby(keys).mean().stack()
    detected = cast(pd.Series, detected).rename("fraction_detected")
    table = pd.concat([means, detected], axis=1).reset_index().rename(columns=names)
    n_cells = cast(pd.Series, grouped.size()).rename("n_cells").reset_index()
    n_cells = n_cells.rename(columns=names)
    return n_cells.merge(table, on=["condition", "celltype"])


def run_cohort(
    spec: DatasetSpec, fine_column: str = "celltype", output_dir: Path | None = None
) -> dict[str, Path]:
    """Write the four cohort tables for `spec` and their sidecars; return
    their paths by table name."""
    factors_path = spec.factors_path()
    if not factors_path.exists():
        raise FileNotFoundError(
            f"{factors_path} not found. Produce it with:\n"
            f"    uv run cccrise-run --dataset {spec.key} --rise-rank <N> --cp-rank <M>"
        )
    output_dir = output_dir or VALIDATION_DIR
    output_dir.mkdir(parents=True, exist_ok=True)
    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== Cohort summary: {spec.label} ===")
    print(f"1. Loading the data and projecting it onto {factors_path}...")
    # Raises unless the data's cells, genes and centering match the fit's
    adata = load_factors_to_anndata(factors_path, adata=spec.load())
    # `correct_conditions` indexes conditions in sorted order; the fit's rows
    # must be in that order too
    conditions = np.unique(adata.obs[spec.condition_column].astype(str))
    fit_conditions = load_factors_netcdf(factors_path).coords["condition"].values
    assert np.array_equal(conditions, fit_conditions.astype(str))

    print("2. Summarizing conditions and cell types...")
    tables = {
        "cohort_samples": sample_table(adata, spec, conditions),
        "cohort_celltype_counts": celltype_counts(adata, spec, fine_column),
        "celltype_component_weights": celltype_weights(adata, spec, fine_column),
        "carrier_expression": carrier_expression(
            adata, spec, fine_column, genes := top_pair_genes(adata)
        ),
    }
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_path": relpath(factors_path),
            "factors_sha256": sha256_file(factors_path),
            "fit_fingerprint_checked": True,
            "fine_celltype_key": fine_column,
            "top_pairs_per_component": TOP_PAIRS,
            "carrier_expression_genes": genes,
            "cp_rank": int(np.shape(adata.uns["A"])[1]),
            "resulting_dims": resulting_dims(spec, adata),
        }
    )
    paths = {}
    for name, table in tables.items():
        path = output_dir / f"{name}_{spec.output_key}.parquet"
        table.to_parquet(path, index=False)
        write_metadata(path, metadata, header=HEADER)
        print(f"   Wrote {len(table)} rows to {relpath(path)}")
        paths[name] = path
    return paths


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--fine-celltype-column",
        default="celltype",
        help="`obs` column of the fine cell type annotation (default: celltype).",
    )
    parser.add_argument(
        "--output-dir",
        default=None,
        help="Directory for the tables; defaults to data/validation_results/.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    run_cohort(
        resolve_dataset(args),
        fine_column=args.fine_celltype_column,
        output_dir=Path(args.output_dir) if args.output_dir else None,
    )


if __name__ == "__main__":
    main()
