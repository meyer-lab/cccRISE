#!/usr/bin/env python
"""
Runner: patient-resampled bootstrap of the CCC-RISE logistic regression
weights.

Fits the whole pipeline once on the full cohort at a fixed, already-selected
(RISE rank, CP rank) pair -- RISE, the interaction tensor, CP, then a logistic
regression on the condition factors -- and then repeats all of it on
``--n-boot`` bootstrap resamples of the *patient roster*. Each replicate's
components are matched back onto the full-cohort fit's components on the
ligand-receptor mode and sign-corrected before its weights are recorded
(`logreg_stability.bootstrap_logreg_weights`), so a component's weights across
replicates form a distribution rather than an unordered pile.

Writes the two CSVs `figureLogRegBoot` reads:

    logreg_bootstrap_weights_<dataset>.csv   one row per (replicate, component)
    logreg_bootstrap_summary_<dataset>.csv   one row per component: interval, sign and selection stability

    uv run cccrise-logregboot --dataset alad --rise-rank 25 --cp-rank 10 --n-boot 100
"""

import argparse
from pathlib import Path

import pandas as pd

from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..stability.logreg_stability import (
    bootstrap_logreg_weights,
    fit_logreg_pipeline,
    summarize_bootstrap_weights,
    top_lr_pairs,
)
from ._cli import (
    add_dataset_argument,
    add_group_arguments,
    dataset_metadata,
    resolve_group_labels,
    resulting_dims,
)
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, write_metadata

HEADER = """\
Patient-resampled bootstrap of the CCC-RISE logistic regression weights.
Generated by cccrise.runners.run_logreg_bootstrap -- do not hand-edit.
"""


def output_paths(spec: DatasetSpec, output_root: Path) -> dict[str, Path]:
    return {
        "bootstrap_weights": output_root / f"logreg_bootstrap_weights_{spec.key}.csv",
        "bootstrap_summary": output_root / f"logreg_bootstrap_summary_{spec.key}.csv",
    }


def run_logreg_bootstrap(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    n_boot: int = 100,
    group_column: str | None = None,
    control_label: str | None = None,
    other_label: str | None = None,
    ci_level: float = 95.0,
    stratify: bool = True,
    scoring: str = "roc_auc",
    n_iter_max: int = 100,
    tol: float = 1e-3,
    complex_sep: str | None = "&",
    random_state: int = 42,
    output_root: Path = DATA_DIR,
) -> dict[str, pd.DataFrame]:
    """Bootstrap the patient roster and re-run the pipeline, reporting each CP
    component's logistic regression weight distribution.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank, cp_rank : int
        The already-selected ranks the bootstrap is conditional on; every
        replicate is fit at exactly these, so the spread reported is
        patient-sampling variability alone.
    n_boot : int, default=100
        Bootstrap replicates. Each one refits RISE and CP, so runtime is
        `n_boot` times a full pipeline run.
    group_column : str, optional
        Column in `adata.obs` carrying the binary group label. Defaults to
        `spec.group_column`.
    control_label, other_label : str, optional
        Values of `group_column` mapped to the reference and other class.
        Default to `_cli.DEFAULT_GROUP_LABELS[spec.key]` when not given.
    ci_level : float, default=95.0
        Central percentile interval width reported per component.
    stratify : bool, default=True
        Draw patients within each group, holding the class balance fixed; see
        `utils.resample_conditions`.
    scoring : str, default="roc_auc"
        Scoring the logistic regression selects its regularization strength
        by; see `logreg.fit_logreg_weights`.
    n_iter_max, tol
        Fitting controls for the RISE and CP fits.
    complex_sep : str, optional
        Communication-tensor option; see `ccc_rise.calc_communication_score`.
    random_state : int, default=42
        Seed for the full-cohort fit; replicate `b` uses
        ``random_state + b + 1``.
    output_root : Path, default=DATA_DIR
        Root directory for this runner's outputs.

    Returns
    -------
    dict[str, pd.DataFrame]
        Keyed 'bootstrap_weights', 'bootstrap_summary'.
    """
    group_column, control_label, other_label = resolve_group_labels(
        spec, group_column, control_label, other_label
    )

    paths = output_paths(spec, output_root)
    for path in paths.values():
        path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(
        f"=== Logistic regression weight bootstrap: {spec.label} "
        f"(RISE rank {rise_rank}, CP rank {cp_rank}) ==="
    )
    print(
        f"    n_boot={n_boot}  stratify={stratify}  scoring={scoring!r}  "
        f"group_column={group_column!r}  control={control_label!r}  "
        f"other={other_label!r}"
    )

    print("1. Loading data...")
    adata = spec.load()
    adata = add_cond_idxs(adata, spec.condition_column)
    lr_pairs = import_ligand_receptor_pairs()

    print("2. Fitting the full-cohort reference pipeline...")
    reference = fit_logreg_pipeline(
        adata,
        condition_column=spec.condition_column,
        group_column=group_column,
        control_label=control_label,
        other_label=other_label,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        lr_pairs=lr_pairs,
        rise_n_iter_max=n_iter_max,
        rise_tol=tol,
        cp_n_iter_max=n_iter_max,
        cp_tol=tol,
        complex_sep=complex_sep,
        scoring=scoring,
        random_state=random_state,
    )
    print(f"   Reference CP R2X: {reference['r2x_cp']:.4f}")

    print(f"3. Running {n_boot} patient-resampled replicates...")
    bootstrap_weights = bootstrap_logreg_weights(
        adata,
        reference=reference,
        condition_column=spec.condition_column,
        group_column=group_column,
        control_label=control_label,
        other_label=other_label,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        n_boot=n_boot,
        lr_pairs=lr_pairs,
        rise_n_iter_max=n_iter_max,
        rise_tol=tol,
        cp_n_iter_max=n_iter_max,
        cp_tol=tol,
        complex_sep=complex_sep,
        scoring=scoring,
        stratify=stratify,
        random_state=random_state,
    )

    print("4. Summarizing each component's weight distribution...")
    bootstrap_summary = summarize_bootstrap_weights(
        bootstrap_weights, reference["logreg_weights"], ci_level=ci_level
    )
    # Label each component by the LR pair it loads onto hardest in the
    # reference fit, so the figure can name components without re-reading the
    # factors.
    labels = top_lr_pairs(reference["factors"][3], reference["lr_symbols"], top_n=1)
    bootstrap_summary = bootstrap_summary.merge(
        labels[["Component", "LRPair", "DLoading"]].rename(
            columns={"LRPair": "TopLRPair", "DLoading": "TopLRLoading"}
        ),
        on="Component",
        how="left",
    )

    print("5. Writing outputs...")
    outputs = {
        "bootstrap_weights": bootstrap_weights,
        "bootstrap_summary": bootstrap_summary,
    }
    for key, df in outputs.items():
        df.to_csv(paths[key], index=False)
        print(f"   {paths[key]}")

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "rise_rank": rise_rank,
            "cp_rank": cp_rank,
            "n_boot": n_boot,
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "ci_level": ci_level,
            "stratify": stratify,
            "scoring": scoring,
            "n_iter_max": n_iter_max,
            "tol": tol,
            "complex_sep": complex_sep,
            "random_state": random_state,
            "match_mode_weights": {"3": 1.0},
            "reference_r2x_cp": float(reference["r2x_cp"]),
            "reference_logreg_weights": reference["logreg_weights"],
            "n_components_ci_excludes_zero": int(
                bootstrap_summary["CIExcludesZero"].sum()
            ),
            "min_component_match_score": float(
                bootstrap_summary["MinMatchScore"].min()
            ),
            "resulting_dims": resulting_dims(
                spec, adata, n_lr_pairs=len(reference["lr_symbols"])
            ),
            "outputs": [relpath(p) for p in paths.values()],
        },
    )
    for path in paths.values():
        sidecar = write_metadata(path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar} (and its sibling)")

    return outputs


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank every replicate's interaction tensor is built at.",
    )
    parser.add_argument(
        "--cp-rank",
        type=int,
        required=True,
        help="CP rank every replicate is fit at.",
    )
    parser.add_argument(
        "--n-boot",
        type=int,
        default=100,
        help="Bootstrap replicates; each refits the whole pipeline (default: 100).",
    )
    add_group_arguments(parser)
    parser.add_argument(
        "--ci-level",
        type=float,
        default=95.0,
        help="Central percentile interval width, in percent (default: 95).",
    )
    parser.add_argument(
        "--no-stratify",
        action="store_false",
        dest="stratify",
        help="Draw patients from the whole cohort instead of within each "
        "group, letting the class balance vary between replicates.",
    )
    parser.add_argument(
        "--scoring",
        type=str,
        default="roc_auc",
        help="Scoring the logistic regression selects its regularization "
        "strength by (default: roc_auc).",
    )
    parser.add_argument("--n-iter-max", type=int, default=100)
    parser.add_argument("--tol", type=float, default=1e-3)
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output-root",
        type=Path,
        default=DATA_DIR,
        help=f"Root directory for this runner's outputs (default: {DATA_DIR}).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_logreg_bootstrap(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        n_boot=args.n_boot,
        group_column=args.group_column,
        control_label=args.control_label,
        other_label=args.other_label,
        ci_level=args.ci_level,
        stratify=args.stratify,
        scoring=args.scoring,
        n_iter_max=args.n_iter_max,
        tol=args.tol,
        complex_sep=args.complex_sep,
        random_state=args.random_state,
        output_root=args.output_root,
    )


if __name__ == "__main__":
    main()
