#!/usr/bin/env python
"""
Runner: phenotype AUC for every benchmarked method, on one dataset.

Scores each method registered in `benchmarks.registry` through the single
cross-validated AUC defined in `benchmarks.auc`, and writes one row per
(method, classifier) to a CSV the benchmark figure reads.

This is the number Reviewer #1 asked for -- "please also report ALAD status AUC
as for CCC-RISE" -- reported identically for every method, including CCC-RISE
itself. The per-component ANOVA (`cccrise.anova`) remains the manuscript's
primary component-phenotype statistic; this exists because an ANOVA cannot be
computed for a method whose components are not CCC-RISE's.

Every method is scored against the same labels, in the same row order, after the
same read-depth correction, with the same folds. The only thing that varies
between rows is the score matrix.

    uv run cccrise-bench-auc --dataset alad
    uv run cccrise-bench-auc --dataset alad --methods ccc_rise --n-permutations 200
    uv run cccrise-bench-auc --dataset alad --classifiers l1_logreg l2_logreg
"""

import argparse
from pathlib import Path

import pandas as pd

from ..anova import prepare_group_labels
from ..benchmarks.auc import CLASSIFIERS, DEFAULT_CLASSIFIER, cv_auc
from ..benchmarks.registry import (
    METHOD_KEYS,
    MethodInputs,
    method_labels,
    resolve_methods,
)
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ._cli import (
    add_dataset_argument,
    add_group_arguments,
    dataset_metadata,
    resolve_group_labels,
    resolve_output,
    resulting_dims,
    selected_cp_rank,
    selected_rise_rank,
)
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, write_metadata

HEADER = """\
Cross-validated phenotype AUC per benchmarked method.
Generated by cccrise.runners.run_benchmark_auc -- do not hand-edit.
"""


def run_benchmark_auc(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    methods: list[str] | None = None,
    classifiers: list[str] | None = None,
    group_column: str | None = None,
    control_label: str | None = None,
    other_label: str | None = None,
    n_splits: int = 10,
    n_repeats: int = 5,
    inner_splits: int = 5,
    n_permutations: int = 0,
    n_boot: int = 2000,
    ci_level: float = 95.0,
    random_state: int = 42,
    factors_path: Path | None = None,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Score every requested method and write the benchmark table.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank, cp_rank : int
        Ranks passed to any method that has to fit something. CCC-RISE itself
        reads the published factor model rather than refitting, so `rise_rank`
        is recorded for provenance rather than used by it.
    methods : list[str] | None
        Registry keys to score; all of them when None.
    classifiers : list[str] | None
        Keys into `benchmarks.auc.CLASSIFIERS`. More than one produces a
        sensitivity table rather than a single number -- every method is scored
        by each, so the rows stay comparable within a classifier.
    group_column, control_label, other_label : str | None
        The binary outcome, resolved from the registry when not given.
        `ALADstatus` has three levels and is collapsed here, once, for all
        methods.
    n_splits, n_repeats, inner_splits, n_permutations, n_boot, ci_level
        Cross-validation controls; see `benchmarks.auc.cv_auc`.
    random_state : int, default=42
        Seed for the folds, the bootstrap and any method that fits.
    factors_path : Path | None
        Published factor model CCC-RISE is read from; defaults to the dataset's
        canonical `.nc`.
    output_path : Path | None
        CSV destination; defaults to `data/benchmark_auc_<dataset>.csv`.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The benchmark table, the CSV path and the sidecar path.
    """
    group_column, control_label, other_label = resolve_group_labels(
        spec, group_column, control_label, other_label
    )
    selected = resolve_methods(methods)
    classifier_keys = classifiers or [DEFAULT_CLASSIFIER]
    unknown = [c for c in classifier_keys if c not in CLASSIFIERS]
    if unknown:
        raise ValueError(
            f"Unknown classifier(s) {unknown}. Available: {sorted(CLASSIFIERS)}"
        )

    factors_path = factors_path or spec.factors_path()
    if not factors_path.exists():
        raise FileNotFoundError(
            f"{factors_path} not found. Produce it with\n"
            f"    uv run cccrise-run --dataset {spec.key}"
        )
    output_path = output_path or (DATA_DIR / spec.benchmark_auc_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== Benchmark AUC: {spec.label} ===")
    print(
        f"    methods={[m.key for m in selected]}  classifiers={classifier_keys}\n"
        f"    group={group_column!r} ({control_label!r} vs {other_label!r})  "
        f"seed={random_state}"
    )

    print("1. Loading data and ligand-receptor pairs...")
    adata = add_cond_idxs(spec.load(), spec.condition_column)
    lr_pairs = import_ligand_receptor_pairs()
    print(f"   AnnData shape: {adata.shape}, LR pairs: {len(lr_pairs)}")

    inputs = MethodInputs(
        spec=spec,
        adata=adata,
        lr_pairs=lr_pairs,
        factors_path=factors_path,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        random_state=random_state,
    )

    raw_labels = method_labels(inputs, group_column)
    labels = prepare_group_labels(
        raw_labels, control_label=control_label, other_label=other_label
    )
    print(
        f"2. Outcome: {labels.value_counts().to_dict()} "
        f"(from {raw_labels.value_counts().to_dict()})"
    )

    rows: list[dict] = []
    for method in selected:
        print(f"3. Scoring {method.label}...")
        scored = method.fit(inputs)
        if list(scored.condition_names) != list(labels.index):
            raise ValueError(
                f"{method.key} returned conditions in a different order than the "
                "labels; scores and labels must be aligned condition-for-condition."
            )
        for classifier in classifier_keys:
            result = cv_auc(
                scored.scores,
                labels,
                classifier=classifier,
                n_splits=n_splits,
                n_repeats=n_repeats,
                inner_splits=inner_splits,
                random_state=random_state,
                n_permutations=n_permutations,
                n_boot=n_boot,
                ci_level=ci_level,
            )
            rows.append(
                result.to_row(
                    Method=method.key,
                    Label=method.label,
                    Axis=method.axis,
                    Classifier=classifier,
                    Rank=scored.rank,
                )
            )
            print(
                f"   {method.label:18s} [{classifier}] AUC "
                f"{result.auc:.3f} ({result.auc_lo:.3f}-{result.auc_hi:.3f})"
                + (
                    f"  null {result.null_auc:.3f} p={result.null_p:.4f}"
                    if result.null_auc is not None
                    else ""
                )
            )

    table = pd.DataFrame(rows)
    front = ["Method", "Label", "Axis", "Classifier", "Rank", "AUC", "AUCLo", "AUCHi"]
    table = table[front + [c for c in table.columns if c not in front]]

    print(f"4. Writing {len(table)} rows to {output_path}...")
    table.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "methods": [m.key for m in selected],
            "classifiers": classifier_keys,
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "n_splits": n_splits,
            "n_repeats": n_repeats,
            "inner_splits": inner_splits,
            "n_permutations": n_permutations,
            "n_boot": n_boot,
            "ci_level": ci_level,
            "random_state": random_state,
            "rise_rank": rise_rank,
            "cp_rank": cp_rank,
            "factors_path": relpath(factors_path),
            "class_balance": {str(k): int(v) for k, v in labels.value_counts().items()},
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=len(lr_pairs)),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return table, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--methods",
        nargs="+",
        default=None,
        choices=METHOD_KEYS,
        help="Registry keys to score (default: every registered method).",
    )
    parser.add_argument(
        "--classifiers",
        nargs="+",
        default=[DEFAULT_CLASSIFIER],
        choices=sorted(CLASSIFIERS),
        help=f"Classifier(s) behind the AUC (default: {DEFAULT_CLASSIFIER}).",
    )
    add_group_arguments(parser)
    parser.add_argument("--rise-rank", type=int, default=None)
    parser.add_argument("--cp-rank", type=int, default=None)
    parser.add_argument("--n-splits", type=int, default=10)
    parser.add_argument("--n-repeats", type=int, default=5)
    parser.add_argument("--inner-splits", type=int, default=5)
    parser.add_argument(
        "--n-permutations",
        type=int,
        default=0,
        help="Label permutations for the null AUC; each repeats the whole CV.",
    )
    parser.add_argument("--n-boot", type=int, default=2000)
    parser.add_argument("--ci-level", type=float, default=95.0)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--factors",
        type=str,
        default=None,
        help="Published factor model CCC-RISE is read from "
        "(default: the dataset's canonical .nc).",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV destination; defaults to data/benchmark_auc_<dataset>.csv.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_benchmark_auc(
        spec,
        rise_rank=selected_rise_rank(spec, args.rise_rank),
        cp_rank=selected_cp_rank(spec, args.cp_rank),
        methods=args.methods,
        classifiers=args.classifiers,
        group_column=args.group_column,
        control_label=args.control_label,
        other_label=args.other_label,
        n_splits=args.n_splits,
        n_repeats=args.n_repeats,
        inner_splits=args.inner_splits,
        n_permutations=args.n_permutations,
        n_boot=args.n_boot,
        ci_level=args.ci_level,
        random_state=args.random_state,
        factors_path=Path(args.factors) if args.factors else None,
        output_path=resolve_output(
            args.output, DATA_DIR, spec.benchmark_auc_filename()
        ),
    )


if __name__ == "__main__":
    main()
