#!/usr/bin/env python
"""
Runner: CP rank selection by the multi-start rule (RANK_SELECTION_RULE.md).

On the communication tensor of the dataset's canonical RISE fit, fits CP at
every rank from `RULE_N_STARTS` production starts (the seeded SVD
initialisations `ccc_rise.parafac_multistart` uses) and as many random
starts. Each rank is scored by `rank_selection.select_rank_by_rule` over the
production starts; the random starts are a reported diagnostic, as is the R2X
elbow (kneedle on 1 - the production starts' median R2X).

Fits run in float64, on the GPU with ``--backend cupy``. With ``--compress``
they run on a CANDELINC core keeping `CP_COMPRESSION_ENERGY` of every mode's
energy, each start initialised on the full tensor and projected onto the
bases; factors are mapped back and every R2X is against the full tensor. One
checkpoint per fit (``output/cache/cpd_rank_rule/<dataset>_<setting>/``), so a
run resumes.

Writes, in ``data/rank_selection_results/``:

    cpd_rank_rule_<dataset>.parquet          one row per (rank, start)
    cpd_rank_rule_summary_<dataset>.parquet  one row per rank: the rule

    uv run python -m cccrise.runners.run_cpd_rank_rule --dataset alad --backend cupy
    uv run python -m cccrise.runners.run_cpd_rank_rule --dataset ibd --backend cupy --compress
"""

import argparse
import time
from pathlib import Path

import numpy as np
import pandas as pd
import tensorly as tl
from tensorly.cp_tensor import CPTensor
from tensorly.decomposition import parafac
from tensorly.decomposition._cp import initialize_cp

from ..ccc_rise import (
    CP_FIT_OPTIONS,
    calculate_interaction_tensor,
    cp_start_seeds,
    seeded_cp_fit_options,
)
from ..factors import clean_memory, load_factors_to_anndata
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..rank_selection import (
    CP_COMPRESSION_ENERGY,
    RULE_N_STARTS,
    RULE_PASS_SHARE,
    Factors,
    Start,
    candelinc_compress,
    cp_core_consistency,
    kneedle_elbow,
    matched_congruence,
    r2x_without_reconstruction,
    screen_starts,
    select_rank_by_rule,
)
from ._cli import (
    CP_N_ITER_MAX,
    CP_TOL,
    add_dataset_argument,
    dataset_metadata,
    parse_ranks,
    resolve_dataset,
)
from .datasets import RANK_SELECTION_DIR, DatasetSpec
from .provenance import REPO_ROOT, build_metadata, sha256_file, write_metadata

FAMILIES = ("svd", "random")
CHECKPOINT_DIR = REPO_ROOT / "output" / "cache" / "cpd_rank_rule"
HEADER = """\
CP rank selection by the multi-start rule. Generated by
cccrise.runners.run_cpd_rank_rule -- do not hand-edit.
"""


def interaction_tensor(spec: DatasetSpec, cached: Path | None) -> np.ndarray:
    """The communication tensor of `spec`'s canonical RISE fit, or `cached`
    (a ``.npy`` of it)."""
    if cached is not None:
        return np.load(cached)
    adata = add_cond_idxs(spec.load(), spec.condition_column)
    adata = load_factors_to_anndata(
        spec.factors_path(), adata, condition_column=spec.condition_column
    )
    tensor, _ = calculate_interaction_tensor(
        adata, import_ligand_receptor_pairs(), complex_sep="&"
    )
    return tensor


def start_factors(tensor: np.ndarray, rank: int, family: str, seed: int) -> CPTensor:
    """A start's initial factors on the full tensor: the production seeded SVD
    initialisation (`seeded_cp_fit_options`, as ``parafac(init="svd")`` draws
    it) or a seeded random one."""
    if family == "svd":
        options = seeded_cp_fit_options(seed)
        return initialize_cp(tensor, rank, init="svd", svd=options["svd"],
                             random_state=seed, normalize_factors=True)  # fmt: skip
    return initialize_cp(tensor, rank, init="random", random_state=seed,
                         normalize_factors=True)  # fmt: skip


def fit_from(target: np.ndarray, rank: int, init: CPTensor, backend: str):
    """CP-ALS on `target` in float64 from `init`; NumPy weights and factors,
    and the iterations run."""
    tl.set_backend(backend)
    try:
        device = tl.tensor(target, dtype=tl.float64)
        start = CPTensor(
            (tl.tensor(init.weights), [tl.tensor(f) for f in init.factors])
        )
        cp, errors = parafac(device, rank, n_iter_max=CP_N_ITER_MAX, tol=CP_TOL,
                             init=start, normalize_factors=True, return_errors=True)  # fmt: skip
        weights = tl.to_numpy(cp.weights).astype(float)
        factors = [tl.to_numpy(f).astype(float) for f in cp.factors]
    finally:
        tl.set_backend("numpy")
        if backend == "cupy":
            clean_memory()
    return weights, factors, len(errors)


class Fitter:
    """Fits (or reads back) each start of each rank, one checkpoint per fit."""

    def __init__(self, tensor, backend, compress, fits_dir, n_random, max_rank):
        self.tensor, self.backend, self.fits_dir = tensor, backend, fits_dir
        self.n_random, self.compress, self.max_rank = n_random, compress, max_rank
        self._target = None

    def target(self) -> tuple[np.ndarray, Factors | None]:
        """The tensor fits run on and the bases that decompress them, built
        only once a fit is needed (resumed runs read every fit back)."""
        if self._target is None:
            self._target = (self.tensor, None)
            if self.compress:
                core, bases, _lost = candelinc_compress(
                    self.tensor, self.max_rank, energy=CP_COMPRESSION_ENERGY
                )
                self._target = (core, bases)
        return self._target

    def seeds(self, family: str, random_state: int) -> list[int]:
        if family == "svd":
            return [int(s) for s in cp_start_seeds(random_state, RULE_N_STARTS)]
        return list(range(self.n_random))

    def start(self, rank: int, family: str, i: int, seed: int) -> Start:
        path = self.fits_dir / f"r{rank}_{family}{i}.npz"
        if not path.exists():
            self._fit(path, rank, family, seed)
        z = np.load(path)
        assert int(z["seed"]) == seed, f"{path} was fit from seed {int(z['seed'])}"
        return z["weights"], [z[f"f{m}"] for m in range(4)], float(z["r2x"])

    def _fit(self, path: Path, rank: int, family: str, seed: int) -> None:
        core, bases = self.target()
        init = start_factors(self.tensor, rank, family, seed)
        if bases is not None:
            init = CPTensor(
                (
                    init.weights,
                    [b.T @ f for b, f in zip(bases, init.factors, strict=True)],
                )
            )
        began = time.perf_counter()
        weights, factors, n_iter = fit_from(core, rank, init, self.backend)
        if bases is not None:
            factors = [b @ f for b, f in zip(bases, factors, strict=True)]
        r2x = r2x_without_reconstruction(self.tensor, weights, factors)
        tmp = path.with_suffix(".tmp.npz")
        np.savez(tmp, weights=weights, **{f"f{m}": f for m, f in enumerate(factors)},
                 r2x=r2x, n_iter=n_iter, seconds=time.perf_counter() - began, seed=seed)  # fmt: skip
        tmp.rename(path)
        print(f"   r{rank} {path.stem}: R2X {r2x:.6f}, {n_iter} iterations", flush=True)

    def rank_starts(self, rank: int, random_state: int) -> dict[str, list[Start]]:
        return {
            family: [self.start(rank, family, i, seed)
                     for i, seed in enumerate(self.seeds(family, random_state))]
            for family in FAMILIES
        }  # fmt: skip


def start_rows(tensor, rank, starts, production_fit: Factors | None) -> pd.DataFrame:
    """Per start of one rank: R2X, the screen, core consistency, FMS to the
    family's best passing start and to the production fit."""
    frames = []
    for family, family_starts in starts.items():
        table = screen_starts(family_starts).assign(Rank=rank, Family=family)
        table["Start"] = range(len(family_starts))
        table["Borderline"] = table["Borderline"].str.len()
        table["CoreConsistency"] = [
            cp_core_consistency(tensor, w, f) for w, f, _ in family_starts
        ]
        table["FMSToProduction"] = [
            matched_congruence(production_fit, f).mean() if production_fit else np.nan
            for _w, f, _r in family_starts
        ]  # fmt: skip
        frames.append(table)
    return pd.concat(frames, ignore_index=True)


def score(tensor, starts_by_rank: dict[int, dict[str, list[Start]]]):
    """The rule over the production starts, the per-start table, and the
    diagnostic elbow."""
    production = ((rank, starts["svd"]) for rank, starts in starts_by_rank.items())
    selected, summary, _fit = select_rank_by_rule(tensor, production)
    rows = []
    for rank, starts in starts_by_rank.items():
        table = screen_starts(starts["svd"])
        passing = table[table["Passes"]]
        best = starts["svd"][int(passing["R2X"].idxmax())][1] if len(passing) else None
        rows.append(start_rows(tensor, rank, starts, best))
    per_start = pd.concat(rows, ignore_index=True)
    medians = per_start[per_start["Family"] == "svd"].groupby("Rank")["R2X"].median()
    elbow = kneedle_elbow(medians.index, 1 - medians.to_numpy())
    summary["Selected"] = summary["Rank"] == selected
    return selected, summary, per_start, int(elbow)


def run(
    spec: DatasetSpec, ranks, backend, compress, n_random, random_state, tensor_cache
):
    print(
        f"=== CP rank rule: {spec.label}  ranks={ranks}  backend={backend}  compress={compress}"
    )
    tensor = interaction_tensor(spec, tensor_cache)
    setting = "e999" if compress else "full"
    fits_dir = CHECKPOINT_DIR / f"{spec.output_key}_{setting}"
    fits_dir.mkdir(parents=True, exist_ok=True)
    fitter = Fitter(tensor, backend, compress, fits_dir, n_random, max(ranks))
    starts = {rank: fitter.rank_starts(rank, random_state) for rank in ranks}
    selected, summary, per_start, elbow = score(tensor, starts)
    per_start_path = RANK_SELECTION_DIR / f"cpd_rank_rule_{spec.output_key}.parquet"
    summary_path = (
        RANK_SELECTION_DIR / f"cpd_rank_rule_summary_{spec.output_key}.parquet"
    )
    per_start.to_parquet(per_start_path, index=False)
    summary.to_parquet(summary_path, index=False)
    metadata = build_metadata(dataset_metadata(spec) | {
        "factors_sha256": sha256_file(spec.factors_path()),
        "interaction_tensor_shape": list(tensor.shape),
        "tensor_source": str(tensor_cache) if tensor_cache else "rebuilt from the factors",
        "cp_ranks": list(ranks), "selected_rank": selected,
            "pass_share": RULE_PASS_SHARE, "elbow_diagnostic": elbow,
        "production_starts": RULE_N_STARTS, "random_starts": n_random, "random_state": random_state,
        "cp_fit_options": CP_FIT_OPTIONS, "cp_n_iter_max": CP_N_ITER_MAX, "cp_tol": CP_TOL,
        "backend": backend, "float64": True,
        "compression_energy": CP_COMPRESSION_ENERGY if compress else None,
        "fits_dir": str(fits_dir.relative_to(REPO_ROOT)),
        "summary_file": summary_path.name,
    })  # fmt: skip
    write_metadata(per_start_path, metadata, header=HEADER)
    print(
        f"   selected rank {selected} (elbow, diagnostic: {elbow}); wrote {per_start_path.name}"
    )
    return selected, summary, per_start


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--ranks", default="1:17", help="CP ranks (default 1:17, i.e. 1-16)."
    )
    parser.add_argument("--backend", choices=("numpy", "cupy"), default="numpy")
    parser.add_argument("--compress", action="store_true",
                        help="Fit on a CANDELINC core keeping CP_COMPRESSION_ENERGY.")  # fmt: skip
    parser.add_argument("--random-starts", type=int, default=RULE_N_STARTS)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument("--tensor-cache", type=Path, default=None,
                        help="A .npy of the communication tensor, to skip rebuilding it.")  # fmt: skip
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    run(resolve_dataset(args), parse_ranks(args.ranks), args.backend, args.compress,
        args.random_starts, args.random_state, args.tensor_cache)  # fmt: skip


if __name__ == "__main__":
    main()
