#!/usr/bin/env python
"""
Runner: a cell-type granularity ladder, and how much of each cccRISE component
a cell-type mean represents at every step (`validation.granularity_ladder`).

Each coarse type is split by bisecting k-means of its own expression into
m = 2, 4, 8, 16, 32 subtypes (at most one per `MIN_CELLS` cells), and, as a
control, into random parts of the same sizes (20 seeds). The coarse and fine
annotations are the ladder's two "real annotation" points. Per level, for each
cccRISE component's sample-scaled sender (`sc_B`) and receiver (`rc_C`)
per-cell loadings: the variance explained by (sample x type) means -- what a
pseudobulk tensor at that granularity sees -- and by type alone. Also, per
coarse type, whether different cells send and receive each component.

Writes, in ``data/validation_results/``:

    granularity_ladder_labels_<dataset>.parquet       per cell: the label of every
                                                      fitted level (``cccrise-benchmark
                                                      --celltype-labels``)
    granularity_representability_<dataset>.parquet    (level, seed, side, component)
    granularity_separation_<dataset>.parquet          (component, coarse type)
    granularity_dominance_<dataset>.parquet           (level, subtype): largest sample's share

    uv run python -m cccrise.runners.run_granularity_ladder --dataset alad
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from ..comparators.agreement import sample_scaled
from ..factors import load_factors_to_anndata
from ..validation.granularity_ladder import (
    MIN_CELLS,
    random_split,
    representability,
    sample_dominance,
    sender_receiver_separation,
    subtype_labels,
    type_components,
)
from ._cli import add_dataset_argument, dataset_metadata
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

COARSE, FINE = "broad_cell_type", "celltype"
LADDER = (2, 4, 8, 16, 32)
#: Ladder steps the comparators are refit on (labels file columns).
FIT_STEPS = (2, 4, 8)
N_SEEDS = 20
SIDES = {"sender": "sc_B", "receiver": "rc_C"}
HEADER = """\
Granularity ladder (expression subtypes and random splits of each coarse type)
and how much of each cccRISE component a cell-type mean represents.
Generated by cccrise.runners.run_granularity_ladder -- do not hand-edit.
"""


def _outputs(spec: DatasetSpec) -> dict[str, Path]:
    names = {
        "labels": "granularity_ladder_labels",
        "representability": "granularity_representability",
        "separation": "granularity_separation",
        "dominance": "granularity_dominance",
    }
    return {k: VALIDATION_DIR / f"{v}_{spec.key}.parquet" for k, v in names.items()}


def _levels(adata, random_state: int) -> tuple[dict, dict]:
    """Every level's labels: {name: labels} for the expression and annotation
    levels, and {(m, seed): labels} for the random splits."""
    coarse = adata.obs[COARSE].astype(str).to_numpy()
    print(">> Principal components per coarse type")
    components = type_components(adata.X, coarse)
    levels = {"coarse": coarse, "fine": adata.obs[FINE].astype(str).to_numpy()}
    rng = np.random.default_rng(random_state)
    randoms = {}
    for m in LADDER:
        print(f">> Subtypes, m = {m}")
        levels[f"expr_m{m}"] = subtype_labels(components, coarse, m)
        for seed in range(N_SEEDS):
            randoms[(m, seed)] = random_split(levels[f"expr_m{m}"], coarse, rng)
    return levels, randoms


def _representability_rows(loadings, samples, levels, randoms) -> pd.DataFrame:
    frames = []
    for side, values in loadings.items():
        for name, labels in levels.items():
            frames.append(
                representability(values, samples, labels).assign(
                    side=side, level=name, kind=name.split("_")[0], seed=-1
                )
            )
        for (m, seed), labels in randoms.items():
            frames.append(
                representability(values, samples, labels).assign(
                    side=side, level=f"rand_m{m}", kind="rand", seed=seed
                )
            )
    out = pd.concat(frames, ignore_index=True)
    out["m"] = out["level"].str.extract(r"_m(\d+)$")[0].astype(float)
    return out


def run_granularity_ladder(spec: DatasetSpec, random_state: int = 0) -> dict:
    git_sha()
    print(f">> Loading {spec.label} with cccRISE's per-cell loadings")
    adata = load_factors_to_anndata(spec.factors_path(), adata=spec.load())
    if not adata.obs_names.is_unique:
        raise ValueError("Cell names must be unique to key the ladder labels")
    samples = adata.obs[spec.condition_column].astype(str).to_numpy()
    loadings = {
        side: sample_scaled(adata.obsm[key], samples) for side, key in SIDES.items()
    }
    levels, randoms = _levels(adata, random_state)
    labels = pd.DataFrame(
        {
            **{f"expr_m{m}": levels[f"expr_m{m}"] for m in FIT_STEPS},
            **{f"rand_m{m}": randoms[(m, 0)] for m in FIT_STEPS},
        },
        index=adata.obs_names.astype(str),
    )
    tables = {
        "labels": labels,
        "representability": _representability_rows(loadings, samples, levels, randoms),
        "separation": sender_receiver_separation(
            loadings["sender"], loadings["receiver"], levels["coarse"]
        ),
        "dominance": pd.concat(
            [
                sample_dominance(lab, samples).assign(level=name)
                for name, lab in {**levels, **labels}.items()
            ],
            ignore_index=True,
        ),
    }
    paths = _outputs(spec)
    for name, table in tables.items():
        table.to_parquet(paths[name], index=name == "labels")
        print(f"   Wrote {len(table)} rows to {paths[name]}")
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_path": relpath(spec.factors_path()),
            "factors_sha256": sha256_file(spec.factors_path()),
            "coarse_column": COARSE,
            "fine_column": FINE,
            "ladder_m": list(LADDER),
            "fit_steps": list(FIT_STEPS),
            "min_cells_per_subtype": MIN_CELLS,
            "n_random_seeds": N_SEEDS,
            "random_state": random_state,
            "n_types": {k: len(np.unique(v)) for k, v in levels.items()},
            "outputs": {k: relpath(v) for k, v in paths.items()},
        }
    )
    write_metadata(paths["representability"], metadata, header=HEADER)
    return tables


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--random-state", type=int, default=0)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    run_granularity_ladder(DATASETS[args.dataset], random_state=args.random_state)


if __name__ == "__main__":
    main()
