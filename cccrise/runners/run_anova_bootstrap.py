#!/usr/bin/env python
"""
Runner: patient-resampled bootstrap of the CCC-RISE ANOVA effect sizes.

Fits the whole pipeline once on the full cohort at a fixed, already-selected
(RISE rank, CP rank) pair -- RISE, the interaction tensor, CP, then a one-way
ANOVA on the condition factors -- and then repeats all of it on
``--n-boot`` bootstrap resamples of the *patient roster*. Each replicate's
components are matched back onto the full-cohort fit's components on the
ligand-receptor mode and sign-corrected before its statistics are recorded
(`anova_stability.bootstrap_anova`), so a component's effect sizes across
replicates form a distribution rather than an unordered pile.

Writes the replicate-level CSV `figureAnovaBoot` reads:

    anova_bootstrap_<dataset>.csv   one row per (replicate, component)

    uv run cccrise-anovaboot --dataset alad --rise-rank 25 --cp-rank 10 --n-boot 100
"""

import argparse
from pathlib import Path

import pandas as pd

from ..ccc_rise import (
    CP_COMPRESSION_OPTIONS,
    CP_FIT_OPTIONS,
    RISE_COMPRESSION_OPTIONS,
)
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..validation.anova_stability import (
    bootstrap_anova,
    fit_anova_pipeline,
    summarize_bootstrap_anova,
    top_lr_pairs,
)
from ._cli import (
    CP_N_ITER_MAX,
    CP_TOL,
    REPLICATE_COMPRESS,
    RISE_N_ITER_MAX,
    RISE_TOL,
    add_dataset_argument,
    add_group_arguments,
    add_scoring_arguments,
    dataset_metadata,
    resolve_anova_labels,
    resolve_output,
    resulting_dims,
)
from .datasets import DATASETS, DatasetSpec, scoring_output_dir
from .provenance import build_metadata, git_sha, write_metadata

HEADER = """\
Patient-resampled bootstrap of the CCC-RISE ANOVA effect sizes.
Generated by cccrise.runners.run_anova_bootstrap -- do not hand-edit.
"""


def run_anova_bootstrap(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    n_boot: int = 100,
    group_column: str | None = None,
    control_label: str | None = None,
    other_label: str | None = None,
    ci_level: float = 95.0,
    alpha: float = 0.05,
    stratify: bool = True,
    rise_n_iter_max: int = RISE_N_ITER_MAX,
    cp_n_iter_max: int = CP_N_ITER_MAX,
    rise_tol: float = RISE_TOL,
    cp_tol: float = CP_TOL,
    complex_sep: str | None = "&",
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
    random_state: int = 42,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Bootstrap the patient roster and re-run the pipeline, reporting each CP
    component's ANOVA effect-size distribution.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank, cp_rank : int
        The already-selected ranks the bootstrap is conditional on; every
        replicate is fit at exactly these, so the spread reported is
        patient-sampling variability alone.
    n_boot : int, default=100
        Bootstrap replicates. Each one refits RISE and CP, so runtime is
        `n_boot` times a full pipeline run.
    group_column : str, optional
        Column in `adata.obs` carrying the group label. Defaults to
        `spec.outcome_column` (every level tested), else `spec.group_column`.
    control_label, other_label : str, optional
        Values of `group_column` mapped to the reference and other class.
        Default to `_cli.DEFAULT_GROUP_LABELS[spec.key]` when not given.
    ci_level : float, default=95.0
        Central percentile interval width on eta-squared reported per component.
    alpha : float, default=0.05
        Significance threshold for `FracSignificant`.
    stratify : bool, default=True
        Draw patients within each group, holding the class balance fixed; see
        `utils.resample_conditions`.
    rise_n_iter_max, cp_n_iter_max, rise_tol, cp_tol
        Fitting controls for the RISE and CP fits.
    complex_sep, communication_score, hill_k : str | None, str, float
        Communication-tensor options; see `ccc_rise.calc_communication_score`.
    random_state : int, default=42
        Seed for the full-cohort fit; replicate `b` uses
        ``replicate_seed(random_state, b)`` (``random_state * 1000 + b + 1``).
    output_path : Path, optional
        CSV destination; defaults to the registry's anova bootstrap filename.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The replicate ANOVA table, the CSV path, and the sidecar path.
    """
    group_column, control_label, other_label = resolve_anova_labels(
        spec, group_column, control_label, other_label
    )

    output_path = output_path or (
        scoring_output_dir(communication_score) / spec.anova_bootstrap_filename()
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(
        f"=== ANOVA effect-size bootstrap: {spec.label} "
        f"(RISE rank {rise_rank}, CP rank {cp_rank}) ==="
    )
    print(
        f"    n_boot={n_boot}  stratify={stratify}  alpha={alpha}  "
        f"group_column={group_column!r}  control={control_label!r}  "
        f"other={other_label!r}"
    )
    print(f"    backend={spec.backend or 'auto'}  compress={REPLICATE_COMPRESS}")

    print("1. Loading data...")
    adata = spec.load()
    adata = add_cond_idxs(adata, spec.condition_column)
    lr_pairs = import_ligand_receptor_pairs()

    print("2. Fitting the full-cohort reference pipeline...")
    reference = fit_anova_pipeline(
        adata,
        condition_column=spec.condition_column,
        group_column=group_column,
        control_label=control_label,
        other_label=other_label,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        lr_pairs=lr_pairs,
        rise_n_iter_max=rise_n_iter_max,
        rise_tol=rise_tol,
        cp_n_iter_max=cp_n_iter_max,
        cp_tol=cp_tol,
        complex_sep=complex_sep,
        communication_score=communication_score,
        hill_k=hill_k,
        random_state=random_state,
        backend=spec.backend,
        compress=REPLICATE_COMPRESS,
    )
    print(f"   Reference CP R2X: {reference['r2x_cp']:.4f}")

    print(f"3. Running {n_boot} patient-resampled replicates...")
    bootstrap_anova_df = bootstrap_anova(
        adata,
        reference=reference,
        condition_column=spec.condition_column,
        group_column=group_column,
        control_label=control_label,
        other_label=other_label,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        n_boot=n_boot,
        lr_pairs=lr_pairs,
        rise_n_iter_max=rise_n_iter_max,
        rise_tol=rise_tol,
        cp_n_iter_max=cp_n_iter_max,
        cp_tol=cp_tol,
        complex_sep=complex_sep,
        communication_score=communication_score,
        hill_k=hill_k,
        stratify=stratify,
        patient_column=spec.patient_column,
        random_state=random_state,
        backend=spec.backend,
        compress=REPLICATE_COMPRESS,
    )

    print("4. Summarizing each component's effect-size distribution...")
    summary = summarize_bootstrap_anova(
        bootstrap_anova_df, reference["anova"], ci_level=ci_level, alpha=alpha
    )
    # Label each component by the LR pair it loads onto hardest in the
    # reference fit, so the summary table can name components clearly.
    labels = top_lr_pairs(reference["factors"][3], reference["lr_symbols"], top_n=1)
    summary = summary.merge(
        labels[["Component", "LRPair", "DLoading"]].rename(
            columns={"LRPair": "TopLRPair", "DLoading": "TopLRLoading"}
        ),
        on="Component",
        how="left",
    )
    print(summary.to_string(index=False))

    print(f"5. Writing {len(bootstrap_anova_df)} rows to {output_path}...")
    bootstrap_anova_df.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "rise_rank": rise_rank,
            "cp_rank": cp_rank,
            "n_boot": n_boot,
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "ci_level": ci_level,
            "alpha": alpha,
            "stratify": stratify,
            "patient_column": spec.patient_column,
            "rise_n_iter_max": rise_n_iter_max,
            "cp_n_iter_max": cp_n_iter_max,
            "rise_tol": rise_tol,
            "cp_tol": cp_tol,
            "cp_fit_options": CP_FIT_OPTIONS,
            "complex_sep": complex_sep,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "random_state": random_state,
            "backend": spec.backend or "auto",
            "compress": REPLICATE_COMPRESS,
            "rise_compression_options": RISE_COMPRESSION_OPTIONS,
            "cp_compression_options": CP_COMPRESSION_OPTIONS,
            "match_mode_weights": {"3": 1.0},
            "reference_r2x_cp": float(reference["r2x_cp"]),
            "reference_eta_squared": reference["anova"]["EtaSquared"].tolist(),
            "reference_f": reference["anova"]["F"].tolist(),
            "reference_p": reference["anova"]["P"].tolist(),
            "reference_group_mean_diff": reference["anova"]["GroupMeanDiff"].tolist(),
            "reference_top_lr_pair": summary["TopLRPair"].tolist(),
            "reference_top_lr_loading": summary["TopLRLoading"].astype(float).tolist(),
            "n_components_significant": int((summary["ReferenceP"] < alpha).sum()),
            "min_component_match_score": float(summary["MinMatchScore"].min()),
            "resulting_dims": resulting_dims(
                spec, adata, n_lr_pairs=len(reference["lr_symbols"])
            ),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")

    return bootstrap_anova_df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank every replicate's interaction tensor is built at.",
    )
    parser.add_argument(
        "--cp-rank",
        type=int,
        required=True,
        help="CP rank every replicate is fit at.",
    )
    parser.add_argument(
        "--n-boot",
        type=int,
        default=100,
        help="Bootstrap replicates; each refits the whole pipeline (default: 100).",
    )
    add_group_arguments(parser)
    parser.add_argument(
        "--ci-level",
        type=float,
        default=95.0,
        help="Central percentile interval width on eta-squared, in percent (default: 95).",
    )
    parser.add_argument(
        "--alpha",
        type=float,
        default=0.05,
        help="Significance threshold for FracSignificant (default: 0.05).",
    )
    parser.add_argument(
        "--no-stratify",
        action="store_false",
        dest="stratify",
        help="Draw patients from the whole cohort instead of within each "
        "group, letting the class balance vary between replicates.",
    )
    parser.add_argument("--rise-n-iter-max", type=int, default=RISE_N_ITER_MAX)
    parser.add_argument("--cp-n-iter-max", type=int, default=CP_N_ITER_MAX)
    parser.add_argument("--rise-tol", type=float, default=RISE_TOL)
    parser.add_argument("--cp-tol", type=float, default=CP_TOL)
    parser.add_argument("--complex-sep", type=str, default="&")
    add_scoring_arguments(parser)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV destination; defaults to anova_bootstrap_<dataset>.csv in data/ "
        "(data/alt_score_methods/<score>/ for a non-default score).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_anova_bootstrap(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        n_boot=args.n_boot,
        group_column=args.group_column,
        control_label=args.control_label,
        other_label=args.other_label,
        ci_level=args.ci_level,
        alpha=args.alpha,
        stratify=args.stratify,
        rise_n_iter_max=args.rise_n_iter_max,
        cp_n_iter_max=args.cp_n_iter_max,
        rise_tol=args.rise_tol,
        cp_tol=args.cp_tol,
        complex_sep=args.complex_sep,
        communication_score=args.communication_score,
        hill_k=args.hill_k,
        random_state=args.random_state,
        output_path=resolve_output(
            args.output,
            scoring_output_dir(args.communication_score),
            spec.anova_bootstrap_filename(),
        ),
    )


if __name__ == "__main__":
    main()
