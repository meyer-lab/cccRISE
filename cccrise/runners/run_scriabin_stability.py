def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--analysis", choices=tuple(ANALYSES), required=True)
    parser.add_argument("--dataset", choices=("alad", "ibd", "panc8"), required=True)
    parser.add_argument(
        "--workers", type=int, default=4, help="remedy: processes (default 4)"
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args, command = parse_command(build_parser(), "cccrise-scriabin-stability", argv)
    if args.dataset not in ANALYSES[args.analysis]:
        raise SystemExit(
            f"--analysis {args.analysis} covers {', '.join(ANALYSES[args.analysis])} only"
        )
    print(f"== {args.analysis} on {args.dataset}", flush=True)
    if args.analysis == "seed_agreement":
        table, settings = seed_agreement(args.dataset)
    else:
        table, settings = remedy(args.dataset, args.workers)
    SCRIABIN_DIR.mkdir(parents=True, exist_ok=True)
    path = SCRIABIN_DIR / f"{args.analysis}_{args.dataset}.parquet"
    table.to_parquet(path, index=False)
    metadata = build_metadata(
        {"analysis": args.analysis, "dataset": args.dataset} | settings
    )
    record_output(path, metadata, command, header=HEADER)
    print(f"   wrote {path.name} ({len(table)} rows)")


if __name__ == "__main__":
    main()
