"""
Runner: whether Scriabin's interaction programs reproduce between random
seeds, where they stop reproducing, and what making them reproduce takes
(`figureR_scriabin_model`).

Writes one table per analysis and dataset to ``data/scriabin/`` (each
recorded in the folder's ``provenance.yaml``):

- ``seed_agreement_<dataset>`` (alad, ibd, panc8): agreement between every
  pair of seeds (1111, upstream's own, and 2-10) at each step of Scriabin's
  program discovery, from upstream R runs (``rcheck/faithful/ip_runs.R``,
  `SEED_RUNS`) under each preprocessing and grouping:

  - ``similarity``: Pearson r of a group's averaged LR similarity, over the
    LR pairs both runs keep;
  - ``tom``: Pearson r of its signed topological overlap, each run at its
    own soft power;
  - ``modules``: best-match Jaccard of its modules;
  - ``programs``: best-match Jaccard of the programs merged over every
    subsampled group (`scriabin.merge_programs_incremental`, Jaccard
    `MERGE_THRESHOLD`; upstream's merge, exactly).

  Only groups of more than `scriabin.ITERATE_THRESHOLD` cells are
  subsampled; smaller ones use the full cell-cell interaction matrix (CCIM)
  and are identical across seeds, so they are left out. For ALAD and IBD,
  ``lr_sets`` adds cccRISE's: best-match Jaccard of each component's
  carrying LR pairs (`covariation.carrying_pairs`) between seed refits
  (``rcheck/shared/cccrise_refits.py``; `CCCRISE_REFITS`).
- ``remedy_<dataset>`` (alad, panc8): merged-program agreement in the port
  (`comparators.scriabin`, equal to upstream R wherever no randomness is
  involved), for each subsampling (`SUBSAMPLING`: the published number of
  subsamples, 512, or each group's full CCIM) and settings (`SETTINGS`:
  the published defaults, or tuned ones):

  - ``seed``: between every pair of seeds (subsampled only; the full CCIM
    involves no randomness);
  - ``leave_one_out``: per seed and group, the merge without that group
    against the merge of all groups.

  ALAD: every sample, on cccRISE's inputs (``singlecell_cache/shared/alad``).
  panc8: the cell types of more than `scriabin.ITERATE_THRESHOLD` cells,
  with the authors' preprocessing (``singlecell_cache/authors/panc8/port``).
  Each unit's random draws come from its own generator, seeded by (seed,
  group index, subsamples). Units are checkpointed under
  ``rcheck/out/scriabin/remedy_<dataset>/``.

Inputs (git-ignored): R runs under ``rcheck/out/`` with their similarities
exported (``Rscript rcheck/shared/export_sims.R <seed dirs>``); job lists in
``rcheck/authors/jobs.py`` and ``rcheck/shared/run_s1.sh``.

Usage:

    uv run cccrise-scriabin-stability --analysis seed_agreement --dataset panc8
    uv run cccrise-scriabin-stability --analysis remedy --dataset alad --workers 4
"""

