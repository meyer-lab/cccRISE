_DATA: dict = {}


def _load_alad() -> None:
    d = CACHE_DIR / "shared" / "alad"
    X = scipy.io.mmread(d / "lr_expr.mtx").T.tocsr()
    features = pd.Index(pd.read_csv(d / "lr_features.csv", header=None)[0])
    lr, meta = pd.read_csv(d / "lr.csv"), pd.read_csv(d / "meta.csv")
    _DATA.update(
        X=X,
        lig=features.get_indexer(lr["ligand"]),
        rec=features.get_indexer(lr["receptor"]),
        names=lr["lr_name"].to_numpy(),
        meta=meta,
        group_column="sample",
    )


def _load_panc8() -> None:
    d = CACHE_DIR / "authors" / "panc8" / "port"
    X = sp.csr_matrix(scipy.io.mmread(d / "lr_expr.mtx"))
    genes = pd.Index((d / "genes.txt").read_text().split())
    lr, meta = pd.read_csv(d / "lr.csv"), pd.read_csv(d / "meta.csv")
    _DATA.update(
        X=X,
        lig=genes.get_indexer(lr.ligand),
        rec=genes.get_indexer(lr.receptor),
        names=lr.lr_name.to_numpy(),
        meta=meta,
        group_column="celltype",
    )


LOADERS = {"alad": _load_alad, "panc8": _load_panc8}
REMEDY_INPUTS = {
    "alad": "singlecell_cache/shared/alad",
    "panc8": "singlecell_cache/authors/panc8/port",
}


def remedy_groups(dataset: str) -> list[str]:
    """ALAD: every sample; panc8: the subsampled cell types."""
    LOADERS[dataset]()
    counts = _DATA["meta"][_DATA["group_column"]].value_counts()
    if dataset == "alad":
        return sorted(counts.index)
    return sorted(counts.index[counts > scriabin.ITERATE_THRESHOLD])


def _group_inputs(group: str, full: bool):
    """A group's ligand and receptor values and cell types: every cell for
    the full CCIM; for subsampling, as ip_runs.R, without the types of fewer
    than `scriabin.MIN_CELL` cells when the group is subsampled."""
    meta = _DATA["meta"]
    rows = np.flatnonzero(meta[_DATA["group_column"]].to_numpy() == group)
    types = meta["celltype"].to_numpy()[rows]
    if not full and len(rows) > scriabin.ITERATE_THRESHOLD:
        counts = pd.Series(types).value_counts()
        keep = np.isin(types, counts.index[counts >= scriabin.MIN_CELL])
        rows, types = rows[keep], types[keep]
    Xs = _DATA["X"][rows]
    return Xs[:, _DATA["lig"]].toarray(), Xs[:, _DATA["rec"]].toarray(), types


def _unit(args: tuple) -> tuple:
    """Modules of one (group, subsampling, seed) at every setting."""
    group, index, subsampling, seed = args
    lig, rec, types = _group_inputs(group, full=subsampling == "full")
    names = _DATA["names"]
    if subsampling == "full":
        keep, sim = scriabin.ccim_similarity(lig, rec)
        sim = pd.DataFrame(np.clip(sim, 0, 1), index=names[keep], columns=names[keep])
    else:
        n = 0 if subsampling == "published" else subsampling
        rng = np.random.default_rng(np.random.SeedSequence([seed, index, n]))
        draws = scriabin.draw_subsamples(
            types, rng, scriabin.ProgramSettings(n_iterate=n or None)
        )
        sim = scriabin.averaged_similarity(lig, rec, names, draws, factored=True)
    return args, {
        k: scriabin.modules_from_similarity(sim, st).modules
        for k, (st, _) in SETTINGS.items()
    }


def _checkpointed_units(dataset: str, jobs: list[tuple], workers: int) -> dict:
    """Every unit's modules, computed once and kept as JSON (written
    atomically) so an interrupted run resumes."""
    folder = RUNS_DIR / "scriabin" / f"remedy_{dataset}"
    folder.mkdir(parents=True, exist_ok=True)

    def path(job):
        group, _, subsampling, seed = job
        return folder / f"{group}__{subsampling}__{seed}.json"

    todo = [j for j in jobs if not path(j).exists()]
    print(f"   {len(jobs) - len(todo)} of {len(jobs)} units checkpointed", flush=True)
    with ProcessPoolExecutor(workers, initializer=LOADERS[dataset]) as ex:
        for k, (job, modules) in enumerate(ex.map(_unit, todo, chunksize=1), start=1):
            tmp = path(job).with_suffix(".partial")
            tmp.write_text(json.dumps(modules))
            tmp.replace(path(job))
            if k % 50 == 0 or k == len(todo):
                print(f"   {k} / {len(todo)} units", flush=True)
    return {j: json.loads(path(j).read_text()) for j in jobs}


def _merge(per_group: dict, threshold: float) -> list[set]:
    return _sets(scriabin.merge_programs_incremental(per_group, threshold))


def _condition_rows(
    modules: dict, groups: list[str], seeds: tuple, setting: str
) -> list[dict]:
    threshold = SETTINGS[setting][1]
    per = {s: {g: modules[s][g][setting] for g in groups} for s in seeds}
    ref = {s: _merge(per[s], threshold) for s in seeds}
    rows = [
        {"Measure": "seed", "SeedA": a, "SeedB": b, "Value": best_match(ref[a], ref[b])}
        for a, b in itertools.combinations(seeds, 2)
    ]
    for s in seeds:
        rows += [
            {
                "Measure": "leave_one_out",
                "SeedA": s,
                "Group": g,
                "Value": best_match(
                    ref[s],
                    _merge({k: v for k, v in per[s].items() if k != g}, threshold),
                ),
            }
            for g in groups
        ]
    return rows


def _remedy_rows(units: dict, groups: list[str]) -> pd.DataFrame:
    """Seed and leave-one-out rows of every (subsampling, settings)."""
    rows = []
    for subsampling, setting in itertools.product(SUBSAMPLING, SETTINGS):
        seeds = (None,) if subsampling == "full" else SEEDS
        modules = {s: {g: units[(g, subsampling, s)] for g in groups} for s in seeds}
        rows += [
            r | {"Subsampling": str(subsampling), "Settings": setting}
            for r in _condition_rows(modules, groups, seeds, setting)
        ]
    columns = ["Subsampling", "Settings", "Measure", "SeedA", "SeedB", "Group", "Value"]
    return (
        pd.DataFrame(rows)
        .reindex(columns=columns)
        .astype({"SeedA": "Int64", "SeedB": "Int64"})
    )


def _remedy_settings(dataset: str, groups: list[str]) -> dict:
    return {
        "seeds": list(SEEDS),
        "subsampling": [str(n) for n in SUBSAMPLING],
        "settings": {
            k: {
                "r2_cutoff": st.r2_cutoff,
                "max_soft_power": st.max_soft_power,
                "min_module_size": st.min_module_size,
                "cut_height_quantile": st.cut_height_quantile,
                "merge_threshold": thr,
            }
            for k, (st, thr) in SETTINGS.items()
        },
        "groups": groups,
        "inputs": REMEDY_INPUTS[dataset],
    }


def remedy(dataset: str, workers: int) -> tuple[pd.DataFrame, dict]:
    groups = remedy_groups(dataset)
    jobs: list[tuple] = [
        (g, i, n, s)
        for i, g in enumerate(groups)
        for n in SUBSAMPLING[:2]
        for s in SEEDS
    ]
    jobs += [(g, i, "full", None) for i, g in enumerate(groups)]
    units = {
        (g, n, s): m
        for (g, _, n, s), m in _checkpointed_units(dataset, jobs, workers).items()
    }
    return _remedy_rows(units, groups), _remedy_settings(dataset, groups)


