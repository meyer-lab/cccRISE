HEADER = """\
Scriabin's interaction programs between seeds (figureR_scriabin_model).
Generated by cccrise.runners.run_scriabin_stability -- do not hand-edit.
"""

RUNS_DIR = REPO_ROOT / "rcheck" / "out"
CACHE_DIR = REPO_ROOT / "singlecell_cache"
SEEDS = (1111, 2, 3, 4, 5, 6, 7, 8, 9, 10)
#: Upstream `FindAllInteractionPrograms`' default merge Jaccard
MERGE_THRESHOLD = 0.15
#: (preprocessing, grouping, run root under `RUNS_DIR`) per dataset
SEED_RUNS = {
    "alad": [
        ("cccrise", "sample", "shared/alad/s1"),
        ("sct_alra", "sample", "authors/alad/alra"),
        ("sct", "sample", "authors/alad/sct"),
    ],
    "ibd": [("cccrise", "sample", "shared/ibd/s1")],
    "panc8": [
        ("cccrise", "sample", "shared/panc8/donor"),
        ("cccrise", "celltype", "shared/panc8/bytype"),
        ("sct_alra", "sample", "authors/panc8/donor"),
        ("sct_alra", "celltype", "authors/panc8/bytype"),
    ],
}
#: cccRISE refit seeds per dataset (ALAD: seed 42's replicates; IBD: all five)
CCCRISE_REFITS = {
    "alad": tuple(range(42001, 42011)),
    "ibd": (42, 42001, 42002, 42003, 42004),
}
SUBSAMPLING = ("published", 512, "full")
SETTINGS = {
    "default": (scriabin.UPSTREAM, MERGE_THRESHOLD),
    "tuned": (
        scriabin.ProgramSettings(
            r2_cutoff=0.5,
            max_soft_power=None,
            min_module_size=5,
            cut_height_quantile=0.25,
        ),
        0.4,
    ),
}
ANALYSES = {"seed_agreement": ("alad", "ibd", "panc8"), "remedy": ("alad", "panc8")}


def best_match(a: list[set], b: list[set]) -> float:
    """Mean best-match Jaccard of two collections of sets, in both
    directions, averaged (1 if both are empty)."""
    if not a or not b:
        return float(a == b)
    universe = {x: i for i, x in enumerate(sorted(set().union(*a, *b)))}
    ma, mb = (
        np.array(
            [np.isin(np.arange(len(universe)), [universe[x] for x in s]) for s in sets],
            float,
        )
        for sets in (a, b)
    )
    inter = ma @ mb.T
    j = inter / (ma.sum(1)[:, None] + mb.sum(1)[None, :] - inter)
    return float((j.max(axis=1).mean() + j.max(axis=0).mean()) / 2)


def _modules(modules: dict) -> dict[str, list]:
    """A run's modules, a one-pair module (a JSON scalar) as a list."""
    return {k: v if isinstance(v, list) else [v] for k, v in modules.items()}


def _sets(modules: dict) -> list[set]:
    return [set(v) for v in _modules(modules).values()]


