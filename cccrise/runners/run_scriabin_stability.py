# Seed agreement: upstream R runs
# =============================================================================


def _run_json(run: Path, group: str) -> dict:
    return json.loads((run / f"{group}.json").read_text())


def _similarity(run: Path, group: str) -> pd.DataFrame:
    sims = run / "sims"
    if not (sims / f"{group}.txt").exists():
        raise FileNotFoundError(
            f"{sims / group}.txt not found; export it with\n"
            f"    Rscript rcheck/shared/export_sims.R {run}"
        )
    names = (sims / f"{group}.txt").read_text().splitlines()
    m = np.fromfile(sims / f"{group}.f64").reshape(len(names), len(names), order="F")
    return pd.DataFrame(m, index=names, columns=names)


def _upper(m: pd.DataFrame, names: pd.Index) -> np.ndarray:
    v = m.loc[names, names].to_numpy()
    return v[np.triu_indices(len(names), 1)]


def _pearson(x: np.ndarray, y: np.ndarray) -> float:
    ok = np.isfinite(x) & np.isfinite(y)
    return float(np.corrcoef(x[ok], y[ok])[0, 1]) if ok.sum() > 2 else np.nan


def subsampled_groups(root: Path) -> list[str]:
    """The groups of a run that upstream subsamples, after checking every
    seed's run is complete."""
    first = root / f"seed{SEEDS[0]}"
    groups = sorted(
        f.stem for f in first.glob("*.json") if f.stem not in ("merged", "kept")
    )
    missing = [
        f"seed{s}/{g}"
        for s in SEEDS
        for g in groups
        if not (root / f"seed{s}" / f"{g}.rds").exists()
    ]
    if missing:
        raise FileNotFoundError(
            f"{root}: {len(missing)} runs missing, e.g. {missing[0]}"
        )
    return [
        g for g in groups if _run_json(first, g)["n_cells"] > scriabin.ITERATE_THRESHOLD
    ]


def _group_rows(root: Path, group: str) -> list[dict]:
    """Similarity, TOM and module agreement of one group, every seed pair."""
    runs = {s: root / f"seed{s}" for s in SEEDS}
    stages = {}
    for s, run in runs.items():
        js = _run_json(run, group)
        sim = _similarity(run, group)
        tom = _wgcna.signed_tom(np.clip(sim.to_numpy(), 0, 1) ** js["soft_power"])
        stages[s] = (
            _sets(js["modules"]),
            sim,
            pd.DataFrame(tom, index=sim.index, columns=sim.index),
        )
    rows = []
    for a, b in itertools.combinations(SEEDS, 2):
        (ma, sa, ta), (mb, sb, tb) = stages[a], stages[b]
        shared = sa.index.intersection(sb.index)
        values = {
            "similarity": _pearson(_upper(sa, shared), _upper(sb, shared)),
            "tom": _pearson(_upper(ta, shared), _upper(tb, shared)),
            "modules": best_match(ma, mb),
        }
        rows += [
            {"Group": group, "Stage": k, "SeedA": a, "SeedB": b, "Value": v}
            for k, v in values.items()
        ]
    return rows


def _program_rows(root: Path, groups: list[str]) -> list[dict]:
    merged = {
        s: _sets(
            scriabin.merge_programs_incremental(
                {
                    g: _modules(_run_json(root / f"seed{s}", g)["modules"])
                    for g in groups
                },
                MERGE_THRESHOLD,
            )
        )
        for s in SEEDS
    }
    return [
        {
            "Stage": "programs",
            "SeedA": a,
            "SeedB": b,
            "Value": best_match(merged[a], merged[b]),
        }
        for a, b in itertools.combinations(SEEDS, 2)
    ]


def scriabin_seed_rows(preprocessing: str, grouping: str, root: Path) -> pd.DataFrame:
    groups = subsampled_groups(root)
    rows = [r for g in groups for r in _group_rows(root, g)] + _program_rows(
        root, groups
    )
    print(
        f"   {root.relative_to(RUNS_DIR)}: {len(groups)} subsampled groups", flush=True
    )
    return pd.DataFrame(rows).assign(
        Method="Scriabin", Preprocessing=preprocessing, Grouping=grouping
    )


def cccrise_seed_rows(dataset: str) -> pd.DataFrame:
    """Best-match Jaccard of cccRISE's carrying LR sets between seed refits."""
    sets = {}
    for seed in CCCRISE_REFITS[dataset]:
        fit = np.load(
            RUNS_DIR / "cccrise" / dataset / "s1" / f"seed{seed}.npz", allow_pickle=True
        )
        D, symbols = fit["cp_D"], fit["lr_symbols"]
        sets[seed] = [set(symbols[carrying_pairs(D[:, c])]) for c in range(D.shape[1])]
    rows = [
        {
            "Stage": "lr_sets",
            "SeedA": a,
            "SeedB": b,
            "Value": best_match(sets[a], sets[b]),
        }
        for a, b in itertools.combinations(CCCRISE_REFITS[dataset], 2)
    ]
    return pd.DataFrame(rows).assign(
        Method="cccRISE", Preprocessing="cccrise", Grouping="sample"
    )


def seed_agreement(dataset: str) -> tuple[pd.DataFrame, dict]:
    parts = [scriabin_seed_rows(p, g, RUNS_DIR / r) for p, g, r in SEED_RUNS[dataset]]
    if dataset in CCCRISE_REFITS:
        parts.append(cccrise_seed_rows(dataset))
    columns = [
        "Method",
        "Preprocessing",
        "Grouping",
        "Group",
        "Stage",
        "SeedA",
        "SeedB",
        "Value",
    ]
    table = pd.concat(parts, ignore_index=True).reindex(columns=columns)
    settings = {
        "seeds": list(SEEDS),
        "merge_threshold": MERGE_THRESHOLD,
        "iterate_threshold": scriabin.ITERATE_THRESHOLD,
        "runs": {f"{p}/{g}": f"rcheck/out/{r}" for p, g, r in SEED_RUNS[dataset]},
    }
    if dataset in CCCRISE_REFITS:
        settings["cccrise_refits"] = {
            "dir": f"rcheck/out/cccrise/{dataset}/s1",
            "seeds": list(CCCRISE_REFITS[dataset]),
        }
    return table, settings


