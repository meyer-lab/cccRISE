#!/usr/bin/env python
"""
Runner: the comparators along the granularity ladder, one row per fit.

Collects, for every annotation level the comparators were fit on (coarse,
fine, and the `run_granularity_ladder` expression and random-split levels;
each from ``cccrise-benchmark`` and ``cccrise-comparator-agreement`` run with
that level's ``--suffix``):

- linear CKA with cccRISE on the condition and LR modes (and whether it is
  above the null);
- containment of every cccRISE component in the fit's span, per mode;
- for CP fits, the column closest to cccRISE's C4 on the LR mode (|cos|),
  with its eta-squared and maxT permutation p on the CLAD associations; for
  every fit, its best maxT p over every column and association;
- for CP fits, the share of columns on one cell type (sender and receiver
  participation ratio < 1.5) and on one sample (condition participation
  ratio < 1.5).

Writes ``data/validation_results/granularity_fits_<dataset>.parquet``.

    uv run python -m cccrise.runners.run_granularity_summary --dataset alad
"""

import argparse

import numpy as np
import pandas as pd

from ..benchmark import read_fits
from ..comparators.agreement import aligned_modes, unit_columns
from ..factors import load_factors_netcdf
from ..validation.program_breadth import participation_ratio
from ._cli import add_dataset_argument, dataset_metadata
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, write_metadata

#: level -> (output suffix, kind, ladder step m)
LEVELS = {
    "coarse": ("", "annotation", None),
    "fine": ("_fine", "annotation", None),
    **{f"expr_m{m}": (f"_expr_m{m}", "expr", m) for m in (2, 4, 8)},
    **{f"rand_m{m}": (f"_rand_m{m}", "rand", m) for m in (2, 4, 8)},
}
TARGET = 4
CLAD = ("6-Month CLAD/Died vs. No CLAD", "1-Year CLAD/Died vs. No CLAD")
ONE = 1.5
HEADER = """\
Comparator fits along the granularity ladder: agreement with cccRISE, the
C4-closest column's clinical association, and concentration.
Generated by cccrise.runners.run_granularity_summary -- do not hand-edit.
"""


def _key(method, rank_mode):
    return {"method": method, "rank_mode": rank_mode}


def _agreement(suffix: str, spec: DatasetSpec) -> tuple[pd.DataFrame, pd.DataFrame]:
    sub = pd.read_parquet(
        VALIDATION_DIR / f"comparator_subspace_{spec.key}{suffix}.parquet"
    )
    con = pd.read_parquet(
        VALIDATION_DIR / f"comparator_containment_{spec.key}{suffix}.parquet"
    )
    return sub[sub["statistic"] == "linear_cka"], con[
        con["direction"] == "cccRISE in comparator"
    ]


def _agreement_fields(fit, cka, containment) -> dict:
    row = {}
    for mode in ("condition", "lr"):
        c = cka[(cka["method"] == fit.method) & (cka["rank_mode"] == fit.rank_mode)]
        c = c[c["mode"] == mode].iloc[0]
        row[f"cka_{mode}"] = float(c["observed"])
        row[f"cka_{mode}_q95"] = float(max(c["perm_q95"], c["gauss_q95"]))
        k = containment[
            (containment["method"] == fit.method)
            & (containment["rank_mode"] == fit.rank_mode)
            & (containment["mode"] == mode)
        ].set_index("component")
        for comp, value in k["containment"].items():
            row[f"contain_C{comp}_{mode}"] = float(value)
    return row


def _clinical_fields(fit, anova, lr, ref_lr) -> dict:
    cos = np.abs(unit_columns(lr).T @ unit_columns(ref_lr[:, [TARGET - 1]]))[:, 0]
    best = int(np.argmax(cos)) + 1
    rows = anova[(anova["Method"] == fit.method) & (anova["RankMode"] == fit.rank_mode)]
    out = {"best_permp": float(rows["PermPAdj"].min())}
    if fit.kind != "cp":  # a Tucker LR column has no condition column of its own
        return out
    out |= {"c4_column": best, "c4_lr_cos": float(cos.max())}
    for name, label in zip(CLAD, ("6m", "1y"), strict=True):
        r = rows[(rows["Association"] == name) & (rows["Component"] == best)].iloc[0]
        out[f"c4_eta2_{label}"] = float(r["EtaSquared"])
        out[f"c4_permp_{label}"] = float(r["PermPAdj"])
    return out


def _concentration_fields(fit) -> dict:
    if fit.kind != "cp":
        return {}
    one_type = (participation_ratio(fit.modes["sender"]) < ONE) & (
        participation_ratio(fit.modes["receiver"]) < ONE
    )
    one_sample = participation_ratio(fit.condition_factor) < ONE
    return {
        "share_one_type": float(one_type.mean()),
        "share_one_sample": float(one_sample.mean()),
        "share_one_sample_and_type": float((one_type & one_sample).mean()),
    }


def _level_rows(spec, level, lr_names, ref_lr) -> list[dict]:
    suffix, kind, m = LEVELS[level]
    path = VALIDATION_DIR / spec.benchmark_fits_filename(suffix)
    if not path.exists():
        print(f"   {level}: no fits, skipped")
        return []
    fits, info, _c = read_fits(path)
    anova = pd.read_parquet(VALIDATION_DIR / spec.benchmark_anova_filename(suffix))
    cka, containment = _agreement(suffix, spec)
    rows = []
    for fit in (f for f in fits if f.method != "cccRISE"):
        lr = aligned_modes(fit, info, lr_names)["lr"]
        rows.append(
            {
                "level": level,
                "kind": kind,
                "m": m,
                "n_types": len(info["celltypes"]),
                **_key(fit.method, fit.rank_mode),
                "rank": fit.rank,
                **_agreement_fields(fit, cka, containment),
                **_clinical_fields(fit, anova, lr, ref_lr),
                **_concentration_fields(fit),
            }
        )
    return rows


def run_granularity_summary(spec: DatasetSpec) -> pd.DataFrame:
    git_sha()
    ds = load_factors_netcdf(spec.factors_path())
    lr_names = ds.coords["lr_pair"].values.astype(str)
    ref_lr = np.asarray(ds["cp_D"].values)
    table = pd.DataFrame(
        [row for level in LEVELS for row in _level_rows(spec, level, lr_names, ref_lr)]
    )
    path = VALIDATION_DIR / f"granularity_fits_{spec.key}.parquet"
    table.to_parquet(path, index=False)
    print(f"   Wrote {len(table)} rows to {path}")
    write_metadata(
        path,
        build_metadata(
            dataset_metadata(spec)
            | {
                "levels": {k: v[0] for k, v in LEVELS.items()},
                "target_component": TARGET,
                "clad_associations": list(CLAD),
                "one_threshold": ONE,
                "output": relpath(path),
            }
        ),
        header=HEADER,
    )
    return table


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    return parser


def main(argv: list[str] | None = None) -> None:
    run_granularity_summary(DATASETS[build_parser().parse_args(argv).dataset])


if __name__ == "__main__":
    main()
