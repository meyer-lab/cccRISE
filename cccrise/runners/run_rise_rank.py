#!/usr/bin/env python
"""
Runner: RISE (PARAFAC2) rank selection by bi-cross-validation.

BiCV holds out a fraction of the cells and a fraction of the genes, fits
PARAFAC2 on the remaining block, and scores the prediction of the held-out
block. Each fold is CANDELINC-compressed once (`--compress`, default `auto`)
so a rank sweep pays one data traversal per fold rather than one per
(rank, fold) pair.

    uv run cccrise-riserank --dataset alad --ranks 5:51:5 --n-repeats 3
"""

import argparse
from pathlib import Path

import pandas as pd
from scrise.rank_selection import bicv

from ._cli import (
    RISE_N_ITER_MAX,
    RISE_TOL,
    add_dataset_argument,
    dataset_metadata,
    parse_ranks,
    resolve_output,
    resulting_dims,
)
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, git_sha, write_metadata

DEFAULT_RANKS = [5, 10, 15, 20, 25, 30, 35, 40, 45, 50]

HEADER = """\
RISE rank selection (bi-cross-validation). Generated by
cccrise.runners.run_rise_rank -- do not hand-edit.
"""


def run_rise_rank_selection(
    spec: DatasetSpec,
    ranks: list[int],
    n_repeats: int = 3,
    held_out_cell_frac: float = 0.5,
    held_out_gene_frac: float = 0.5,
    rise_n_iter_max: int = RISE_N_ITER_MAX,
    rise_tol: float = RISE_TOL,
    compress: str | int | bool = "auto",
    n_power_iter: int = 2,
    backend: str | None = None,
    random_state: int = 0,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Run the BiCV sweep and persist the CSV plus its sidecar.

    `rise_n_iter_max` sits above `bicv`'s own default because an under-converged fit
    reads as a worse rank.

    `backend` is passed to `parafac2` ('cpu', 'cupy', 'mlx', or None to
    auto-detect). `PARAFAC2_BACKEND` in the environment does the same thing
    without a flag.

    `output_path` defaults to the canonical name the figure reads.

    Returns the sweep results, the CSV path, and the sidecar path.
    """
    output_path = output_path or (DATA_DIR / spec.rise_rank_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== RISE BiCV rank selection: {spec.label} ===")
    print(f"    ranks={ranks}  n_repeats={n_repeats}  compress={compress}")
    print(
        f"    holdout: {held_out_cell_frac:.0%} of cells, "
        f"{held_out_gene_frac:.0%} of genes"
    )

    print("1. Loading data...")
    adata = spec.load()
    print(f"   AnnData shape: {adata.shape}")

    # `compress` is upstream's `L`: "auto" sizes the subspace from the rank,
    # an integer sets it directly. There is no separate oversample knob.
    compression_kwarg = {"n_power_iter": n_power_iter}

    print("2. Running BiCV sweep...")
    df = bicv(
        adata,
        ranks=ranks,
        n_repeats=n_repeats,
        held_out_cell_frac=held_out_cell_frac,
        held_out_gene_frac=held_out_gene_frac,
        random_state=random_state,
        tolerance=rise_tol,
        max_iter=rise_n_iter_max,
        compress=compress,
        compression_kwarg=compression_kwarg,
        parafac2_kwarg={"normalize_slices": True, "fix_B_identity": True}
        | ({"backend": backend} if backend else {}),
        condition_key=spec.condition_column,
    )

    print(f"3. Writing {output_path}...")
    df.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "ranks": ranks,
            "n_repeats": n_repeats,
            "held_out_cell_frac": held_out_cell_frac,
            "held_out_gene_frac": held_out_gene_frac,
            "rise_n_iter_max": rise_n_iter_max,
            "rise_tol": rise_tol,
            "compress": compress,
            "n_power_iter": n_power_iter,
            "backend": backend or "auto",
            "random_state": random_state,
            "resulting_dims": resulting_dims(spec, adata),
        },
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--ranks",
        type=str,
        default=",".join(str(r) for r in DEFAULT_RANKS),
        help="RISE ranks: comma list and/or start:stop[:step] slices "
        f"(default: {','.join(str(r) for r in DEFAULT_RANKS)}).",
    )
    parser.add_argument(
        "--n-repeats", type=int, default=3, help="BiCV splits per rank."
    )
    parser.add_argument("--held-out-cell-frac", type=float, default=0.5)
    parser.add_argument("--held-out-gene-frac", type=float, default=0.5)
    parser.add_argument("--rise-n-iter-max", type=int, default=RISE_N_ITER_MAX)
    parser.add_argument("--rise-tol", type=float, default=RISE_TOL)
    parser.add_argument(
        "--compress",
        type=str,
        default="auto",
        help="CANDELINC compression passed to bicv: 'auto', an integer "
        "dimension, or 'none' to fit the full training block.",
    )
    parser.add_argument(
        "--n-power-iter",
        type=int,
        default=2,
        help="Power iterations in the compression's randomized range finder.",
    )
    parser.add_argument(
        "--backend",
        type=str,
        default=None,
        choices=["cpu", "cupy", "mlx"],
        help="parafac2 backend (default: auto-detect; PARAFAC2_BACKEND also works).",
    )
    parser.add_argument("--random-state", type=int, default=0)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV output path (default: data/rise_rank_<dataset>.csv).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    compress: str | int | bool = args.compress
    if isinstance(compress, str):
        if compress.lower() in ("none", "false", "no"):
            compress = False
        elif compress.isdigit():
            compress = int(compress)

    run_rise_rank_selection(
        spec,
        ranks=parse_ranks(args.ranks),
        n_repeats=args.n_repeats,
        held_out_cell_frac=args.held_out_cell_frac,
        held_out_gene_frac=args.held_out_gene_frac,
        rise_n_iter_max=args.rise_n_iter_max,
        rise_tol=args.rise_tol,
        compress=compress,
        n_power_iter=args.n_power_iter,
        backend=args.backend,
        random_state=args.random_state,
        output_path=resolve_output(args.output, DATA_DIR, spec.rise_rank_filename()),
    )


if __name__ == "__main__":
    main()
