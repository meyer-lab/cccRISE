#!/usr/bin/env python
"""
Runner: RISE (PARAFAC2) rank selection by bi-cross-validation.

Sweeps `rank_selection.run_bicv` over a set of RISE ranks, writes the
per-rank/per-fold table to CSV, and writes a provenance sidecar recording the
parameters and a per-rank summary of held-out block R2X.

By default each fold is CANDELINC-compressed once and every rank is fit inside
the resulting core, with the streaming passes that build it running on the GPU
when one is available (see `rank_selection.rise_candelinc_compress`). That is
what makes a cohort-scale sweep affordable: the fold's data traversal is paid
once instead of once per (rank, fold) pair, and the fits themselves land on
per-condition slabs of at most `max(ranks) + oversample` on a side.
`--no-compress` and `--device cpu` recover the original behaviour.

The CSV lands at the filename `figureRISErank` reads, and the pipeline runner
cites it as evidence for the RISE rank it was given.

    uv run cccrise-riserank --dataset alad --ranks 5:51:5 --n-folds 5
"""

import argparse
from pathlib import Path

import pandas as pd

from ..rank_selection import run_bicv
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    parse_ranks,
    resolve_output,
    resulting_dims,
)
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, git_sha, write_metadata

DEFAULT_RANKS = [5, 10, 15, 20, 25, 30, 35, 40, 45, 50]

HEADER = """\
RISE rank selection (bi-cross-validation). Generated by
cccrise.runners.run_rise_rank -- do not hand-edit.
"""


def run_rise_rank_selection(
    spec: DatasetSpec,
    ranks: list[int],
    n_folds: int = 5,
    gene_test_frac: float = 0.1,
    n_iter_max: int = 300,
    tol: float = 1e-8,
    compress: bool = True,
    oversample: int = 10,
    n_power_iter: int = 2,
    device: str | None = None,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Run the BiCV sweep and persist the CSV plus its sidecar.

    `n_iter_max` sits above the single-fit default of 100 because an
    under-converged fit reads as a worse rank -- but not higher, because these
    fits reach the cap rather than the tolerance, so cost is linear in it and
    on ALAD the selected rank is unchanged anywhere from 25 to 1000 iterations.

    `output_path` defaults to the canonical name the figure reads.

    Returns the sweep results, the CSV path, and the sidecar path.
    """
    output_path = output_path or (DATA_DIR / spec.rise_rank_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== RISE BiCV rank selection: {spec.label} ===")
    print(f"    ranks={ranks}  n_folds={n_folds}  compress={compress}")

    print("1. Loading data...")
    adata = spec.load()
    print(f"   AnnData shape: {adata.shape}")

    print("2. Running BiCV sweep...")
    df = run_bicv(
        adata,
        ranks=ranks,
        condition_column=spec.condition_column,
        n_folds=n_folds,
        gene_test_frac=gene_test_frac,
        n_iter_max=n_iter_max,
        tol=tol,
        compress=compress,
        oversample=oversample,
        n_power_iter=n_power_iter,
        device=device,
    )

    print(f"3. Writing {output_path}...")
    df.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "ranks": ranks,
            "n_folds": n_folds,
            "gene_test_frac": gene_test_frac,
            "n_iter_max": n_iter_max,
            "tol": tol,
            "compressed": compress,
            "oversample": oversample if compress else None,
            "n_power_iter": n_power_iter if compress else None,
            # `run_bicv` seeds each fold with its fold index, so the sweep is
            # reproducible without a separate seed argument.
            "random_state": "fold index (see rank_selection.run_bicv)",
            "resulting_dims": resulting_dims(spec, adata),
        },
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--ranks",
        type=str,
        default=",".join(str(r) for r in DEFAULT_RANKS),
        help="RISE ranks: comma list and/or start:stop[:step] slices "
        f"(default: {','.join(str(r) for r in DEFAULT_RANKS)}).",
    )
    parser.add_argument("--n-folds", type=int, default=5, help="BiCV folds per rank.")
    parser.add_argument("--gene-test-frac", type=float, default=0.1)
    parser.add_argument("--n-iter-max", type=int, default=300)
    parser.add_argument("--tol", type=float, default=1e-8)
    parser.add_argument(
        "--no-compress",
        dest="compress",
        action="store_false",
        help="Refit the full training block at every rank instead of "
        "CANDELINC-compressing each fold once.",
    )
    parser.add_argument(
        "--oversample",
        type=int,
        default=10,
        help="Basis columns each fold's core keeps beyond max(ranks).",
    )
    parser.add_argument(
        "--n-power-iter",
        type=int,
        default=2,
        help="Power iterations in the compression's randomized range finder.",
    )
    parser.add_argument(
        "--device",
        type=str,
        default=None,
        help="'cuda' or 'cpu' (default: GPU when CuPy and CUDA are available).",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV output path (default: data/rise_rank_<dataset>.csv).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_rise_rank_selection(
        spec,
        ranks=parse_ranks(args.ranks),
        n_folds=args.n_folds,
        gene_test_frac=args.gene_test_frac,
        n_iter_max=args.n_iter_max,
        tol=args.tol,
        compress=args.compress,
        oversample=args.oversample,
        n_power_iter=args.n_power_iter,
        device=args.device,
        output_path=resolve_output(args.output, DATA_DIR, spec.rise_rank_filename()),
    )


if __name__ == "__main__":
    main()
