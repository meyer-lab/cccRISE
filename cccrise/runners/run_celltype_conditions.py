#!/usr/bin/env python
"""
Runner: clinical association of cccRISE components within single cell types.

For every cccRISE component, side (sender `sc_B`, receiver `rc_C`; per-cell,
sample-scaled) and fine cell type, the per-sample mean loading over the type's
cells is tested against each clinical association (Figure 3's), with the
benchmark's patient-block label permutations and a maxT adjustment across all
units per association (`validation.celltype_conditions`). Run at a primary
``--min-cells`` (3) and at 1 as a sensitivity analysis.

Writes, in ``data/validation_results/``:

    celltype_condition_anova_<dataset>.parquet  one row per (min_cells, association, unit)
    celltype_condition_means_<dataset>.parquet  per-sample means and cell counts

    uv run python -m cccrise.runners.run_celltype_conditions --dataset alad
"""

import argparse
import time

import numpy as np
import pandas as pd

from ..comparators.agreement import sample_scaled
from ..factors import load_factors_to_anndata
from ..figures.figure3._common import ASSOCIATIONS
from ..import_data import add_cond_idxs
from ..validation.celltype_conditions import (
    MIN_CELLS,
    MIN_SAMPLES,
    per_sample_means,
    unit_maxt,
)
from ._cli import add_dataset_argument, dataset_metadata
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata
from .run_benchmark_anova import _null_plans

FINE_COLUMN = "celltype"
SIDES = {"sender": "sc_B", "receiver": "rc_C"}
HEADER = """\
Clinical association of cccRISE components within single fine cell types,
maxT-adjusted across all (component, side, cell type) units per association.
Generated by cccrise.runners.run_celltype_conditions -- do not hand-edit.
"""


def _means(adata, spec: DatasetSpec, conditions: np.ndarray) -> pd.DataFrame:
    samples = adata.obs[spec.condition_column].astype(str).to_numpy()
    types = adata.obs[FINE_COLUMN].astype(str).to_numpy()
    frames = [
        per_sample_means(
            sample_scaled(adata.obsm[key], samples), samples, types, conditions
        ).assign(side=side)
        for side, key in SIDES.items()
    ]
    return pd.concat(frames, ignore_index=True)


def _units(means: pd.DataFrame, conditions, min_cells: int) -> dict[tuple, np.ndarray]:
    kept = means[means["n_cells"] >= min_cells]
    wide = kept.pivot_table(
        index=["side", "type", "component"], columns="condition", values="mean"
    ).reindex(columns=conditions)
    return {key: row.to_numpy(float) for key, row in wide.iterrows()}


def run_celltype_conditions(
    spec: DatasetSpec,
    min_cells: tuple[int, ...] = (MIN_CELLS, 1),
    min_samples: int = MIN_SAMPLES,
    n_permutations: int = 10_000,
    random_state: int = 42,
) -> pd.DataFrame:
    git_sha()
    adata = add_cond_idxs(spec.load(), spec.condition_column)
    adata = load_factors_to_anndata(spec.factors_path(), adata=adata)
    conditions = np.unique(adata.obs[spec.condition_column].astype(str))
    means = _means(adata, spec, conditions)
    plans = _null_plans(
        adata, spec, conditions, ASSOCIATIONS, n_permutations, random_state
    )
    frames = []
    for cells in min_cells:
        units = _units(means, conditions, cells)
        for name, (kept, codes, perms) in plans.items():
            start = time.time()
            table = unit_maxt(units, kept, codes, perms, min_samples)
            if table.empty:
                continue
            keys = pd.DataFrame(
                table.pop("key").tolist(), columns=["side", "type", "component"]
            )
            frames.append(
                pd.concat([keys, table], axis=1).assign(
                    association=name, min_cells=cells
                )
            )
            print(
                f"   min_cells {cells}, {name}: {len(table)} units, {time.time() - start:.0f} s"
            )
    out = pd.concat(frames, ignore_index=True)
    paths = {
        "anova": VALIDATION_DIR / f"celltype_condition_anova_{spec.key}.parquet",
        "means": VALIDATION_DIR / f"celltype_condition_means_{spec.key}.parquet",
    }
    out.to_parquet(paths["anova"], index=False)
    means.to_parquet(paths["means"], index=False)
    write_metadata(
        paths["anova"],
        build_metadata(
            dataset_metadata(spec)
            | {
                "factors_path": relpath(spec.factors_path()),
                "factors_sha256": sha256_file(spec.factors_path()),
                "fine_column": FINE_COLUMN,
                "min_cells": list(min_cells),
                "min_samples": min_samples,
                "n_permutations": n_permutations,
                "random_state": random_state,
                "loadings": "per-cell sc_B / rc_C x sqrt(n_cells of the sample)",
                "outputs": {k: relpath(v) for k, v in paths.items()},
            }
        ),
        header=HEADER,
    )
    print(f"   Wrote {len(out)} rows to {paths['anova']}")
    return out


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--min-samples", type=int, default=MIN_SAMPLES)
    parser.add_argument("--n-permutations", type=int, default=10_000)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    run_celltype_conditions(
        DATASETS[args.dataset],
        min_samples=args.min_samples,
        n_permutations=args.n_permutations,
    )


if __name__ == "__main__":
    main()
