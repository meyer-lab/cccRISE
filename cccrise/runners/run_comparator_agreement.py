#!/usr/bin/env python
"""
Runner: cross-method agreement of cccRISE with the tensor comparators.

Reads every fit ``cccrise-benchmark`` cached (``benchmark_fits_<dataset>.nc``:
cccRISE and pseudobulk CPD / Tensor-cell2cell / STACCato in each rank mode) and,
on the condition and ligand-receptor modes the methods share
(`comparators.agreement`):

- linear CKA and the mean principal-angle cosine of each comparator fit's span
  against cccRISE's, with row-permutation and Gaussian nulls;
- per component, containment in the other method's span, in both directions,
  against a row-permutation null, and the "shared" calls (contained on both
  modes);
- the Hungarian match on joint condition x LR congruence.

From cccRISE's per-cell loadings (`sc_B` / `rc_C`, scaled by sqrt(n_cells) of
each cell's sample; `agreement.sample_scaled`) it also writes how each
component spreads over cell types (fraction of each type's cells carrying it,
each type's share of its loading), the same inside each component's dominant
sample, and the cell-type-aggregated sender / receiver loadings compared with
each comparator's sender / receiver factors.

Writes, in ``data/validation_results/``:

    comparator_subspace_<dataset>.parquet       (fit, mode, statistic)
    comparator_containment_<dataset>.parquet    (direction, fit, mode, component)
    comparator_matching_<dataset>.parquet       Hungarian pairs, joint congruence
    comparator_cell_fractions_<dataset>.parquet (side, component, cell type)
    comparator_sample_fractions_<dataset>.parquet (side, component, cell type in its dominant sample)
    comparator_cell_overlap_<dataset>.parquet   (component, cell type): active as sender, receiver, both, either
    comparator_celltype_modes_<dataset>.parquet (fit, side, component pair |cos|)

    uv run cccrise-comparator-agreement --dataset alad
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from ..benchmark import ComparatorFit, read_fits
from ..comparators.agreement import (
    cell_type_fractions,
    cell_type_overlap,
    celltype_profiles,
    containment_table,
    dominant_sample_fractions,
    joint_congruence,
    sample_scaled,
    subspace_agreement,
    type_eta_squared,
    unit_columns,
)
from ..factors import load_factors_netcdf, load_factors_to_anndata
from ._cli import add_dataset_argument, dataset_metadata, resulting_dims
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

MODES = ("condition", "lr")
TAU_FRACS = (0.25, 0.5, 0.75)
HEADER = """\
Cross-method agreement of cccRISE with the tensor comparators on the shared
condition and LR modes, and cccRISE's per-cell spread over cell types.
Generated by cccrise.runners.run_comparator_agreement -- do not hand-edit.
"""


def _outputs(spec: DatasetSpec) -> dict[str, Path]:
    names = (
        "subspace",
        "containment",
        "matching",
        "cell_fractions",
        "sample_fractions",
        "cell_overlap",
        "celltype_modes",
    )
    return {n: VALIDATION_DIR / f"comparator_{n}_{spec.key}.parquet" for n in names}


def _aligned_modes(
    fit: ComparatorFit, info: dict, cccrise_lr: np.ndarray
) -> dict[str, np.ndarray]:
    """A fit's condition and LR factors with LR rows in cccRISE's order."""
    if fit.method == "cccRISE":
        return {"condition": fit.condition_factor, "lr": fit.modes["lr"]}
    order = pd.Index(info["lr_pairs"]).get_indexer(cccrise_lr)
    if (order < 0).any():
        raise ValueError("cccRISE LR pairs missing from the comparator tensor")
    return {"condition": fit.condition_factor, "lr": fit.modes["lr"][order]}


def _fit_label(fit: ComparatorFit) -> dict[str, str]:
    return {"method": fit.method, "rank_mode": fit.rank_mode, "rank": fit.rank}


def _subspace_rows(ref, fits, rng, n_null) -> pd.DataFrame:
    frames = []
    for fit, modes in fits:
        for mode in MODES:
            t = subspace_agreement(modes[mode], ref[mode], n_null, rng)
            frames.append(t.assign(mode=mode, **_fit_label(fit)))
    return pd.concat(frames, ignore_index=True)


def _containment_rows(ref, fits, rng, n_null) -> pd.DataFrame:
    frames = []
    for fit, modes in fits:
        for mode in MODES:
            for direction, span, cols in (
                ("cccRISE in comparator", modes[mode], ref[mode]),
                ("comparator in cccRISE", ref[mode], modes[mode]),
            ):
                t = containment_table(span, cols, n_null, rng)
                frames.append(
                    t.assign(direction=direction, mode=mode, **_fit_label(fit))
                )
    return pd.concat(frames, ignore_index=True)


def _matching_rows(ref, fits) -> pd.DataFrame:
    rows = []
    for fit, modes in fits:
        if fit.kind != "cp":
            continue
        cong, r, c = joint_congruence(ref, modes, list(MODES))
        per_mode = {
            m: np.abs(unit_columns(ref[m]).T @ unit_columns(modes[m])) for m in MODES
        }
        rows += [
            {
                **_fit_label(fit),
                "cccrise_component": int(i) + 1,
                "comparator_component": int(j) + 1,
                "joint_congruence": float(cong[i, j]),
                **{f"{m}_congruence": float(per_mode[m][i, j]) for m in MODES},
            }
            for i, j in zip(r, c, strict=True)
        ]
    return pd.DataFrame(rows)


def _cell_rows(adata, spec: DatasetSpec, cccrise: ComparatorFit, conditions):
    """Per side: cell-type fractions over all cells, and inside each
    component's dominant sample, of the sample-scaled per-cell loadings."""
    types = adata.obs[spec.celltype_column].astype(str).to_numpy()
    samples = adata.obs[spec.condition_column].astype(str).to_numpy()
    overall, dominant = [], []
    for side, key in (("sender", "sc_B"), ("receiver", "rc_C")):
        loadings = sample_scaled(adata.obsm[key], samples)
        frac = cell_type_fractions(loadings, types, TAU_FRACS)
        eta = dict(enumerate(type_eta_squared(loadings, types), start=1))
        overall.append(
            frac.assign(side=side, type_eta_squared=frac["component"].map(eta))
        )
        dom = dominant_sample_fractions(
            loadings, types, samples, cccrise.condition_factor, conditions, 0.5
        )
        dominant.append(dom.assign(side=side))
    return pd.concat(overall, ignore_index=True), pd.concat(dominant, ignore_index=True)


def _celltype_mode_rows(adata, celltype_column, comparators, celltypes) -> pd.DataFrame:
    """|cos| between cccRISE's cell-type-aggregated sender/receiver loadings and
    each CP comparator's sender/receiver factor."""
    types = adata.obs[celltype_column].astype(str).to_numpy()
    rows = []
    for side, key in (("sender", "sc_B"), ("receiver", "rc_C")):
        profile = celltype_profiles(adata.obsm[key], types, celltypes)
        for fit, _modes in comparators:
            if fit.kind != "cp":
                continue
            cos = np.abs(unit_columns(profile).T @ unit_columns(fit.modes[side]))
            rows += [
                {
                    **_fit_label(fit),
                    "side": side,
                    "cccrise_component": i + 1,
                    "comparator_component": j + 1,
                    "abs_cosine": float(cos[i, j]),
                }
                for i in range(cos.shape[0])
                for j in range(cos.shape[1])
            ]
    return pd.DataFrame(rows)


def run_comparator_agreement(
    spec: DatasetSpec, n_null: int = 1000, random_state: int = 42
) -> dict[str, pd.DataFrame]:
    git_sha()
    fits_path = VALIDATION_DIR / spec.benchmark_fits_filename()
    fits, info, conditions = read_fits(fits_path)
    cccrise = next(f for f in fits if f.method == "cccRISE")
    ds = load_factors_netcdf(spec.factors_path())
    if not np.array_equal(ds.coords["condition"].values.astype(str), conditions):
        raise ValueError("Cached fits and the canonical factors disagree on conditions")
    cccrise_lr = ds.coords["lr_pair"].values.astype(str)
    ref = _aligned_modes(cccrise, info, cccrise_lr)
    comparators = [
        (f, _aligned_modes(f, info, cccrise_lr)) for f in fits if f.method != "cccRISE"
    ]
    rng = np.random.default_rng(random_state)
    print(">> Subspace agreement and containment")
    tables = {
        "subspace": _subspace_rows(ref, comparators, rng, n_null),
        "containment": _containment_rows(ref, comparators, rng, n_null),
        "matching": _matching_rows(ref, comparators),
    }
    print(">> Per-cell loadings")
    adata = load_factors_to_anndata(spec.factors_path(), adata=spec.load())
    tables["cell_fractions"], tables["sample_fractions"] = _cell_rows(
        adata, spec, cccrise, conditions
    )
    samples = adata.obs[spec.condition_column].astype(str).to_numpy()
    tables["cell_overlap"] = cell_type_overlap(
        sample_scaled(adata.obsm["sc_B"], samples),
        sample_scaled(adata.obsm["rc_C"], samples),
        adata.obs[spec.celltype_column].astype(str).to_numpy(),
        0.5,
    )
    tables["celltype_modes"] = _celltype_mode_rows(
        adata, spec.celltype_column, comparators, info["celltypes"]
    )
    paths = _outputs(spec)
    for name, table in tables.items():
        table.to_parquet(paths[name], index=False)
        print(f"   Wrote {len(table)} rows to {paths[name]}")
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "fits_path": relpath(fits_path),
            "fits_sha256": sha256_file(fits_path),
            "factors_path": relpath(spec.factors_path()),
            "factors_sha256": sha256_file(spec.factors_path()),
            "modes": list(MODES),
            "n_null": n_null,
            "random_state": random_state,
            "contained_threshold": 0.85,
            "tau_fracs": list(TAU_FRACS),
            "per_cell_loadings": "scaled by sqrt(n_cells) of the cell's sample",
            "outputs": {k: relpath(v) for k, v in paths.items()},
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=len(cccrise_lr)),
        }
    )
    write_metadata(paths["subspace"], metadata, header=HEADER)
    return tables


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--n-null", type=int, default=1000)
    parser.add_argument("--random-state", type=int, default=42)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    run_comparator_agreement(
        DATASETS[args.dataset], n_null=args.n_null, random_state=args.random_state
    )


if __name__ == "__main__":
    main()
