"""
Runner: cell-permutation significance testing of CCC-RISE communication.

Permutes cell loadings ($P_i$ rows) across cells within each condition $i$
while preserving raw expression ($X_i$) and LR pair annotations
(`compute_communication_significance`), and computes empirical $p$-values and
$Z$-score effect sizes for each condition $\times$ sender $\times$ receiver
$\times$ LR pair. Group differences between patients are tested separately,
from the figures, by `validation.significance.patient_permutation_differential`.

Loads a RISE fit produced by `run_ccc_rise` (`--reference-source`) rather
than fitting PARAFAC2 itself; see `utils.load_rise_reference`.

Writes the per-LR pair observed vs. null scores and z-scores to
significance_lr_<dataset>.parquet:

    uv run cccrise-significance --dataset alad \
        --reference-source cccrise/data/factors/bal_alad_factors.nc --n-perms 1000
"""

import argparse
from pathlib import Path

import pandas as pd

from ..import_data import import_ligand_receptor_pairs
from ..validation.significance import (
    fit_significance_pipeline,
    summarize_significance_lr,
    summarize_significance_overview,
)
from ._cli import (
    add_dataset_argument,
    add_scoring_arguments,
    dataset_metadata,
    resolve_output,
    resulting_dims,
)
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec, scoring_output_dir
from .provenance import build_metadata, git_sha, relpath, write_metadata

HEADER = """\
Permutation-based significance testing of CCC-RISE communication scores.
Generated by cccrise.runners.run_significance -- do not hand-edit.
"""


def output_paths(spec: DatasetSpec, output_root: Path) -> dict[str, Path]:
    """Map the output file keys to absolute destination paths."""
    return {
        "lr": output_root / spec.significance_lr_filename(),
    }


def run_significance(
    spec: DatasetSpec,
    reference_source: str | Path,
    n_perms: int = 1000,
    communication_score: str = "expression_product",
    complex_sep: str | None = "&",
    complex_agg_method: str = "min",
    hill_k: float = 0.5,
    random_state: int = 42,
    output_path: Path | None = None,
    output_root: Path | None = None,
) -> tuple[pd.DataFrame, dict[str, Path]]:
    """Load a shared RISE fit, run permutation significance testing, and
    write output tables.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    reference_source : str | Path
        A factors.nc written by `run_ccc_rise` or `run_alt_comm_score`; its RISE fit is loaded
        rather than refit.
    n_perms : int, default=1000
        Number of permutations.
    communication_score : str, default='expression_product'
        Scoring function for ligand-receptor interactions. Independent of
        whichever score `reference_source` itself was built with.
    complex_sep : str, default='&'
        Delimiter for multi-subunit complexes.
    complex_agg_method : str, default='min'
        Subunit aggregation method ('min', 'mean', 'gmean').
    hill_k : float, default=0.5
        Half-saturation constant for Hill scoring.
    random_state : int, default=42
        Seed for permutations.
    output_path : Path, optional
        Custom path for the primary LR significance table.
    output_root : Path, optional
        Directory for runner outputs. Defaults to `VALIDATION_DIR` for
        `communication_score="expression_product"` (the canonical location
        figures read), or `comparison_output_dir(communication_score)`
        (under `validation_results/alt_score_methods/`) for any other score.

    Returns
    -------
    tuple[pd.DataFrame, dict[str, Path]]
        The LR significance table and the mapping of written file paths.
    """
    output_root = output_root or scoring_output_dir(communication_score, VALIDATION_DIR)
    paths = output_paths(spec, output_root)
    if output_path is not None:
        paths["lr"] = output_path

    for path in paths.values():
        path.parent.mkdir(parents=True, exist_ok=True)

    git_sha()

    print(f"=== Permutation Significance Testing: {spec.label} (n_perms {n_perms}) ===")
    print(
        f"    score={communication_score!r}  complex_sep={complex_sep!r}  "
        f"reference_source={reference_source!r}"
    )

    print("1. Loading dataset...")
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()
    print(f"   AnnData shape: {adata.shape}, LR pairs: {len(lr_pairs)}")

    print("2. Loading the shared RISE fit and computing permutation significance...")
    results = fit_significance_pipeline(
        adata=adata,
        condition_column=spec.condition_column,
        reference_path=reference_source,
        lr_pairs=lr_pairs,
        n_perms=n_perms,
        communication_score=communication_score,
        complex_sep=complex_sep,
        complex_agg_method=complex_agg_method,
        hill_k=hill_k,
        random_state=random_state,
        validate=False,
    )
    print(f"   RISE fit R2X: {results['r2x_rise']:.4f}")

    print("3. Generating summary metrics on the fly...")
    lr_df = summarize_significance_lr(results)
    overview_df = summarize_significance_overview(results)

    print(overview_df.to_string(index=False))

    print(f"4. Writing {len(lr_df)} LR pairs to {paths['lr']}...")
    lr_df.to_parquet(paths["lr"], index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "reference_source": relpath(reference_source),
            "n_perms": n_perms,
            "communication_score": communication_score,
            "complex_sep": complex_sep,
            "complex_agg_method": complex_agg_method,
            "hill_k": hill_k,
            "r2x_rise": float(results["r2x_rise"]),
            "random_state": random_state,
            "total_tensor_entries": int(overview_df["TotalEntries"].iloc[0]),
            "cohort_fraction_significant_p05": float(
                overview_df["FractionSignificant_p05"].iloc[0]
            ),
            "cohort_fraction_significant_p01": float(
                overview_df["FractionSignificant_p01"].iloc[0]
            ),
            "cohort_median_zscore": float(overview_df["MedianZScore"].iloc[0]),
            "cohort_mean_zscore": float(overview_df["MeanZScore"].iloc[0]),
            "resulting_dims": resulting_dims(
                spec, adata, n_lr_pairs=len(results["filtered_lr_pairs"])
            ),
            "outputs": [relpath(paths["lr"])],
        }
    )
    sidecar = write_metadata(paths["lr"], metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")

    return lr_df, paths


def build_parser() -> argparse.ArgumentParser:
    """Build the argument parser for significance testing."""
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--reference-source",
        type=str,
        required=True,
        help="A factors.nc written by run_ccc_rise or run_alt_comm_score, whose RISE fit is reused "
        "rather than refit.",
    )
    parser.add_argument(
        "--n-perms",
        type=int,
        default=1000,
        help="Number of permutations (default: 1000).",
    )
    add_scoring_arguments(parser)
    parser.add_argument(
        "--complex-sep",
        type=str,
        default="&",
        help="Separator for multi-subunit complexes (default: '&').",
    )
    parser.add_argument(
        "--complex-agg-method",
        type=str,
        default="min",
        choices=["min", "mean", "gmean"],
        help="Complex subunit aggregation method (default: min).",
    )
    parser.add_argument(
        "--random-state",
        type=int,
        default=42,
        help="Random seed (default: 42).",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Primary Parquet destination; defaults to significance_lr_<dataset>.parquet "
        "under --output-root.",
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        default=None,
        help="Root directory for outputs (default: data/validation_results/ "
        "for expression_product, its alt_score_methods/<communication-score>/ "
        "otherwise).",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    """Entry point for cccrise-significance."""
    parser = build_parser()
    args = parser.parse_args(argv)
    spec = DATASETS[args.dataset]
    output_root = args.output_root or scoring_output_dir(
        args.communication_score, VALIDATION_DIR
    )

    run_significance(
        spec=spec,
        reference_source=args.reference_source,
        n_perms=args.n_perms,
        communication_score=args.communication_score,
        complex_sep=args.complex_sep,
        complex_agg_method=args.complex_agg_method,
        hill_k=args.hill_k,
        random_state=args.random_state,
        output_path=resolve_output(
            args.output, output_root, spec.significance_lr_filename()
        ),
        output_root=output_root,
    )


if __name__ == "__main__":
    main()
