#!/usr/bin/env python
"""
Runner: are the components CCC-RISE reports reproducible under resampling?

Both ranks are already chosen (see `rank_selection.select_rise_rank` and
`select_cpd_rank` for the rules, and issue #168 for the pinned values), so this
runner takes them as inputs rather than producing them. What it measures is
whether the components recovered at those ranks survive resampling the data:
per replicate, each reference component's factor match score against its
best-matching replicate component.

One replicate loop serves both stages. A replicate resamples the AnnData once,
refits RISE once, scores RISE stability from that fit, then builds the
communication tensor from the *same* fit and scores CPD stability -- so the two
stages' rows for a replicate describe the same resampled dataset, and the
expensive PARAFAC2 fit is paid for once instead of twice.

Axes, and what each one asks:

  cells       Cells bootstrapped with replacement within each condition, the
              cohort held fixed. Robustness to which cells were captured and
              to sequencing depth. Refits RISE.
  conditions  Whole conditions bootstrapped with replacement, drawn within
              phenotype strata, keeping every cell of a drawn condition.
              Robustness to which patients were enrolled -- the axis the
              manuscript's claims rest on, and the one expected to look
              worse. Refits RISE.
  lr_pairs    The reference tensor's ligand-receptor mode bootstrapped.
              Robustness to which interactions the database contains. Costs
              no PARAFAC2 fit.
  permuted    The reference tensor's entries permuted: the chance floor an
              observed FMS has to be read against. Costs no PARAFAC2 fit.

    uv run ccc-rise-stability --dataset alad --rise-rank 25 --cp-rank 4 \
        --n-replicates 20 --axes cells,conditions,lr_pairs,permuted
"""

import argparse
from pathlib import Path

import pandas as pd

from ..import_data import import_ligand_receptor_pairs
from ..stability import (
    DEFAULT_AXES,
    PERMUTED_AXIS,
    RISE_REFIT_AXES,
    StabilitySpec,
    component_stability,
    metric_interval,
    replicate_seed,
    summarize_component_stability,
)
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    resolve_output,
    resulting_dims,
)
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, git_sha, write_metadata

#: Every axis the runner knows how to run, in report order.
ALL_AXES = (*DEFAULT_AXES, PERMUTED_AXIS)

HEADER = """\
Per-component RISE and CPD stability at fixed ranks under resampling.
Generated by cellcommunicationpf2.runners.run_component_stability -- do not
hand-edit.
"""


def run_component_stability(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    axes: tuple[str, ...] = DEFAULT_AXES,
    n_replicates: int = 20,
    rise_n_iter_max: int = 100,
    rise_tol: float = 1e-6,
    n_iter_max: int = 100,
    tol: float = 1e-3,
    init: str = "svd",
    svd: str = "randomized_svd",
    complex_sep: str | None = "&",
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
    random_state: int = 0,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Score per-component RISE and CPD stability at fixed ranks.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank, cp_rank : int
        The already-selected ranks. Stability is a claim about the chosen
        model, so both are fixed rather than swept.
    axes : tuple[str, ...], default=DEFAULT_AXES
        Resampling axes to run; see the module docstring.
    n_replicates : int, default=20
        Replicates per axis.
    rise_n_iter_max, rise_tol, n_iter_max, tol, init, svd
        Fitting controls for the RISE and CP fits.
    complex_sep, communication_score, hill_k
        Communication-tensor options; see `ccc_rise.calc_communication_score`.
    random_state : int, default=0
        Base seed for the reference fit and the replicates.
    output_path : Path, optional
        CSV destination; defaults to the registry's stability filename.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The long per-component table, the CSV path, and the sidecar path.
    """
    output_path = output_path or (DATA_DIR / spec.stability_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    rise_axes = [axis for axis in axes if axis in RISE_REFIT_AXES]
    print(f"=== Component stability: {spec.label} ===")
    print(f"    RISE rank {rise_rank}, CP rank {cp_rank}, {n_replicates} replicates")
    print(f"    Axes: {', '.join(axes)}")
    print(
        f"    {1 + len(rise_axes) * n_replicates} PARAFAC2 fits, "
        f"{1 + len(axes) * n_replicates} CP fits"
    )

    print("1. Loading data...")
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()
    print(f"   AnnData shape: {adata.shape}")
    print(f"   Ligand-receptor pairs: {len(lr_pairs)}")

    stability_spec = StabilitySpec(
        condition_column=spec.condition_column,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        group_column=spec.group_column,
        rise_n_iter_max=rise_n_iter_max,
        rise_tol=rise_tol,
        cp_n_iter_max=n_iter_max,
        cp_tol=tol,
        init=init,
        svd=svd,
        complex_sep=complex_sep,
        communication_score=communication_score,
        hill_k=hill_k,
    )

    print("2. Fitting the reference model on the full cohort...")
    reference = stability_spec.fit(
        adata.copy(), lr_pairs, random_state=random_state, keep_tensor=True
    )
    assert reference.tensor is not None
    tensor_shape = tuple(int(dim) for dim in reference.tensor.shape)
    print(f"   Interaction tensor shape: {tensor_shape}")
    print(f"   RISE R2X {reference.r2x_rise:.4f}, CP R2X {reference.r2x_cp:.4f}")

    print("3. Running resampled replicates...")
    df = component_stability(
        stability_spec,
        adata,
        reference,
        lr_pairs,
        axes=axes,
        n_replicates=n_replicates,
        random_state=random_state,
    )

    print("4. Aggregate FMS across replicates, per stage and axis:")
    aggregate = metric_interval(df, "FMS", by=("Stage", "Axis"))
    print(aggregate.to_string(index=False))
    print("   Per-component stability:")
    print(summarize_component_stability(df).to_string(index=False))

    print(f"5. Writing {len(df)} rows to {output_path}...")
    df.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "rise_rank": rise_rank,
            "cp_rank": cp_rank,
            "axes": list(axes),
            "n_replicates": n_replicates,
            "rise_n_iter_max": rise_n_iter_max,
            "rise_tol": rise_tol,
            "n_iter_max": n_iter_max,
            "tol": tol,
            "init": init,
            "svd": svd,
            "complex_sep": complex_sep,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "random_state": random_state,
            "seed_formula": (
                "random_state * 1000 + replicate + 1; one seed drives the "
                "resample, the RISE refit and the CP fit, so a "
                "replicate's RISE and CPD rows are the same resampled dataset "
                "(see stability.replicate_seed)"
            ),
            "resampling": {
                "cells": "cells bootstrapped with replacement within each condition",
                "conditions": (
                    "whole conditions bootstrapped with replacement"
                    + (
                        f", stratified by {spec.group_column}"
                        if spec.group_column
                        else ", unstratified"
                    )
                ),
                "lr_pairs": (
                    "reference tensor's ligand-receptor mode bootstrapped "
                    "with replacement; no PARAFAC2 refit"
                ),
                PERMUTED_AXIS: (
                    "reference tensor's entries permuted, giving the chance "
                    "floor; no PARAFAC2 refit"
                ),
            },
            "condition_mode_alignment": (
                "reference condition-mode rows expanded onto the replicate's "
                "roster by draw (see stability.reference_condition_rows)"
            ),
            "lr_mode_alignment": (
                "reference ligand-receptor mode rows expanded by the drawn LR indices"
            ),
            "fms_definition": (
                "congruence product across all modes (3 modes for RISE, 4 modes "
                "for CPD), weights ignored (see stability.per_component_fms)"
            ),
            "component_numbering": ("reference fit after ccc_rise.standardize_cc_pf2"),
            "lr_roster_stable": True,
            "interaction_tensor_shape": list(tensor_shape),
            "r2x_pf2": float(reference.r2x_rise),
            "r2x_cp": float(reference.r2x_cp),
            "reference_seed": random_state,
            "first_replicate_seed": replicate_seed(random_state, 0),
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=tensor_shape[3]),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")

    return df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank every fit uses; see rank_selection.select_rise_rank.",
    )
    parser.add_argument(
        "--cp-rank",
        type=int,
        required=True,
        help="CP rank every fit uses; see rank_selection.select_cpd_rank.",
    )
    parser.add_argument(
        "--axes",
        type=str,
        default=",".join(DEFAULT_AXES),
        help=(
            "Comma-separated resampling axes. Cohort axes draw with "
            f"replacement. Options: {', '.join(ALL_AXES)}."
        ),
    )
    parser.add_argument("--n-replicates", type=int, default=20)
    parser.add_argument("--rise-n-iter-max", type=int, default=100)
    parser.add_argument("--rise-tol", type=float, default=1e-6)
    parser.add_argument("--n-iter-max", type=int, default=100)
    parser.add_argument("--tol", type=float, default=1e-3)
    parser.add_argument("--init", type=str, default="svd", choices=["random", "svd"])
    parser.add_argument(
        "--svd",
        type=str,
        default="randomized_svd",
        choices=["randomized_svd", "truncated_svd"],
    )
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument(
        "--communication-score",
        type=str,
        default="expression_product",
        choices=[
            "expression_product",
            "expression_mean",
            "expression_gmean",
            "expression_hill",
        ],
    )
    parser.add_argument("--hill-k", type=float, default=0.5)
    parser.add_argument("--random-state", type=int, default=0)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV destination; defaults to data/component_stability_<dataset>.csv.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_component_stability(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        axes=tuple(axis.strip() for axis in args.axes.split(",") if axis.strip()),
        n_replicates=args.n_replicates,
        rise_n_iter_max=args.rise_n_iter_max,
        rise_tol=args.rise_tol,
        n_iter_max=args.n_iter_max,
        tol=args.tol,
        init=args.init,
        svd=args.svd,
        complex_sep=args.complex_sep,
        communication_score=args.communication_score,
        hill_k=args.hill_k,
        random_state=args.random_state,
        output_path=resolve_output(args.output, DATA_DIR, spec.stability_filename()),
    )


if __name__ == "__main__":
    main()
