#!/usr/bin/env python
"""
Runner: RISE eigen-states and cccRISE components across fine cell types.

For every RISE eigen-state (the cells' projections) and every cccRISE
component's sender (`sc_B`) and receiver (`rc_C`) loading -- each sample-scaled
and oriented so its high tail is positive -- takes its active cells (above half
its 99th percentile) and describes how they sit across fine cell types
(`validation.eigenstate_celltypes`): whole fine types (a finer annotation
would capture the program) or fractions cutting across several. A null of
random directions in RISE space gives the same summaries for scores tied to
no program.

Writes, in ``data/validation_results/``:

    eigenstate_celltype_summary_<dataset>.parquet  one row per score
    eigenstate_celltype_profile_<dataset>.parquet  (score, fine type) active fractions
    eigenstate_celltype_hist_<dataset>.parquet     (score, bin, fine type) counts
    eigenstate_celltype_null_<dataset>.parquet     one row per random direction

    uv run cccrise-eigenstate-celltypes --dataset alad
"""

import argparse

import numpy as np
import pandas as pd

from ..comparators.agreement import sample_scaled
from ..factors import load_factors_netcdf, load_factors_to_anndata
from ..validation.eigenstate_celltypes import (
    orient,
    random_direction_null,
    score_units,
)
from ._cli import add_dataset_argument, dataset_metadata, resulting_dims
from .datasets import DATASETS, VALIDATION_DIR, DatasetSpec
from .provenance import build_metadata, git_sha, relpath, sha256_file, write_metadata

FINE_COLUMN = "celltype"
HEADER = """\
RISE eigen-states and cccRISE components across fine cell types: which cells
are active and whether they are whole fine types or fractions. Generated by
cccrise.runners.run_eigenstate_celltypes -- do not hand-edit.
"""


def _scores(adata, spec: DatasetSpec) -> dict[str, np.ndarray]:
    samples = adata.obs[spec.condition_column].astype(str).to_numpy()
    out = {}
    for prefix, key in (("E", "projections"), ("S", "sc_B"), ("R", "rc_C")):
        values = orient(sample_scaled(adata.obsm[key], samples))
        out |= {f"{prefix}{k + 1}": values[:, k] for k in range(values.shape[1])}
    return out


def _cp_loadings(spec: DatasetSpec) -> pd.DataFrame:
    """|B| and |C| of every eigen-state on every cccRISE component."""
    ds = load_factors_netcdf(spec.factors_path())
    b, c = np.abs(ds["cp_B"].values), np.abs(ds["cp_C"].values)
    rows = {"unit": [f"E{i + 1}" for i in range(b.shape[0])]}
    for k in range(b.shape[1]):
        rows[f"abs_B_C{k + 1}"] = b[:, k]
        rows[f"abs_C_C{k + 1}"] = c[:, k]
    return pd.DataFrame(rows)


def run_eigenstate_celltypes(
    spec: DatasetSpec, n_bins: int = 60, n_null: int = 200, random_state: int = 42
) -> dict[str, pd.DataFrame]:
    git_sha()
    adata = load_factors_to_anndata(spec.factors_path(), adata=spec.load())
    samples = adata.obs[spec.condition_column].astype(str).to_numpy()
    coarse = adata.obs[spec.celltype_column].astype(str).to_numpy()
    fine = adata.obs[FINE_COLUMN].astype(str).to_numpy()
    summary, profile, hist = score_units(_scores(adata, spec), coarse, fine, n_bins)
    tables = {
        "summary": summary.merge(_cp_loadings(spec), on="unit", how="left"),
        "profile": profile,
        "hist": hist,
        "null": random_direction_null(
            sample_scaled(adata.obsm["projections"], samples),
            fine,
            coarse,
            n_null,
            np.random.default_rng(random_state),
        ),
    }
    paths = {
        name: VALIDATION_DIR / f"eigenstate_celltype_{name}_{spec.key}.parquet"
        for name in tables
    }
    for name, table in tables.items():
        table.to_parquet(paths[name], index=False)
    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "factors_path": relpath(spec.factors_path()),
            "factors_sha256": sha256_file(spec.factors_path()),
            "fine_column": FINE_COLUMN,
            "scores": "projections (E), sc_B (S), rc_C (R); sample-scaled, oriented",
            "active": "score > 0.5 x its 99th percentile",
            "calls": "fine-aligned: >= 80% of active cells in fine types >= 80% "
            "active; cross-cutting: >= 50% in fine types 20-80% active, >= 2 such "
            "types holding >= 5% each",
            "null": f"{n_null} random unit directions in sample-scaled RISE space",
            "random_state": random_state,
            "n_bins": n_bins,
            "outputs": {k: relpath(v) for k, v in paths.items()},
            "resulting_dims": resulting_dims(spec, adata),
        }
    )
    write_metadata(paths["summary"], metadata, header=HEADER)
    print(f"   Wrote {len(summary)} scores to {paths['summary']}")
    return tables


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument("--n-bins", type=int, default=60)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    run_eigenstate_celltypes(DATASETS[args.dataset], n_bins=args.n_bins)


if __name__ == "__main__":
    main()
