#!/usr/bin/env python
"""
Runner: phenotype AUC as a function of CP rank.

Fits RISE once per method, then sweeps CP rank over that single interaction
tensor, scoring each rank through the same `benchmarks.auc.cv_auc` the
single-rank benchmark table uses.

This is the direct, quantitative answer to Reviewer #1's comment #4. The ALAD
ranks used to be chosen because they "yielded the optimal predictive performance
for ALAD status"; they are now chosen by BiCV and CORCONDIA, which never see the
phenotype. Showing the AUC-versus-rank curve, with the selected rank marked and
a permuted-label null beside it, measures how much of the original number came
from selecting the rank against the outcome -- rather than asserting the bias
is gone.

CP rank is capped by the tensor's smallest mode, which differs by method: the
pseudobulk tensor's sender/receiver modes are cell types (8 on ALAD), so it
stops at 8, while CCC-RISE's are eigen-states and it runs to the RISE rank (19).
Ranks above a method's cap are skipped and recorded as skipped.

    uv run cccrise-bench-rank --dataset alad
    uv run cccrise-bench-rank --dataset alad --ranks 1:20 --n-permutations 25
"""

import argparse
from pathlib import Path

import pandas as pd

from ..anova import prepare_group_labels
from ..benchmarks.auc import CLASSIFIERS, DEFAULT_CLASSIFIER, cv_auc
from ..benchmarks.rank_sweep import (
    SWEEP_BUILDERS,
    ccc_rise_sweep_tensor,
    pseudobulk_sweep_tensor,
)
from ..figures.commonFuncs.plotGeneral import get_sample_to_group
from ..import_data import import_ligand_receptor_pairs
from ._cli import (
    add_dataset_argument,
    add_group_arguments,
    dataset_metadata,
    parse_ranks,
    resolve_group_labels,
    resolve_output,
    resulting_dims,
    selected_rise_rank,
)
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, git_sha, write_metadata

DEFAULT_RANKS = list(range(1, 20))

HEADER = """\
Phenotype AUC as a function of CP rank, per benchmarked method.
Generated by cccrise.runners.run_benchmark_rank -- do not hand-edit.
"""


def run_benchmark_rank(
    spec: DatasetSpec,
    rise_rank: int,
    ranks: list[int],
    methods: list[str] | None = None,
    classifier: str = DEFAULT_CLASSIFIER,
    group_column: str | None = None,
    control_label: str | None = None,
    other_label: str | None = None,
    n_splits: int = 10,
    n_repeats: int = 5,
    inner_splits: int = 5,
    n_permutations: int = 25,
    n_boot: int = 1000,
    ci_level: float = 95.0,
    complex_sep: str | None = "&",
    random_state: int = 42,
    output_path: Path | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Sweep CP rank for each method and score every rank's condition factor.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank : int
        RISE rank the CCC-RISE tensor is built at, fit once for the whole sweep.
    ranks : list[int]
        CP ranks to score. Ranks above a method's cap are skipped.
    methods : list[str] | None
        Keys into `benchmarks.rank_sweep.SWEEP_BUILDERS`; all when None.
    classifier : str
        Key into `benchmarks.auc.CLASSIFIERS`.
    group_column, control_label, other_label : str | None
        The binary outcome, resolved from the registry when not given.
    n_splits, n_repeats, inner_splits, n_permutations, n_boot, ci_level
        Cross-validation controls; see `benchmarks.auc.cv_auc`. The permutation
        null runs at *every* rank, because "more components score higher by
        chance alone" is precisely the confound this curve has to rule out.
    complex_sep : str | None
        Communication-tensor option.
    random_state : int
        Seed for the fits, the folds and the bootstrap.
    output_path : Path | None
        CSV destination; defaults to `data/benchmark_rank_<dataset>.csv`.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The per-rank table, the CSV path and the sidecar path.
    """
    group_column, control_label, other_label = resolve_group_labels(
        spec, group_column, control_label, other_label
    )
    keys = methods or list(SWEEP_BUILDERS)
    unknown = [k for k in keys if k not in SWEEP_BUILDERS]
    if unknown:
        raise ValueError(
            f"Unknown method(s) {unknown}. Available: {sorted(SWEEP_BUILDERS)}"
        )
    if classifier not in CLASSIFIERS:
        raise ValueError(
            f"Unknown classifier {classifier!r}. Available: {sorted(CLASSIFIERS)}"
        )

    output_path = output_path or (DATA_DIR / spec.benchmark_rank_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== Benchmark AUC vs CP rank: {spec.label} ===")
    print(
        f"    methods={keys}  ranks={ranks[0]}-{ranks[-1]}  classifier={classifier!r}\n"
        f"    group={group_column!r} ({control_label!r} vs {other_label!r})  "
        f"perms/rank={n_permutations}  seed={random_state}"
    )

    print("1. Loading data and ligand-receptor pairs...")
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()
    print(f"   AnnData shape: {adata.shape}, LR pairs: {len(lr_pairs)}")

    raw_labels = get_sample_to_group(adata, spec.condition_column, group_column)
    labels = prepare_group_labels(
        raw_labels, control_label=control_label, other_label=other_label
    )
    print(f"2. Outcome: {labels.value_counts().to_dict()}")

    selected_cp = spec.cp_rank
    rows: list[dict] = []
    tensor_facts: dict[str, dict] = {}

    for key in keys:
        print(f"3. Building the {key} tensor (RISE fit once)...")
        # Called by name rather than through SWEEP_BUILDERS: the two builders
        # take different arguments, so dispatching through the dict gives the
        # call site a union type and no argument checking at all.
        if key == "ccc_rise":
            sweep = ccc_rise_sweep_tensor(
                adata.copy(),
                lr_pairs,
                spec.condition_column,
                rise_rank=rise_rank,
                complex_sep=complex_sep,
                random_state=random_state,
            )
        else:
            sweep = pseudobulk_sweep_tensor(
                adata.copy(),
                lr_pairs,
                spec.condition_column,
                groupby=spec.celltype_column or "celltype",
                complex_sep=complex_sep,
                random_state=random_state,
            )
        tensor_facts[key] = sweep.extra | {"max_cp_rank": sweep.max_rank}
        skipped = [r for r in ranks if r > sweep.max_rank]
        print(
            f"   {sweep.label}: tensor {sweep.tensor.shape}, CP rank capped at "
            f"{sweep.max_rank}" + (f" (skipping {skipped})" if skipped else "")
        )

        for rank, scored in sweep.iter_scores(ranks):
            result = cv_auc(
                scored.scores,
                labels,
                classifier=classifier,
                n_splits=n_splits,
                n_repeats=n_repeats,
                inner_splits=inner_splits,
                random_state=random_state,
                n_permutations=n_permutations,
                n_boot=n_boot,
                ci_level=ci_level,
            )
            rows.append(
                result.to_row(
                    Method=sweep.key,
                    Label=sweep.label,
                    Classifier=classifier,
                    Rank=rank,
                    MaxRank=sweep.max_rank,
                    IsSelectedRank=bool(
                        selected_cp is not None and rank == int(selected_cp)
                    ),
                )
            )
            marker = " <- selected" if rows[-1]["IsSelectedRank"] else ""
            print(
                f"   rank {rank:>2}: AUC {result.auc:.3f} "
                f"({result.auc_lo:.3f}-{result.auc_hi:.3f})"
                + (
                    f"  null {result.null_auc:.3f} p={result.null_p:.3f}"
                    if result.null_auc is not None
                    else ""
                )
                + marker
            )

    table = pd.DataFrame(rows)
    front = ["Method", "Label", "Classifier", "Rank", "AUC", "AUCLo", "AUCHi"]
    table = table[front + [c for c in table.columns if c not in front]]

    print(f"4. Writing {len(table)} rows to {output_path}...")
    table.to_csv(output_path, index=False)

    metadata = build_metadata(
        dataset_metadata(spec)
        | {
            "methods": keys,
            "ranks": ranks,
            "classifier": classifier,
            "rise_rank": rise_rank,
            "selected_cp_rank": None if selected_cp is None else int(selected_cp),
            "group_column": group_column,
            "control_label": control_label,
            "other_label": other_label,
            "n_splits": n_splits,
            "n_repeats": n_repeats,
            "inner_splits": inner_splits,
            "n_permutations": n_permutations,
            "n_boot": n_boot,
            "ci_level": ci_level,
            "complex_sep": complex_sep,
            "random_state": random_state,
            "tensors": tensor_facts,
            "class_balance": {str(k): int(v) for k, v in labels.value_counts().items()},
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=len(lr_pairs)),
        }
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return table, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--methods", nargs="+", default=None, choices=sorted(SWEEP_BUILDERS)
    )
    parser.add_argument(
        "--ranks",
        type=str,
        default="1:20",
        help="CP ranks to sweep, e.g. '1:20' or '1,3,5,10' (default: 1:20).",
    )
    parser.add_argument(
        "--classifier",
        type=str,
        default=DEFAULT_CLASSIFIER,
        choices=sorted(CLASSIFIERS),
    )
    add_group_arguments(parser)
    parser.add_argument("--rise-rank", type=int, default=None)
    parser.add_argument("--n-splits", type=int, default=10)
    parser.add_argument("--n-repeats", type=int, default=5)
    parser.add_argument("--inner-splits", type=int, default=5)
    parser.add_argument(
        "--n-permutations",
        type=int,
        default=25,
        help="Label permutations per rank; the null curve is what rules out "
        "'more components score higher by chance' (default: 25).",
    )
    parser.add_argument("--n-boot", type=int, default=1000)
    parser.add_argument("--ci-level", type=float, default=95.0)
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument("--output", type=str, default=None)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_benchmark_rank(
        spec,
        rise_rank=selected_rise_rank(spec, args.rise_rank),
        ranks=parse_ranks(args.ranks),
        methods=args.methods,
        classifier=args.classifier,
        group_column=args.group_column,
        control_label=args.control_label,
        other_label=args.other_label,
        n_splits=args.n_splits,
        n_repeats=args.n_repeats,
        inner_splits=args.inner_splits,
        n_permutations=args.n_permutations,
        n_boot=args.n_boot,
        ci_level=args.ci_level,
        complex_sep=args.complex_sep,
        random_state=args.random_state,
        output_path=resolve_output(
            args.output, DATA_DIR, spec.benchmark_rank_filename()
        ),
    )


if __name__ == "__main__":
    main()
