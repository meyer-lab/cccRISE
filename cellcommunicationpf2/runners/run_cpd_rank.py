#!/usr/bin/env python
"""
Runner: CPD rank selection on the interaction tensor.

Fits RISE once at a fixed (already-selected) rank, builds the 4D communication
tensor from that single fit, then sweeps CP ranks over it with entry-masked
imputation cross-validation. Every rank in a sweep therefore sees identical
RISE factors.

The CSV lands at the filename `figureCPDrank` reads, and the pipeline runner
cites it as evidence for the CP rank it was given.

    uv run ccc-rise-cpdrank --dataset alad --rise-rank 25 --ranks 1:26 --n-masks 5
"""

import argparse
import time
from pathlib import Path

import numpy as np
import pandas as pd

from ..ccc_rise import validate_cp_rank
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..rank_selection import cp_masked_reconstruction_sweep
from ..tensor import calculate_interaction_tensor, rise_store_r2x
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    parse_ranks,
    resolve_output,
    resulting_dims,
)
from .datasets import DATA_DIR, DATASETS, DatasetSpec
from .provenance import build_metadata, file_info, git_sha, write_metadata

RUNNER_NAME = "cpd_rank_masked_imputation"
DEFAULT_RANKS = list(range(1, 26))

HEADER = """\
CPD rank selection (entry-masked imputation CV). Generated by
cellcommunicationpf2.runners.run_cpd_rank -- do not hand-edit, except for
`selection.selected_rank` and `selection.notes`, which record which CP rank you
picked off this sweep and why.
"""


def summarize(df: pd.DataFrame) -> dict:
    """Per-rank mean/SEM of held-out entry R2X, plus the argmax rank."""
    agg = {"mean": ("HeldOutR2X", "mean"), "sem": ("HeldOutR2X", "sem")}
    if "InSampleR2X" in df.columns:
        agg["in_sample"] = ("InSampleR2X", "mean")
    stats = df.groupby("Rank").agg(**agg)

    per_rank = []
    for rank, row in stats.iterrows():
        entry = {
            "rank": int(rank),
            "held_out_r2x_mean": float(row["mean"]),
            "held_out_r2x_sem": float(row["sem"]),
        }
        if "in_sample" in stats.columns:
            entry["in_sample_r2x_mean"] = float(row["in_sample"])
        per_rank.append(entry)

    return {
        "best_rank_by_mean_held_out_r2x": int(stats["mean"].idxmax()),
        "per_rank": per_rank,
    }


def build_interaction_tensor(
    spec: DatasetSpec,
    rise_rank: int,
    complex_sep: str | None,
    n_iter_max: int,
    tol: float,
    random_state: int | None,
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
) -> tuple[np.ndarray, dict]:
    """Fit RISE at `rise_rank` and return the 4D communication tensor.

    Returns the tensor plus sidecar fields describing the fit.
    """
    adata = spec.load()
    adata = add_cond_idxs(adata, spec.condition_column)
    lr_pairs = import_ligand_receptor_pairs()

    adata, r2x_pf2 = rise_store_r2x(
        adata,
        rank=rise_rank,
        n_iter_max=n_iter_max,
        tolerance=tol,
        random_state=random_state,
    )
    tensor = calculate_interaction_tensor(
        adata,
        lr_pairs=lr_pairs,
        complex_sep=complex_sep,
        communication_score=communication_score,
        hill_k=hill_k,
    )
    facts = {
        "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=tensor.shape[3]),
        "lr_pairs_annotated": len(lr_pairs),
        "r2x_pf2": float(r2x_pf2),
    }
    return tensor, facts


def run_cpd_rank_selection(
    spec: DatasetSpec,
    rise_rank: int,
    ranks: list[int],
    n_masks: int = 5,
    mask_frac: float = 0.1,
    n_iter_max: int = 100,
    tol: float = 1e-3,
    init: str = "random",
    complex_sep: str | None = "&",
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
    random_state: int | None = 42,
    output_path: Path | None = None,
    selected_rank: int | None = None,
    notes: str | None = None,
) -> tuple[pd.DataFrame, Path, Path]:
    """Sweep CP ranks over one interaction tensor and persist CSV plus sidecar.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank : int
        RISE rank the interaction tensor is built at. CP rank selection is
        conditional on the already-selected RISE rank.
    ranks : list[int]
        CP ranks to evaluate.
    n_masks : int, default=5
        Random mask replicates per rank.
    mask_frac : float, default=0.1
        Fraction of tensor entries held out per mask.
    n_iter_max, tol, init
        Fitting controls for the RISE fit and the masked CP fits.
    complex_sep, communication_score, hill_k
        Communication-tensor options; see `ccc_rise.calc_communication_score`.
    random_state : int, optional
        Base seed for the RISE fit and the mask replicates.
    output_path : Path, optional
        CSV destination. Defaults to the canonical name the figure reads.
    selected_rank : int, optional
        CP rank you are adopting from this sweep, recorded in the sidecar.
    notes : str, optional
        Rationale for `selected_rank`, recorded in the sidecar.

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The sweep results, the CSV path, and the sidecar path.
    """
    output_path = output_path or (DATA_DIR / spec.cpd_rank_filename())
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(
        f"=== CPD imputation rank selection: {spec.label} (RISE rank {rise_rank}) ==="
    )
    print(f"    ranks={ranks}  n_masks={n_masks}  mask_frac={mask_frac}")

    print("1. Loading data and fitting RISE...")
    tensor, tensor_facts = build_interaction_tensor(
        spec,
        rise_rank=rise_rank,
        complex_sep=complex_sep,
        n_iter_max=n_iter_max,
        tol=tol,
        random_state=random_state,
        communication_score=communication_score,
        hill_k=hill_k,
    )
    print(f"   Interaction tensor shape: {tensor.shape}")
    validate_cp_rank(max(ranks), tensor.shape)

    print("2. Running masked-imputation CP sweep...")
    start = time.time()
    df = cp_masked_reconstruction_sweep(
        tensor,
        ranks=ranks,
        n_masks=n_masks,
        mask_frac=mask_frac,
        n_iter_max=n_iter_max,
        init=init,
        random_state=random_state,
    )
    runtime = time.time() - start

    print(f"3. Writing {output_path}...")
    df.to_csv(output_path, index=False)

    summary = summarize(df)
    metadata = build_metadata(
        RUNNER_NAME,
        dataset_metadata(spec)
        | {
            "method": "masked_entry_imputation_cv",
            "rise_rank": rise_rank,
            "cp_ranks": ranks,
            "n_masks": n_masks,
            "mask_frac": mask_frac,
            "n_iter_max": n_iter_max,
            "tol": tol,
            "init": init,
            "complex_sep": complex_sep,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "random_state": random_state,
            "interaction_tensor_shape": list(tensor.shape),
            "runtime_seconds": round(runtime, 1),
        }
        | tensor_facts
        | summary
        | {
            "selection": {"selected_rank": selected_rank, "notes": notes},
            "outputs": {"sweep_csv": file_info(output_path)},
        },
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    print(
        "   Best mean held-out entry R2X at CP rank "
        f"{summary['best_rank_by_mean_held_out_r2x']}"
    )
    return df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank the interaction tensor is built at.",
    )
    parser.add_argument(
        "--ranks",
        type=str,
        default=f"{DEFAULT_RANKS[0]}:{DEFAULT_RANKS[-1] + 1}",
        help="CP ranks: comma list and/or start:stop[:step] slices (default: 1:26).",
    )
    parser.add_argument("--n-masks", type=int, default=5)
    parser.add_argument("--mask-frac", type=float, default=0.1)
    parser.add_argument("--n-iter-max", type=int, default=100)
    parser.add_argument("--tol", type=float, default=1e-3)
    parser.add_argument("--init", type=str, default="random", choices=["random", "svd"])
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument(
        "--communication-score",
        type=str,
        default="expression_product",
        choices=[
            "expression_product",
            "expression_mean",
            "expression_gmean",
            "expression_hill",
        ],
    )
    parser.add_argument("--hill-k", type=float, default=0.5)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV output path (default: data/cpd_rank_<dataset>.csv).",
    )
    parser.add_argument(
        "--selected-rank",
        type=int,
        default=None,
        help="Record the CP rank you are adopting from this sweep in the sidecar.",
    )
    parser.add_argument(
        "--notes",
        type=str,
        default=None,
        help="Rationale for --selected-rank, recorded in the sidecar.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = DATASETS[args.dataset]
    run_cpd_rank_selection(
        spec,
        rise_rank=args.rise_rank,
        ranks=parse_ranks(args.ranks),
        n_masks=args.n_masks,
        mask_frac=args.mask_frac,
        n_iter_max=args.n_iter_max,
        tol=args.tol,
        init=args.init,
        complex_sep=args.complex_sep,
        communication_score=args.communication_score,
        hill_k=args.hill_k,
        random_state=args.random_state,
        output_path=resolve_output(args.output, DATA_DIR, spec.cpd_rank_filename()),
        selected_rank=args.selected_rank,
        notes=args.notes,
    )


if __name__ == "__main__":
    main()
