#!/usr/bin/env python
"""
Runner: CPD rank selection on the interaction tensor by entry-masked imputation CV.

Fits RISE at a fixed (already-selected) rank, builds the 4D communication
tensor, then sweeps `rank_selection.cp_masked_reconstruction_sweep` over CP
ranks. Writes the per-rank/per-mask table to CSV plus a YAML sidecar.

The RISE fit dominates runtime and is identical for every CP rank in a sweep,
so the interaction tensor is cached in the system temp directory, keyed by
everything that determines it. Extending a rank range therefore skips the
refit; entries older than a day are pruned.

The CSV lands at the filename `figureCPDrank` looks for
(``cpd_rank_imputation_<dataset>_rise<rise_rank>.csv``), and the pipeline
runner reads the sidecar to fill in its ``rank_selection.cpd`` block.

    uv run ccc-rise-cpdrank --dataset alad --rise-rank 25 --ranks 1:26 --n-masks 5
"""

import argparse
import hashlib
import json
import tempfile
import time
from pathlib import Path

import numpy as np
import pandas as pd

from ..ccc_rise import validate_cp_rank
from ..import_data import add_cond_idxs, import_ligand_receptor_pairs
from ..rank_selection import cp_masked_reconstruction_sweep
from ..tensor import (
    calculate_interaction_tensor,
    rise_store_r2x,
    run_fms_r2x_analysis,
)
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    parse_ranks,
    resolve_dataset,
    resolve_output,
    resulting_dims,
)
from .datasets import DATA_DIR, DatasetSpec
from .provenance import build_metadata, file_info, write_metadata

RUNNER_NAME = "cpd_rank_masked_imputation"

#: Age at which a temp-file interaction-tensor cache is pruned.
CACHE_MAX_AGE_HOURS = 24
DEFAULT_RANKS = list(range(1, 26))

HEADER = """\
CPD rank selection (entry-masked imputation CV) -- generated by
cellcommunicationpf2.runners.run_cpd_rank. Do not hand-edit, except for
`selection.selected_rank` and `selection.notes`, which are there to record
which CP rank you picked off this sweep and why. The pipeline runner copies
those two fields into its own provenance file.
"""


def summarize(df: pd.DataFrame) -> dict:
    """Per-rank mean/SEM of held-out entry R2X, plus the argmax rank."""
    agg = {"mean": ("HeldOutR2X", "mean"), "sem": ("HeldOutR2X", "sem")}
    if "InSampleR2X" in df.columns:
        agg["in_sample"] = ("InSampleR2X", "mean")
    stats = df.groupby("Rank").agg(**agg)

    per_rank = []
    for rank, row in stats.iterrows():
        entry = {
            "rank": int(rank),
            "held_out_r2x_mean": float(row["mean"]),
            "held_out_r2x_sem": None if pd.isna(row["sem"]) else float(row["sem"]),
        }
        if "in_sample" in stats.columns:
            entry["in_sample_r2x_mean"] = float(row["in_sample"])
        per_rank.append(entry)

    return {
        "best_rank_by_mean_held_out_r2x": int(stats["mean"].idxmax()),
        "per_rank": per_rank,
    }


def build_interaction_tensor(
    spec: DatasetSpec,
    rise_rank: int,
    complex_sep: str | None,
    n_iter_max: int,
    tol: float,
    random_state: int | None,
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
) -> tuple[np.ndarray, dict]:
    """Fit RISE at `rise_rank` and return the 4D communication tensor.

    Returns the tensor plus a small dict of facts about the fit (RISE R2X,
    dataset shape) for the YAML sidecar.
    """
    adata = spec.load()
    adata = add_cond_idxs(adata, spec.condition_column)
    lr_pairs = import_ligand_receptor_pairs()

    adata, r2x_pf2 = rise_store_r2x(
        adata,
        rank=rise_rank,
        n_iter_max=n_iter_max,
        tolerance=tol,
        random_state=random_state,
    )
    tensor = calculate_interaction_tensor(
        adata,
        lr_pairs=lr_pairs,
        complex_sep=complex_sep,
        communication_score=communication_score,
        hill_k=hill_k,
    )
    return tensor, {
        "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=tensor.shape[3]),
        "lr_pairs_annotated": len(lr_pairs),
        "r2x_pf2": float(r2x_pf2),
    }


def _cached_interaction_tensor(spec: DatasetSpec, **kwargs) -> tuple[np.ndarray, dict]:
    """Build the interaction tensor, reusing a temp-file cache across invocations.

    The RISE fit dominates runtime and is identical for every CP rank in a
    sweep, so extending a rank range should not pay for it again. The cache key
    covers everything that determines the tensor, so a hit is always a tensor
    this run would have rebuilt identically.

    Entries older than `CACHE_MAX_AGE_HOURS` are pruned, which bounds the space
    these multi-GB files can take without deleting a cache another sweep may be
    mid-way through reading -- pruning "every key but mine" would let two
    concurrent runs on different datasets destroy each other's work.

    The cache lives in the system temp directory, so it is not a durable
    artifact: the durable record of a sweep is its CSV and provenance sidecar.
    """
    key = hashlib.sha256(
        repr(
            (
                spec.key,
                str(spec.source_file),
                spec.condition_column,
                spec.gene_threshold,
                sorted(kwargs.items()),
            )
        ).encode()
    ).hexdigest()[:16]
    cache_dir = Path(tempfile.gettempdir())
    cache_path = cache_dir / f"ccc_rise_tensor_{key}.npy"
    facts_path = cache_path.with_suffix(".facts.json")

    cutoff = time.time() - CACHE_MAX_AGE_HOURS * 3600
    for stale in cache_dir.glob("ccc_rise_tensor_*"):
        try:
            if stale.stat().st_mtime < cutoff:
                stale.unlink(missing_ok=True)
        except OSError:
            continue

    if cache_path.exists() and facts_path.exists():
        print(f"1. Reusing cached interaction tensor from {cache_path}...")
        return np.load(cache_path), json.loads(facts_path.read_text())

    print("1. Loading data and fitting RISE...")
    tensor, facts = build_interaction_tensor(spec, **kwargs)
    np.save(cache_path, tensor)
    facts_path.write_text(json.dumps(facts))
    print(f"   Cached interaction tensor to {cache_path}")
    return tensor, facts


def run_cpd_rank_selection(
    spec: DatasetSpec,
    rise_rank: int,
    ranks: list[int],
    n_masks: int = 5,
    mask_frac: float = 0.1,
    n_iter_max: int = 100,
    tol: float = 1e-3,
    init: str = "random",
    complex_sep: str | None = "&",
    communication_score: str = "expression_product",
    hill_k: float = 0.5,
    random_state: int | None = 42,
    output_path: Path | None = None,
    fms_runs: int = 0,
    fms_output_path: Path | None = None,
    selected_rank: int | None = None,
    notes: str | None = None,
    checksum_source: bool = True,
) -> tuple[pd.DataFrame, Path, Path]:
    """Run the masked-imputation CP sweep and persist the CSV plus YAML sidecar.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry.
    rise_rank : int
        RISE rank the interaction tensor is built at (i.e. the already-selected
        RISE rank -- CP rank selection is conditional on it).
    ranks : list[int]
        CP ranks to evaluate.
    n_masks : int, default=5
        Random mask replicates per rank.
    mask_frac : float, default=0.1
        Fraction of tensor entries held out per mask.
    n_iter_max, tol, init
        Fitting controls for the RISE fit and the masked CP fits.
    complex_sep, communication_score, hill_k
        Communication-tensor construction options; see
        `ccc_rise.calc_communication_score`.
    random_state : int, optional
        Base seed for the RISE fit and the mask replicates.
    output_path : Path, optional
        CSV destination. Defaults to the canonical name the figure expects.
    selected_rank : int, optional
        CP rank you are adopting from this sweep, recorded in the sidecar.
    fms_runs : int, default=0
        Bootstrap replicates per rank for the FMS-elbow criterion the
        supplemental figures use (`tensor.run_fms_r2x_analysis`). Issue #164
        asks for CP rank to be justified by imputation CV *and* the FMS elbow;
        0 skips it, since it roughly doubles the sweep cost.
    fms_output_path : Path, optional
        CSV destination for the FMS curve. Defaults to the sweep CSV's name
        with a ``_fms`` suffix.
    notes : str, optional
        Free-text rationale for `selected_rank`, recorded in the sidecar.
    checksum_source : bool, default=True
        Hash the raw `.h5ad` into the sidecar's ``source_sha256`` (issue #164).

    Returns
    -------
    tuple[pd.DataFrame, Path, Path]
        The sweep results, the CSV path, and the YAML sidecar path.
    """
    output_path = output_path or (DATA_DIR / spec.cpd_rank_filename(rise_rank))
    output_path.parent.mkdir(parents=True, exist_ok=True)

    print(
        f"=== CPD imputation rank selection: {spec.label} (RISE rank {rise_rank}) ==="
    )
    print(f"    ranks={ranks}  n_masks={n_masks}  mask_frac={mask_frac}")

    tensor, tensor_facts = _cached_interaction_tensor(
        spec,
        rise_rank=rise_rank,
        complex_sep=complex_sep,
        n_iter_max=n_iter_max,
        tol=tol,
        random_state=random_state,
        communication_score=communication_score,
        hill_k=hill_k,
    )
    print(f"   Interaction tensor shape: {tensor.shape}")

    # Sweeping past the tensor's smallest mode is not a slow experiment, it is a
    # 975 GiB allocation (issue #164). Drop those ranks and say so, rather than
    # failing partway through a sweep that is otherwise fine.
    max_rank = min(tensor.shape)
    dropped_ranks = [r for r in ranks if r > max_rank]
    ranks = [r for r in ranks if r <= max_rank]
    if dropped_ranks:
        print(
            f"   Skipping CP ranks {dropped_ranks}: they exceed the tensor's "
            f"smallest mode ({max_rank})."
        )
    if not ranks:
        raise ValueError(
            f"No CP ranks left to evaluate: every requested rank exceeds the "
            f"tensor's smallest mode ({max_rank}) for shape {tuple(tensor.shape)}."
        )
    validate_cp_rank(max(ranks), tensor.shape)

    print("2. Running masked-imputation CP sweep...")
    start = time.time()
    df = cp_masked_reconstruction_sweep(
        tensor,
        ranks=ranks,
        n_masks=n_masks,
        mask_frac=mask_frac,
        n_iter_max=n_iter_max,
        init=init,
        random_state=random_state,
    )
    runtime = time.time() - start

    print(f"3. Writing {output_path}...")
    df.to_csv(output_path, index=False)

    outputs = {"sweep_csv": file_info(output_path)}
    fms_summary: dict = {}
    if fms_runs > 0:
        # The second of the two criteria issue #164 asks for: bootstrap the
        # tensor's LR mode at each rank and score factor-match stability, the
        # elbow criterion the supplemental figures already plot.
        fms_output_path = fms_output_path or output_path.with_name(
            f"{output_path.stem}_fms.csv"
        )
        print(f"4. Running FMS stability sweep ({fms_runs} runs/rank)...")
        fms_start = time.time()
        fms_df = run_fms_r2x_analysis(
            tensor, rank_list=ranks, runs=fms_runs, svd_init=init
        )
        fms_df.to_csv(fms_output_path, index=False)
        outputs["fms_csv"] = file_info(fms_output_path)
        fms_stats = fms_df.groupby("Component")["FMS"].mean()
        fms_summary = {
            "fms_runs": fms_runs,
            "best_rank_by_mean_fms": int(fms_stats.idxmax()),
            "fms_per_rank": [
                {"rank": int(rank), "fms_mean": float(value)}
                for rank, value in fms_stats.items()
            ],
            "fms_runtime_seconds": round(time.time() - fms_start, 1),
        }
        print(f"   Highest mean FMS at CP rank {fms_summary['best_rank_by_mean_fms']}")

    summary = summarize(df)
    metadata = build_metadata(
        RUNNER_NAME,
        dataset_metadata(spec, checksum_source=checksum_source)
        | {
            "method": "masked_entry_imputation_cv"
            + (" + fms_elbow" if fms_runs else ""),
            "rise_rank": rise_rank,
            "cp_ranks": ranks,
            "cp_ranks_skipped_over_max_mode": dropped_ranks or None,
            "max_cp_rank": max_rank,
            "n_masks": n_masks,
            "mask_frac": mask_frac,
            "n_iter_max": n_iter_max,
            "tol": tol,
            "init": init,
            "complex_sep": complex_sep,
            "communication_score": communication_score,
            "hill_k": hill_k,
            "random_state": random_state,
            "resulting_dims": tensor_facts.get("resulting_dims"),
            "lr_pairs_annotated": tensor_facts.get("lr_pairs_annotated"),
            "interaction_tensor_shape": list(tensor.shape),
            "r2x_pf2": tensor_facts.get("r2x_pf2"),
            "runtime_seconds": round(runtime, 1),
        }
        | summary
        | fms_summary
        | {
            "selection": {"selected_rank": selected_rank, "notes": notes},
            "outputs": outputs,
        },
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    print(
        "   Best mean held-out entry R2X at CP rank "
        f"{summary['best_rank_by_mean_held_out_r2x']}"
    )
    return df, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    add_dataset_argument(parser)
    parser.add_argument(
        "--rise-rank",
        type=int,
        required=True,
        help="RISE rank the interaction tensor is built at (CP rank selection "
        "is conditional on the already-selected RISE rank).",
    )
    parser.add_argument(
        "--ranks",
        type=str,
        default=f"{DEFAULT_RANKS[0]}:{DEFAULT_RANKS[-1] + 1}",
        help="CP ranks: comma list and/or start:stop[:step] slices (default: 1:26).",
    )
    parser.add_argument("--n-masks", type=int, default=5)
    parser.add_argument("--mask-frac", type=float, default=0.1)
    parser.add_argument("--n-iter-max", type=int, default=100)
    parser.add_argument("--tol", type=float, default=1e-3)
    parser.add_argument("--init", type=str, default="random", choices=["random", "svd"])
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument(
        "--communication-score",
        type=str,
        default="expression_product",
        choices=[
            "expression_product",
            "expression_mean",
            "expression_gmean",
            "expression_hill",
        ],
    )
    parser.add_argument("--hill-k", type=float, default=0.5)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="CSV output path (default: cellcommunicationpf2/data/"
        "cpd_rank_imputation_<dataset>_rise<rise_rank>.csv).",
    )
    parser.add_argument(
        "--fms-runs",
        type=int,
        default=0,
        help="Bootstrap replicates per rank for the FMS-elbow criterion "
        "(0 = skip). Roughly doubles the sweep cost.",
    )
    parser.add_argument(
        "--fms-output",
        type=str,
        default=None,
        help="CSV path for the FMS curve (default: the sweep CSV name + '_fms').",
    )
    parser.add_argument(
        "--selected-rank",
        type=int,
        default=None,
        help="Record the CP rank you are adopting from this sweep in the sidecar.",
    )
    parser.add_argument(
        "--notes",
        type=str,
        default=None,
        help="Free-text rationale for --selected-rank, recorded in the sidecar.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = resolve_dataset(args)
    output = resolve_output(
        args.output, DATA_DIR, spec.cpd_rank_filename(args.rise_rank)
    )
    run_cpd_rank_selection(
        spec,
        rise_rank=args.rise_rank,
        ranks=parse_ranks(args.ranks),
        n_masks=args.n_masks,
        mask_frac=args.mask_frac,
        n_iter_max=args.n_iter_max,
        tol=args.tol,
        init=args.init,
        complex_sep=args.complex_sep,
        communication_score=args.communication_score,
        hill_k=args.hill_k,
        random_state=args.random_state,
        output_path=output,
        fms_runs=args.fms_runs,
        fms_output_path=Path(args.fms_output) if args.fms_output else None,
        selected_rank=args.selected_rank,
        notes=args.notes,
        checksum_source=not args.skip_source_checksum,
    )


if __name__ == "__main__":
    main()
