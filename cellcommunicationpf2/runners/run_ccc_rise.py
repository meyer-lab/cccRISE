#!/usr/bin/env python
"""
Runner: the end-to-end CCC-RISE pipeline.

Loads a registered dataset, runs RISE at `--rise-rank` followed by CP
decomposition of the interaction tensor at `--cp-rank`, and serializes the
factor model to NetCDF along with a YAML provenance sidecar.

The ``.nc`` file is written in the format the figure modules already read, via
`figures.common.get_alad_data` / `factors.load_factors_to_anndata`.

The sidecar's ``rank_selection`` block records *which* rank-selection run
justifies the chosen ranks. It is auto-populated from the sibling sweep
sidecars written by `run_rise_rank` / `run_cpd_rank` when those exist, and
``--rise-rank-notes`` / ``--cpd-rank-notes`` let you state the rationale
directly.

    uv run ccc-rise-run --dataset alad --rise-rank 25 --cp-rank 14
    uv run ccc-rise-run --dataset ibd  --rise-rank 20 --cp-rank 10
"""

import argparse
import time
from pathlib import Path
from typing import Any

import anndata
import numpy as np
import xarray as xr

from ..ccc_rise import validate_cp_rank
from ..factors import factors_to_xarray, save_factors_netcdf
from ..import_data import import_ligand_receptor_pairs
from ..tensor import run_ccc_rise_workflow
from ._cli import (
    add_dataset_argument,
    dataset_metadata,
    resolve_dataset,
    resolve_output,
    resulting_dims,
)
from .datasets import DATA_DIR, DatasetSpec
from .provenance import (
    build_metadata,
    file_info,
    git_sha,
    read_metadata,
    relpath,
    sidecar_path,
    write_metadata,
)

RUNNER_NAME = "ccc_rise_pipeline"

HEADER = """\
CCC-RISE pipeline provenance -- generated by
cellcommunicationpf2.runners.run_ccc_rise. Records exactly how the sibling
.nc factor model was produced.

Do not hand-edit, with one exception: the `rank_selection.rise.notes` and
`rank_selection.cpd.notes` fields exist to document *why* these ranks were
chosen. They are seeded from the matching rank-selection sweep sidecars (and
from --rise-rank-notes / --cpd-rank-notes), but a re-run overwrites them, so
keep the reasoning in the PR as well.
"""


def _rank_selection_block(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    rise_sidecar: Path | None,
    cpd_sidecar: Path | None,
    rise_notes: str | None,
    cpd_notes: str | None,
) -> dict[str, Any]:
    """Build the ``rank_selection`` block, pulling from sweep sidecars if present.

    For each stage this records the chosen rank, the method, the sweep files it
    came from, and a free-text rationale.
    """

    def stage(
        rank: int,
        method: str,
        default_csv: Path,
        sidecar: Path | None,
        notes: str | None,
    ) -> dict[str, Any]:
        csv_path = default_csv
        sidecar = sidecar or sidecar_path(default_csv)

        # Keys are laid out in a fixed order so sidecars diff cleanly across
        # runs, whether or not a sweep was found.
        block: dict[str, Any] = {
            "rank": rank,
            "method": method,
            "sweep_csv": relpath(csv_path) if csv_path.exists() else None,
            "fms_csv": None,
            "sweep_yaml": relpath(sidecar) if sidecar.exists() else None,
            "sweep_generated": None,
            "sweep_git_commit": None,
            "sweep_selected_rank": None,
            "notes": notes,
        }

        if not sidecar.exists():
            if block["notes"] is None:
                block["notes"] = (
                    f"No {method} sweep sidecar found at {relpath(sidecar)}; run "
                    "the matching rank-selection runner, or record the rationale "
                    "here."
                )
            return block

        meta = read_metadata(sidecar)
        outputs = meta.get("outputs") or {}
        selection = meta.get("selection") or {}
        # The sweep knows what it actually ran (e.g. imputation CV plus the FMS
        # elbow); prefer its own label over the default for this stage.
        block["method"] = meta.get("method", method)
        block["sweep_csv"] = (outputs.get("sweep_csv") or {}).get(
            "path", block["sweep_csv"]
        )
        # The CPD sweep optionally also produces an FMS-elbow curve; cite it too.
        if outputs.get("fms_csv"):
            block["fms_csv"] = outputs["fms_csv"].get("path")
        block["sweep_generated"] = meta.get("generated")
        block["sweep_git_commit"] = meta.get("git_sha")
        block["sweep_selected_rank"] = selection.get("selected_rank")
        if block["notes"] is None:
            block["notes"] = selection.get("notes")
        return block

    return {
        "rise": stage(
            rise_rank,
            "bicv",
            DATA_DIR / spec.rise_rank_filename(),
            rise_sidecar,
            rise_notes,
        ),
        "cpd": stage(
            cp_rank,
            "masked_entry_imputation_cv",
            DATA_DIR / spec.cpd_rank_filename(rise_rank),
            cpd_sidecar,
            cpd_notes,
        ),
    }


def run_pipeline(
    spec: DatasetSpec,
    rise_rank: int,
    cp_rank: int,
    n_iter_max: int = 100,
    tol: float = 1e-3,
    random_state: int | None = 42,
    complex_sep: str | None = "&",
    svd_init: str = "svd",
    output_path: Path | None = None,
    rise_rank_sidecar: Path | None = None,
    cpd_rank_sidecar: Path | None = None,
    rise_rank_notes: str | None = None,
    cpd_rank_notes: str | None = None,
    checksum_source: bool = True,
) -> tuple[anndata.AnnData, xr.Dataset, Path, Path]:
    """Run CCC-RISE end to end and serialize the factor model plus provenance.

    Parameters
    ----------
    spec : DatasetSpec
        Dataset registry entry (loader, condition column, output naming).
    rise_rank : int
        Rank for the RISE / PARAFAC2 stage.
    cp_rank : int
        Rank for the CP decomposition of the interaction tensor.
    n_iter_max : int, default=100
        Maximum iterations for both the PARAFAC2 and CP fits.
    tol : float, default=1e-3
        Convergence tolerance for both fits.
    random_state : int, optional, default=42
        Seed for the decompositions and the PaCMAP embedding.
    complex_sep : str, optional, default="&"
        Separator for multimeric complexes in the ligand-receptor annotation.
    svd_init : str, default="svd"
        Initialization for the CP fit.
    output_path : Path, optional
        NetCDF destination. Defaults to the dataset's canonical factors path,
        which is what the figure modules already load.
    rise_rank_sidecar, cpd_rank_sidecar : Path, optional
        Rank-selection sweep sidecars to cite. Default to the canonical sweep
        filenames for this dataset/rank when they exist.
    rise_rank_notes, cpd_rank_notes : str, optional
        Rationale for each chosen rank, written into the provenance file.
    checksum_source : bool, default=True
        Hash the raw `.h5ad` into the sidecar's ``source_sha256``. This is the
        field that detects source-data drift (issue #164); disable only when the
        few minutes of hashing genuinely matter.

    Returns
    -------
    tuple[anndata.AnnData, xr.Dataset, Path, Path]
        The fitted AnnData, the factor Dataset, the ``.nc`` path, and the
        ``.yaml`` sidecar path.
    """
    output_path = output_path or spec.factors_path()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Pin the code version before writing anything: see `provenance.git_sha`.
    git_sha()

    print(f"=== CCC-RISE pipeline: {spec.label} ===")
    print(f"    RISE rank={rise_rank}  CP rank={cp_rank}  seed={random_state}")

    print("1. Loading data and ligand-receptor pairs...")
    adata = spec.load()
    lr_pairs = import_ligand_receptor_pairs()
    print(f"   AnnData shape: {adata.shape}, LR pairs: {len(lr_pairs)}")

    # Fail in seconds rather than after an hours-long RISE fit. `ccc_rise` re-checks
    # against the real tensor; this predicts its shape from what we already know.
    n_conditions = int(adata.obs[spec.condition_column].nunique())
    validate_cp_rank(cp_rank, (n_conditions, rise_rank, rise_rank))

    print("2. Running CCC-RISE workflow...")
    start = time.time()
    adata, r2x_cp = run_ccc_rise_workflow(
        adata=adata,
        rise_rank=rise_rank,
        lr_pairs=lr_pairs,
        cp_rank=cp_rank,
        condition_column=spec.condition_column,
        n_iter_max=n_iter_max,
        tol=tol,
        random_state=random_state,
        complex_sep=complex_sep,
        # Nothing downstream of this runner reads a PaCMAP embedding out of the
        # `.nc`, so computing one here would be discarded work.
        doEmbedding=False,
        svd_init=svd_init,
    )
    runtime = time.time() - start
    r2x_pf2 = adata.uns.get("r2x_pf2")
    print(f"   Done in {runtime:.0f}s. CP R2X: {r2x_cp:.4f}")

    print("3. Converting factors to xarray...")
    condition_names = np.unique(adata.obs[spec.condition_column].unique())
    cpd_factors = [adata.uns["A"], adata.uns["B"], adata.uns["C"], adata.uns["D"]]
    ds = factors_to_xarray(
        cpd_factors=cpd_factors,
        cpd_weights=adata.uns["weights"],
        filtered_lr_pairs=adata.uns["lr_pairs"],
        condition_names=condition_names,
        gene_names=list(adata.var_names),
        pf2_factors=[adata.uns["Pf2_A"], adata.uns["Pf2_B"], adata.uns["Pf2_C"]],
        pf2_weights=adata.uns["Pf2_weights"],
        r2x_cp=r2x_cp,
        r2x_pf2=r2x_pf2,
        attrs={
            "dataset_name": spec.key,
            "dataset_label": spec.label,
            "condition_key": spec.condition_column,
            "complex_sep": complex_sep or "",
        },
    )

    print(f"4. Saving factor model to {output_path}...")
    save_factors_netcdf(ds, output_path)

    if checksum_source and spec.source_file is not None:
        print("5. Hashing source data for the provenance record...")

    rank_selection = _rank_selection_block(
        spec,
        rise_rank=rise_rank,
        cp_rank=cp_rank,
        rise_sidecar=rise_rank_sidecar,
        cpd_sidecar=cpd_rank_sidecar,
        rise_notes=rise_rank_notes,
        cpd_notes=cpd_rank_notes,
    )
    n_lr_used = len(adata.uns["lr_pairs"])
    evidence = [
        block[key]
        for block in rank_selection.values()
        for key in ("sweep_csv", "fms_csv")
        if block.get(key)
    ]
    metadata = build_metadata(
        RUNNER_NAME,
        dataset_metadata(spec, checksum_source=checksum_source)
        | {
            "rise_rank": rise_rank,
            "cp_rank": cp_rank,
            "rank_selection_evidence": evidence or None,
            "n_iter_max": n_iter_max,
            "tol": tol,
            "random_state": random_state,
            "complex_sep": complex_sep,
            "svd_init": svd_init,
            "lr_pairs_annotated": len(lr_pairs),
            "resulting_dims": resulting_dims(spec, adata, n_lr_pairs=n_lr_used),
            "interaction_tensor_shape": [
                len(condition_names),
                rise_rank,
                rise_rank,
                n_lr_used,
            ],
            "r2x_pf2": None if r2x_pf2 is None else float(r2x_pf2),
            "r2x_cp": float(r2x_cp),
            "runtime_seconds": round(runtime, 1),
            "rank_selection": rank_selection,
            "outputs": {"factors_nc": file_info(output_path)},
        },
    )
    sidecar = write_metadata(output_path, metadata, header=HEADER)
    print(f"   Wrote provenance to {sidecar}")
    return adata, ds, output_path, sidecar


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    add_dataset_argument(parser)
    parser.add_argument("--rise-rank", type=int, required=True, help="RISE rank.")
    parser.add_argument("--cp-rank", type=int, required=True, help="CP (CPD) rank.")
    parser.add_argument("--n-iter-max", type=int, default=100)
    parser.add_argument("--tol", type=float, default=1e-3)
    parser.add_argument("--random-state", type=int, default=42)
    parser.add_argument("--complex-sep", type=str, default="&")
    parser.add_argument(
        "--svd-init", type=str, default="svd", choices=["svd", "random"]
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="NetCDF output path (default: the dataset's canonical factors file, "
        "which the figure modules already load).",
    )
    parser.add_argument(
        "--rise-rank-selection",
        type=str,
        default=None,
        help="Path to the RISE rank-selection YAML sidecar to cite.",
    )
    parser.add_argument(
        "--cpd-rank-selection",
        type=str,
        default=None,
        help="Path to the CPD rank-selection YAML sidecar to cite.",
    )
    parser.add_argument(
        "--rise-rank-notes",
        type=str,
        default=None,
        help="Rationale for the chosen RISE rank, recorded in the provenance file.",
    )
    parser.add_argument(
        "--cpd-rank-notes",
        type=str,
        default=None,
        help="Rationale for the chosen CP rank, recorded in the provenance file.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    spec = resolve_dataset(args)
    output = resolve_output(args.output, DATA_DIR, spec.factors_filename)
    run_pipeline(
        spec,
        rise_rank=args.rise_rank,
        cp_rank=args.cp_rank,
        n_iter_max=args.n_iter_max,
        tol=args.tol,
        random_state=args.random_state,
        complex_sep=args.complex_sep,
        svd_init=args.svd_init,
        output_path=output,
        rise_rank_sidecar=(
            Path(args.rise_rank_selection) if args.rise_rank_selection else None
        ),
        cpd_rank_sidecar=(
            Path(args.cpd_rank_selection) if args.cpd_rank_selection else None
        ),
        rise_rank_notes=args.rise_rank_notes,
        cpd_rank_notes=args.cpd_rank_notes,
        checksum_source=not args.skip_source_checksum,
    )


if __name__ == "__main__":
    main()
